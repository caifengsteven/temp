class TemporalKAN(layers.Layer):
    """Simplified implementation of Temporal Kolmogorov-Arnold Networks (TKAN)"""
    def __init__(self, units, activation='relu', **kwargs):
        super(TemporalKAN, self).__init__(**kwargs)
        self.units = units
        self.activation_fn = activation
        
    def build(self, input_shape):
        self.w_x = self.add_weight(shape=(input_shape[-1], self.units),
                                  initializer='glorot_uniform',
                                  trainable=True, name='w_x')
        self.w_h = self.add_weight(shape=(self.units, self.units),
                                  initializer='glorot_uniform',
                                  trainable=True, name='w_h')
        self.b = self.add_weight(shape=(self.units,),
                                initializer='zeros',
                                trainable=True, name='bias')
        self.state_size = self.units
        self.built = True
        
    def call(self, inputs, states=None):
        prev_output = states[0] if states is not None else tf.zeros((tf.shape(inputs)[0], self.units))
        x = tf.matmul(inputs, self.w_x)
        h = tf.matmul(prev_output, self.w_h)
        output = tf.nn.relu(x + h + self.b)
        return output, [output]
    
    def get_initial_state(self, inputs=None, batch_size=None, dtype=None):
        return [tf.zeros((batch_size, self.units), dtype=dtype)]

class DynamicVWAPModel:
    """Implementation of the Dynamic VWAP execution model from the paper"""
    
    def __init__(self, lookback_window=120, prediction_horizon=12, feature_dim=4, 
                 use_tkan=True, hidden_dim=64, learning_rate=0.001):
        self.lookback_window = lookback_window
        self.prediction_horizon = prediction_horizon
        self.feature_dim = feature_dim
        self.use_tkan = use_tkan
        self.hidden_dim = hidden_dim
        self.learning_rate = learning_rate
        self.model = self._build_model()
        
    def _build_model(self):
        # Input layer
        inputs = keras.Input(shape=(self.lookback_window, self.feature_dim))
        
        # Initialize learnable base volume curve (uniformly)
        base_volume_curve = tf.Variable(
            initial_value=tf.ones((self.prediction_horizon,)) / self.prediction_horizon,
            trainable=True, name='base_volume_curve'
        )
        
        # RNN component (either TKAN or LSTM)
        if self.use_tkan:
            rnn_layer = keras.layers.RNN(
                TemporalKAN(self.hidden_dim), 
                return_sequences=True, 
                return_state=True,
                name='tkan_layer'
            )
        else:
            rnn_layer = keras.layers.LSTM(
                self.hidden_dim, 
                return_sequences=True, 
                return_state=True,
                name='lstm_layer'
            )
        
        # Process input sequence
        if self.use_tkan:
            sequence_output, h_state = rnn_layer(inputs)
            states = [h_state]
        else:
            sequence_output, h_state, c_state = rnn_layer(inputs)
            states = [h_state, c_state]
            
        # Initialize list to store allocated volumes
        allocated_volumes = []
        remaining_volume = tf.constant(1.0)
        
        # Sequential allocation process
        for i in range(self.prediction_horizon - 1):
            # Get hidden state for current timestep
            current_hidden = sequence_output[:, self.lookback_window - self.prediction_horizon + i]
            
            # Create input for adjustment network
            if i == 0:
                adjustment_input = current_hidden
            else:
                # Concatenate hidden state with previous allocations
                previous_allocations = tf.stack(allocated_volumes, axis=1)
                adjustment_input = tf.concat([current_hidden, tf.reshape(previous_allocations, 
                                                                         [-1, i])], axis=1)
            
            # Dynamic adjustment network (3-layer MLP)
            x = layers.Dense(32, activation='relu')(adjustment_input)
            x = layers.Dense(16, activation='relu')(x)
            adjustment_factor = layers.Dense(1, activation='tanh')(x)
            
            # Scale adjustment factor to range [0, 2]
            adjustment_factor = 1.0 + adjustment_factor
            
            # Apply adjustment to base volume
            raw_allocation = adjustment_factor * base_volume_curve[i]
            
            # Clip to ensure non-negativity and not exceeding remaining volume
            allocation = tf.clip_by_value(raw_allocation, 0.0, remaining_volume)
            allocated_volumes.append(allocation)
            
            # Update remaining volume
            remaining_volume = remaining_volume - allocation
        
        # Final timestep: allocate all remaining volume
        allocated_volumes.append(remaining_volume)
        
        # Stack all allocations to create final volume curve
        volume_curve = tf.stack(allocated_volumes, axis=1)
        
        # Create model
        model = keras.Model(inputs=inputs, outputs=volume_curve)
        
        # Compile model
        optimizer = keras.optimizers.Adam(learning_rate=self.learning_rate)
        model.compile(optimizer=optimizer, loss='mae')  # Using MAE for absolute VWAP loss
        
        return model
    
    def normalize_base_volume_curve(self):
        """Ensure base volume curve sums to 1 and is non-negative"""
        weights = self.model.trainable_weights
        for w in weights:
            if w.name == 'base_volume_curve:0':
                # Apply softmax to ensure non-negativity and sum-to-one
                w.assign(tf.nn.softmax(w))
    
    def fit(self, X_train, y_train, X_val=None, y_val=None, epochs=100, batch_size=128):
        """Train the model with early stopping"""
        callbacks = [
            keras.callbacks.EarlyStopping(
                monitor='val_loss' if X_val is not None else 'loss',
                patience=10,
                min_delta=0.00001
            ),
            keras.callbacks.LearningRateScheduler(
                lambda epoch, lr: lr * 0.25 if epoch % 5 == 0 and epoch > 0 else lr,
                verbose=0
            ),
            # Custom callback to normalize base volume curve after each epoch
            keras.callbacks.LambdaCallback(on_epoch_end=lambda epoch, logs: self.normalize_base_volume_curve())
        ]
        
        start_time = time.time()
        history = self.model.fit(
            X_train, y_train,
            validation_data=(X_val, y_val) if X_val is not None else None,
            epochs=epochs,
            batch_size=batch_size,
            callbacks=callbacks,
            verbose=1
        )
        training_time = time.time() - start_time
        
        return history, training_time
    
    def predict(self, X):
        """Generate predictions for input data"""
        return self.model.predict(X)


class VWAPEvaluator:
    """Evaluation metrics for VWAP execution strategies"""
    
    @staticmethod
    def calculate_vwap(prices, volumes):
        """Calculate VWAP given price and volume arrays"""
        return np.sum(prices * volumes) / np.sum(volumes)
    
    @staticmethod
    def absolute_vwap_loss(prices, target_volumes, predicted_volumes):
        """Calculate absolute difference between achieved VWAP and market VWAP"""
        market_vwap = VWAPEvaluator.calculate_vwap(prices, target_volumes)
        execution_vwap = VWAPEvaluator.calculate_vwap(prices, predicted_volumes)
        return np.abs(execution_vwap - market_vwap)
    
    @staticmethod
    def quadratic_vwap_loss(prices, target_volumes, predicted_volumes):
        """Calculate squared difference between achieved VWAP and market VWAP"""
        market_vwap = VWAPEvaluator.calculate_vwap(prices, target_volumes)
        execution_vwap = VWAPEvaluator.calculate_vwap(prices, predicted_volumes)
        return (execution_vwap - market_vwap) ** 2
    
    @staticmethod
    def volume_curve_r2(target_volumes, predicted_volumes):
        """Calculate R² score for volume curve prediction"""
        return r2_score(target_volumes, predicted_volumes)
    
    @staticmethod
    def evaluate_model(model, X_test, prices_test, volumes_test):
        """Comprehensive evaluation of model performance"""
        predictions = model.predict(X_test)
        
        # Normalize predictions to ensure sum to 1
        predictions = predictions / np.sum(predictions, axis=1, keepdims=True)
        
        # Initialize results containers
        abs_losses = []
        quad_losses = []
        r2_scores = []
        
        # Calculate metrics for each test sample
        for i in range(len(X_test)):
            abs_loss = VWAPEvaluator.absolute_vwap_loss(
                prices_test[i], volumes_test[i], predictions[i]
            )
            quad_loss = VWAPEvaluator.quadratic_vwap_loss(
                prices_test[i], volumes_test[i], predictions[i]
            )
            r2 = VWAPEvaluator.volume_curve_r2(
                volumes_test[i], predictions[i]
            )
            
            abs_losses.append(abs_loss)
            quad_losses.append(quad_loss)
            r2_scores.append(r2)
        
        # Compute average metrics
        results = {
            'absolute_vwap_loss': np.mean(abs_losses),
            'quadratic_vwap_loss': np.mean(quad_losses),
            'r2_score': np.mean(r2_scores),
            'predictions': predictions
        }
        
        return results


class MarketDataSimulator:
    """Generate simulated cryptocurrency market data"""
    
    def __init__(self, n_samples=1000, horizon=12, features=4, assets=["BTC", "ETH", "BNB", "ADA", "XRP"]):
        self.n_samples = n_samples
        self.horizon = horizon
        self.features = features
        self.assets = assets
        
    def generate_volume_patterns(self):
        """Generate realistic market volume patterns"""
        patterns = {}
        
        # Define some typical patterns (U-shape, reverse J, etc.)
        base_patterns = {
            'u_shape': lambda t, h: 1.5 - np.sin(np.pi * t / h),
            'reverse_j': lambda t, h: 0.5 + np.exp(-t / (h * 0.3)),
            'j_shape': lambda t, h: 0.5 + np.exp(-(h - t) / (h * 0.3)),
            'flat': lambda t, h: np.ones_like(t)
        }
        
        for asset in self.assets:
            # Random pattern selection with some noise
            pattern_type = np.random.choice(list(base_patterns.keys()))
            t = np.arange(self.horizon)
            
            # Generate base pattern
            raw_pattern = base_patterns[pattern_type](t, self.horizon)
            
            # Add some noise
            noise = np.random.normal(0, 0.1, self.horizon)
            noisy_pattern = raw_pattern + noise
            
            # Ensure non-negativity
            noisy_pattern = np.maximum(noisy_pattern, 0.01)
            
            # Normalize to sum to 1
            normalized_pattern = noisy_pattern / np.sum(noisy_pattern)
            
            patterns[asset] = normalized_pattern
            
        return patterns
    
    def generate_data(self, asset="BTC"):
        """Generate simulated market data for a specific asset"""
        # Get volume pattern for the asset
        volume_patterns = self.generate_volume_patterns()
        base_volume_pattern = volume_patterns[asset]
        
        # Initialize containers
        X = np.zeros((self.n_samples, self.horizon + 15, self.features))  # Features: [price, volume, hour, day]
        prices = np.zeros((self.n_samples, self.horizon))
        volumes = np.zeros((self.n_samples, self.horizon))
        
        for i in range(self.n_samples):
            # Generate initial price and volatility
            initial_price = np.random.uniform(10, 60000)  # Wide range to cover different assets
            volatility = np.random.uniform(0.005, 0.05)
            
            # Generate price series with random walk
            price_series = [initial_price]
            for j in range(self.horizon + 14):
                price_move = np.random.normal(0, volatility * price_series[-1])
                new_price = max(price_series[-1] + price_move, 0.01)  # Ensure positive price
                price_series.append(new_price)
            
            price_series = np.array(price_series)
            
            # Generate volume series based on pattern with some randomness
            volume_pattern = base_volume_pattern * np.random.uniform(0.8, 1.2, self.horizon)
            volume_pattern = volume_pattern / np.sum(volume_pattern)  # Re-normalize
            
            # Create volumes for lookback period
            lookback_volumes = np.random.exponential(1, 15) 
            full_volumes = np.concatenate([lookback_volumes, volume_pattern])
            
            # Generate temporal features
            hours = np.arange(self.horizon + 15) % 24 / 24.0  # Normalized hour of day
            days = np.arange(self.horizon + 15) % 7 / 7.0     # Normalized day of week
            
            # Populate feature matrix
            X[i, :, 0] = price_series
            X[i, :, 1] = full_volumes
            X[i, :, 2] = hours
            X[i, :, 3] = days
            
            # Save target prices and volumes
            prices[i] = price_series[-self.horizon:]
            volumes[i] = volume_pattern
        
        # Split into train, validation, test
        train_size = int(0.7 * self.n_samples)
        val_size = int(0.1 * self.n_samples)
        
        X_train = X[:train_size]
        X_val = X[train_size:train_size+val_size]
        X_test = X[train_size+val_size:]
        
        prices_train = prices[:train_size]
        prices_val = prices[train_size:train_size+val_size]
        prices_test = prices[train_size+val_size:]
        
        volumes_train = volumes[:train_size]
        volumes_val = volumes[train_size:train_size+val_size]
        volumes_test = volumes[train_size+val_size:]
        
        return {
            'X_train': X_train, 'X_val': X_val, 'X_test': X_test,
            'prices_train': prices_train, 'prices_val': prices_val, 'prices_test': prices_test,
            'volumes_train': volumes_train, 'volumes_val': volumes_val, 'volumes_test': volumes_test
        }


class NaiveVWAPStrategy:
    """Baseline VWAP strategy using uniform allocation"""
    
    def __init__(self, horizon=12):
        self.horizon = horizon
        
    def predict(self, X):
        """Generate uniform volume predictions"""
        batch_size = X.shape[0]
        # Return uniform allocation for each sample
        return np.ones((batch_size, self.horizon)) / self.horizon


class StaticVWAPStrategy:
    """Simplified static VWAP strategy using a fixed volume curve"""
    
    def __init__(self, horizon=12):
        self.horizon = horizon
        # Initialize with a U-shaped curve which is common in markets
        t = np.arange(horizon)
        pattern = 1.5 - np.sin(np.pi * t / horizon)
        self.fixed_pattern = pattern / np.sum(pattern)
        
    def predict(self, X):
        """Generate predictions using the fixed volume curve"""
        batch_size = X.shape[0]
        # Return the same fixed pattern for each sample
        return np.tile(self.fixed_pattern, (batch_size, 1))


