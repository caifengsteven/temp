def simulate_asset_data(n_assets: int, 
                        time_periods: int = 1000, 
                        seed: int = 42) -> Tuple[np.ndarray, np.ndarray]:
    """
    Simulate asset return data with realistic covariance structure.
    
    Args:
        n_assets: Number of assets to simulate
        time_periods: Number of time periods for historical data
        seed: Random seed
        
    Returns:
        Tuple of (expected returns, covariance matrix)
    """
    np.random.seed(seed)
    
    # Create a base correlation matrix with some structure
    # Start with identity matrix
    corr = np.eye(n_assets)
    
    # Add some correlation structure (e.g., assets within sectors are more correlated)
    n_sectors = max(1, n_assets // 10)
    sector_size = n_assets // n_sectors
    
    for s in range(n_sectors):
        start_idx = s * sector_size
        end_idx = min(n_assets, (s + 1) * sector_size)
        
        # Assets within the same sector have higher correlation
        for i in range(start_idx, end_idx):
            for j in range(start_idx, end_idx):
                if i != j:
                    corr[i, j] = 0.3 + 0.2 * np.random.rand()
    
    # Add some random correlation between sectors
    for i in range(n_assets):
        for j in range(i+1, n_assets):
            if corr[i, j] == 0:  # If not already set (different sectors)
                corr[i, j] = 0.1 * np.random.rand()
                corr[j, i] = corr[i, j]
    
    # Ensure the correlation matrix is positive definite
    min_eig = np.min(np.linalg.eigvals(corr))
    if min_eig < 0:
        corr -= 1.1 * min_eig * np.eye(n_assets)
    
    # Generate volatilities for each asset (typically between 10% and 40% annually)
    vols = 0.1 + 0.3 * np.random.rand(n_assets)
    
    # Convert correlation to covariance
    cov = np.diag(vols) @ corr @ np.diag(vols)
    
    # Generate expected returns (typically between -5% and 15% annually)
    exp_returns = -0.05 + 0.2 * np.random.rand(n_assets)
    
    return exp_returns, cov


def evaluate_heuristics(n_assets: int, k_ratio: float, seed: int = 42) -> Dict:
    """
    Test different heuristics for asset selection with simulated data.
    
    Args:
        n_assets: Number of assets in the portfolio
        k_ratio: Ratio of assets to select (between 0 and 1)
        seed: Random seed
    
    Returns:
        Dictionary of results with performance metrics for each heuristic
    """
    # Round k to nearest integer
    k = max(1, int(np.ceil(k_ratio * n_assets)))
    
    # Simulate asset data
    exp_returns, cov_matrix = simulate_asset_data(n_assets, seed=seed)
    
    # Initialize optimizer
    optimizer = PortfolioOptimizer(exp_returns, cov_matrix)
    
    # Dictionary to store results
    results = {
        'n_assets': n_assets,
        'k': k,
        'heuristics': {}
    }
    
    # Test each heuristic
    heuristics = {
        'SR': optimizer.top_k_sharpe,
        'W': optimizer.top_k_weight,
        'F': optimizer.forward_selection,
        'B': optimizer.backward_selection,
        'OSCAR': optimizer.oscar
    }
    
    for name, method in heuristics.items():
        start_time = time.time()
        try:
            selected_indices, weights, sharpe = method(k)
            elapsed_time = time.time() - start_time
            
            results['heuristics'][name] = {
                'time': elapsed_time,
                'sharpe': sharpe,
                'selected_indices': selected_indices
            }
        except Exception as e:
            results['heuristics'][name] = {
                'error': str(e)
            }
    
    # Compare to optimal sharpe ratio with all assets
    opt_weights = optimizer.optimize_tangent_portfolio()
    opt_sharpe = optimizer.sharpe_ratio(opt_weights)
    results['optimal_sharpe'] = opt_sharpe
    
    # Calculate relative performance (as % of optimal)
    for name in results['heuristics']:
        if 'sharpe' in results['heuristics'][name]:
            rel_perf = results['heuristics'][name]['sharpe'] / opt_sharpe * 100
            results['heuristics'][name]['relative_performance'] = rel_perf
    
    return results


