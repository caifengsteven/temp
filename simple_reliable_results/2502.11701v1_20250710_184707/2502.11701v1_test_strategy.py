def hit_count_analysis(results_list: List[Dict], reference_heuristic: str = 'OSCAR'):
    """
    Analyze the hit count (overlap in selected assets) between heuristics.
    
    Args:
        results_list: List of results dictionaries
        reference_heuristic: Heuristic to use as reference
    
    Returns:
        DataFrame with hit count statistics
    """
    data = []
    
    for result in results_list:
        if reference_heuristic not in result['heuristics'] or 'selected_indices' not in result['heuristics'][reference_heuristic]:
            continue
            
        ref_indices = set(result['heuristics'][reference_heuristic]['selected_indices'])
        row = {
            'n_assets': result['n_assets'],
            'k': result['k']
        }
        
        for name in ['SR', 'W', 'F', 'B']:
            if name in result['heuristics'] and 'selected_indices' in result['heuristics'][name]:
                heur_indices = set(result['heuristics'][name]['selected_indices'])
                overlap = len(ref_indices.intersection(heur_indices))
                row[f'{name}_hit'] = overlap
                row[f'{name}_hit_pct'] = overlap / len(ref_indices) * 100
            else:
                row[f'{name}_hit'] = None
                row[f'{name}_hit_pct'] = None
                
        data.append(row)
    
    return pd.DataFrame(data)


def diagonal_dominance_analysis(n_assets_list: List[int], trials: int = 5):
    """
    Analyze the relationship between diagonal dominance and OSCAR performance.
    
    Args:
        n_assets_list: List of numbers of assets to test
        trials: Number of trials for each n_assets value
    
    Returns:
        DataFrame with diagonal dominance metrics and OSCAR performance
    """
    data = []
    
    for n_assets in n_assets_list:
        for seed in range(trials):
            # Simulate data
            exp_returns, cov_matrix = simulate_asset_data(n_assets, seed=seed+100)
            
            # Calculate diagonal dominance measure
            diag_mean = np.mean(np.abs(np.diag(cov_matrix)))
            offdiag_mean = np.sum(np.abs(cov_matrix)) - np.sum(np.abs(np.diag(cov_matrix)))
            offdiag_mean /= (n_assets * (n_assets - 1))
            
            diagonal_dominance = diag_mean / (diag_mean + offdiag_mean)
            
            # Test OSCAR for different k values
            k_ratios = [0.05, 0.1, 0.15, 0.2]
            avg_performance = 0
            
            for k_ratio in k_ratios:
                result = evaluate_heuristics(n_assets, k_ratio, seed=seed+100)
                if 'OSCAR' in result['heuristics'] and 'relative_performance' in result['heuristics']['OSCAR']:
                    avg_performance += result['heuristics']['OSCAR']['relative_performance']
            
            avg_performance /= len(k_ratios)
            
            data.append({
                'n_assets': n_assets,
                'seed': seed,
                'diagonal_dominance': diagonal_dominance,
                'avg_oscar_performance': avg_performance
            })
    
    return pd.DataFrame(data)


