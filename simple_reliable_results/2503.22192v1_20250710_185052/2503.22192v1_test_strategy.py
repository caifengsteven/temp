class StockDataGenerator:
    """Generate synthetic stock price data for testing"""
    
    def __init__(self, n_samples=1000, volatility=0.01, trend=0.001):
        self.n_samples = n_samples
        self.volatility = volatility
        self.trend = trend
        
    def generate_stock_data(self):
        # Start with a base price
        price = 100
        prices = [price]
        
        # Generate daily returns with some trend and volatility
        for _ in range(self.n_samples - 1):
            # Random component (volatility)
            change = np.random.normal(0, self.volatility)
            # Add trend component
            change += self.trend
            # Apply change to price
            price *= (1 + change)
            prices.append(price)
        
        # Create DataFrame with OHLCV data
        dates = pd.date_range(start='2020-01-01', periods=self.n_samples, freq='D')
        df = pd.DataFrame(index=dates)
        df['Close'] = prices
        
        # Generate Open, High, Low prices based on Close
        df['Open'] = df['Close'].shift(1) * (1 + np.random.normal(0, self.volatility/2, self.n_samples))
        df.loc[df.index[0], 'Open'] = df.loc[df.index[0], 'Close'] * 0.99
        
        df['High'] = df[['Open', 'Close']].max(axis=1) * (1 + np.abs(np.random.normal(0, self.volatility/2, self.n_samples)))
        df['Low'] = df[['Open', 'Close']].min(axis=1) * (1 - np.abs(np.random.normal(0, self.volatility/2, self.n_samples)))
        
        # Generate volume data
        df['Volume'] = np.random.randint(100000, 1000000, self.n_samples)
        
        return df

class FeatureEngineering:
    """Implement technical indicators as described in the paper"""
    
    def __init__(self, df):
        self.df = df.copy()
        
    def calculate_features(self):
        # Price-based indicators
        self._calculate_log_returns()
        self._calculate_price_range()
        self._calculate_moving_averages()
        self._calculate_roc()
        
        # Momentum indicators
        self._calculate_rsi()
        self._calculate_macd()
        self._calculate_stochastic_oscillator()
        
        # Volatility indicators
        self._calculate_atr()
        self._calculate_rolling_volatility()
        self._calculate_bollinger_bands()
        
        # Volume and price action indicators
        self._calculate_force_index()
        self._calculate_obv()
        self._calculate_cci()
        
        # Drop NaN values
        self.df.dropna(inplace=True)
        
        return self.df
    
    def _calculate_log_returns(self):
        self.df['Log_Returns'] = np.log(self.df['Close'] / self.df['Close'].shift(1))
        
    def _calculate_price_range(self):
        self.df['Price_Range'] = (self.df['High'] - self.df['Low']) / self.df['Close']
        
    def _calculate_moving_averages(self):
        for period in [5, 10, 20, 50]:
            self.df[f'SMA_{period}'] = self.df['Close'].rolling(window=period).mean()
            self.df[f'EMA_{period}'] = self.df['Close'].ewm(span=period).mean()
            
    def _calculate_roc(self):
        for period in [5, 10, 20]:
            self.df[f'ROC_{period}'] = ((self.df['Close'] - self.df['Close'].shift(period)) / 
                                       self.df['Close'].shift(period)) * 100
            
    def _calculate_rsi(self, period=14):
        delta = self.df['Close'].diff()
        gain = (delta.where(delta > 0, 0)).rolling(window=period).mean()
        loss = (-delta.where(delta < 0, 0)).rolling(window=period).mean()
        
        rs = gain / loss
        self.df['RSI'] = 100 - (100 / (1 + rs))
        
    def _calculate_macd(self, fast=12, slow=26, signal=9):
        ema_fast = self.df['Close'].ewm(span=fast).mean()
        ema_slow = self.df['Close'].ewm(span=slow).mean()
        
        self.df['MACD'] = ema_fast - ema_slow
        self.df['MACD_Signal'] = self.df['MACD'].ewm(span=signal).mean()
        self.df['MACD_Hist'] = self.df['MACD'] - self.df['MACD_Signal']
        
    def _calculate_stochastic_oscillator(self, k_period=14, d_period=3):
        low_min = self.df['Low'].rolling(window=k_period).min()
        high_max = self.df['High'].rolling(window=k_period).max()
        
        self.df['%K'] = 100 * ((self.df['Close'] - low_min) / (high_max - low_min))
        self.df['%D'] = self.df['%K'].rolling(window=d_period).mean()
        
    def _calculate_atr(self, period=14):
        high_low = self.df['High'] - self.df['Low']
        high_close = (self.df['High'] - self.df['Close'].shift(1)).abs()
        low_close = (self.df['Low'] - self.df['Close'].shift(1)).abs()
        
        ranges = pd.concat([high_low, high_close, low_close], axis=1)
        true_range = ranges.max(axis=1)
        
        self.df['ATR'] = true_range.rolling(window=period).mean()
        
    def _calculate_rolling_volatility(self, period=20):
        self.df['Volatility'] = self.df['Log_Returns'].rolling(window=period).std() * np.sqrt(period)
        
    def _calculate_bollinger_bands(self, period=20, std_dev=2):
        self.df['BB_Middle'] = self.df['Close'].rolling(window=period).mean()
        std = self.df['Close'].rolling(window=period).std()
        
        self.df['BB_Upper'] = self.df['BB_Middle'] + (std_dev * std)
        self.df['BB_Lower'] = self.df['BB_Middle'] - (std_dev * std)
        
    def _calculate_force_index(self, period=13):
        self.df['Force_Index'] = self.df['Close'].diff(1) * self.df['Volume']
        self.df['Force_Index_EMA'] = self.df['Force_Index'].ewm(span=period).mean()
        
    def _calculate_obv(self):
        self.df['OBV'] = np.nan
        self.df.loc[0, 'OBV'] = 0
        
        for i in range(1, len(self.df)):
            if self.df['Close'].iloc[i] > self.df['Close'].iloc[i-1]:
                self.df.loc[self.df.index[i], 'OBV'] = self.df['OBV'].iloc[i-1] + self.df['Volume'].iloc[i]
            elif self.df['Close'].iloc[i] < self.df['Close'].iloc[i-1]:
                self.df.loc[self.df.index[i], 'OBV'] = self.df['OBV'].iloc[i-1] - self.df['Volume'].iloc[i]
            else:
                self.df.loc[self.df.index[i], 'OBV'] = self.df['OBV'].iloc[i-1]
                
    def _calculate_cci(self, period=20):
        tp = (self.df['High'] + self.df['Low'] + self.df['Close']) / 3
        tp_ma = tp.rolling(window=period).mean()
        md = (tp - tp_ma).abs().rolling(window=period).mean()
        
        self.df['CCI'] = (tp - tp_ma) / (0.015 * md)

class VAEModel:
    """Variational Autoencoder model for feature extraction"""
    
    def __init__(self, input_dim, latent_dim=8, intermediate_dim=16, beta=0.5):
        self.input_dim = input_dim
        self.latent_dim = latent_dim
        self.intermediate_dim = intermediate_dim
        self.beta = beta
        self.model = None
        self.encoder = None
        
    def build_model(self):
        # VAE Encoder
        inputs = Input(shape=(self.input_dim,), name='encoder_input')
        x = Dense(self.intermediate_dim, activation='relu')(inputs)
        z_mean = Dense(self.latent_dim, name='z_mean')(x)
        z_log_var = Dense(self.latent_dim, name='z_log_var')(x)
        
        # Sampling function
        def sampling(args):
            z_mean, z_log_var = args
            batch = tf.shape(z_mean)[0]
            dim = tf.shape(z_mean)[1]
            epsilon = tf.random.normal(shape=(batch, dim))
            return z_mean + tf.exp(0.5 * z_log_var) * epsilon
        
        z = tf.keras.layers.Lambda(sampling, output_shape=(self.latent_dim,), name='z')([z_mean, z_log_var])
        
        # VAE Decoder
        decoder_h = Dense(self.intermediate_dim, activation='relu')
        decoder_mean = Dense(self.input_dim, activation='linear')
        
        h_decoded = decoder_h(z)
        x_decoded_mean = decoder_mean(h_decoded)
        
        # VAE Loss
        def vae_loss(x, x_decoded_mean):
            reconstruction_loss = tf.keras.losses.mse(x, x_decoded_mean) * self.input_dim
            kl_loss = -0.5 * tf.reduce_sum(1 + z_log_var - tf.square(z_mean) - tf.exp(z_log_var), axis=-1)
            return tf.reduce_mean(reconstruction_loss + self.beta * kl_loss)
        
        # Full VAE model
        vae = Model(inputs, x_decoded_mean)
        vae.compile(optimizer=Adam(learning_rate=0.001), loss=vae_loss)
        
        # Encoder model
        encoder = Model(inputs, z_mean)
        
        self.model = vae
        self.encoder = encoder
        
        return vae, encoder

class TransformerModel:
    """Transformer model for sequence modeling"""
    
    def __init__(self, input_dim, seq_length, num_heads=8, ff_dim=64, num_transformer_blocks=2):
        self.input_dim = input_dim
        self.seq_length = seq_length
        self.num_heads = num_heads
        self.ff_dim = ff_dim
        self.num_transformer_blocks = num_transformer_blocks
        self.model = None
        
    def transformer_encoder(self, inputs):
        # Normalization and Attention
        x = LayerNormalization(epsilon=1e-6)(inputs)
        x = MultiHeadAttention(
            key_dim=self.input_dim // self.num_heads, num_heads=self.num_heads, dropout=0.1
        )(x, x)
        x = Dropout(0.1)(x)
        res = Add()([x, inputs])
        
        # Feed Forward Part
        x = LayerNormalization(epsilon=1e-6)(res)
        x = Dense(self.ff_dim, activation='relu')(x)
        x = Dense(self.input_dim)(x)
        x = Dropout(0.1)(x)
        return Add()([x, res])
    
    def build_model(self):
        inputs = Input(shape=(self.seq_length, self.input_dim))
        x = inputs
        
        # Apply Transformer blocks
        for _ in range(self.num_transformer_blocks):
            x = self.transformer_encoder(x)
            
        # Global pooling and output layer
        x = tf.keras.layers.GlobalAveragePooling1D()(x)
        x = Dense(64, activation='relu')(x)
        outputs = Dense(1)(x)
        
        model = Model(inputs=inputs, outputs=outputs)
        model.compile(optimizer=Adam(learning_rate=0.001), loss='mse')
        
        self.model = model
        return model

class LSTMModel:
    """LSTM model for sequential data modeling"""
    
    def __init__(self, input_dim, seq_length, lstm_units=128):
        self.input_dim = input_dim
        self.seq_length = seq_length
        self.lstm_units = lstm_units
        self.model = None
        
    def build_model(self):
        model = Sequential()
        
        # First LSTM layer
        model.add(Bidirectional(LSTM(self.lstm_units, return_sequences=True), 
                               input_shape=(self.seq_length, self.input_dim)))
        model.add(Dropout(0.2))
        
        # Second LSTM layer
        model.add(Bidirectional(LSTM(self.lstm_units)))
        model.add(Dropout(0.2))
        
        # Output layer with batch normalization and tanh activation
        model.add(Dense(1))
        model.add(BatchNormalization())
        model.add(Activation('tanh'))
        
        model.compile(optimizer=Adam(learning_rate=0.001), loss='mse')
        
        self.model = model
        return model

class EnsembleModel:
    """Ensemble model combining VAE, Transformer and LSTM"""
    
    def __init__(self, vae_model, transformer_model, lstm_model, initial_weights=[0.3, 0.3, 0.4]):
        self.vae_model = vae_model
        self.transformer_model = transformer_model
        self.lstm_model = lstm_model
        self.weights = initial_weights
        
    def predict(self, x_vae, x_transformer, x_lstm):
        # Get predictions from each model
        vae_pred = self.vae_model.predict(x_vae)
        transformer_pred = self.transformer_model.predict(x_transformer)
        lstm_pred = self.lstm_model.predict(x_lstm)
        
        # Apply weighted average
        ensemble_pred = (
            self.weights[0] * vae_pred + 
            self.weights[1] * transformer_pred + 
            self.weights[2] * lstm_pred
        )
        
        return ensemble_pred
        
    def adjust_weights(self, x_vae, x_transformer, x_lstm, y_true):
        """Simple weight adjustment based on individual model performance"""
        # Get predictions from each model
        vae_pred = self.vae_model.predict(x_vae)
        transformer_pred = self.transformer_model.predict(x_transformer)
        lstm_pred = self.lstm_model.predict(x_lstm)
        
        # Calculate MSE for each model
        vae_mse = mean_squared_error(y_true, vae_pred)
        transformer_mse = mean_squared_error(y_true, transformer_pred)
        lstm_mse = mean_squared_error(y_true, lstm_pred)
        
        # Inverse of MSE (lower error = higher weight)
        inv_errors = [1/vae_mse, 1/transformer_mse, 1/lstm_mse]
        sum_inv_errors = sum(inv_errors)
        
        # Update weights based on inverse error
        self.weights = [e/sum_inv_errors for e in inv_errors]
        
        return self.weights

class ModelEvaluator:
    """Evaluate model performance using various metrics"""
    
    @staticmethod
    def evaluate_model(y_true, y_pred):
        # Calculate RMSE
        rmse = math.sqrt(mean_squared_error(y_true, y_pred))
        
        # Calculate MAPE
        mape = mean_absolute_percentage_error(y_true, y_pred) * 100
        
        # Calculate R² Score
        r2 = r2_score(y_true, y_pred)
        
        # Calculate Directional Accuracy
        direction_true = np.sign(np.diff(np.append([y_true[0]], y_true)))
        direction_pred = np.sign(np.diff(np.append([y_true[0]], y_pred)))
        directional_accuracy = np.mean(direction_true == direction_pred)
        
        return {
            'RMSE': rmse,
            'MAPE': mape,
            'R2_Score': r2,
            'Directional_Accuracy': directional_accuracy
        }
    
    @staticmethod
    def plot_results(y_true, y_pred, title='Actual vs Predicted Values'):
        plt.figure(figsize=(12, 6))
        plt.plot(y_true, label='Actual')
        plt.plot(y_pred, label='Predicted')
        plt.title(title)
        plt.legend()
        plt.show()
        
        # Scatter plot
        plt.figure(figsize=(10, 6))
        plt.scatter(y_true, y_pred)
        plt.plot([min(y_true), max(y_true)], [min(y_true), max(y_true)], 'r--')
        plt.xlabel('Actual')
        plt.ylabel('Predicted')
        plt.title('Prediction Scatter Plot')
        plt.show()

def prepare_sequences(data, seq_length):
    """Prepare sequences for model training"""
    X, y = [], []
    
    for i in range(len(data) - seq_length):
        X.append(data[i:i+seq_length])
        y.append(data[i+seq_length, 0])  # Target is the next close price
        
    return np.array(X), np.array(y)

