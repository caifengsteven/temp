def expectation(x):
    return np.mean(x)

def expected_shortfall(x, alpha=0.9):
    """Expected Shortfall at level alpha"""
    sorted_x = np.sort(x)
    var = np.percentile(x, 100 * alpha)
    es_samples = sorted_x[sorted_x >= var]
    return np.mean(es_samples)

def inter_expected_shortfall_range(x, p=0.75):
    """Inter-Expected Shortfall Range at level p"""
    return (1/(1-p)) * (np.mean(np.sort(x)[int(p*len(x)):]) - np.mean(np.sort(x)[:int((1-p)*len(x))]))


