class DeepBSDEMethod(DeepBSDESolver):
    """Implementation of the original deep BSDE method"""
    
    def __init__(self, d, T, N, x0, batch_size=2**12):
        super().__init__(d, T, N, x0, batch_size)
        # Initialize y0 as a trainable parameter
        self.y0 = tf.Variable(0.0, dtype=tf.float32)
        
        # Compile optimizer
        self.optimizer = Adam(learning_rate=0.001)
    
    def drift(self, t, x, y, z):
        """Define the drift function b(t, x, y, z)"""
        # Example: controlled Brownian motion with drift -z/r
        r = 1.0
        return -z / r
    
    def diffusion(self, t, x):
        """Define the diffusion function σ(t, x)"""
        # Example: constant diffusion
        sigma = 0.25
        return sigma * np.eye(self.d, dtype=np.float32)
    
    def driver(self, t, x, y, z):
        """Define the driver function f(t, x, y, z)"""
        # Example: running cost of the control problem
        r = 1.0
        return 0.5 * r * np.sum(np.square(z), axis=1)
    
    def terminal_condition(self, x):
        """Define the terminal condition g(x)"""
        # Example: terminal cost
        return -np.abs(x[:, 0] - x[:, 1])
    
    def simulate_path(self, y0, dW, training=False):
        """Simulate forward and backward SDEs"""
        batch_size = dW.shape[0]
        X = np.zeros((batch_size, self.N+1, self.d), dtype=np.float32)
        Y = np.zeros((batch_size, self.N+1, 1), dtype=np.float32)
        Z = np.zeros((batch_size, self.N, self.d), dtype=np.float32)
        
        # Initialize
        X[:, 0, :] = self.x0
        Y[:, 0, 0] = y0
        
        # Forward simulation
        for n in range(self.N):
            t_n = n * self.dt
            
            # Get Z from neural network
            if training:
                with tf.GradientTape() as tape:
                    Z[:, n, :] = self.z_nets[n](tf.convert_to_tensor(X[:, n, :], dtype=tf.float32))
            else:
                Z[:, n, :] = self.z_nets[n](tf.convert_to_tensor(X[:, n, :], dtype=tf.float32))
            
            # Forward step for X
            b = self.drift(t_n, X[:, n, :], Y[:, n, 0], Z[:, n, :])
            sigma = self.diffusion(t_n, X[:, n, :])
            X[:, n+1, :] = X[:, n, :] + b * self.dt + np.matmul(sigma, dW[:, n, :, np.newaxis])[:, :, 0]
            
            # Forward step for Y
            f = self.driver(t_n, X[:, n, :], Y[:, n, 0], Z[:, n, :])
            Y[:, n+1, 0] = Y[:, n, 0] - f * self.dt + np.sum(Z[:, n, :] * dW[:, n, :], axis=1)
        
        # Terminal condition
        g = self.terminal_condition(X[:, -1, :])
        
        return X, Y, Z, g
    
    def loss_fn(self, y0, dW):
        """Compute mean squared error at terminal time"""
        _, Y, _, g = self.simulate_path(y0, dW, training=True)
        return tf.reduce_mean(tf.square(Y[:, -1, 0] - g))
    
    @tf.function
    def train_step(self, dW):
        """Single training step with gradient computation"""
        with tf.GradientTape() as tape:
            loss = self.loss_fn(self.y0, dW)
        
        # Get gradients and trainable variables
        variables = [self.y0] + [var for net in self.z_nets for var in net.trainable_variables]
        gradients = tape.gradient(loss, variables)
        
        # Apply gradients
        self.optimizer.apply_gradients(zip(gradients, variables))
        
        return loss
    
