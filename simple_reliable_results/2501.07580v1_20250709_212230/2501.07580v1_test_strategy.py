def apply_returns(df, cols=None):
    if cols is None:
        cols = [col for col in df.columns if col not in ['date', 'day_of_week', 'day_of_month', 'month']]
    
    for col in cols:
        if 'sin' not in col and df[col].dtype != 'object':
            df[f'{col}_return'] = df[col].pct_change()
    
    return df

def apply_log_returns(df, cols=None):
    if cols is None:
        cols = [col for col in df.columns if col not in ['date', 'day_of_week', 'day_of_month', 'month']]
    
    for col in cols:
        if 'sin' not in col and df[col].dtype != 'object' and (df[col] > 0).all():
            df[f'{col}_log_return'] = np.log(df[col] / df[col].shift(1))
        elif 'sin' not in col and df[col].dtype != 'object':
            # Use cubic root for values that can be negative as mentioned in the paper
            df[f'{col}_cubic_root'] = np.cbrt(df[col])
    
    return df

def apply_ema_ratio(df, cols=None):
    if cols is None:
        # Only apply to price-like columns as mentioned in the paper
        cols = ['open', 'high', 'low', 'close', 'typical']
    
    for col in cols:
        # Calculate 14-period EMA
        ema_col = f'{col}_ema_14'
        if ema_col not in df.columns:
            df[ema_col] = df[col].ewm(span=14, adjust=False).mean()
        
        # Calculate ratio
        df[f'{col}_ema_ratio'] = df[col] / df[ema_col]
    
    return df

def apply_ema_diff_ratio(df, cols=None):
    if cols is None:
        # Only apply to price-like columns
        cols = ['open', 'high', 'low', 'close', 'typical']
    
    for col in cols:
        # Calculate 14-period EMA
        ema_col = f'{col}_ema_14'
        if ema_col not in df.columns:
            df[ema_col] = df[col].ewm(span=14, adjust=False).mean()
        
        # Calculate difference
        diff = df[col] - df[col].shift(1)
        ema_diff = df[ema_col] - df[ema_col].shift(1)
        
        # Calculate ratio of differences
        df[f'{col}_ema_diff_ratio'] = diff / ema_diff
    
    return df

def standardize_features(df, cols=None):
    if cols is None:
        # Exclude date and categorical columns
        cols = [col for col in df.columns if col not in ['date', 'day_of_week', 'day_of_month', 'month']]
    
    for col in cols:
        if df[col].dtype != 'object' and not pd.isna(df[col]).all():
            mean = df[col].mean()
            std = df[col].std()
            if std > 0:
                df[f'{col}_std'] = (df[col] - mean) / std
    
    return df

# Custom Directional Accuracy Function
def directional_accuracy(y_true, y_pred):
    # Convert to numpy arrays if they're not already
    y_true = np.array(y_true)
    y_pred = np.array(y_pred)
    
    # Calculate the directions (up or down)
    true_dir = np.sign(np.diff(y_true))
    pred_dir = np.sign(np.diff(y_pred))
    
    # Calculate accuracy
    correct_dir = np.sum(true_dir == pred_dir)
    total_dir = len(true_dir)
    
    return correct_dir / total_dir if total_dir > 0 else 0

