# Function to train and evaluate LightGBM models
def train_and_evaluate_lightgbm(data, transformation_method, target_suffix):
    # Start timer
    start_time = time.time()
    
    # Define target variable based on transformation method
    if transformation_method == 'returns':
        target_col = f'close{target_suffix}'
    elif transformation_method == 'log_returns':
        target_col = f'close{target_suffix}'
    elif transformation_method == 'ema_ratio':
        target_col = f'close{target_suffix}'
    elif transformation_method == 'ema_diff_ratio':
        target_col = f'close{target_suffix}'
    else:
        target_col = f'close{target_suffix}'
    
    # Prepare data
    df = data.copy()
    df = df.dropna()
    
    # Split into train and test sets (80% train, 20% test)
    train_size = int(len(df) * 0.8)
    train_df = df.iloc[:train_size]
    test_df = df.iloc[train_size:]
    
    # Extract features and target
    feature_cols = [col for col in df.columns if col != 'date' and col != target_col and not pd.isna(df[col]).any()]
    
    X_train = train_df[feature_cols]
    y_train = train_df[target_col]
    X_test = test_df[feature_cols]
    y_test = test_df[target_col]
    
    # Define LightGBM parameters
    params = {
        'objective': 'regression',
        'metric': 'mse',
        'boosting_type': 'gbdt',
        'num_leaves': 31,
        'learning_rate': 0.05,
        'feature_fraction': 0.9,
        'bagging_fraction': 0.8,
        'bagging_freq': 5,
        'verbose': -1
    }
    
    # Create dataset
    train_data = lgb.Dataset(X_train, label=y_train)
    
    # Train model with 3-fold time series cross-validation
    tscv = TimeSeriesSplit(n_splits=3)
    
    # Train final model
    model = lgb.train(
        params,
        train_data,
        num_boost_round=1000,
        verbose_eval=False
    )
    
    # Make predictions
    y_pred = model.predict(X_test)
    
    # Calculate metrics
    mae = mean_absolute_error(y_test, y_pred)
    rmse = np.sqrt(mean_squared_error(y_test, y_pred))
    da = directional_accuracy(y_test, y_pred)
    
    # Get training time
    training_time = time.time() - start_time
    
    # Get feature importance
    feature_importance = model.feature_importance(importance_type='gain')
    feature_names = model.feature_name()
    importance_df = pd.DataFrame({'Feature': feature_names, 'Importance': feature_importance})
    importance_df = importance_df.sort_values('Importance', ascending=False).head(10)
    
    return {
        'transformation_method': transformation_method,
        'mae': mae,
        'rmse': rmse,
        'da': da,
        'training_time': training_time,
        'feature_importance': importance_df,
        'y_test': y_test,
        'y_pred': y_pred
    }

# Random Walk benchmark
def random_walk_benchmark(df):
    # Use previous day's close as prediction
    df['rw_pred'] = df['close'].shift(1)
    
    # Calculate metrics for test set
    test_size = int(len(df) * 0.2)
    test_df = df.iloc[-test_size:]
    
    mae = mean_absolute_error(test_df['close'], test_df['rw_pred'])
    rmse = np.sqrt(mean_squared_error(test_df['close'], test_df['rw_pred']))
    da = 0.5  # By definition, random walk has 50% directional accuracy
    
    return {
        'transformation_method': 'Random Walk',
        'mae': mae,
        'rmse': rmse,
        'da': da,
        'training_time': 0,
        'y_test': test_df['close'],
        'y_pred': test_df['rw_pred']
    }

