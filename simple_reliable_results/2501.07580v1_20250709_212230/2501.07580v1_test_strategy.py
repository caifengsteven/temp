# Function to generate synthetic stock price data
def generate_synthetic_stock_data(days=2000, seed=42):
    np.random.seed(seed)
    
    # Initial price
    initial_price = 100.0
    
    # Generate random daily returns with some trend and seasonality
    daily_returns = np.random.normal(0.0005, 0.015, days)  # Mean positive return, realistic volatility
    
    # Add trend component
    trend = np.linspace(0, 0.001, days)
    daily_returns += trend
    
    # Add cyclical component (weekly pattern)
    weekly_cycle = 0.002 * np.sin(np.linspace(0, days/5 * 2 * np.pi, days))
    daily_returns += weekly_cycle
    
    # Calculate price series
    prices = [initial_price]
    for ret in daily_returns:
        prices.append(prices[-1] * (1 + ret))
    prices = np.array(prices[:-1])
    
    # Generate OHLC data
    dates = pd.date_range(start='2018-01-01', periods=days)
    high = prices * (1 + np.random.uniform(0.001, 0.02, days))
    low = prices * (1 - np.random.uniform(0.001, 0.02, days))
    open_prices = prices * (1 + np.random.normal(0, 0.005, days))
    close_prices = prices
    
    # Generate volume data with some correlation to price changes
    volume = np.abs(np.diff(np.append(open_prices[0], close_prices))) * 1000000 + np.random.normal(1000000, 500000, days)
    volume = np.maximum(volume, 100000)  # Ensure positive volume
    
    # Create DataFrame
    df = pd.DataFrame({
        'date': dates,
        'open': open_prices,
        'high': high,
        'low': low,
        'close': close_prices,
        'volume': volume
    })
    
    return df

# Feature Engineering Functions
def calculate_typical_price(df):
    df['typical'] = (df['high'] + df['low'] + df['close']) / 3
    return df

def add_lag_features(df):
    for col in ['open', 'close', 'typical']:
        for lag in [1, 5, 30]:
            df[f'{col}_lag_{lag}'] = df[col].shift(lag)
    return df

def add_rolling_features(df):
    for window in [5, 14, 30]:
        df[f'close_sma_{window}'] = df['close'].rolling(window=window).mean()
        df[f'close_std_{window}'] = df['close'].rolling(window=window).std()
        df[f'volume_sma_{window}'] = df['volume'].rolling(window=window).mean()
    return df

def add_technical_indicators(df):
    # RSI (Relative Strength Index)
    delta = df['close'].diff()
    gain = (delta.where(delta > 0, 0)).rolling(window=14).mean()
    loss = (-delta.where(delta < 0, 0)).rolling(window=14).mean()
    rs = gain / loss
    df['rsi_14'] = 100 - (100 / (1 + rs))
    
    # EMA (Exponential Moving Average)
    df['ema_14'] = df['close'].ewm(span=14, adjust=False).mean()
    
    # MACD (Moving Average Convergence Divergence)
    df['ema_12'] = df['close'].ewm(span=12, adjust=False).mean()
    df['ema_26'] = df['close'].ewm(span=26, adjust=False).mean()
    df['macd'] = df['ema_12'] - df['ema_26']
    df['macd_signal'] = df['macd'].ewm(span=9, adjust=False).mean()
    df['macd_hist'] = df['macd'] - df['macd_signal']
    
    # Rate of Change (ROC)
    df['roc_14'] = df['close'].pct_change(periods=14) * 100
    
    # Average True Range (ATR)
    tr1 = df['high'] - df['low']
    tr2 = abs(df['high'] - df['close'].shift(1))
    tr3 = abs(df['low'] - df['close'].shift(1))
    df['tr'] = pd.DataFrame([tr1, tr2, tr3]).max()
    df['atr_14'] = df['tr'].rolling(14).mean()
    
    # Stochastic Oscillator
    df['lowest_14'] = df['low'].rolling(14).min()
    df['highest_14'] = df['high'].rolling(14).max()
    df['stoch_k'] = 100 * ((df['close'] - df['lowest_14']) / (df['highest_14'] - df['lowest_14']))
    df['stoch_d'] = df['stoch_k'].rolling(3).mean()
    
    # Psychological Line (PSY)
    df['price_up'] = np.where(df['close'] > df['close'].shift(1), 1, 0)
    df['psy_14'] = df['price_up'].rolling(14).sum() / 14 * 100
    
    return df

def add_cross_features(df):
    # Price gap features
    df['gap_overnight'] = df['open'] - df['close'].shift(1)
    df['gap_ratio'] = df['gap_overnight'] / df['close'].shift(1)
    
    # ATR ratio
    df['atr_open_ratio'] = df['atr_14'] / df['open']
    
    # Price differences
    df['open_close_diff'] = df['open'] - df['close'].shift(1)
    df['high_low_ratio'] = df['high'] / df['low']
    
    # EMA-based features
    df['close_ema_ratio'] = df['close'] / df['ema_14']
    df['open_ema_ratio'] = df['open'] / df['ema_14']
    
    # Slope differences (simple version for testing)
    df['price_slope_5'] = (df['close'] - df['close'].shift(5)) / 5
    df['rsi_slope_5'] = (df['rsi_14'] - df['rsi_14'].shift(5)) / 5
    df['slope_diff_price_rsi'] = df['price_slope_5'] - df['rsi_slope_5']
    
    df['volume_slope_5'] = (df['volume'] - df['volume'].shift(5)) / 5
    df['slope_diff_price_volume'] = df['price_slope_5'] - df['volume_slope_5']
    
    return df

def add_cyclical_features(df):
    # Extract datetime components
    df['day_of_week'] = df['date'].dt.dayofweek
    df['day_of_month'] = df['date'].dt.day
    df['month'] = df['date'].dt.month
    
    # Convert to cyclical features using sine
    df['day_of_week_sin'] = np.sin(2 * np.pi * df['day_of_week'] / 7)
    df['day_of_month_sin'] = np.sin(2 * np.pi * df['day_of_month'] / 31)
    df['month_sin'] = np.sin(2 * np.pi * df['month'] / 12)
    
    return df

