class FinancialDataset(Dataset):
    """PyTorch dataset for financial data"""
    
    def __init__(self, features, labels, normalize=True):
        self.features = torch.tensor(features, dtype=torch.float32)
        self.labels = torch.tensor(labels, dtype=torch.long)
        self.normalize = normalize
        
        if self.normalize:
            self._normalize_features()
            
    def _normalize_features(self):
        """Normalize features using the approach described in the paper"""
        batch_size, seq_len, feat_dim = self.features.shape
        
        for b in range(batch_size):
            for f in range(feat_dim):
                # Calculate mean and std for each feature
                mean = torch.mean(self.features[b, :, f])
                std = torch.std(self.features[b, :, f])
                
                # Avoid division by zero
                if std > 0:
                    self.features[b, :, f] = (self.features[b, :, f] - mean) / std
                
    def __len__(self):
        return len(self.labels)
    
    def __getitem__(self, idx):
        return self.features[idx], self.labels[idx]

