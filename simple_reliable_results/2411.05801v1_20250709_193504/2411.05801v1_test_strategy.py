import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from scipy import stats
import random

class PersonalitySimulator:
    """Simulate personalities based on the Five-Factor Model and their investment behaviors"""
    
    # Personality trait levels
    TRAIT_LEVELS = ["Low", "Medium", "High"]
    
    # Five-Factor Model traits
    TRAITS = ["Openness", "Conscientiousness", "Extraversion", "Agreeableness", "Neuroticism"]
    
    # Companies available for investment
    COMPANIES = {
        "Diamond": {"roi": 0.05, "risk": 0.10, "description": "Conservative investment"},
        "Platinum": {"roi": 0.35, "risk": 0.30, "description": "Balanced investment"},
        "Emerald": {"roi": 0.89, "risk": 0.50, "description": "High-risk investment"},
        "Ruby": {"roi": 0.25, "risk": 0.30, "description": "Eco-conscious company"},
        "Sapphire": {"roi": 0.80, "risk": 0.60, "description": "Cutting edge technology company"}
    }
    
    # Research methods
    RESEARCH_METHODS = ["research independently", "talk to expert"]
    
    def __init__(self, seed=None):
        """Initialize the simulator with optional random seed"""
        if seed is not None:
            np.random.seed(seed)
            random.seed(seed)
        
        # Generate all possible personality combinations
        self.all_personas = self._generate_all_personas()
    
    def _generate_all_personas(self):
        """Generate all possible combinations of personality traits (3^5 = 243 personas)"""
        personas = []
        for o in self.TRAIT_LEVELS:
            for c in self.TRAIT_LEVELS:
                for e in self.TRAIT_LEVELS:
                    for a in self.TRAIT_LEVELS:
                        for n in self.TRAIT_LEVELS:
                            persona = {
                                "Openness": o,
                                "Conscientiousness": c,
                                "Extraversion": e,
                                "Agreeableness": a,
                                "Neuroticism": n
                            }
                            personas.append(persona)
        return personas
    
    def _trait_to_numeric(self, trait_value):
        """Convert trait value to numeric (Low=0, Medium=1, High=2)"""
        return self.TRAIT_LEVELS.index(trait_value)
    
    def _add_trait_scores(self, personas):
        """Add numeric trait scores to personas"""
        for persona in personas:
            for trait in self.TRAITS:
                persona[f"{trait}_score"] = self._trait_to_numeric(persona[trait])
        return personas
    
    def run_investment_simulation(self, num_personas=None):
        """
        Run investment simulation for a number of personas
        
        Parameters:
        - num_personas: Number of personas to simulate (if None, use all 243 personas)
        
        Returns:
        - DataFrame with simulation results
        """
        # Select personas for simulation
        if num_personas is None:
            personas = self.all_personas.copy()
        else:
            personas = random.sample(self.all_personas, min(num_personas, len(self.all_personas)))
        
        # Add numeric trait scores
        personas = self._add_trait_scores(personas)
        
        # Run simulation for each persona
        results = []
        for persona in personas:
            # Simulate investment behavior
            result = self._simulate_investment_behavior(persona)
            # Combine persona traits with simulation results
            combined_result = {**persona, **result}
            results.append(combined_result)
        
        return pd.DataFrame(results)
    
    def _simulate_investment_behavior(self, persona):
        """
        Simulate investment behavior for a single persona
        
        This simulates:
        1. Learning style preference
        2. Impulsivity (research time)
        3. Risk appetite
        4. Interest in environmental/tech products
        5. Final investment decision
        """
        # Initialize research counts and methods
        research_counts = {company: 0 for company in self.COMPANIES}
        research_methods = {method: 0 for method in self.RESEARCH_METHODS}
        
        # Simulate learning style preference based on personality traits
        # Higher openness -> more independent research
        # Higher extraversion -> more expert consultation
        independent_research_prob = (
            0.3 + 
            0.2 * persona["Openness_score"] + 
            0.1 * persona["Conscientiousness_score"] - 
            0.2 * persona["Extraversion_score"] - 
            0.1 * persona["Agreeableness_score"] - 
            0.1 * persona["Neuroticism_score"]
        )
        independent_research_prob = max(0.1, min(0.9, independent_research_prob))
        
        # Simulate impulsivity (how much research before making a decision)
        # Higher conscientiousness -> more research
        # Higher neuroticism -> more research
        # Higher extraversion -> less research
        max_research_actions = 25  # Maximum possible research actions (5 companies × 5 times)
        
        # Base research amount adjusted by personality
        research_tendency = (
            10 + 
            persona["Conscientiousness_score"] * 3 - 
            persona["Extraversion_score"] * 2 + 
            persona["Neuroticism_score"] * 2 - 
            persona["Openness_score"] * 1
        )
        # Add some randomness
        research_amount = max(1, min(max_research_actions, 
                                    int(np.random.normal(research_tendency, 3))))
        
        # Simulate research process
        for _ in range(research_amount):
            # Choose research method
            if random.random() < independent_research_prob:
                research_method = "research independently"
            else:
                research_method = "talk to expert"
            research_methods[research_method] += 1
            
            # Choose company to research
            # Higher openness -> more likely to research eco/tech companies
            # Higher agreeableness -> more likely to research eco companies
            company_weights = {
                "Diamond": 1.0,
                "Platinum": 1.0,
                "Emerald": 1.0,
                "Ruby": 1.0 + 0.5 * persona["Openness_score"] + 0.7 * persona["Agreeableness_score"],
                "Sapphire": 1.0 + 0.7 * persona["Openness_score"] - 0.2 * persona["Neuroticism_score"]
            }
            
            # Convert to probability distribution
            total_weight = sum(company_weights.values())
            company_probs = {company: weight/total_weight for company, weight in company_weights.items()}
            
            # Choose company based on weights
            companies = list(company_probs.keys())
            probabilities = list(company_probs.values())
            
            # Don't research companies that have been researched 5 times already
            valid_companies = [company for company in companies if research_counts[company] < 5]
            if not valid_companies:
                break  # All companies researched 5 times
                
            # Adjust probabilities for valid companies
            valid_probs = [company_probs[company] for company in valid_companies]
            valid_probs = [p/sum(valid_probs) for p in valid_probs]
            
            company = np.random.choice(valid_companies, p=valid_probs)
            research_counts[company] += 1
        
        # Make investment decision based on personality and research
        # Risk appetite affected by traits:
        # Higher openness -> higher risk tolerance
        # Higher conscientiousness -> lower risk tolerance
        # Higher extraversion -> higher risk tolerance
        # Higher agreeableness -> lower risk tolerance
        # Higher neuroticism -> lower risk tolerance
        risk_appetite = (
            0.4 +  # baseline
            0.1 * persona["Openness_score"] - 
            0.1 * persona["Conscientiousness_score"] + 
            0.1 * persona["Extraversion_score"] - 
            0.1 * persona["Agreeableness_score"] - 
            0.15 * persona["Neuroticism_score"]
        )
        risk_appetite = max(0.1, min(0.9, risk_appetite))
        
        # Calculate "utility" of each company based on research, risk appetite, and personality
        company_utility = {}
        for company, info in self.COMPANIES.items():
            # Base utility from ROI and risk
            risk_adjusted_roi = info["roi"] - (info["risk"] * (1 - risk_appetite))
            
            # Knowledge bonus from research
            knowledge_factor = min(1.0, research_counts[company] / 5.0) * 0.5
            
            # Special bonuses for eco/tech companies based on personality
            special_bonus = 0
            if company == "Ruby":  # Eco-conscious
                special_bonus = 0.1 * persona["Openness_score"] + 0.2 * persona["Agreeableness_score"]
            elif company == "Sapphire":  # Tech
                special_bonus = 0.2 * persona["Openness_score"] - 0.1 * persona["Neuroticism_score"]
            
            company_utility[company] = risk_adjusted_roi + knowledge_factor + special_bonus
        
        # Choose company with highest utility
        investment_decision = max(company_utility, key=company_utility.get)
        
        # Return simulation results
        return {
            "research_total": sum(research_counts.values()),
            "research_independent": research_methods["research independently"],
            "research_expert": research_methods["talk to expert"],
            "research_ratio": research_methods["research independently"] / max(1, sum(research_methods.values())),
            "research_diamond": research_counts["Diamond"],
            "research_platinum": research_counts["Platinum"],
            "research_emerald": research_counts["Emerald"],
            "research_ruby": research_counts["Ruby"],
            "research_sapphire": research_counts["Sapphire"],
            "investment_decision": investment_decision,
            "investment_roi": self.COMPANIES[investment_decision]["roi"],
            "investment_risk": self.COMPANIES[investment_decision]["risk"],
            "eco_interest": research_counts["Ruby"] / max(1, sum(research_counts.values())),
            "tech_interest": research_counts["Sapphire"] / max(1, sum(research_counts.values()))
        }
    
    def analyze_results(self, results):
        """
        Analyze simulation results to find correlations between personality traits and behaviors
        
        Parameters:
        - results: DataFrame with simulation results
        
        Returns:
        - DataFrame with correlation results
        """
        # Map trait levels to numeric values for correlation analysis
        for trait in self.TRAITS:
            results[trait] = results[trait].map({"Low": 0, "Medium": 1, "High": 2})
        
        # Behaviors to analyze
        behaviors = {
            "Learning Style (Independent=+)": "research_ratio",
            "Impulsivity (Less Research=+)": lambda df: -df["research_total"],
            "Risk Appetite": lambda df: df["investment_risk"],
            "Interest in Environmental Products": "eco_interest",
            "Investment in Environmental Products": lambda df: (df["investment_decision"] == "Ruby").astype(int)
        }
        
        # Calculate correlations
        correlation_results = []
        for behavior_name, behavior_value in behaviors.items():
            correlations = {}
            
            # Extract behavior values
            if callable(behavior_value):
                behavior_series = behavior_value(results)
            else:
                behavior_series = results[behavior_value]
            
            # Calculate correlation for each trait
            for trait in self.TRAITS:
                corr, p_value = stats.pearsonr(results[trait], behavior_series)
                
                # Add result
                correlations[trait] = corr
                correlations[f"{trait}_p"] = p_value
            
            # Add behavior name
            correlations["Behavior"] = behavior_name
            correlation_results.append(correlations)
        
        return pd.DataFrame(correlation_results)
    
    def plot_correlations(self, correlation_df):
        """Plot correlation heatmap between traits and behaviors"""
        # Prepare data for heatmap
        behaviors = correlation_df["Behavior"].tolist()
        
        # Extract correlation values
        heatmap_data = []
        for _, row in correlation_df.iterrows():
            trait_correlations = [row[trait] for trait in self.TRAITS]
            heatmap_data.append(trait_correlations)
        
        # Create heatmap
        plt.figure(figsize=(10, 8))
        plt.imshow(heatmap_data, cmap="coolwarm", vmin=-1, vmax=1)
        
        # Add labels
        plt.xticks(range(len(self.TRAITS)), self.TRAITS, rotation=45)
        plt.yticks(range(len(behaviors)), behaviors)
        
        # Add colorbar
        plt.colorbar(label="Correlation Coefficient")
        
        # Add title
        plt.title("Correlation between Personality Traits and Investment Behaviors")
        
        # Add values to cells
        for i in range(len(behaviors)):
            for j in range(len(self.TRAITS)):
                plt.text(j, i, f"{heatmap_data[i][j]:.2f}", 
                        ha="center", va="center", 
                        color="white" if abs(heatmap_data[i][j]) > 0.5 else "black")
        
        plt.tight_layout()
        return plt.gcf()


