class LimitOrderBook:
    """Simulated Limit Order Book (LOB) with multiple price levels"""
    
    def __init__(self, initial_mid_price=100000, tick_size=10, depth=5, seed=None):
        """Initialize LOB with a given mid price and depth"""
        if seed is not None:
            np.random.seed(seed)
            random.seed(seed)
            
        self.tick_size = tick_size
        self.depth = depth
        self.mid_price = initial_mid_price
        self.best_bid = initial_mid_price - tick_size
        self.best_ask = initial_mid_price + tick_size
        
        # Initialize order volumes at each level
        self.bid_volumes = np.random.poisson(100, depth)
        self.ask_volumes = np.random.poisson(100, depth)
        
        # Initialize price levels
        self.bid_prices = np.array([self.best_bid - i * tick_size for i in range(depth)])
        self.ask_prices = np.array([self.best_ask + i * tick_size for i in range(depth)])
        
        # History tracking
        self.price_history = []
        self.record_state()
    
    def record_state(self):
        """Record current state of the order book"""
        self.price_history.append({
            'mid_price': self.mid_price,
            'best_bid': self.best_bid,
            'best_ask': self.best_ask,
            'bid_volumes': self.bid_volumes.copy(),
            'ask_volumes': self.ask_volumes.copy(),
            'spread': self.best_ask - self.best_bid
        })
    
    def update(self, drift=0, volatility=0.0001):
        """Update LOB with a drift and volatility component to simulate market movements"""
        # Simple price movement model
        price_change = np.random.normal(drift, volatility * self.mid_price)
        self.mid_price += price_change
        
        # Update best bid and ask
        self.best_bid = self.mid_price - self.tick_size
        self.best_ask = self.mid_price + self.tick_size
        
        # Update price levels
        self.bid_prices = np.array([self.best_bid - i * self.tick_size for i in range(self.depth)])
        self.ask_prices = np.array([self.best_ask + i * self.tick_size for i in range(self.depth)])
        
        # Regenerate volumes with some persistence (80% of previous value + new random component)
        self.bid_volumes = 0.8 * self.bid_volumes + 0.2 * np.random.poisson(100, self.depth)
        self.ask_volumes = 0.8 * self.ask_volumes + 0.2 * np.random.poisson(100, self.depth)
        
        self.record_state()
        
    def get_total_depth(self, side='bid', levels=None):
        """Calculate total depth up to specified levels"""
        if levels is None:
            levels = self.depth
            
        if side.lower() == 'bid':
            return np.sum(self.bid_volumes[:levels])
        else:
            return np.sum(self.ask_volumes[:levels])
    
    def get_volume_imbalance(self, levels=None):
        """Calculate volume imbalance at specified levels"""
        if levels is None:
            levels = self.depth
            
        bid_depth = self.get_total_depth('bid', levels)
        ask_depth = self.get_total_depth('ask', levels)
        
        if bid_depth + ask_depth == 0:
            return 0.5
        
        return bid_depth / (bid_depth + ask_depth)
    
    def execute_market_order(self, quantity, side='buy'):
        """Execute a market order and return the average execution price and depth consumed"""
        executed_quantity = 0
        total_cost = 0
        depth_consumed = 0
        
        if side.lower() == 'buy':
            # Execute against ask side
            for i in range(self.depth):
                available = self.ask_volumes[i]
                if executed_quantity + available >= quantity:
                    # Partial execution at this level
                    needed = quantity - executed_quantity
                    total_cost += needed * self.ask_prices[i]
                    self.ask_volumes[i] -= needed
                    executed_quantity = quantity
                    depth_consumed += 1
                    break
                else:
                    # Full execution at this level, move to next
                    total_cost += available * self.ask_prices[i]
                    executed_quantity += available
                    self.ask_volumes[i] = 0
                    depth_consumed += 1
                    
                    if i < self.depth - 1:
                        # Refill with some random volume
                        self.ask_volumes[i] = np.random.poisson(50)
        else:
            # Execute against bid side
            for i in range(self.depth):
                available = self.bid_volumes[i]
                if executed_quantity + available >= quantity:
                    # Partial execution at this level
                    needed = quantity - executed_quantity
                    total_cost += needed * self.bid_prices[i]
                    self.bid_volumes[i] -= needed
                    executed_quantity = quantity
                    depth_consumed += 1
                    break
                else:
                    # Full execution at this level, move to next
                    total_cost += available * self.bid_prices[i]
                    executed_quantity += available
                    self.bid_volumes[i] = 0
                    depth_consumed += 1
                    
                    if i < self.depth - 1:
                        # Refill with some random volume
                        self.bid_volumes[i] = np.random.poisson(50)
        
        # If we couldn't execute everything, adjust
        if executed_quantity < quantity:
            print(f"Warning: Could only execute {executed_quantity} out of {quantity} shares")
        
        avg_price = total_cost / executed_quantity if executed_quantity > 0 else 0
        
        # Record the state after execution
        self.record_state()
        
        return avg_price, depth_consumed, executed_quantity


class DQNAgent:
    """Simplified DQN Agent for optimal execution"""
    
    def __init__(self, state_size, action_size, learning_rate=0.001, discount_factor=0.9999):
        self.state_size = state_size
        self.action_size = action_size
        self.learning_rate = learning_rate
        self.discount_factor = discount_factor
        self.epsilon = 1.0  # Exploration rate
        self.epsilon_min = 0.02
        self.epsilon_decay = 0.995
        self.memory = deque(maxlen=2000)
        
        # Simple Q-network representation (for simulation only)
        # In practice, this would be a neural network
        self.q_table = np.zeros((10, 10, action_size))  # Simplified state space discretization
    
    def discretize_state(self, state):
        """Convert continuous state to discrete indices for q-table"""
        holdings_idx = min(int(state[0] * 10), 9)
        time_idx = min(int(state[1] * 10), 9)
        return holdings_idx, time_idx
    
    def act(self, state):
        """Choose an action based on current state"""
        if np.random.rand() <= self.epsilon:
            return random.randrange(self.action_size)
        
        state_idx = self.discretize_state(state)
        return np.argmax(self.q_table[state_idx])
    
    def train(self, state, action, reward, next_state, done):
        """Update Q-values based on experience"""
        state_idx = self.discretize_state(state)
        next_state_idx = self.discretize_state(next_state)
        
        # Q-learning update rule
        best_next_action = np.argmax(self.q_table[next_state_idx])
        td_target = reward + self.discount_factor * self.q_table[next_state_idx][best_next_action] * (1 - done)
        td_error = td_target - self.q_table[state_idx][action]
        self.q_table[state_idx][action] += self.learning_rate * td_error
        
        # Decay epsilon
        if self.epsilon > self.epsilon_min:
            self.epsilon *= self.epsilon_decay


class OptimalExecutionEnv:
    """Environment for optimal execution problem"""
    
    def __init__(self, order_size=20000, time_window=1800, time_step=1, min_action_size=20, 
                 penalty_factor=5, depth_penalty_factor=2, direction='buy', seed=None):
        """Initialize execution environment"""
        self.order_size = order_size
        self.time_window = time_window  # seconds
        self.time_step = time_step  # seconds
        self.min_action_size = min_action_size
        self.penalty_factor = penalty_factor
        self.depth_penalty_factor = depth_penalty_factor
        self.direction = direction
        
        # Initialize limit order book
        self.lob = LimitOrderBook(seed=seed)
        
        # Initialize state variables
        self.reset()
    
    def reset(self):
        """Reset the environment to initial state"""
        self.remaining_size = self.order_size
        self.executed_size = 0
        self.elapsed_time = 0
        self.done = False
        self.arrival_price = self.lob.mid_price
        self.implementation_shortfall = 0
        self.total_reward = 0
        self.execution_history = []
        
        # Reset LOB
        self.lob = LimitOrderBook(initial_mid_price=self.lob.mid_price)
        
        return self._get_state()
    
    def _get_state(self):
        """Construct state representation for agent"""
        # Normalized remaining holdings
        holdings_pct = self.remaining_size / self.order_size
        
        # Normalized time remaining
        time_pct = self.elapsed_time / self.time_window
        
        # Volume imbalances at different levels
        imbalances = [self.lob.get_volume_imbalance(i+1) for i in range(5)]
        
        # Best bid/ask prices normalized by arrival price
        norm_bid = self.lob.best_bid / self.arrival_price
        norm_ask = self.lob.best_ask / self.arrival_price
        
        return np.array([holdings_pct, time_pct] + imbalances + [norm_bid, norm_ask])
    
    def step(self, action):
        """Execute one step in the environment"""
        # Update market
        self.lob.update()
        
        # Interpret action: 0 = do nothing, 1-4 = execute k*min_size
        quantity = 0
        if action > 0:
            quantity = action * self.min_action_size
            quantity = min(quantity, self.remaining_size)  # Cannot execute more than remaining
        
        # Calculate reward components
        reward = 0
        depth_consumed = 0
        avg_price = 0
        
        if quantity > 0:
            # Execute market order
            avg_price, depth_consumed, executed = self.lob.execute_market_order(
                quantity, 'buy' if self.direction == 'buy' else 'sell')
            
            # Update remaining size
            self.remaining_size -= executed
            self.executed_size += executed
            
            # Calculate implementation shortfall component
            if self.direction == 'buy':
                price_diff = self.arrival_price - avg_price
            else:
                price_diff = avg_price - self.arrival_price
            
            shortfall = executed * price_diff / self.order_size
            self.implementation_shortfall += shortfall
            
            # Calculate depth penalty
            depth_penalty = -self.depth_penalty_factor * depth_consumed / self.order_size
            
            # Combined reward
            reward = shortfall + depth_penalty
            
            # Record execution
            self.execution_history.append({
                'time': self.elapsed_time,
                'quantity': executed,
                'price': avg_price,
                'shortfall': shortfall,
                'depth_penalty': depth_penalty,
                'reward': reward
            })
        
        # Update time
        self.elapsed_time += self.time_step
        
        # Check if done
        if self.remaining_size <= 0 or self.elapsed_time >= self.time_window:
            self.done = True
            
            # Add penalty for remaining inventory
            if self.remaining_size > 0:
                remaining_penalty = -self.penalty_factor * self.remaining_size / self.order_size
                reward += remaining_penalty
        
        self.total_reward += reward
        
        return self._get_state(), reward, self.done, {
            'remaining': self.remaining_size,
            'executed': self.executed_size,
            'shortfall': self.implementation_shortfall,
            'avg_price': avg_price if quantity > 0 else None,
            'depth': depth_consumed
        }


def twap_execution(env, verbose=False):
    """Time-Weighted Average Price execution strategy"""
    state = env.reset()
    done = False
    rewards = []
    
    # Calculate TWAP execution size per step
    steps = env.time_window // env.time_step
    size_per_step = env.order_size / steps
    
    step_count = 0
    while not done:
        # Execute fixed amount each step
        action = int(np.ceil(size_per_step / env.min_action_size))
        next_state, reward, done, info = env.step(action)
        
        rewards.append(reward)
        state = next_state
        step_count += 1
        
        if verbose and step_count % 100 == 0:
            print(f"TWAP Step {step_count}: Executed {info['executed']}/{env.order_size}, " 
                  f"Reward: {reward:.4f}, Total: {sum(rewards):.4f}")
    
    return {
        'total_reward': sum(rewards),
        'implementation_shortfall': env.implementation_shortfall,
        'steps': step_count,
        'execution_history': env.execution_history
    }


