def train_rl_agent(env, episodes=100, verbose=False):
    """Train RL agent for optimal execution"""
    state_size = 9  # holdings_pct, time_pct, 5 imbalances, normalized bid/ask
    action_size = 5  # do nothing, or execute 1-4 * min_size
    
    agent = DQNAgent(state_size, action_size)
    
    # Training loop
    rewards_history = []
    
    for episode in range(episodes):
        state = env.reset()
        done = False
        episode_rewards = []
        
        step_count = 0
        while not done:
            # Choose action
            action = agent.act(state)
            
            # Take action
            next_state, reward, done, info = env.step(action)
            
            # Train agent
            agent.train(state, action, reward, next_state, done)
            
            state = next_state
            episode_rewards.append(reward)
            step_count += 1
            
            if verbose and step_count % 100 == 0:
                print(f"Episode {episode+1}, Step {step_count}: " 
                      f"Executed {info['executed']}/{env.order_size}, " 
                      f"Reward: {reward:.4f}, Total: {sum(episode_rewards):.4f}")
        
        total_reward = sum(episode_rewards)
        rewards_history.append(total_reward)
        
        if verbose or (episode + 1) % 10 == 0:
            print(f"Episode {episode+1}/{episodes} - Total Reward: {total_reward:.4f}, "
                  f"Implementation Shortfall: {env.implementation_shortfall:.4f}, "
                  f"Epsilon: {agent.epsilon:.4f}")
    
    return agent, rewards_history


