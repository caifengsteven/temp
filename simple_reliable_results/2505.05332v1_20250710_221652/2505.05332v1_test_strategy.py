def simulate_price_series(n_days=43, minutes_per_day=240, mean_return=0, volatility=0.01, correlation=0.8):
    """Simulate price series for two correlated assets"""
    n_steps = n_days * minutes_per_day
    
    # Generate correlated returns
    cov_matrix = np.array([[1, correlation], [correlation, 1]])
    returns = np.random.multivariate_normal(
        mean=[mean_return/minutes_per_day, mean_return/minutes_per_day], 
        cov=cov_matrix * (volatility**2 / minutes_per_day), 
        size=n_steps
    )
    
    # Convert returns to prices starting at 100
    prices1 = 100 * np.exp(np.cumsum(returns[:, 0]))
    prices2 = 100 * np.exp(np.cumsum(returns[:, 1]))
    
    return prices1, prices2


def evaluate_strategy(prices1, prices2, strategy_name, window_size=60):
    """Evaluate a trading strategy on the given price series"""
    pair_trader = PairTrading(window_size=window_size)
    
    # Initialize variables
    position = 0
    trades = []
    equity_curve = [1.0]  # Start with 1.0 (100%)
    spread_history = []
    
    # Select strategy function based on name
    if strategy_name == "NO_SIG":
        signal_func = pair_trader.generate_signal_no_sig
    elif strategy_name == "SIG":
        signal_func = pair_trader.generate_signal_sig
    elif strategy_name == "SE_SIG":
        signal_func = pair_trader.generate_signal_se_sig
    elif strategy_name == "SE_SIG_DIFF":
        signal_func = pair_trader.generate_signal_se_sig_diff
    else:
        raise ValueError(f"Unknown strategy name: {strategy_name}")
    
    # Run strategy
    for i in range(window_size, len(prices1)):
        spread = prices1[i] - prices2[i]
        spread_history.append(spread)
        
        if len(spread_history) > 20:  # Use at least 20 observations for spread statistics
            spread_history.pop(0)
            
            # Generate trading signal
            new_position = signal_func(
                prices1[max(0, i-window_size):i+1], 
                prices2[max(0, i-window_size):i+1],
                spread_history
            )
            
            # Execute trades
            if new_position != position:
                # Record trade
                trades.append({
                    'timestamp': i,
                    'action': 'BUY' if new_position == 1 else 'SELL' if new_position == -1 else 'CLOSE',
                    'price1': prices1[i],
                    'price2': prices2[i],
                    'spread': spread
                })
                
                # Update P&L if closing position
                if position != 0 and new_position == 0:
                    entry_spread = trades[-2]['spread']
                    exit_spread = spread
                    pnl = (exit_spread - entry_spread) * position
                    equity_curve.append(equity_curve[-1] * (1 + pnl * 0.01))  # Scale PnL for better visualization
                
                position = new_position
                pair_trader.position = position
    
    # Calculate statistics
    if len(equity_curve) <= 1:
        return {
            'overall_return': 0,
            'mean_daily_return': 0,
            'max_drawdown': 0,
            'std': 0,
            'sharpe_ratio': 0,
            'count': 0,
            'equity_curve': [1.0] * len(prices1[window_size:])
        }
    
    # Create full equity curve (fill in gaps)
    full_equity_curve = [1.0] * window_size
    trade_idx = 0
    for i in range(window_size, len(prices1)):
        if trade_idx < len(trades) and trades[trade_idx]['timestamp'] == i:
            if trades[trade_idx]['action'] == 'CLOSE':
                full_equity_curve.append(equity_curve[trade_idx+1])
                trade_idx += 1
            else:
                full_equity_curve.append(full_equity_curve[-1])
                trade_idx += 1
        else:
            full_equity_curve.append(full_equity_curve[-1])
    
    # Calculate performance metrics
    overall_return = (full_equity_curve[-1] / full_equity_curve[0] - 1) * 100
    daily_returns = np.array([(full_equity_curve[i+minutes_per_day] / full_equity_curve[i] - 1) 
                             for i in range(0, len(full_equity_curve) - minutes_per_day, minutes_per_day)])
    mean_daily_return = np.mean(daily_returns) * 100
    
    # Calculate max drawdown
    peak = full_equity_curve[0]
    drawdowns = []
    for equity in full_equity_curve:
        if equity > peak:
            peak = equity
        drawdown = (peak - equity) / peak
        drawdowns.append(drawdown)
    max_drawdown = max(drawdowns) * 100
    
    # Calculate Sharpe ratio
    std = np.std(daily_returns) * 100
    sharpe_ratio = (mean_daily_return / std) if std > 0 else 0
    
    return {
        'overall_return': overall_return,
        'mean_daily_return': mean_daily_return,
        'max_drawdown': max_drawdown,
        'std': std,
        'sharpe_ratio': sharpe_ratio,
        'count': len(trades),
        'equity_curve': full_equity_curve
    }


