class StockDataGenerator:
    """Generate synthetic stock data for testing"""
    
    def __init__(self, n_stocks=100, days=500, features=10):
        self.n_stocks = n_stocks
        self.days = days
        self.features = features
        self.stock_codes = [f"STOCK{i:04d}" for i in range(n_stocks)]
        
    def generate_data(self):
        """Generate synthetic stock price data and technical indicators"""
        # Generate stock prices with different volatility profiles
        data = []
        
        for stock_id, code in enumerate(self.stock_codes):
            # Base volatility for this stock
            base_volatility = np.random.uniform(0.01, 0.05)
            
            # Generate price series
            prices = [100]  # Starting price
            for i in range(self.days-1):
                # Time-varying volatility with some clustering effect
                if i % 50 < 25:  # Create periods of higher volatility
                    vol = base_volatility * 2
                else:
                    vol = base_volatility
                
                # Generate return with some mean reversion
                ret = np.random.normal(0, vol)
                new_price = prices[-1] * (1 + ret)
                prices.append(new_price)
            
            # Calculate daily returns
            returns = np.diff(prices) / prices[:-1]
            
            # Calculate realized range volatility (proxy)
            realized_volatility = []
            for i in range(1, len(prices)-1):
                high = prices[i] * (1 + np.random.uniform(0, 0.5 * base_volatility))
                low = prices[i] * (1 - np.random.uniform(0, 0.5 * base_volatility))
                rrv = (np.log(high) - np.log(low))**2 / (4 * np.log(2))
                realized_volatility.append(rrv)
            
            # Generate features similar to those in the paper
            features = np.zeros((len(returns)-1, self.features))
            
            # Feature 1: RANK60 - percentile of current price in past 60 days
            for i in range(60, len(returns)):
                features[i-60, 0] = np.sum(prices[i] >= prices[max(0, i-60):i]) / min(60, i)
            
            # Feature 2-3: BETA5, BETA20
            for i in range(20, len(returns)):
                features[i-20, 1] = np.polyfit(range(5), prices[i-5:i], 1)[0] / prices[i-1]
                features[i-20, 2] = np.polyfit(range(20), prices[i-20:i], 1)[0] / prices[i-1]
            
            # Feature 4: CNTD60
            for i in range(60, len(returns)):
                up = np.mean(returns[i-60:i] > 0)
                down = np.mean(returns[i-60:i] < 0)
                features[i-60, 3] = up - down
            
            # Feature 5-6: MIN5, MIN10
            for i in range(10, len(returns)):
                features[i-10, 4] = min(prices[i-5:i]) / prices[i-1]
                features[i-10, 5] = min(prices[i-10:i]) / prices[i-1]
            
            # Feature 7: KLEN - similar to price volatility
            features[:, 6] = np.random.uniform(0.01, 0.03, size=len(features))
            
            # Feature 8: STD5
            for i in range(5, len(returns)):
                features[i-5, 7] = np.std(prices[i-5:i]) / prices[i-1]
            
            # Feature 9-10: VMA5, VSTD10 (volume-based features)
            volumes = np.random.uniform(50000, 200000, size=len(returns))
            for i in range(10, len(returns)):
                features[i-10, 8] = np.mean(volumes[i-5:i]) / volumes[i-1]
                features[i-10, 9] = np.std(volumes[i-10:i]) / volumes[i-1]
            
            # Add some noise and scale features
            features = features + np.random.normal(0, 0.01, size=features.shape)
            
            # Create dataframe records
            for i in range(60, len(returns)-1):
                record = {
                    'stock_code': code,
                    'date': i,
                    'return': returns[i],
                    'next_return': returns[i+1],
                    'realized_volatility': realized_volatility[i-1],
                    'stock_id': stock_id
                }
                
                # Add features
                for j in range(self.features):
                    record[f'feature_{j}'] = features[i-60, j]
                
                data.append(record)
        
        return pd.DataFrame(data)


class GaussianMixtureModel:
    """Simplified version of the paper's Gaussian Mixture Distribution model"""
    
    def __init__(self, n_components=5, embedding_dim=20, history_len=10):
        self.n_components = n_components
        self.embedding_dim = embedding_dim
        self.history_len = history_len
        self.model = None
        self.scaler = StandardScaler()
        
    def build_model(self, n_features, n_stocks):
        """Build the neural network model with code embedding"""
        # Input for technical indicators
        feature_input = Input(shape=(self.history_len, n_features), name='feature_input')
        
        # Flatten features for simplicity (in the paper they use Crossformer)
        features_flat = Flatten()(feature_input)
        features_dense = Dense(64, activation='relu')(features_flat)
        
        # Stock code embedding
        stock_input = Input(shape=(1,), name='stock_input')
        stock_embedding = Embedding(n_stocks, self.embedding_dim)(stock_input)
        stock_embedding_flat = Flatten()(stock_embedding)
        
        # Fusion network
        merged = Concatenate()([features_dense, stock_embedding_flat])
        hidden = Dense(64, activation='relu')(merged)
        hidden = Dense(32, activation='relu')(hidden)
        
        # Output layers for Gaussian mixture parameters
        weights = Dense(self.n_components, activation='softmax', name='weights')(hidden)
        means = Dense(self.n_components, name='means')(hidden)
        stddevs = Dense(self.n_components, activation='softplus', name='stddevs')(hidden)
        
        # Build and compile model
        model = Model(inputs=[feature_input, stock_input], 
                     outputs=[weights, means, stddevs])
        
        # Custom loss function for Gaussian mixture
        def negative_log_likelihood(y_true, y_pred):
            # This is a placeholder - in real implementation, this would compute
            # the negative log likelihood of the mixture model
            return tf.reduce_mean(tf.square(y_true - y_pred))
        
        model.compile(optimizer='adam', loss={'weights': 'mse', 
                                             'means': negative_log_likelihood,
                                             'stddevs': 'mse'})
        
        self.model = model
        return model
    
    def prepare_data(self, df, window_size=10):
        """Prepare windowed data for model training/testing"""
        feature_cols = [col for col in df.columns if col.startswith('feature_')]
        
        X_features = []
        X_stocks = []
        y_returns = []
        y_volatility = []
        
        stock_codes = df['stock_code'].unique()
        stock_map = {code: i for i, code in enumerate(stock_codes)}
        
        for stock_code in stock_codes:
            stock_data = df[df['stock_code'] == stock_code].sort_values('date')
            
            if len(stock_data) < window_size + 1:
                continue
                
            features = stock_data[feature_cols].values
            returns = stock_data['next_return'].values
            volatility = stock_data['realized_volatility'].values
            stock_idx = stock_map[stock_code]
            
            # Create sliding windows
            for i in range(len(stock_data) - window_size):
                X_features.append(features[i:i+window_size])
                X_stocks.append(stock_idx)
                y_returns.append(returns[i+window_size-1])
                y_volatility.append(volatility[i+window_size-1])
        
        return np.array(X_features), np.array(X_stocks), np.array(y_returns), np.array(y_volatility)
    
    def train(self, df, epochs=10, batch_size=32, validation_split=0.2):
        """Train the model"""
        X_features, X_stocks, y_returns, _ = self.prepare_data(df, self.history_len)
        
        # Scale features
        X_features_reshaped = X_features.reshape(-1, X_features.shape[-1])
        X_features_scaled = self.scaler.fit_transform(X_features_reshaped)
        X_features = X_features_scaled.reshape(X_features.shape)
        
        # Use returns as targets for all outputs (simplified)
        history = self.model.fit(
            [X_features, X_stocks],
            {'weights': np.ones((len(y_returns), self.n_components)) / self.n_components,
             'means': np.tile(y_returns[:, np.newaxis], (1, self.n_components)),
             'stddevs': np.ones((len(y_returns), self.n_components)) * 0.01},
            epochs=epochs,
            batch_size=batch_size,
            validation_split=validation_split,
            verbose=1
        )
        
        return history
    
    def predict(self, df):
        """Make predictions with the model"""
        X_features, X_stocks, _, _ = self.prepare_data(df, self.history_len)
        
        # Scale features
        X_features_reshaped = X_features.reshape(-1, X_features.shape[-1])
        X_features_scaled = self.scaler.transform(X_features_reshaped)
        X_features = X_features_scaled.reshape(X_features.shape)
        
        # Get model predictions
        weights, means, stddevs = self.model.predict([X_features, X_stocks])
        
        # Calculate the mixture variance using the formula from the paper
        mixture_variance = np.zeros(len(weights))
        for i in range(len(weights)):
            w = weights[i]
            mu = means[i]
            sigma = stddevs[i]
            
            # Implementing equation (4) from the paper
            weighted_means_squared = np.sum(w * np.square(mu))
            mean_squared = np.square(np.sum(w * mu))
            weighted_variances = np.sum(w * np.square(sigma))
            
            mixture_variance[i] = weighted_means_squared - mean_squared + weighted_variances
            
        return weights, means, stddevs, np.sqrt(mixture_variance)
    
    def evaluate(self, df, true_returns, predicted_variance):
        """Evaluate model performance"""
        # Calculate MSE
        realized_volatility = df['realized_volatility'].values[-len(predicted_variance):]
        mse = np.mean(np.square(np.sqrt(realized_volatility) - predicted_variance))
        
        # Calculate QLIKE
        qlike = np.mean(realized_volatility / np.square(predicted_variance) + 
                        np.log(np.square(predicted_variance)))
        
        # Simplified CRPS calculation
        # In reality, CRPS would need to be calculated by comparing the entire distribution
        crps = np.mean(np.abs(true_returns - np.mean(predicted_variance)))
        
        return {
            'MSE': mse,
            'QLIKE': qlike,
            'CRPS': crps
        }

