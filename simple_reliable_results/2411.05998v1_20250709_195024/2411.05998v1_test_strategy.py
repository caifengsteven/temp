class ResidualBlock(nn.Module):
    """Residual block as described in the paper"""
    def __init__(self, input_dim, hidden_dim):
        super().__init__()
        self.layer_norm = nn.LayerNorm(input_dim)
        self.linear1 = nn.Linear(input_dim, hidden_dim)
        self.linear2 = nn.Linear(hidden_dim, hidden_dim)
        self.linear3 = nn.Linear(hidden_dim, input_dim)
        self.dropout = nn.Dropout(0.2)
        
    def forward(self, x):
        residual = x
        x = self.layer_norm(x)
        x = self.linear1(x)
        x = self.swish(x)
        x = self.dropout(x)
        x = self.linear2(x)
        x = self.linear3(x)
        x = x + residual
        return x
    
    def swish(self, x):
        """Swish activation function: x * sigmoid(x)"""
        return x * torch.sigmoid(x)


class MLPEncoder(nn.Module):
    """Traditional MLP encoder without residual connections"""
    def __init__(self, input_dim, hidden_dim, latent_dim):
        super().__init__()
        self.fc1 = nn.Linear(input_dim, hidden_dim)
        self.fc2 = nn.Linear(hidden_dim, hidden_dim)
        self.fc_mu = nn.Linear(hidden_dim, latent_dim)
        self.fc_logvar = nn.Linear(hidden_dim, latent_dim)
        
    def forward(self, x):
        h = F.relu(self.fc1(x))
        h = F.relu(self.fc2(h))
        mu = self.fc_mu(h)
        logvar = self.fc_logvar(h)
        return mu, logvar


class MLPDecoder(nn.Module):
    """Traditional MLP decoder without residual connections"""
    def __init__(self, latent_dim, hidden_dim, output_dim):
        super().__init__()
        self.fc1 = nn.Linear(latent_dim, hidden_dim)
        self.fc2 = nn.Linear(hidden_dim, hidden_dim)
        self.fc_mu = nn.Linear(hidden_dim, output_dim)
        self.fc_logvar = nn.Linear(hidden_dim, 1)  # Single sigma for homoscedastic noise
        
    def forward(self, z):
        h = F.relu(self.fc1(z))
        h = F.relu(self.fc2(h))
        mu = self.fc_mu(h)
        logvar = self.fc_logvar(h)
        return mu, logvar


class ResidualEncoder(nn.Module):
    """Encoder with residual connections"""
    def __init__(self, input_dim, hidden_dim, latent_dim, num_blocks=2):
        super().__init__()
        self.input_proj = nn.Linear(input_dim, hidden_dim)
        self.blocks = nn.ModuleList([
            ResidualBlock(hidden_dim, hidden_dim) for _ in range(num_blocks)
        ])
        self.fc_mu = nn.Linear(hidden_dim, latent_dim)
        self.fc_logvar = nn.Linear(hidden_dim, latent_dim)
        
    def forward(self, x):
        h = self.input_proj(x)
        for block in self.blocks:
            h = block(h)
        mu = self.fc_mu(h)
        logvar = self.fc_logvar(h)
        return mu, logvar


class ResidualDecoder(nn.Module):
    """Decoder with residual connections"""
    def __init__(self, latent_dim, hidden_dim, output_dim, num_blocks=2, heteroscedastic=False):
        super().__init__()
        self.heteroscedastic = heteroscedastic
        self.input_proj = nn.Linear(latent_dim, hidden_dim)
        self.blocks = nn.ModuleList([
            ResidualBlock(hidden_dim, hidden_dim) for _ in range(num_blocks)
        ])
        self.fc_mu = nn.Linear(hidden_dim, output_dim)
        
        if heteroscedastic:
            # Output a variance for each feature
            self.fc_logvar = nn.Linear(hidden_dim, output_dim)
        else:
            # Output a single variance
            self.fc_logvar = nn.Linear(hidden_dim, 1)
        
    def forward(self, z):
        h = self.input_proj(z)
        for block in self.blocks:
            h = block(h)
        mu = self.fc_mu(h)
        logvar = self.fc_logvar(h)
        if not self.heteroscedastic:
            # Broadcast the single variance to all dimensions
            logvar = logvar.expand_as(mu)
        return mu, logvar


class VAE(nn.Module):
    """Base VAE implementation"""
    def __init__(self, encoder, decoder):
        super().__init__()
        self.encoder = encoder
        self.decoder = decoder
    
    def encode(self, x):
        mu, logvar = self.encoder(x)
        return mu, logvar
    
    def reparameterize(self, mu, logvar):
        std = torch.exp(0.5 * logvar)
        eps = torch.randn_like(std)
        return mu + eps * std
        
    def decode(self, z):
        mu, logvar = self.decoder(z)
        return mu, logvar
    
    def forward(self, x):
        mu_z, logvar_z = self.encode(x)
        z = self.reparameterize(mu_z, logvar_z)
        mu_x, logvar_x = self.decode(z)
        return mu_x, logvar_x, mu_z, logvar_z
    
    def sample(self, num_samples):
        """Generate samples from the model"""
        device = next(self.parameters()).device
        z = torch.randn(num_samples, self.encoder.fc_mu.out_features).to(device)
        mu, logvar = self.decode(z)
        # Sample from the distribution
        std = torch.exp(0.5 * logvar)
        eps = torch.randn_like(std)
        return mu + eps * std
        
    def calculate_loss(self, x, beta=1.0):
        """Calculate standard VAE loss"""
        mu_x, logvar_x, mu_z, logvar_z = self.forward(x)
        
        # Reconstruction loss (log likelihood)
        var_x = torch.exp(logvar_x)
        recon_loss = 0.5 * torch.sum(((x - mu_x) ** 2) / var_x + logvar_x + np.log(2 * np.pi), dim=1).mean()
        
        # KL divergence
        kl_loss = -0.5 * torch.sum(1 + logvar_z - mu_z.pow(2) - logvar_z.exp(), dim=1).mean()
        
        # Total loss
        loss = recon_loss + beta * kl_loss
        
        return loss, recon_loss, kl_loss


def generate_mixture_of_gaussians(num_samples, num_components=2, dim=2, std_scale=1.0, mean_scale=5.0):
    """Generate data from a mixture of Gaussians"""
    components = []
    weights = np.random.dirichlet(np.ones(num_components))
    
    for i in range(num_components):
        # Generate random mean and covariance for each component
        mean = np.random.randn(dim) * mean_scale
        cov = np.eye(dim) * (0.1 + np.random.rand()) * std_scale
        
        # Generate samples for this component
        n_samples = int(weights[i] * num_samples)
        samples = np.random.multivariate_normal(mean, cov, size=n_samples)
        components.append(samples)
    
    # Combine all components
    data = np.vstack(components)
    np.random.shuffle(data)
    
    return data[:num_samples]  # Ensure exactly num_samples are returned


def impute_missing_values(model, data, missing_mask):
    """Impute missing values using the method described in the paper"""
    device = next(model.parameters()).device
    
    # Copy data and apply missing mask
    data_masked = data.clone()
    data_masked[missing_mask] = 0  # Set missing values to 0
    
    # Get observed data indices
    observed_mask = ~missing_mask
    
    # Sample from encoder multiple times
    num_samples = 10000
    all_z_samples = []
    
    # Convert to PyTorch tensors
    x_masked = data_masked.to(device)
    
    # Get latent distribution parameters
    mu_z, logvar_z = model.encode(x_masked)
    
    # Generate samples from encoder
    for _ in range(num_samples):
        z = model.reparameterize(mu_z, logvar_z)
        all_z_samples.append(z)
    
    all_z_samples = torch.stack(all_z_samples)
    
    # Compute weights
    all_weights = []
    for z in all_z_samples:
        # Decode z to get the likelihood parameters
        mu_x, logvar_x = model.decode(z)
        
        # Compute likelihood of observed data
        log_likelihood = 0
        for i, observed in enumerate(observed_mask[0]):
            if observed:
                x_obs = data[0, i].to(device)
                mu = mu_x[0, i]
                var = torch.exp(logvar_x[0, i])
                log_likelihood -= 0.5 * ((x_obs - mu) ** 2 / var + torch.log(var) + np.log(2 * np.pi))
        
        all_weights.append(log_likelihood.item())
    
    # Normalize weights
    all_weights = np.array(all_weights)
    all_weights = np.exp(all_weights - np.max(all_weights))
    all_weights /= np.sum(all_weights)
    
    # Weighted imputation
    imputed_values = torch.zeros_like(data)
    for i, z in enumerate(all_z_samples):
        mu_x, _ = model.decode(z)
        imputed_values += all_weights[i] * mu_x
    
    # Use original values where data is observed
    result = data.clone()
    result[missing_mask] = imputed_values[missing_mask]
    
    return result


