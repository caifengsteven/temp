    def covariance_at_lag(self, i, j, k):
        """
        Calculate the theoretical cross-covariance at lag k
        
        Parameters:
        - i, j: indices of the components
        - k: lag (k >= 0)
        
        Returns:
        - γ_ij(k): the cross-covariance
        """
