        H_est = np.zeros(N)
        for i in range(N):
            # Calculate autocovariances at different lags
            acov = np.array([np.mean(Y_centered[:-k, i] * Y_centered[k:, i]) if k > 0 else var_est[i] 
                             for k in lags if k < n_obs//2])
            valid_lags = np.array([k for k in lags if k < n_obs//2 and k > 0])
            
            if len(valid_lags) > 1:
                # Log-log regression to estimate H
                log_lags = np.log(valid_lags)
                log_acov = np.log(np.maximum(1e-10, abs(acov[1:])))  # Avoid log of negative values
                slope, _ = np.polyfit(log_lags, log_acov, 1)
                H_est[i] = max(0.01, min(0.99, (slope + 2) / 2))  # H = (slope + 2) / 2
            else:
                H_est[i] = 0.2  # Default to rough volatility
        
        # Estimate alpha based on AR(1) coefficient
        alpha_est = np.zeros(N)
        for i in range(N):
            ar1 = np.corrcoef(Y_centered[:-1, i], Y_centered[1:, i])[0, 1]
            alpha_est[i] = max(0.01, -np.log(ar1) / dt)
        
        # Estimate nu based on var and alpha
        nu_est = np.sqrt(2 * alpha_est * var_est / gamma(2 * H_est + 1))
        
        # Estimate rho from contemporaneous correlations
        rho_est = np.corrcoef(Y_centered.T)
        
        # Estimate eta based on asymmetries in cross-correlations (simplified)
        eta_est = np.zeros((N, N))
        for i in range(N):
            for j in range(i+1, N):
                # Compare Y_i(t+1) with Y_j(t) vs Y_j(t+1) with Y_i(t)
                corr_ij = np.corrcoef(Y_centered[:-1, j], Y_centered[1:, i])[0, 1]
                corr_ji = np.corrcoef(Y_centered[:-1, i], Y_centered[1:, j])[0, 1]
                
                # Asymmetry
                eta_est[i, j] = (corr_ij - corr_ji) / 4  # Scale factor is arbitrary
                eta_est[j, i] = -eta_est[i, j]
        
        return {
            'mu': mu_est,
            'alpha': alpha_est,
            'nu': nu_est,
            'H': H_est,
            'rho': rho_est,
            'eta': eta_est
        }

