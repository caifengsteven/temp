    def allocate_budget(self, date: str, market_data: Dict[str, pd.DataFrame], frequency: int = 30) -> Dict[str, float]:
        """Budget allocation conference"""
        # Check if it's time to rebalance
        current_date = datetime.strptime(date, "%Y-%m-%d")
        if self.last_rebalance_date is None:
            should_rebalance = True
        else:
            last_date = datetime.strptime(self.last_rebalance_date, "%Y-%m-%d")
            days_passed = (current_date - last_date).days
            should_rebalance = days_passed >= frequency
        
        if not should_rebalance:
            return self.budget_allocations
        
        # Get reports from each agent
        agent_reports = []
        for agent in self.agents:
            # Calculate agent performance
            asset_data = market_data[agent.asset]
            latest_price = asset_data['price'].iloc[-1]
            
            # Calculate profit situation
            current_value = agent.cash + (agent.position * latest_price)
            profit_pct = (current_value - self.budget_allocations[agent.name]) / self.budget_allocations[agent.name] * 100
            
            # Calculate risk metrics
            recent_prices = asset_data['price'].iloc[-30:].values
            volatility = np.std(recent_prices) / np.mean(recent_prices) * 100
            
            # Calculate expected return (simplified)
            expected_return = profit_pct * 0.7  # Past performance is a partial indicator of future
            if agent.asset == "Bitcoin":
                # Higher risk, higher potential return
                expected_return = expected_return * 1.2
            elif agent.asset == "Forex":
                # Lower risk, lower potential return
                expected_return = expected_return * 0.8
            
            # Agent's budget expectation
            current_allocation_pct = self.budget_allocations[agent.name] / self.total_portfolio_value * 100
            
            if expected_return > 5 and volatility < 10:
                budget_expectation = "Increase"
                reason = "Strong performance with manageable risk"
            elif expected_return < 0 and volatility > 15:
                budget_expectation = "Decrease"
                reason = "Poor performance with high risk"
            else:
                budget_expectation = "Maintain"
                reason = "Balanced performance and risk"
            
            agent_reports.append({
                "agent": agent.name,
                "asset": agent.asset,
                "profit_pct": profit_pct,
                "volatility": volatility,
                "expected_return": expected_return,
                "current_allocation_pct": current_allocation_pct,
                "budget_expectation": budget_expectation,
                "reason": reason
            })
        
        # Store in memory
        self.memory.add_market_info({"date": date, "agent_reports": agent_reports})
        
        # Calculate new allocations
        total_expected_return = sum(max(0.1, report["expected_return"]) for report in agent_reports)
        total_volatility = sum(report["volatility"] for report in agent_reports)
        
        new_allocations = {}
        for report in agent_reports:
            # Weight by expected return and inversely by volatility
            expected_return_weight = max(0.1, report["expected_return"]) / total_expected_return
            volatility_weight = 1 - (report["volatility"] / total_volatility)
            
            # Combine weights
            combined_weight = 0.7 * expected_return_weight + 0.3 * volatility_weight
            
            # Calculate new allocation
            new_allocation = self.total_portfolio_value * combined_weight
            
            # Ensure minimum allocation
            new_allocation = max(new_allocation, self.total_portfolio_value * 0.1)
            
            new_allocations[report["agent"]] = new_allocation
        
        # Normalize allocations
        total_new_allocation = sum(new_allocations.values())
        for agent_name in new_allocations:
            new_allocations[agent_name] = (new_allocations[agent_name] / total_new_allocation) * self.total_portfolio_value
        
        # Record rebalancing
        rebalance_record = {
            "date": date,
            "previous_allocations": self.budget_allocations.copy(),
            "new_allocations": new_allocations,
            "agent_reports": agent_reports
        }
        self.history.append(rebalance_record)
        
        # Update allocations
        self.budget_allocations = new_allocations
        self.last_rebalance_date = date
        
        return new_allocations
    
