class LSTMModel(nn.Module):
    def __init__(self, input_dim, hidden_dim, num_layers, output_dim):
        super(LSTMModel, self).__init__()
        self.hidden_dim = hidden_dim
        self.num_layers = num_layers
        
        self.lstm = nn.LSTM(input_dim, hidden_dim, num_layers, batch_first=True)
        self.fc = nn.Linear(hidden_dim, output_dim)
        self.softmax = nn.Softmax(dim=1)
        
    def forward(self, x):
        h0 = torch.zeros(self.num_layers, x.size(0), self.hidden_dim).to(x.device)
        c0 = torch.zeros(self.num_layers, x.size(0), self.hidden_dim).to(x.device)
        
        out, _ = self.lstm(x, (h0, c0))
        out = self.fc(out[:, -1, :])
        out = self.softmax(out)
        return out

class TransformerModel(nn.Module):
    def __init__(self, input_dim, d_model, nhead, num_layers, output_dim):
        super(TransformerModel, self).__init__()
        self.embedding = nn.Linear(input_dim, d_model)
        encoder_layer = nn.TransformerEncoderLayer(d_model=d_model, nhead=nhead, batch_first=True)
        self.transformer_encoder = nn.TransformerEncoder(encoder_layer, num_layers=num_layers)
        self.fc = nn.Linear(d_model, output_dim)
        self.softmax = nn.Softmax(dim=1)
        
    def forward(self, x):
        x = self.embedding(x)
        x = self.transformer_encoder(x)
        x = x.mean(dim=1)  # Global average pooling
        x = self.fc(x)
        x = self.softmax(x)
        return x

def generate_synthetic_market_data(num_stocks, num_days, trend='upward'):
    """Generate synthetic OHLCV data for multiple stocks"""
    data = {}
    
    for stock_idx in range(num_stocks):
        # Base price with some randomness
        if trend == 'upward':
            drift = np.random.uniform(0.0001, 0.0005)  # Upward trend
        else:
            drift = np.random.uniform(-0.0002, 0.0002)  # Range-bound
            
        volatility = np.random.uniform(0.005, 0.02)
        
        # Starting price
        base_price = np.random.uniform(50, 200)
        
        # Generate daily returns with drift and volatility
        daily_returns = np.random.normal(drift, volatility, num_days)
        
        # Calculate closing prices
        closes = base_price * np.cumprod(1 + daily_returns)
        
        # Generate OHLCV data
        opens = closes * np.random.normal(1, 0.005, num_days)
        highs = np.maximum(opens, closes) * np.random.normal(1.01, 0.005, num_days)
        lows = np.minimum(opens, closes) * np.random.normal(0.99, 0.005, num_days)
        volumes = np.random.lognormal(15, 1, num_days)
        
        stock_data = pd.DataFrame({
            'open': opens,
            'high': highs,
            'low': lows,
            'close': closes,
            'volume': volumes
        })
        
        data[f'stock_{stock_idx}'] = stock_data
    
    return data

def preprocess_data(data, window_size=252):
    """Transform OHLCV data into model input features"""
    all_features = []
    
    for stock_name, stock_data in data.items():
        # Calculate transformed features
        o_prime = np.log(stock_data['open'] / stock_data['close'])
        h_prime = np.log(stock_data['high'] / stock_data['close'])
        l_prime = np.log(stock_data['low'] / stock_data['close'])
        c_prime = np.log(stock_data['close'] / stock_data['close'].shift(1))
        v_prime = np.log(stock_data['volume'])
        
        # Combine features
        features = pd.DataFrame({
            'o_prime': o_prime,
            'h_prime': h_prime,
            'l_prime': l_prime,
            'c_prime': c_prime,
            'v_prime': v_prime
        }).dropna()
        
        # Standardize features
        scaler = StandardScaler()
        features_scaled = scaler.fit_transform(features)
        
        all_features.append(features_scaled)
    
    # Create windowed data for sequence models
    X = []
    for i in range(len(all_features[0]) - window_size):
        window_data = []
        for stock_idx in range(len(all_features)):
            window_data.append(all_features[stock_idx][i:i+window_size])
        X.append(np.array(window_data).transpose(1, 0, 2))  # Shape: [window_size, num_stocks, features]
    
    return np.array(X)

def calculate_returns(data, start_idx, period=21):
    """Calculate stock returns for a period starting from start_idx"""
    returns = []
    
    for stock_name, stock_data in data.items():
        start_price = stock_data['close'].iloc[start_idx]
        end_price = stock_data['close'].iloc[start_idx + period]
        stock_return = np.log(end_price / start_price)
        returns.append(stock_return)
    
    return np.array(returns)

def generate_max_sortino_target(returns):
    """Generate Max-Sortino portfolio weights as target"""
    n = len(returns)
    mean_returns = returns
    
    # Calculate semi-variance (downside risk)
    negative_returns = np.minimum(returns - np.mean(returns), 0)
    semi_variance = np.outer(negative_returns, negative_returns) / len(returns)
    
    # Ensure semi-variance matrix is positive definite
    semi_variance = semi_variance + 1e-8 * np.eye(n)
    
    # Define optimization function (Dinkelbach's algorithm)
    def optimize_sortino(y):
        def objective(w):
            return -(w.dot(mean_returns) - y * np.sqrt(w.dot(semi_variance).dot(w)))
        
        constraints = [{'type': 'eq', 'fun': lambda w: np.sum(w) - 1}]
        bounds = [(0, 1) for _ in range(n)]
        
        result = minimize(objective, np.ones(n) / n, method='SLSQP', bounds=bounds, constraints=constraints)
        return result.x, result.fun
    
    # Initialize y
    w_init = np.ones(n) / n
    y = w_init.dot(mean_returns) / np.sqrt(w_init.dot(semi_variance).dot(w_init))
    
    # Iterative solution
    for _ in range(10):  # Usually converges in a few iterations
        w, neg_objective = optimize_sortino(y)
        new_y = w.dot(mean_returns) / np.sqrt(w.dot(semi_variance).dot(w))
        
        if abs(new_y - y) < 1e-6:
            break
            
        y = new_y
    
    return w

def generate_one_hot_target(returns):
    """Generate One-Hot portfolio weights as target (all-in on best performing stock)"""
    best_stock_idx = np.argmax(returns)
    weights = np.zeros(len(returns))
    weights[best_stock_idx] = 1.0
    return weights

def train_model(model, train_loader, criterion, optimizer, epochs=100):
    """Train a deep learning model"""
    model.train()
    losses = []
    
    for epoch in range(epochs):
        epoch_loss = 0
        for inputs, targets in train_loader:
            optimizer.zero_grad()
            outputs = model(inputs)
            loss = criterion(outputs, targets)
            loss.backward()
            optimizer.step()
            epoch_loss += loss.item()
        
        losses.append(epoch_loss / len(train_loader))
        if epoch % 10 == 0:
            print(f'Epoch {epoch}, Loss: {losses[-1]:.6f}')
    
    return losses

def evaluate_portfolio(weights, returns):
    """Evaluate portfolio performance metrics"""
    portfolio_return = weights.dot(returns)
    
    # Calculate Sharpe ratio (assuming 0 risk-free rate)
    sharpe_ratio = portfolio_return / np.std(returns)
    
    # Calculate Sortino ratio
    downside_returns = np.minimum(returns - np.mean(returns), 0)
    semi_variance = np.mean(downside_returns ** 2)
    sortino_ratio = portfolio_return / np.sqrt(semi_variance)
    
    return portfolio_return, sharpe_ratio, sortino_ratio

def backtest_portfolio(models, X_test, data, window_size=252, target_type='max_sortino', ensemble_size=5):
    """Backtest portfolio performance using ensemble of models"""
    cumulative_return = 1.0
    returns_history = [cumulative_return]
    
    for i in range(len(X_test)):
        # Get model inputs
        inputs = torch.tensor(X_test[i:i+1], dtype=torch.float32)
        
        # Aggregate predictions from ensemble
        all_weights = []
        for model in models[:ensemble_size]:
            model.eval()
            with torch.no_grad():
                weights = model(inputs).numpy()[0]
                all_weights.append(weights)
        
        # Average weights across ensemble
        portfolio_weights = np.mean(all_weights, axis=0)
        
        # Calculate actual returns for the next period
        stock_returns = calculate_returns(data, i + window_size, period=21)
        
        # Update portfolio value
        period_return = portfolio_weights.dot(np.exp(stock_returns) - 1)
        cumulative_return *= (1 + period_return)
        returns_history.append(cumulative_return)
    
    return returns_history

