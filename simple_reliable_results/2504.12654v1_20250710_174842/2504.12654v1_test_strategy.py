@dataclass
class Professional:
    domain: Domain
    experience_years: int
    explicit_knowledge: float  # 0-100 scale
    relational_tacit_knowledge: float  # 0-100 scale
    somatic_tacit_knowledge: float  # 0-100 scale
    ai_collaboration_frequency: float  # 0-1 scale
    
    def calculate_market_value(self) -> float:
        """Calculate professional's market value based on knowledge types and experience."""
        # Base value from experience with diminishing returns
        base_value = 50000 + 5000 * min(self.experience_years, 15) + 2000 * max(0, self.experience_years - 15)
        
        # Premium for knowledge types (explicit least valuable, somatic most valuable)
        knowledge_premium = (
            self.explicit_knowledge * 100 + 
            self.relational_tacit_knowledge * 300 + 
            self.somatic_tacit_knowledge * 500
        )
        
        return base_value + knowledge_premium


@dataclass
class AISystem:
    capability_explicit: float  # 0-100 scale
    capability_relational_tacit: float  # 0-100 scale
    capability_somatic_tacit: float  # 0-100 scale
    learning_rate: float  # 0-1 scale
    domain_specificity: Dict[Domain, float]  # Domain to capability multiplier
    
    def can_automate_task(self, task: 'Task') -> float:
        """Return probability (0-1) of successfully automating a given task."""
        domain_multiplier = self.domain_specificity.get(task.domain, 0.5)
        
        knowledge_match = (
            task.explicit_knowledge_required * self.capability_explicit +
            task.relational_tacit_required * self.capability_relational_tacit +
            task.somatic_tacit_required * self.capability_somatic_tacit
        ) / (task.explicit_knowledge_required + task.relational_tacit_required + task.somatic_tacit_required)
        
        return min(0.95, knowledge_match * domain_multiplier / 100)


@dataclass
class Task:
    name: str
    domain: Domain
    explicit_knowledge_required: float  # 0-100 scale
    relational_tacit_required: float  # 0-100 scale
    somatic_tacit_required: float  # 0-100 scale
    
    def calculate_automation_susceptibility(self) -> float:
        """Calculate how susceptible a task is to automation (0-1)."""
        # Somatic tasks are hardest to automate
        total_knowledge = self.explicit_knowledge_required + self.relational_tacit_required + self.somatic_tacit_required
        
        if total_knowledge == 0:
            return 0
            
        weighted_sum = (
            self.explicit_knowledge_required * 0.9 +
            self.relational_tacit_required * 0.6 +
            self.somatic_tacit_required * 0.1
        )
        
        return weighted_sum / total_knowledge


class ExternalizationSimulation:
    def __init__(self, professionals: List[Professional], ai_system: AISystem, tasks: List[Task]):
        self.professionals = professionals
        self.ai_system = ai_system
        self.tasks = tasks
        self.time_steps = 0
        self.externalization_history = []
        self.market_value_history = {p: [] for p in range(len(professionals))}
        self.task_automation_history = {t: [] for t in range(len(tasks))}
    
    def simulate_step(self):
        """Simulate one time step of expertise externalization."""
        self.time_steps += 1
        
        # For each professional, simulate collaboration with AI
        for i, professional in enumerate(self.professionals):
            # Only externalize knowledge if collaborating with AI
            if random.random() < professional.ai_collaboration_frequency:
                self._externalize_knowledge(professional)
            
            # Track market value
            self.market_value_history[i].append(professional.calculate_market_value())
        
        # For each task, recalculate automation probability
        for i, task in enumerate(self.tasks):
            automation_prob = self.ai_system.can_automate_task(task)
            self.task_automation_history[i].append(automation_prob)
            
    def _externalize_knowledge(self, professional: Professional):
        """Simulate knowledge externalization from professional to AI system."""
        # Choose externalization mechanism
        mechanism = random.choice(list(ExternalizationMechanism))
        
        # Calculate how much knowledge is externalized based on mechanism
        externalization_rate = self.ai_system.learning_rate
        
        # Different mechanisms have different effectiveness for different knowledge types
        if mechanism == ExternalizationMechanism.DIRECT_DEMONSTRATION:
            explicit_transfer = 0.2 * externalization_rate
            relational_transfer = 0.7 * externalization_rate
            somatic_transfer = 0.1 * externalization_rate
        elif mechanism == ExternalizationMechanism.INTERACTIVE_REFINEMENT:
            explicit_transfer = 0.3 * externalization_rate
            relational_transfer = 0.6 * externalization_rate
            somatic_transfer = 0.1 * externalization_rate
        else:  # EXPLICITATION
            explicit_transfer = 0.7 * externalization_rate
            relational_transfer = 0.3 * externalization_rate
            somatic_transfer = 0.05 * externalization_rate
            
        # Transfer knowledge to AI (proportional to professional's knowledge)
        domain_multiplier = self.ai_system.domain_specificity.get(professional.domain, 0.5)
        
        # Calculate knowledge transfer
        explicit_knowledge_gain = professional.explicit_knowledge * explicit_transfer * domain_multiplier
        relational_knowledge_gain = professional.relational_tacit_knowledge * relational_transfer * domain_multiplier
        somatic_knowledge_gain = professional.somatic_tacit_knowledge * somatic_transfer * domain_multiplier
        
        # Cap AI capabilities at 100
        self.ai_system.capability_explicit = min(100, self.ai_system.capability_explicit + explicit_knowledge_gain)
        self.ai_system.capability_relational_tacit = min(100, self.ai_system.capability_relational_tacit + relational_knowledge_gain)
        self.ai_system.capability_somatic_tacit = min(100, self.ai_system.capability_somatic_tacit + somatic_knowledge_gain)
        
        # Log externalization event
        self.externalization_history.append({
            "time_step": self.time_steps,
            "domain": professional.domain.value,
            "mechanism": mechanism.value,
            "explicit_gain": explicit_knowledge_gain,
            "relational_gain": relational_knowledge_gain,
            "somatic_gain": somatic_knowledge_gain
        })
    
    def run_simulation(self, steps: int):
        """Run simulation for specified number of steps."""
        for _ in range(steps):
            self.simulate_step()
            
