def analyze_domain_impact(results: Dict, professionals: List[Professional], tasks: List[Task]):
    """Analyze how externalization impacts different domains."""
    try:
        # Group professionals by domain
        domain_professionals = {}
        for i, prof in enumerate(professionals):
            if prof.domain not in domain_professionals:
                domain_professionals[prof.domain] = []
            domain_professionals[prof.domain].append(i)
        
        # Calculate average market value change by domain
        domain_market_changes = {}
        for domain, prof_indices in domain_professionals.items():
            domain_changes = []
            for idx in prof_indices:
                values = results["market_values"][idx]
                if len(values) >= 2:  # Need at least 2 points to calculate change
                    pct_change = (values[-1] - values[0]) / values[0] * 100
                    domain_changes.append(pct_change)
            
            if domain_changes:
                domain_market_changes[domain.value] = sum(domain_changes) / len(domain_changes)
        
        # Group tasks by domain
        domain_tasks = {}
        for i, task in enumerate(tasks):
            if task.domain not in domain_tasks:
                domain_tasks[task.domain] = []
            domain_tasks[task.domain].append(i)
        
        # Calculate average automation probability change by domain
        domain_automation_changes = {}
        for domain, task_indices in domain_tasks.items():
            domain_changes = []
            for idx in task_indices:
                values = results["task_automation"][idx]
                if len(values) >= 2:  # Need at least 2 points to calculate change
                    abs_change = values[-1] - values[0]
                    domain_changes.append(abs_change)
            
            if domain_changes:
                domain_automation_changes[domain.value] = sum(domain_changes) / len(domain_changes)
        
        # Print analysis
        print("\n--- Domain Impact Analysis ---")
        print("\nAverage Market Value Change by Domain:")
        for domain, change in domain_market_changes.items():
            print(f"{domain}: {change:.2f}%")
        
        print("\nAverage Automation Probability Change by Domain:")
        for domain, change in domain_automation_changes.items():
            print(f"{domain}: {change:.2f} (absolute change)")
        
        return {
            "market_changes": domain_market_changes,
            "automation_changes": domain_automation_changes
        }
    except Exception as e:
        print(f"Error in domain impact analysis: {e}")
        return None


