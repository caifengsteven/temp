    def backtest_strategy(self, predictions, meta_test, y_test, top_pct=0.1):
        """Backtest a simple top/bottom portfolio strategy"""
        unique_dates = meta_test['date'].unique()
        returns = []
        benchmark_returns = []
        
        for i, date in enumerate(unique_dates[:-1]):
            # Skip the last day as we don't have next day returns
            next_date = unique_dates[i + 1]
            
            # Get predictions for the current date
            date_mask = meta_test['date'] == date
            date_tickers = meta_test.loc[date_mask, 'ticker'].values
            date_predictions = predictions[date_mask]
            
            # Select top and bottom stocks
            n_select = max(1, int(len(date_tickers) * top_pct))
            
            # Sort by prediction
            sorted_indices = np.argsort(date_predictions)
            top_indices = sorted_indices[-n_select:]
            bottom_indices = sorted_indices[:n_select]
            
            # Get top and bottom tickers
            top_tickers = date_tickers[top_indices]
            bottom_tickers = date_tickers[bottom_indices]
            
            # Calculate next day returns for selected stocks
            next_date_mask = meta_test['date'] == next_date
            next_date_returns = y_test[next_date_mask]
            next_date_tickers = meta_test.loc[next_date_mask, 'ticker'].values
            
            # Calculate portfolio return (long top, short bottom)
            portfolio_return = 0
            count = 0
            
            for ticker in top_tickers:
                if ticker in next_date_tickers:
                    idx = np.where(next_date_tickers == ticker)[0][0]
                    portfolio_return += next_date_returns[idx]
                    count += 1
            
            for ticker in bottom_tickers:
                if ticker in next_date_tickers:
                    idx = np.where(next_date_tickers == ticker)[0][0]
                    portfolio_return -= next_date_returns[idx]
                    count += 1
            
            if count > 0:
                portfolio_return /= count
            
            # Calculate benchmark return (equal weight all stocks)
            benchmark_return = np.mean(next_date_returns)
            
            returns.append(portfolio_return)
            benchmark_returns.append(benchmark_return)
        
        # Calculate performance metrics
        cumulative_returns = np.cumprod(1 + np.array(returns)) - 1
        benchmark_cumulative_returns = np.cumprod(1 + np.array(benchmark_returns)) - 1
        
        # Calculate Sharpe ratio (simplified, assuming zero risk-free rate)
        sharpe_ratio = np.mean(returns) / np.std(returns) * np.sqrt(252)  # Annualized
        
        # Calculate maximum drawdown
        running_max = np.maximum.accumulate(cumulative_returns + 1)
        drawdown = (cumulative_returns + 1) / running_max - 1
        max_drawdown = np.min(drawdown)
        
        return {
            'returns': returns,
            'cumulative_returns': cumulative_returns,
            'benchmark_returns': benchmark_returns,
            'benchmark_cumulative_returns': benchmark_cumulative_returns,
            'sharpe_ratio': sharpe_ratio,
            'max_drawdown': max_drawdown,
            'annualized_return': (1 + cumulative_returns[-1]) ** (252 / len(returns)) - 1
        }
    
