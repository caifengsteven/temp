            next_date = returns.index[date_idx + 1]
            
            # For each stock
            for ticker in returns.columns:
                # Get lookback features
                ticker_features = []
                for lb in range(lookback):
                    # Get features from lookback days
                    lb_date = returns.index[date_idx - lb]
                    for feat in features.keys():
                        ticker_features.append(features[feat].loc[lb_date, ticker])
                
                # Get target (next day return)
                target = returns.loc[next_date, ticker]
                
                X_list.append(ticker_features)
                y_list.append(target)
