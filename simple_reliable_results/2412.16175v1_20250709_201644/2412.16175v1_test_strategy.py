    # Fit curve to sqrt(N log N log log N)
    from scipy.optimize import curve_fit
    
    def regret_function(N, C):
        return C * np.sqrt(N * np.log(N) * np.log(np.log(N)))
    
    popt, _ = curve_fit(regret_function, iteration_counts, cumulative_regrets)
    
