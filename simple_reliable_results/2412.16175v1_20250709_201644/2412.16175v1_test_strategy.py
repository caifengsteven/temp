class CTRLPortfolioOptimizer:
    """
    Continuous-Time Reinforcement Learning (CTRL) algorithm for mean-variance portfolio optimization
    based on the baseline algorithm described in the paper.
    """
    def __init__(self, d, mu, sigma, r, T, x0, z, eps=0.1, max_iter=100):
        """
        Initialize the CTRL algorithm.
        
        Args:
            d: Number of risky assets
            mu: Expected return vector (d x 1)
            sigma: Volatility matrix (d x d)
            r: Risk-free rate
            T: Investment horizon
            x0: Initial wealth
            z: Target expected terminal wealth
            eps: Temperature parameter
            max_iter: Maximum number of iterations
        """
        self.d = d
        self.mu = mu
        self.sigma = sigma
        self.sigma_sigma_T = sigma @ sigma.T  # Covariance matrix
        self.r = r
        self.T = T
        self.x0 = x0
        self.z = z
        self.eps = eps
        self.max_iter = max_iter
        
        # Initialize parameters
        self.theta1 = np.zeros(d)  # Mean parameter
        self.theta2 = np.eye(d)    # Covariance parameter
        self.theta3 = 5.0          # Fixed as suggested in the paper
        self.w = 1.5               # Lagrange multiplier
        self.pi1 = np.array([0.0, 0.0])  # Critic parameters
        self.pi2 = 0.0
        
    def value_function(self, t, x):
        """Compute the value function at (t, x)"""
        return (x - self.w)**2 * np.exp(-self.theta3 * (self.T - t)) + \
               self.pi2 * (t**2 - self.T**2) + self.pi1 * (t - self.T) - (self.w - self.z)**2
    
    def sample_action(self, t, x):
        """Sample action from the policy"""
        mean = -self.theta1 * (x - self.w)
        cov = self.theta2 * np.exp(self.theta3 * (self.T - t))
        return np.random.multivariate_normal(mean, cov)
    
    def deterministic_action(self, t, x):
        """Deterministic policy for execution"""
        return -self.theta1 * (x - self.w)
    
    def simulate_wealth(self, policy_type='stochastic', dt=0.01):
        """
        Simulate wealth trajectory using either stochastic or deterministic policy
        
        Args:
            policy_type: 'stochastic' or 'deterministic'
            dt: Time step
        
        Returns:
            times: Time points
            wealth: Wealth trajectory
            actions: Portfolio allocations
        """
        num_steps = int(self.T / dt)
        times = np.linspace(0, self.T, num_steps + 1)
        wealth = np.zeros(num_steps + 1)
        actions = np.zeros((num_steps + 1, self.d))
        
        wealth[0] = self.x0
        
        for i in range(num_steps):
            t = times[i]
            x = wealth[i]
            
            # Select action based on policy type
            if policy_type == 'stochastic':
                u = self.sample_action(t, x)
            else:
                u = self.deterministic_action(t, x)
            
            actions[i] = u
            
            # Simulate price changes
            dW = np.random.normal(0, np.sqrt(dt), self.d)
            returns = (self.mu - self.r) * dt + self.sigma @ dW
            
            # Update wealth
            wealth[i+1] = x + u @ returns
            
        return times, wealth, actions
    
    def update_parameters(self, trajectories, an):
        """
        Update parameters based on observed trajectories
        
        Args:
            trajectories: List of (times, wealth, actions) tuples
            an: Learning rate
        """
        delta_theta1 = np.zeros_like(self.theta1)
        delta_theta2 = np.zeros_like(self.theta2)
        delta_w = 0
        
        for times, wealth, actions in trajectories:
            num_steps = len(times) - 1
            
            # Accumulate gradients
            for i in range(num_steps):
                t = times[i]
                x = wealth[i]
                u = actions[i]
                next_t = times[i+1]
                next_x = wealth[i+1]
                
                # Value function differentials
                dJ = self.value_function(next_t, next_x) - self.value_function(t, x)
                
                # Log-policy gradients
                dtheta1 = -(x - self.w) * self.theta2 @ u
                dtheta2 = 0.5 * self.theta2 - 0.5 * np.exp(-self.theta3 * (self.T - t)) * np.outer(u, u)
                
                delta_theta1 -= an * dtheta1 * dJ
                delta_theta2 += an * dtheta2 * dJ
            
            # Terminal wealth constraint
            delta_w -= an * (wealth[-1] - self.z)
        
        # Update parameters with projection
        self.theta1 += delta_theta1
        self.theta2 = self.project_to_pd(self.theta2 + delta_theta2)
        self.w += delta_w
    
    def project_to_pd(self, matrix, min_eig=1e-5):
        """Project matrix to positive definite cone"""
        eigvals, eigvecs = np.linalg.eigh(matrix)
        eigvals = np.maximum(eigvals, min_eig)
        return eigvecs @ np.diag(eigvals) @ eigvecs.T
    
    def train(self, num_episodes=10, dt=0.01):
        """Train the CTRL algorithm"""
        sharpe_ratios = []
        theoretical_sr = self.calculate_theoretical_sharpe()
        
        for n in range(self.max_iter):
            # Generate trajectories
            trajectories = [self.simulate_wealth(policy_type='stochastic', dt=dt) 
                           for _ in range(num_episodes)]
            
            # Learning rate
            an = 1.0 / (n + 1)
            
            # Update parameters
            self.update_parameters(trajectories, an)
            
            # Evaluate current policy
            _, terminal_wealth, _ = self.simulate_wealth(policy_type='deterministic', dt=dt)
            sr = self.calculate_sharpe_ratio(terminal_wealth[-1])
            sharpe_ratios.append(sr)
            
            if n % 10 == 0:
                print(f"Iteration {n}, Sharpe Ratio: {sr:.4f}, Theoretical SR: {theoretical_sr:.4f}")
        
        return sharpe_ratios
    
    def calculate_sharpe_ratio(self, terminal_wealth):
        """Calculate Sharpe ratio based on terminal wealth"""
        expected_return = (terminal_wealth / self.x0) - 1
        return expected_return / (np.sqrt(terminal_wealth / self.x0 - 1))
    
    def calculate_theoretical_sharpe(self):
        """Calculate theoretical optimal Sharpe ratio"""
        optimal_theta1 = np.linalg.inv(self.sigma_sigma_T) @ (self.mu - self.r)
        k = (self.mu - self.r).T @ np.linalg.inv(self.sigma_sigma_T) @ (self.mu - self.r) * self.T
        return np.sqrt(np.exp(k) - 1)


