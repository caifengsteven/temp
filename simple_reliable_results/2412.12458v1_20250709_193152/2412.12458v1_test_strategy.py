        """
        Fit an Ornstein-Uhlenbeck model to the spread.
        
        Returns:
        --------
        dict: Parameters of the OU model (mu, lambda, sigma)
        """
        # Create lagged spread
        lagged_spread = spread[:-1]
        current_spread = spread[1:]
        
        # Fit linear regression: S_{t+1} = a * S_t + b + epsilon
        X = np.array(lagged_spread).reshape(-1, 1)
        y = np.array(current_spread)
        model = OLS(y, np.hstack([X, np.ones_like(X)]))
        results = model.fit()
        
