class Autoencoder(nn.Module):
    def __init__(self, input_dim, hidden_dim):
        super(Autoencoder, self).__init__()
        self.encoder = nn.Sequential(
            nn.Linear(input_dim, hidden_dim),
            nn.ReLU()
        )
        self.decoder = nn.Sequential(
            nn.Linear(hidden_dim, input_dim),
            nn.Sigmoid()  # Using sigmoid to match input range
        )
    
    def forward(self, x):
        z = self.encoder(x)
        x_hat = self.decoder(z)
        return x_hat
    
    def encode(self, x):
        return self.encoder(x)

def huber_loss(y_true, y_pred, delta=1.0):
    residual = np.abs(y_true - y_pred)
    quadratic_loss = 0.5 * (residual ** 2)
    linear_loss = delta * (residual - 0.5 * delta)
    return np.where(residual < delta, quadratic_loss, linear_loss).mean()

def generate_dataset(n_samples, input_dim, noise_level, signal_pattern='linear'):
    """
    Generate synthetic data with controllable signal-to-noise ratio
    
    Parameters:
    - n_samples: number of samples to generate
    - input_dim: dimensionality of input embeddings
    - noise_level: level of noise (higher means noisier data)
    - signal_pattern: 'linear' or 'complex' pattern in the data
    
    Returns:
    - X: simulated LLM embeddings
    - y: target values
    - true_signal_dims: which dimensions actually contain signal
    """
    # Generate random embeddings (simulating LLM output)
    X = np.random.rand(n_samples, input_dim)
    
    # Define which dimensions contribute to the signal
    if signal_pattern == 'linear':
        # For linear pattern, only a few dimensions matter
        true_signal_dims = np.random.choice(input_dim, size=min(8, input_dim), replace=False)
        weights = np.zeros(input_dim)
        weights[true_signal_dims] = np.random.uniform(-1, 1, size=len(true_signal_dims))
        
        # Generate target with controllable noise
        y_signal = X @ weights
        y_noise = np.random.normal(0, noise_level, size=n_samples)
        y = y_signal + y_noise
        
    elif signal_pattern == 'complex':
        # For complex pattern, more dimensions interact in non-linear ways
        true_signal_dims = np.random.choice(input_dim, size=min(32, input_dim), replace=False)
        
        # Non-linear interactions between features
        y_signal = np.sin(X[:, true_signal_dims[:4]].sum(axis=1)) + \
                  np.exp(X[:, true_signal_dims[4:8]].mean(axis=1)) + \
                  np.power(X[:, true_signal_dims[8:12]].prod(axis=1), 0.5)
        
        # Add noise
        y_noise = np.random.normal(0, noise_level, size=n_samples)
        y = y_signal + y_noise
    
    # Standardize target
    y = (y - y.mean()) / y.std()
    
    return X, y, true_signal_dims

def train_autoencoder(X_train, hidden_dim, epochs=100, batch_size=64, lr=1e-3, patience=5):
    """Train an autoencoder to compress embeddings"""
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    input_dim = X_train.shape[1]
    
    # Convert to PyTorch tensors
    X_tensor = torch.FloatTensor(X_train).to(device)
    
    # Create dataloader
    dataset = TensorDataset(X_tensor, X_tensor)
    dataloader = DataLoader(dataset, batch_size=batch_size, shuffle=True)
    
    # Initialize model
    model = Autoencoder(input_dim, hidden_dim).to(device)
    optimizer = optim.Adam(model.parameters(), lr=lr)
    criterion = nn.MSELoss()
    
    # Train with early stopping
    best_loss = float('inf')
    patience_counter = 0
    
    for epoch in range(epochs):
        model.train()
        epoch_loss = 0
        
        for x_batch, _ in dataloader:
            optimizer.zero_grad()
            x_hat = model(x_batch)
            loss = criterion(x_hat, x_batch)
            loss.backward()
            optimizer.step()
            
            epoch_loss += loss.item()
        
        avg_loss = epoch_loss / len(dataloader)
        
        # Early stopping
        if avg_loss < best_loss:
            best_loss = avg_loss
            patience_counter = 0
        else:
            patience_counter += 1
            if patience_counter >= patience:
                print(f"Early stopping at epoch {epoch}")
                break
    
    return model

def get_compressed_embeddings(model, X):
    """Get compressed embeddings from autoencoder"""
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    X_tensor = torch.FloatTensor(X).to(device)
    model.eval()
    with torch.no_grad():
        compressed = model.encode(X_tensor).cpu().numpy()
    return compressed

def evaluate_model(X_train, X_test, y_train, y_test):
    """Evaluate random forest on given data"""
    # Train random forest
    rf = RandomForestRegressor(n_estimators=100, random_state=42)
    rf.fit(X_train, y_train)
    
    # Predict and evaluate
    y_pred = rf.predict(X_test)
    mse = mean_squared_error(y_test, y_pred)
    huber = huber_loss(y_test, y_pred)
    
    return huber, mse

