        self.steps = int(T / dt)
        self.times = np.linspace(0, T, self.steps + 1)
        
        # Generate Brownian motion path
        self.dW = np.random.normal(0, np.sqrt(self.dt), self.steps)
        self.W = np.cumsum(np.insert(self.dW, 0, 0))
        
