    def state_dependent_policy(R, wealth_level, base_rho=4.0):
        """Compute policy with state-dependent risk aversion"""
        # Risk aversion increases as wealth increases (wealth-dependent)
        rho_w = base_rho / wealth_level
        
        # Compute myopic component with state-dependent risk aversion
        myopic = gamma * np.power(R, 1-2*p) / (rho_w * np.power(R, -0.5))
        
        # Compute hedging component with state-dependent risk aversion
        hedging = -corr * gamma * (T - base_model.times) * np.power(R, 1-p) / (rho_w * np.power(R, -0.5))
        
        return myopic + hedging
    
    # Simulate wealth trajectory with standard policy
    W_standard = np.ones(base_model.n_steps + 1)
