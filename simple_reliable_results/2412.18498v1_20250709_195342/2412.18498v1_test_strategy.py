class CKLSModel:
    """CKLS model for stochastic volatility"""
    
    def __init__(self, a, b, sigma, p, r0, corr, gamma, rho, T, dt):
        """
        Parameters:
        a, b - CKLS drift parameters
        sigma - CKLS diffusion parameter
        p - CKLS exponent parameter
        r0 - initial value of stochastic factor
        corr - correlation between Brownian motions
        gamma - risk-return trade-off parameter
        rho - risk aversion coefficient
        T - investment horizon
        dt - time step
        """
        self.a = a
        self.b = b
        self.sigma = sigma
        self.p = p
        self.r0 = r0
        self.corr = corr
        self.gamma = gamma
        self.rho = rho
        self.T = T
        self.dt = dt
        self.n_steps = int(T / dt)
        self.times = np.linspace(0, T, self.n_steps + 1)
        
    def simulate_paths(self, n_paths=1):
        """Simulate paths for the CKLS model and stock price"""
        np.random.seed(42)  # For reproducibility
        
        # Initialize arrays
        R = np.zeros((n_paths, self.n_steps + 1))
        S = np.zeros((n_paths, self.n_steps + 1))
        R[:, 0] = self.r0
        S[:, 0] = 1.0
        
        # Generate correlated Brownian motions
        dW1 = np.random.normal(0, np.sqrt(self.dt), (n_paths, self.n_steps))
        dW2 = self.corr * dW1 + np.sqrt(1 - self.corr**2) * np.random.normal(0, np.sqrt(self.dt), (n_paths, self.n_steps))
        
        # Simulate paths
        for i in range(self.n_steps):
            # CKLS process for R
            drift_R = (self.a - self.b * R[:, i]) * self.dt
            diffusion_R = self.sigma * np.power(R[:, i], self.p) * dW2[:, i]
            R[:, i+1] = R[:, i] + drift_R + diffusion_R
            
            # Ensure R remains positive (important for p > 0)
            R[:, i+1] = np.maximum(R[:, i+1], 1e-6)
            
            # Stock price process
            mu_S = 0.03 + self.gamma * np.power(R[:, i], 1-2*self.p)
            drift_S = mu_S * self.dt
            diffusion_S = np.power(R[:, i], -0.5) * dW1[:, i]
            S[:, i+1] = S[:, i] * (1 + drift_S + diffusion_S)
        
        return R, S

    def compute_myopic_strategy(self, R):
        """Compute the myopic component of the equilibrium MV policy"""
        # From equation (3.8) in the paper
        gamma_t = self.gamma * np.ones_like(self.times)
        theta = (self.gamma / self.rho) * np.ones_like(R)
        return theta

    def compute_hedging_demand(self, R):
        """
        Approximate the hedging demand component using a simple model
        This is a simplified version as the full nonlocal BSDE solution would be complex
        """
        # Simple approximation for the hedging term in equation (3.11)
        hedging_demand = -self.corr * self.gamma * (self.T - self.times) * np.power(R, 1-self.p) / (self.rho * np.power(R, -0.5))
        return hedging_demand
    
    def compute_equilibrium_policy(self, R):
        """Compute the full equilibrium MV policy"""
        myopic = self.compute_myopic_strategy(R)
        hedging = self.compute_hedging_demand(R)
        return myopic + hedging

    def simulate_wealth(self, policy, R, S):
        """Simulate wealth process under a given policy"""
        W = np.ones(self.n_steps + 1)
        
        for i in range(self.n_steps):
            # Extract excess return and volatility
            excess_return = self.gamma * np.power(R[i], 1-2*self.p)
            vol = np.power(R[i], -0.5)
            
            # Compute wealth change
            drift_W = policy[i] * excess_return * self.dt
            diffusion_W = policy[i] * vol * np.random.normal(0, np.sqrt(self.dt))
            W[i+1] = W[i] * (1 + drift_W + diffusion_W)
        
        return W


