def generate_synthetic_data(n_days=1000, n_markets=10, seed=42):
    """Generate synthetic price data with realistic properties"""
    np.random.seed(seed)
    
    # Generate dates
    start_date = datetime(2020, 1, 1)
    dates = [start_date + timedelta(days=i) for i in range(n_days)]
    
    # Create market correlation structure
    correlation_matrix = np.eye(n_markets)
    for i in range(n_markets):
        for j in range(i+1, n_markets):
            # Some markets are more correlated than others
            if i % 3 == j % 3:  # Markets in the same sector
                correlation_matrix[i, j] = correlation_matrix[j, i] = 0.7
            else:
                correlation_matrix[i, j] = correlation_matrix[j, i] = 0.3
    
    # Generate correlated returns
    daily_vol = 0.01 * np.ones(n_markets)
    cov_matrix = np.outer(daily_vol, daily_vol) * correlation_matrix
    returns = np.random.multivariate_normal(
        mean=0.0005 * np.ones(n_markets),  # Small positive drift
        cov=cov_matrix,
        size=n_days
    )
    
    # Add autocorrelation/trend to returns (AR(1) process)
    for m in range(n_markets):
        ar_param = 0.05 + 0.03 * np.random.rand()  # Random AR parameter between 0.05 and 0.08
        for t in range(1, n_days):
            returns[t, m] += ar_param * returns[t-1, m]
    
    # Add lead-lag relationships between markets
    for lead_market in range(0, n_markets, 3):  # Every third market is a leader
        for lag_market in range(lead_market + 1, min(lead_market + 3, n_markets)):
            lag_strength = 0.2 + 0.1 * np.random.rand()  # Random lag strength between 0.2 and 0.3
            for t in range(5, n_days):  # 5-day lag effect
                returns[t, lag_market] += lag_strength * returns[t-5, lead_market]
    
    # Convert returns to prices
    prices = 100 * np.cumprod(1 + returns, axis=0)
    
    # Create DataFrames
    market_names = [f"Market_{i}" for i in range(n_markets)]
    price_df = pd.DataFrame(prices, index=dates, columns=market_names)
    returns_df = pd.DataFrame(returns, index=dates, columns=market_names)
    
    return price_df, returns_df


