class PortfolioOptimizer:
    def __init__(self, data):
        """Initialize optimizer with simulated data"""
        self.data = data
        
    def _calculate_optimal_weights_2asset(self, stock_vol, bond_vol, correlation):
        """Calculate optimal weights for 2-asset portfolio using minimum variance"""
        numerator = bond_vol**2 - correlation * stock_vol * bond_vol
        denominator = stock_vol**2 + bond_vol**2 - 2 * correlation * stock_vol * bond_vol
        
        # Ensure weight is between 0 and 1
        w_stock = np.clip(numerator / denominator, 0, 1)
        w_bond = 1 - w_stock
        
        return w_stock, w_bond
    
    def run_portfolio_simulation(self, correlation_model, version='v3', 
                                 rebalance_freq='MS', window=60):
        """
        Run portfolio simulation using the specified correlation model
        
        Parameters:
        - correlation_model: str, which model to use ('gpt_original', 'bert_original', etc.)
        - version: str, which version of the model (v1, v2, v3)
        - rebalance_freq: str, how often to rebalance
        - window: int, lookback window for volatility calculation
        
        Returns:
        - portfolio values over time
        """
        # Create daily date range for portfolio
        daily_dates = pd.date_range(start=self.data.start_date, end=self.data.end_date)
        
        # Initialize portfolio
        portfolio_value = pd.Series(index=daily_dates, dtype=float)
        portfolio_value.iloc[0] = 1000.0  # Start with $1000
        
        # Initialize weights
        w_stock = 0.5
        w_bond = 0.5
        
        # For each rebalance date
        rebalance_dates = pd.date_range(start=self.data.start_date, end=self.data.end_date, freq=rebalance_freq)
        
        for i, rebalance_date in enumerate(rebalance_dates):
            if i == 0:
                continue  # Skip first date, use initial weights
                
