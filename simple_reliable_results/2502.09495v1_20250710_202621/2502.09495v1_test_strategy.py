class DevelopmentFinanceAnalysis:
    """Implements the ML-based clustering approach for development finance projects"""
    
    def __init__(self, data, text_column='description'):
        self.data = data
        self.text_column = text_column
        self.embeddings = None
        self.reduced_embeddings = None
        self.clusters = None
        self.cluster_labels = None
        self.model = None
        
    def generate_embeddings(self):
        """Generate embeddings using a sentence transformer model"""
        print("Generating embeddings...")
        
        # Load a smaller multilingual model for the test
        self.model = SentenceTransformer('paraphrase-MiniLM-L3-v2')
        
        # Generate embeddings
        self.embeddings = self.model.encode(
            self.data[self.text_column].tolist(), 
            show_progress_bar=True
        )
        
        print(f"Embeddings shape: {self.embeddings.shape}")
        return self.embeddings
    
    def reduce_dimensions(self, n_components=12):
        """Reduce dimensions using UMAP"""
        print("Reducing dimensions...")
        
        reducer = umap.UMAP(
            n_components=n_components,
            metric='cosine',
            n_neighbors=15,
            min_dist=0.1,
            random_state=42
        )
        
        self.reduced_embeddings = reducer.fit_transform(self.embeddings)
        print(f"Reduced embeddings shape: {self.reduced_embeddings.shape}")
        return self.reduced_embeddings
    
    def cluster_projects(self, min_cluster_size=15):
        """Cluster projects using HDBSCAN"""
        print("Clustering projects...")
        
        # Apply HDBSCAN clustering
        clusterer = HDBSCAN(
            min_cluster_size=min_cluster_size,
            min_samples=5,
            metric='euclidean',
            cluster_selection_epsilon=0.2,
            prediction_data=True
        )
        
        self.clusters = clusterer.fit(self.reduced_embeddings)
        
        # Add clusters to data
        self.data['cluster'] = self.clusters.labels_
        
        # Count clusters (excluding noise points with label -1)
        num_clusters = len(set(self.clusters.labels_)) - (1 if -1 in self.clusters.labels_ else 0)
        print(f"Number of clusters: {num_clusters}")
        
        # Count outliers
        num_outliers = sum(1 for label in self.clusters.labels_ if label == -1)
        print(f"Number of outliers: {num_outliers} ({num_outliers/len(self.data)*100:.2f}%)")
        
        return self.clusters
    
    def evaluate_clustering(self):
        """Evaluate clustering quality using silhouette, Davies-Bouldin, and Calinski-Harabasz scores"""
        # Filter out noise points for evaluation
        mask = self.clusters.labels_ != -1
        if sum(mask) <= 1:
            print("Not enough clustered points to evaluate")
            return None
        
        embeddings_no_noise = self.reduced_embeddings[mask]
        labels_no_noise = self.clusters.labels_[mask]
        
        # Calculate silhouette score
        if len(set(labels_no_noise)) > 1:
            silhouette = silhouette_score(embeddings_no_noise, labels_no_noise)
            print(f"Silhouette Score: {silhouette:.2f}")
        else:
            silhouette = None
            print("Silhouette Score: N/A (requires at least 2 clusters)")
        
        # Calculate Davies-Bouldin score
        if len(set(labels_no_noise)) > 1:
            davies_bouldin = davies_bouldin_score(embeddings_no_noise, labels_no_noise)
            print(f"Davies-Bouldin Score: {davies_bouldin:.2f}")
        else:
            davies_bouldin = None
            print("Davies-Bouldin Score: N/A (requires at least 2 clusters)")
        
        # Calculate Calinski-Harabasz score
        if len(set(labels_no_noise)) > 1:
            calinski_harabasz = calinski_harabasz_score(embeddings_no_noise, labels_no_noise)
            print(f"Calinski-Harabasz Score: {calinski_harabasz:.2f}")
        else:
            calinski_harabasz = None
            print("Calinski-Harabasz Score: N/A (requires at least 2 clusters)")
        
        return {
            'silhouette': silhouette,
            'davies_bouldin': davies_bouldin,
            'calinski_harabasz': calinski_harabasz
        }
    
    def generate_cluster_labels(self):
        """Generate labels for clusters using c-TF-IDF"""
        print("Generating cluster labels...")
        
        # Create documents per cluster
        documents_per_cluster = {}
        for cluster_id in set(self.clusters.labels_):
            if cluster_id != -1:  # Skip noise cluster
                mask = self.data['cluster'] == cluster_id
                documents_per_cluster[cluster_id] = ' '.join(self.data[mask][self.text_column])
        
        # Vectorize using TF-IDF
        vectorizer = TfidfVectorizer(
            min_df=2, max_df=0.95,
            stop_words='english',
            ngram_range=(1, 2)
        )
        
        # Check if we have any clusters
        if not documents_per_cluster:
            print("No clusters found to label")
            return {}
        
        # Create cluster labels dictionary
        cluster_docs = [documents_per_cluster[i] for i in sorted(documents_per_cluster.keys())]
        X = vectorizer.fit_transform(cluster_docs)
        
        # Get feature names
        feature_names = vectorizer.get_feature_names_out()
        
        # For each cluster, find the top terms
        self.cluster_labels = {}
        for i, cluster_id in enumerate(sorted(documents_per_cluster.keys())):
            # Get the top 10 terms for this cluster by TF-IDF score
            indices = X[i].toarray()[0].argsort()[-10:][::-1]
            top_terms = [feature_names[j] for j in indices]
            
            # Create a label based on the top terms
            self.cluster_labels[cluster_id] = ' - '.join(top_terms[:3])
        
        # Add labels to the dataframe
        self.data['cluster_label'] = self.data['cluster'].map(
            lambda x: self.cluster_labels.get(x, 'Outlier') if x != -1 else 'Outlier'
        )
        
        return self.cluster_labels
    
    def visualize_clusters(self):
        """Visualize clusters using t-SNE for a 2D representation"""
        print("Visualizing clusters...")
        
        # Apply t-SNE for visualization
        tsne = TSNE(n_components=2, random_state=42)
