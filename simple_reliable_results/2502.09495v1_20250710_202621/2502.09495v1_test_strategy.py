        # Create a DataFrame for plotting
        viz_df = pd.DataFrame({
            'x': embeddings_2d[:, 0],
            'y': embeddings_2d[:, 1],
            'cluster': self.data['cluster'],
            'label': self.data['cluster'].map(lambda x: f"Cluster {x}" if x != -1 else "Outliers")
        })
        
        # Plot
        plt.figure(figsize=(12, 10))
        
        # Plot outliers first
        outliers = viz_df[viz_df['cluster'] == -1]
        plt.scatter(outliers['x'], outliers['y'], c='lightgray', s=5, alpha=0.5, label='Outliers')
        
        # Plot clusters
        clusters = viz_df[viz_df['cluster'] != -1]
        
        # Limit to 10 clusters for better visualization
        unique_clusters = sorted(clusters['cluster'].unique())
        if len(unique_clusters) > 10:
            selected_clusters = unique_clusters[:10]
