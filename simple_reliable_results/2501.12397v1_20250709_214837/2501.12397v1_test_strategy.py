@dataclass
class OptionParams:
    """Parameters for option pricing and simulation"""
    S0: float = 100.0                # Initial underlying price
    V0: float = 0.0392               # Initial volatility
    kappa: float = 0.1               # Mean reversion rate
    theta: float = 0.3156            # Long-term mean level
    sigma: float = 0.0331            # Volatility of volatility
    rho: float = -0.681              # Correlation coefficient
    H: float = 0.1                   # Hurst exponent
    T: int = 63                      # Time horizon in days
    dt: float = 1/DAYS_IN_YEAR       # Time step


@dataclass
class IronCondor:
    """Iron Condor portfolio structure"""
    k1: float  # Long put strike
    k2: float  # Short put strike
    k3: float  # Short call strike
    k4: float  # Long call strike
    expiry: int  # Expiry in days
    
    @property
    def moneyness(self) -> float:
        """Calculate x: relative strike position to current price"""
        return abs(self.k2 - 100.0) / 100.0
    
    @property
    def span(self) -> float:
        """Calculate xΔ: distance between strikes"""
        return self.k2 - self.k1
    
    @property
    def asymmetry(self) -> float:
        """Calculate xα: imbalance between put and call spreads"""
        return (100.0 - self.k1) - (self.k4 - 100.0)
    
    def __str__(self):
        return (f"Iron Condor: k=[{self.k1}, {self.k2}, {self.k3}, {self.k4}], "
                f"x={self.moneyness:.2f}, xΔ={self.span:.2f}, xα={self.asymmetry:.2f}")


class BlackScholes:
    """Black-Scholes option pricing model for fast computation"""
    
    @staticmethod
    def d1(S, K, T, r, sigma):
        return (np.log(S/K) + (r + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
    
    @staticmethod
    def d2(S, K, T, r, sigma):
        return (np.log(S/K) + (r - 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
    
    @staticmethod
    def call_price(S, K, T, r, sigma):
        if T <= 0:
            return max(0, S - K)
        d1 = BlackScholes.d1(S, K, T, r, sigma)
        d2 = BlackScholes.d2(S, K, T, r, sigma)
        return S * norm.cdf(d1) - K * np.exp(-r * T) * norm.cdf(d2)
    
    @staticmethod
    def put_price(S, K, T, r, sigma):
        if T <= 0:
            return max(0, K - S)
        d1 = BlackScholes.d1(S, K, T, r, sigma)
        d2 = BlackScholes.d2(S, K, T, r, sigma)
        return K * np.exp(-r * T) * norm.cdf(-d2) - S * norm.cdf(-d1)


class SimpleRoughHeston:
    """Simplified Rough Heston model for simulation"""
    
    def __init__(self, params: OptionParams):
        self.params = params
        
    def simulate_paths(self, n_paths: int = 1000) -> np.ndarray:
        """
        Simulate price paths using a simplified approximation of the Rough Heston model
        Returns array of shape (n_paths, T+1)
        """
        # Initialize paths
        S = np.zeros((n_paths, self.params.T + 1))
        S[:, 0] = self.params.S0
        
        # Create constant volatility with term structure to approximate rough vol behavior
        # This is a significant simplification of the true Rough Heston model
        time_grid = np.arange(self.params.T + 1) * self.params.dt
        vol_term_structure = self.params.V0 * np.exp(-0.2 * time_grid) * (1 + 0.1 * np.sqrt(time_grid))
        
        # Generate correlated random variables
        Z1 = np.random.normal(0, 1, (n_paths, self.params.T))
        Z2 = self.params.rho * Z1 + np.sqrt(1 - self.params.rho**2) * np.random.normal(0, 1, (n_paths, self.params.T))
        
        # Simulate price paths
        for t in range(self.params.T):
            vol = vol_term_structure[t] * np.exp(0.2 * Z2[:, t])
            S[:, t+1] = S[:, t] * np.exp((RISK_FREE_RATE - 0.5 * vol**2) * self.params.dt + vol * np.sqrt(self.params.dt) * Z1[:, t])
            
        return S


class IronCondorAnalyzer:
    """Analyze Iron Condor portfolio performance"""
    
    def __init__(self, params: OptionParams):
        self.params = params
        self.model = SimpleRoughHeston(params)
        
    def calculate_portfolio_value(self, ic: IronCondor, S: float, t: int) -> float:
        """Calculate Iron Condor portfolio value at a given time and price"""
        days_to_expiry = ic.expiry - t
        T_years = days_to_expiry / DAYS_IN_YEAR
        
        # Use current implied volatility (simplified)
        impl_vol = self.params.V0 * (0.8 + 0.4 * abs(S / 100.0 - 1))
        
        # Calculate option prices
        long_put = BlackScholes.put_price(S, ic.k1, T_years, RISK_FREE_RATE, impl_vol)
        short_put = -BlackScholes.put_price(S, ic.k2, T_years, RISK_FREE_RATE, impl_vol)
        short_call = -BlackScholes.call_price(S, ic.k3, T_years, RISK_FREE_RATE, impl_vol)
        long_call = BlackScholes.call_price(S, ic.k4, T_years, RISK_FREE_RATE, impl_vol)
        
        # Sum up the portfolio value
        return long_put + short_put + short_call + long_call
    
    def calculate_initial_premium(self, ic: IronCondor) -> float:
        """Calculate initial premium received for Iron Condor"""
        return -self.calculate_portfolio_value(ic, self.params.S0, 0)
    
    def simulate_portfolio(self, ic: IronCondor, n_paths: int = 1000) -> pd.DataFrame:
        """Simulate Iron Condor portfolio performance"""
        # Simulate price paths
        price_paths = self.model.simulate_paths(n_paths)
        
        # Calculate portfolio values for each path and time
        portfolio_values = np.zeros_like(price_paths)
        initial_premium = self.calculate_initial_premium(ic)
        
        for path in range(n_paths):
            for t in range(self.params.T + 1):
                portfolio_value = self.calculate_portfolio_value(ic, price_paths[path, t], t)
                portfolio_values[path, t] = initial_premium + portfolio_value
        
        # Calculate normalized P&L
        normalized_pnl = portfolio_values / initial_premium
        
        # Classify paths based on final price movement
        final_returns = price_paths[:, -1] / price_paths[:, 0]
        bullish = final_returns > 1.1
        bearish = final_returns < 0.9
        sideways = ~(bullish | bearish)
        
        results = {
            'price_paths': price_paths,
            'portfolio_values': portfolio_values,
            'normalized_pnl': normalized_pnl,
            'initial_premium': initial_premium,
            'bullish_indices': np.where(bullish)[0],
            'bearish_indices': np.where(bearish)[0],
            'sideways_indices': np.where(sideways)[0]
        }
        
        return results
    
    def analyze_portfolio(self, ic: IronCondor, results: Dict, find_optimal_stop: bool = True) -> Dict:
        """Analyze portfolio performance metrics"""
        # Extract data
        normalized_pnl = results['normalized_pnl']
        bullish_indices = results['bullish_indices']
        bearish_indices = results['bearish_indices']
        sideways_indices = results['sideways_indices']
        
        # Calculate metrics at expiration
        final_pnl = normalized_pnl[:, -1]
        success_rate_T = (final_pnl > 0).mean()
        
        # Calculate metrics for different market conditions
        if len(sideways_indices) > 0:
            pnl_sideways_T = final_pnl[sideways_indices].mean()
        else:
            pnl_sideways_T = np.nan
            
        if len(bullish_indices) > 0:
            risk_bullish_T = final_pnl[bullish_indices].mean()
        else:
            risk_bullish_T = np.nan
            
        if len(bearish_indices) > 0:
            risk_bearish_T = final_pnl[bearish_indices].mean()
        else:
            risk_bearish_T = np.nan
        
        # Find optimal stopping time if requested
        if find_optimal_stop:
            # Calculate expected P&L at each time step
            expected_pnl_over_time = normalized_pnl.mean(axis=0)
            optimal_stop_idx = np.argmax(expected_pnl_over_time)
            optimal_stop_day = optimal_stop_idx
            
            # Calculate metrics at optimal stopping time
            pnl_at_optimal_stop = normalized_pnl[:, optimal_stop_idx]
            success_rate_tau = (pnl_at_optimal_stop > 0).mean()
            
            if len(sideways_indices) > 0:
                pnl_sideways_tau = pnl_at_optimal_stop[sideways_indices].mean()
            else:
                pnl_sideways_tau = np.nan
                
            if len(bullish_indices) > 0:
                risk_bullish_tau = pnl_at_optimal_stop[bullish_indices].mean()
            else:
                risk_bullish_tau = np.nan
                
            if len(bearish_indices) > 0:
                risk_bearish_tau = pnl_at_optimal_stop[bearish_indices].mean()
            else:
                risk_bearish_tau = np.nan
        else:
            optimal_stop_day = self.params.T
            success_rate_tau = success_rate_T
            pnl_sideways_tau = pnl_sideways_T
            risk_bullish_tau = risk_bullish_T
            risk_bearish_tau = risk_bearish_T
            
        return {
            'pnl_T': final_pnl.mean(),
            'pnl_tau': normalized_pnl[:, optimal_stop_day].mean(),
            'success_rate_T': success_rate_T,
            'success_rate_tau': success_rate_tau,
            'pnl_sideways_T': pnl_sideways_T,
            'pnl_sideways_tau': pnl_sideways_tau,
            'risk_bullish_T': risk_bullish_T,
            'risk_bullish_tau': risk_bullish_tau,
            'risk_bearish_T': risk_bearish_T,
            'risk_bearish_tau': risk_bearish_tau,
            'optimal_stop_day': optimal_stop_day
        }


