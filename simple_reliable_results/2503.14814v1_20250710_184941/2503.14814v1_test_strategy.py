def compare_kernels(T=2.0):
    """Compare exponential and power-law kernels on the same data."""
    print("\n=== Comparing Kernel Performance ===")
    
    # Generate test data
    test_data = generate_test_data(T)
    
    # For a fair comparison, use the power-law data for both models
    buy_times = test_data['power_law']['buy_times']
    sell_times = test_data['power_law']['sell_times']
    
    # Create new models for fitting
    exp_model = BivariateExponentialHawkes(1.0, 1.0, 0.5, 0.5, 0.5, 0.5, 2.0, 2.0, 2.0, 2.0)
    pl_model = BivariatePowerLawHawkes(1.0, 1.0, 0.5, 0.5, 0.5, 0.5, 1.5, 1.5, 1.5, 1.5)
    
    try:
        # Fit both models to the same data
        print("Fitting exponential kernel model...")
        exp_params = exp_model.fit(buy_times, sell_times, T)
        print("Fitted exponential parameters:", exp_params)
        
        print("Fitting power-law kernel model...")
        pl_params = pl_model.fit(buy_times, sell_times, T)
        print("Fitted power-law parameters:", pl_params)
        
        # Calculate log-likelihood for each model
        exp_ll = exp_model.log_likelihood(buy_times, sell_times, T)
        pl_ll = pl_model.log_likelihood(buy_times, sell_times, T)
        
        print(f"Exponential kernel log-likelihood: {exp_ll:.2f}")
        print(f"Power-law kernel log-likelihood: {pl_ll:.2f}")
        
        # Plot intensity functions
        plot_intensity_functions(exp_model, buy_times, sell_times, T, "Exponential", " (Fitted)")
        plot_intensity_functions(pl_model, buy_times, sell_times, T, "Power-Law", " (Fitted)")
        
        # Return the better model based on log-likelihood
        if pl_ll > exp_ll:
            print("Power-law kernel provides a better fit to the data.")
            return pl_model
        else:
            print("Exponential kernel provides a better fit to the data.")
            return exp_model
            
    except Exception as e:
        print(f"Error during model fitting: {e}")
        # Return the power-law model by default
        return test_data['power_law']['model']


