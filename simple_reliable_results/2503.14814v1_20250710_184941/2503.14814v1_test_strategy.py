class ClusteringBasedLiquidityStrategy:
    """Trading strategy based on clustering behavior in Hawkes processes."""
    
    def __init__(self, hawkes_model, spread=0.01, risk_multiplier=1.0, 
                 min_intensity_threshold=2.0, stop_loss_pct=0.005):
        self.hawkes_model = hawkes_model
        self.spread = spread  # Bid-ask spread
        self.risk_multiplier = risk_multiplier  # Scales order sizes based on intensity
        self.min_intensity_threshold = min_intensity_threshold  # Minimum intensity to trigger order
        self.stop_loss_pct = stop_loss_pct  # Stop loss percentage
        
        # Performance tracking
        self.positions = []  # (entry_time, side, price, size, exit_time, exit_price)
        self.cash = 100000.0  # Initial capital
        self.inventory = 0  # Current position
        self.total_trades = 0
        self.winning_trades = 0
        self.entry_prices = {}  # Track entry prices for stop loss
    
    def calculate_order_size(self, intensity):
        """Calculate order size based on intensity."""
        if intensity < self.min_intensity_threshold:
            return 0
        
        # Base size scaled by intensity and risk multiplier
        base_size = 100
        size = base_size * (intensity / self.min_intensity_threshold) * self.risk_multiplier
        
        # Cap size to prevent excessive risk
        max_size = 1000
        return min(int(size), max_size)
    
    def execute_strategy(self, current_time, current_price, time_horizon=0.1):
        """
        Execute trading strategy based on current market conditions.
        
        Args:
            current_time: Current simulation time
            current_price: Current mid-price
            time_horizon: Time horizon to look ahead for clustering
        
        Returns:
            orders: List of orders to execute (time, side, price, size)
        """
        orders = []
        
        # Calculate current intensities
        buy_intensity = self.hawkes_model.intensity_buy(current_time)
        sell_intensity = self.hawkes_model.intensity_sell(current_time)
        
        # Check stop loss for existing positions
        if self.inventory > 0:
            entry_price = self.entry_prices.get("long")
            if entry_price and current_price < entry_price * (1 - self.stop_loss_pct):
                # Stop loss triggered for long position
                orders.append((current_time, "sell", current_price, self.inventory))
                self.positions.append((self.entry_prices.get("long_time"), "long", 
                                      entry_price, self.inventory, 
                                      current_time, current_price))
                self.cash += current_price * self.inventory
                self.inventory = 0
                self.entry_prices.pop("long", None)
                self.entry_prices.pop("long_time", None)
                self.total_trades += 1
        
        elif self.inventory < 0:
            entry_price = self.entry_prices.get("short")
            if entry_price and current_price > entry_price * (1 + self.stop_loss_pct):
                # Stop loss triggered for short position
                orders.append((current_time, "buy", current_price, -self.inventory))
                self.positions.append((self.entry_prices.get("short_time"), "short", 
                                      entry_price, -self.inventory, 
                                      current_time, current_price))
                self.cash -= current_price * (-self.inventory)
                self.inventory = 0
                self.entry_prices.pop("short", None)
                self.entry_prices.pop("short_time", None)
                self.total_trades += 1
        
        # Detect buy clusters
        if buy_intensity > self.min_intensity_threshold and buy_intensity > 1.5 * sell_intensity:
            # Buy cluster detected - place sell orders at higher price
            if self.inventory <= 0:  # Only go long if not already long
                size = self.calculate_order_size(buy_intensity)
                if size > 0:
                    # Place buy order at slightly lower price (we're providing liquidity)
                    bid_price = current_price - self.spread/2
                    orders.append((current_time, "buy", bid_price, size))
                    self.cash -= bid_price * size
                    self.inventory += size
                    self.entry_prices["long"] = bid_price
                    self.entry_prices["long_time"] = current_time
        
        # Detect sell clusters
        if sell_intensity > self.min_intensity_threshold and sell_intensity > 1.5 * buy_intensity:
            # Sell cluster detected - place buy orders at lower price
            if self.inventory >= 0:  # Only go short if not already short
                size = self.calculate_order_size(sell_intensity)
                if size > 0:
                    # Place sell order at slightly higher price (we're providing liquidity)
                    ask_price = current_price + self.spread/2
                    orders.append((current_time, "sell", ask_price, size))
                    self.cash += ask_price * size
                    self.inventory -= size
                    self.entry_prices["short"] = ask_price
                    self.entry_prices["short_time"] = current_time
        
        # Adjust positions based on intensity decay
        if (0 < buy_intensity < self.min_intensity_threshold and 
            0 < sell_intensity < self.min_intensity_threshold):
            # Low intensity period - reduce exposure
            if self.inventory > 0:
                # Exit long position
                orders.append((current_time, "sell", current_price, self.inventory))
                self.positions.append((self.entry_prices.get("long_time"), "long", 
                                      self.entry_prices.get("long"), self.inventory, 
                                      current_time, current_price))
                self.cash += current_price * self.inventory
                self.total_trades += 1
                self.winning_trades += (current_price > self.entry_prices.get("long", 0))
                self.inventory = 0
                self.entry_prices.pop("long", None)
                self.entry_prices.pop("long_time", None)
            
            elif self.inventory < 0:
                # Exit short position
                orders.append((current_time, "buy", current_price, -self.inventory))
                self.positions.append((self.entry_prices.get("short_time"), "short", 
                                      self.entry_prices.get("short"), -self.inventory, 
                                      current_time, current_price))
                self.cash -= current_price * (-self.inventory)
                self.total_trades += 1
                self.winning_trades += (current_price < self.entry_prices.get("short", float('inf')))
                self.inventory = 0
                self.entry_prices.pop("short", None)
                self.entry_prices.pop("short_time", None)
        
        return orders
    
    def generate_price_path(self, T, dt, volatility=0.01, initial_price=100):
        """Generate a simple price path with random walk."""
        times = np.arange(0, T, dt)
        prices = [initial_price]
        
        for i in range(1, len(times)):
            # Random walk with drift based on order imbalance
            t = times[i]
            buy_intensity = self.hawkes_model.intensity_buy(t)
            sell_intensity = self.hawkes_model.intensity_sell(t)
            
            # Order imbalance factor (-1 to 1)
            imbalance = (buy_intensity - sell_intensity) / (buy_intensity + sell_intensity + 1e-10)
            
            # Price change with imbalance influence
            price_change = np.random.normal(imbalance * 0.0001, volatility * np.sqrt(dt))
            new_price = prices[-1] * (1 + price_change)
            prices.append(new_price)
        
        return times, prices
    
