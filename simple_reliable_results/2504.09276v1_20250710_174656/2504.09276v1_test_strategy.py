class FractionalBrownianMotion:
    """Simulate fractional Brownian motion with Hurst parameter H."""
    
    def __init__(self, H, n_steps=1024):
        self.H = H
        self.n_steps = n_steps
        self.dt = 1.0 / n_steps
        
    def simulate(self):
        """Davies-Harte method for simulating fBm."""
        n = self.n_steps
        # Create the covariance matrix
        r = np.zeros(2 * n)
        r[0] = 1
        for k in range(1, n):
            r[k] = 0.5 * ((k+1)**(2*self.H) - 2*k**(2*self.H) + (k-1)**(2*self.H))
        
        r[n:2*n] = r[1:n][::-1]
        
        # Compute the eigenvalues
        lambda_k = np.fft.fft(r).real
        
        # Generate the process
        W = np.fft.fft(np.sqrt(lambda_k) * (norm.rvs(size=2*n) + 1j*norm.rvs(size=2*n))) / np.sqrt(2*n)
        W = W[:n].real
        
        # Scale by dt^H
        return np.cumsum(W) * self.dt**self.H
    
    def fractional_ou_process(self, x0=0, mu=0, rho=1):
        """Generate fractional Ornstein-Uhlenbeck process."""
        W_H = self.simulate()
        X_H = np.zeros_like(W_H)
        X_H[0] = x0
        
        # Solve the integral equation X_H_t = x0 + rho∫(mu - X_H_s)ds + W_H_t
        for i in range(1, len(W_H)):
            # Simple Euler scheme for the integral
            X_H[i] = X_H[i-1] + rho * (mu - X_H[i-1]) * self.dt + (W_H[i] - W_H[i-1])
            
        return X_H

def compute_integrated_variance(X, g=np.exp):
    """Compute integrated variance from X using function g."""
    n = len(X)
    g_X = g(X)
    
    # Trapezoidal rule for integration
