class LiquidityPool:
    def __init__(self, token_x: str, token_y: str, fee_tier: float, pool_type: str):
        self.token_x = token_x
        self.token_y = token_y
        self.fee_tier = fee_tier
        self.pool_type = pool_type
        self.name = f"{token_x}-{token_y}-{int(fee_tier*10000)}"
        self.current_price = 1.0  # Initial price ratio
        self.price_history = []
        
    def update_price(self, new_price: float):
        self.current_price = new_price
        self.price_history.append(new_price)
        
    def __str__(self):
        return f"{self.name} ({self.pool_type}, fee: {self.fee_tier*100}%)"


class LiquidityPosition:
    def __init__(self, pool: LiquidityPool, position_size: float, 
                 lower_price: float, upper_price: float, deposit_time):
        self.pool = pool
        self.position_size = position_size
        self.lower_price = lower_price
        self.upper_price = upper_price
        self.range_size = (upper_price - lower_price) / lower_price
        self.deposit_time = deposit_time
        self.withdraw_time = None
        self.initial_price = pool.current_price
        self.rewards = 0.0
        self.impermanent_loss = 0.0
        self.is_active = True
        
    def withdraw(self, time):
        if not self.is_active:
            return 0
        
        self.withdraw_time = time
        self.duration = (self.withdraw_time - self.deposit_time).total_seconds() / (24 * 3600)  # in days
        self.is_active = False
        
        # Calculate final IL and returns
        self.calculate_impermanent_loss()
        return self.get_returns()
    
    def calculate_impermanent_loss(self):
        """Calculate impermanent loss based on price change"""
        if not self.is_active:
            return self.impermanent_loss
        
        current_price = self.pool.current_price
        d = current_price / self.initial_price  # price ratio
        
        # Apply equation 6 from the paper for concentrated liquidity IL
        if d < (self.lower_price / self.initial_price):
            # Case where price is below the range
            term1 = d * math.sqrt(self.initial_price / self.lower_price) - 1
            term2 = -1 + math.sqrt(self.lower_price / self.initial_price * d)
            term3 = 1 - math.sqrt(self.initial_price / self.upper_price)
            term4 = 1 - math.sqrt(self.lower_price / self.initial_price)
            self.impermanent_loss = term1 / (term2 * (1 - math.sqrt(self.initial_price / self.upper_price)) + 1 - math.sqrt(self.lower_price / self.initial_price))
            
        elif d > (self.upper_price / self.initial_price):
            # Case where price is above the range
            term1 = math.sqrt(self.upper_price / self.initial_price - d)
            term2 = 1 - math.sqrt(self.initial_price / self.upper_price)
            term3 = -1 * d
            term4 = 1 - math.sqrt(self.initial_price / self.upper_price)
            term5 = 1 - math.sqrt(self.lower_price / self.initial_price)
            self.impermanent_loss = term1 / (term2 * term3 * (1 - math.sqrt(self.initial_price / self.upper_price)) + 1 - math.sqrt(self.lower_price / self.initial_price))
            
        else:
            # Case where price is within the range (similar to Uniswap v2 formula)
            self.impermanent_loss = (2 * math.sqrt(d) / (1 + d)) - 1
            
        return self.impermanent_loss
    
    def calculate_rewards(self, trading_volume: float):
        """Calculate rewards based on trading volume and fee tier"""
        if not self.is_active:
            return self.rewards
            
        # Check if current price is within the position range
        if self.lower_price <= self.pool.current_price <= self.upper_price:
            # More rewards for narrower ranges due to concentrated liquidity
            concentration_factor = 1.0 / self.range_size
            # Cap the concentration factor to prevent unrealistic rewards
            concentration_factor = min(concentration_factor, 50.0)
            
            # Calculate rewards based on fee tier, volume, and concentration
            daily_reward = trading_volume * self.pool.fee_tier * concentration_factor * 0.01
            self.rewards += daily_reward
            
        return self.rewards
    
    def get_returns(self):
        """Calculate total returns (rewards - IL)"""
        return self.rewards + self.impermanent_loss * self.position_size
    
    def get_range_size(self):
        """Return the normalized range size"""
        return self.range_size
    
    def get_duration(self):
        """Return the position duration in days"""
        if self.withdraw_time:
            return self.duration
        else:
            # For active positions, calculate current duration
            current_duration = (datetime.now() - self.deposit_time).total_seconds() / (24 * 3600)
            return current_duration


def simulate_price_movement(initial_price: float, volatility: float, correlation: float, 
                           days: int, daily_steps: int = 1) -> List[float]:
    """Simulate price movement with a given volatility and trend"""
    steps = days * daily_steps
    
    # Generate correlated random walk
    if correlation > 0:
        # For positively correlated assets (like risky-risky pools)
        drift = 0.0001 * correlation  # Small positive drift for correlated assets
    elif correlation < 0:
        # For negatively correlated assets (like stable-risky pools)
        drift = 0  # No drift for uncorrelated assets
    else:
        # For stable-stable pools
        drift = 0
        volatility = volatility * 0.1  # Lower volatility for stablecoins
    
    # Generate price series
    price_series = [initial_price]
    for _ in range(steps):
        # Apply random walk with drift
        random_change = np.random.normal(drift, volatility)
        new_price = price_series[-1] * (1 + random_change)
        # Ensure price doesn't go negative
        new_price = max(new_price, 0.0001)
        price_series.append(new_price)
    
    return price_series


