def run_simulation(days: int = 700):
    """Run a simulation of liquidity provisioning strategies"""
    start_date = datetime(2022, 5, 1)  # As mentioned in the paper
    end_date = start_date + timedelta(days=days)
    
    # Create pools
    pools = create_pool_samples()
    
    results = []
    
    # For each pool, simulate positions and price movements
    for pool in pools:
        print(f"Simulating {pool}...")
        
        # Create positions with different strategies
        positions_data, volatility, correlation = create_position_strategies(pool, days, start_date)
        
        # Simulate price movements
        price_series = simulate_price_movement(
            initial_price=1.0,  # Start at price ratio 1.0
            volatility=volatility,
            correlation=correlation,
            days=days
        )
        
        # Run day-by-day simulation
        daily_trading_volume = 1000000  # Base daily volume in USD
        
        # Adjust volume based on pool type and fee tier
        if pool.pool_type == "stable-stable":
            daily_trading_volume *= 2.0  # Higher volume for stablecoin pairs
        elif pool.pool_type == "stable-risky":
            daily_trading_volume *= 1.5  # Medium volume
        
        # Higher fees usually mean lower volume
        volume_fee_multiplier = 1.0 - (pool.fee_tier * 50)  # Fee impact on volume
        volume_fee_multiplier = max(0.2, volume_fee_multiplier)  # Ensure it doesn't go too low
        daily_trading_volume *= volume_fee_multiplier
        
        # Process each day
        for day in range(days):
            current_date = start_date + timedelta(days=day)
            
            # Update pool price
            pool.update_price(price_series[day])
            
            # Daily trading volume with some randomness
            daily_volume = daily_trading_volume * random.uniform(0.7, 1.3)
            
            # Process active positions
            for position_data in positions_data:
                position = position_data["position"]
                deposit_day = position_data["deposit_day"]
                withdraw_day = position_data["withdraw_day"]
                
                # If this is deposit day, initialize the position
                if day == deposit_day:
                    position.initial_price = pool.current_price
                
                # If position is active
                if deposit_day <= day < withdraw_day:
                    # Calculate rewards for the day
                    position.calculate_rewards(daily_volume)
                    # Update IL based on current price
                    position.calculate_impermanent_loss()
                
                # If this is withdrawal day, close the position and record results
                if day == withdraw_day:
                    position.withdraw(current_date)
                    
                    # Record results
                    results.append({
                        "pool": pool.name,
                        "pool_type": pool.pool_type,
                        "fee_tier": pool.fee_tier,
                        "strategy": position_data["strategy"],
                        "position_size": position.position_size,
                        "range_size": position.range_size,
                        "duration": position.get_duration(),
                        "impermanent_loss": position.impermanent_loss,
                        "rewards": position.rewards,
                        "returns": position.get_returns(),
                        "returns_percent": 100 * position.get_returns() / position.position_size
                    })
    
    # Convert results to DataFrame
    results_df = pd.DataFrame(results)
    return results_df


