class PortfolioOptimization(MMCCAlgorithm):
    def __init__(self, num_periods, discount_factor=0.95):
        super().__init__(
            num_periods=num_periods,
            state_dim=2,  # Wealth and volatility
            control_dim=1,  # Portfolio allocation
            discount_factor=discount_factor
        )
        
    def state_transition(self, t, state, control, stochastic_params):
        # state = [wealth, volatility]
        # control = [portfolio_weight]
        wealth, volatility = state
        portfolio_weight = np.clip(control[0], 0, 1)  # Ensure between 0 and 1
        
        # Parameters
        rf = 0.02/self.T  # Risk-free rate per period
        risk_premium = 0.06/self.T  # Risk premium per period
        vol_mean = 0.2  # Mean volatility
        vol_persistence = 0.9  # Volatility persistence
        vol_volatility = 0.1  # Volatility of volatility
        
        # Stochastic returns
        stock_return = rf + risk_premium + volatility * np.random.normal(0, 1)
        portfolio_return = portfolio_weight * stock_return + (1 - portfolio_weight) * rf
        
        # Update wealth
        new_wealth = wealth * (1 + portfolio_return)
        
        # Update volatility (mean-reverting process)
        new_volatility = vol_persistence * volatility + (1 - vol_persistence) * vol_mean + vol_volatility * np.random.normal(0, 1)
        new_volatility = max(0.01, new_volatility)  # Ensure positive
        
        return np.array([new_wealth, new_volatility])
    
    def reward_function(self, t, state, control, next_state):
        # CRRA utility function
        wealth, _ = state
        new_wealth, _ = next_state
        
        risk_aversion = 2.0
        if risk_aversion == 1:
            utility = np.log(new_wealth)
        else:
            utility = (new_wealth**(1-risk_aversion) - 1) / (1-risk_aversion)
        
        return utility


