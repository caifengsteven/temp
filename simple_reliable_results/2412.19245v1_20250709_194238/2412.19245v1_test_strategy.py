import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from sklearn.metrics import accuracy_score, precision_score, recall_score, f1_score, confusion_matrix
from datetime import datetime, timedelta

class SentimentModels:
    """Simulates various sentiment models described in the paper"""
    
    def __init__(self, accuracy=None):
        """Initialize with known accuracy values from the paper or defaults"""
        if accuracy is None:
            # Default accuracies from Table 3 in the paper
            self.accuracy = {
                'OPT': 0.744,
                'BERT': 0.725,
                'FinBERT': 0.722,
                'LM_dict': 0.501
            }
        else:
            self.accuracy = accuracy
    
    def generate_sentiment_scores(self, num_samples, model_name):
        """Generate sentiment scores with bias toward the model's accuracy"""
        if model_name not in self.accuracy:
            raise ValueError(f"Model {model_name} not recognized")
        
        # Generate scores between 0 and 1 with higher density around 0 (negative) and 1 (positive)
        # to simulate sentiment polarization
        scores = np.random.beta(0.8, 0.8, num_samples)
        
        # Adjust distribution to reflect the model's accuracy
        accuracy = self.accuracy[model_name]
        
        # Introduce noise/accuracy factor
        if model_name == 'LM_dict':
            # LM dictionary has close to random performance
            return scores
        else:
            # Better models have scores that better correlate with actual returns
            # Shift more scores toward extreme values (0 or 1) based on accuracy
            adjustment = (scores - 0.5) * (2 * accuracy - 1)
            return np.clip(0.5 + adjustment, 0, 1)


class MarketSimulator:
    """Simulates stock market data and news events"""
    
    def __init__(self, num_stocks=100, start_date='2021-08-01', end_date='2023-07-31'):
        self.num_stocks = num_stocks
        self.start_date = datetime.strptime(start_date, '%Y-%m-%d')
        self.end_date = datetime.strptime(end_date, '%Y-%m-%d')
        self.trading_days = (self.end_date - self.start_date).days // 2  # Approx trading days
        
        # Market parameters
        self.market_drift = 0.0005  # ~12% annual return
        self.market_vol = 0.01      # ~16% annual volatility
        
        # Generate market and stock data
        self.generate_market_data()
        self.generate_stock_data()
        self.generate_news_events()
        
    def generate_market_data(self):
        """Generate market index data"""
        dates = [self.start_date + timedelta(days=i) for i in range(self.trading_days)]
        dates = [d for d in dates if d.weekday() < 5]  # Filter for weekdays
        
        # Generate market returns
        market_returns = np.random.normal(
            self.market_drift, 
            self.market_vol, 
            len(dates)
        )
        
        # Calculate market index values
        market_values = 100 * np.cumprod(1 + market_returns)
        
        self.market_data = pd.DataFrame({
            'date': dates,
            'market_return': market_returns,
            'market_value': market_values
        })
        
    def generate_stock_data(self):
        """Generate individual stock data"""
        # Create empty DataFrame for stock data
        all_stock_data = []
        
        for stock_id in range(1, self.num_stocks + 1):
            # Generate stock-specific parameters
            stock_beta = np.random.uniform(0.5, 1.5)  # Stock's market sensitivity
            stock_alpha = np.random.normal(0, 0.0002)  # Stock-specific drift
            stock_vol = np.random.uniform(0.015, 0.025)  # Stock-specific volatility
            market_cap = np.random.lognormal(10, 1)  # For value-weighting
            
            # Generate stock returns based on market returns
            stock_returns = []
            for mkt_ret in self.market_data['market_return']:
                # CAPM-inspired return generation
                stock_ret = stock_alpha + stock_beta * mkt_ret + np.random.normal(0, stock_vol)
                stock_returns.append(stock_ret)
            
            # Calculate stock values
            stock_values = 100 * np.cumprod(1 + np.array(stock_returns))
            
            # Create stock DataFrame
            stock_data = pd.DataFrame({
                'date': self.market_data['date'],
                'stock_id': stock_id,
                'stock_return': stock_returns,
                'stock_value': stock_values,
                'market_cap': market_cap
            })
            
            all_stock_data.append(stock_data)
        
        self.stock_data = pd.concat(all_stock_data, ignore_index=True)
        
    def generate_news_events(self):
        """Generate news events for stocks"""
        news_events = []
        
        # News frequency parameters - some stocks get more news than others
        news_freq = np.random.poisson(lam=5, size=self.num_stocks)
        
        for stock_id in range(1, self.num_stocks + 1):
            # How many news items for this stock in total
            num_news = max(1, int(news_freq[stock_id-1] * self.trading_days / 100))
            
            # Randomly select days for news
            news_days = np.random.choice(
                range(len(self.market_data)), 
                size=num_news, 
                replace=False
            )
            
            for day_idx in news_days:
                news_date = self.market_data.iloc[day_idx]['date']
                
                # Create 3-day forward return (used for sentiment labeling)
                try:
                    next_3_days = self.stock_data[
                        (self.stock_data['stock_id'] == stock_id) & 
                        (self.stock_data['date'] >= news_date) & 
                        (self.stock_data['date'] < news_date + timedelta(days=4))
                    ]['stock_return'].values
                    
                    if len(next_3_days) >= 3:
                        forward_3d_return = np.sum(next_3_days[:3])
                    else:
                        continue  # Skip if we don't have enough forward days
                except:
                    continue
                
                # Determine true sentiment based on forward return
                true_sentiment = 1 if forward_3d_return > 0 else 0
                
                # Generate news item
                news_item = {
                    'date': news_date,
                    'stock_id': stock_id,
                    'forward_3d_return': forward_3d_return,
                    'true_sentiment': true_sentiment
                }
                news_events.append(news_item)
        
        self.news_data = pd.DataFrame(news_events)


class SentimentTrader:
    """Implements trading strategies based on sentiment scores"""
    
    def __init__(self, market_simulator, sentiment_models, transaction_cost=0.001):
        self.market_simulator = market_simulator
        self.sentiment_models = sentiment_models
        self.transaction_cost = transaction_cost  # 10 bps as mentioned in the paper
        
    def generate_sentiment_predictions(self):
        """Generate sentiment predictions for each news event"""
        news_with_predictions = self.market_simulator.news_data.copy()
        
        # Number of news items
        num_news = len(news_with_predictions)
        
        # Generate predictions for each model
        for model_name in self.sentiment_models.accuracy.keys():
            # Generate sentiment scores
            scores = self.sentiment_models.generate_sentiment_scores(num_news, model_name)
            news_with_predictions[f'{model_name}_score'] = scores
            
            # Convert scores to binary predictions for evaluation
            news_with_predictions[f'{model_name}_pred'] = (scores > 0.5).astype(int)
        
        self.news_with_predictions = news_with_predictions
        return news_with_predictions
    
    def evaluate_models(self):
        """Evaluate prediction accuracy of each model"""
        results = {}
        
        for model_name in self.sentiment_models.accuracy.keys():
            y_true = self.news_with_predictions['true_sentiment']
            y_pred = self.news_with_predictions[f'{model_name}_pred']
            
            # Calculate metrics
            acc = accuracy_score(y_true, y_pred)
            prec = precision_score(y_true, y_pred)
            rec = recall_score(y_true, y_pred)
            spec = (confusion_matrix(y_true, y_pred)[0, 0] / 
                   (confusion_matrix(y_true, y_pred)[0, 0] + 
                    confusion_matrix(y_true, y_pred)[0, 1]))
            f1 = f1_score(y_true, y_pred)
            
            results[model_name] = {
                'accuracy': acc,
                'precision': prec,
                'recall': rec,
                'specificity': spec,
                'f1_score': f1
            }
        
        self.evaluation_results = results
        return results
    
    def run_trading_strategy(self, model_name):
        """Implement the long-short trading strategy based on sentiment scores"""
        if model_name not in self.sentiment_models.accuracy:
            raise ValueError(f"Model {model_name} not recognized")
        
        # Initialize portfolio values
        portfolio_values = []
        dates = sorted(self.market_simulator.market_data['date'].unique())
        initial_value = 1.0  # Start with $1
        current_value = initial_value
        
        # Track holdings
        current_holdings = {}  # stock_id -> position value
        
        for current_date in dates:
            # Get today's news and sentiment scores
            todays_news = self.news_with_predictions[
                self.news_with_predictions['date'] == current_date
            ]
            
            if len(todays_news) == 0:
                # No news today, portfolio value stays the same
                portfolio_values.append({
                    'date': current_date,
                    'portfolio_value': current_value,
                    'daily_return': 0.0
                })
                continue
            
            # Sell all current positions (with transaction costs)
            for stock_id, position_value in current_holdings.items():
                current_value += position_value * (1 - self.transaction_cost)
            
            current_holdings = {}
            
            # Get stocks with the highest and lowest sentiment scores
            if len(todays_news) >= 10:  # Only trade if we have enough stocks to choose from
                top_pct = 20  # Top 20% as mentioned in the paper
                bottom_pct = 20  # Bottom 20%
                
                # Sort by sentiment score
                sorted_news = todays_news.sort_values(by=f'{model_name}_score', ascending=False)
                
                num_stocks = len(sorted_news)
                num_top = max(1, int(num_stocks * top_pct / 100))
                num_bottom = max(1, int(num_stocks * bottom_pct / 100))
                
                # Get top and bottom stocks
                top_stocks = sorted_news.iloc[:num_top]
                bottom_stocks = sorted_news.iloc[-num_bottom:]
                
                # Calculate weights based on market cap
                top_total_mcap = top_stocks['stock_id'].map(
                    lambda x: self.market_simulator.stock_data[
                        (self.market_simulator.stock_data['stock_id'] == x) & 
                        (self.market_simulator.stock_data['date'] == current_date)
                    ]['market_cap'].values[0] if len(self.market_simulator.stock_data[
                        (self.market_simulator.stock_data['stock_id'] == x) & 
                        (self.market_simulator.stock_data['date'] == current_date)
                    ]) > 0 else 0
                ).sum()
                
                bottom_total_mcap = bottom_stocks['stock_id'].map(
                    lambda x: self.market_simulator.stock_data[
                        (self.market_simulator.stock_data['stock_id'] == x) & 
                        (self.market_simulator.stock_data['date'] == current_date)
                    ]['market_cap'].values[0] if len(self.market_simulator.stock_data[
                        (self.market_simulator.stock_data['stock_id'] == x) & 
                        (self.market_simulator.stock_data['date'] == current_date)
                    ]) > 0 else 0
                ).sum()
                
                # Allocate half of portfolio to long positions, half to short
                long_budget = current_value / 2
                short_budget = current_value / 2
                
                # Take positions (with transaction costs)
                for _, row in top_stocks.iterrows():
                    stock_id = row['stock_id']
                    stock_mcap = self.market_simulator.stock_data[
                        (self.market_simulator.stock_data['stock_id'] == stock_id) & 
                        (self.market_simulator.stock_data['date'] == current_date)
                    ]['market_cap'].values[0]
                    
                    # Weight by market cap
                    weight = stock_mcap / top_total_mcap if top_total_mcap > 0 else 1/num_top
                    position_value = long_budget * weight * (1 - self.transaction_cost)
                    current_holdings[stock_id] = position_value
                
                for _, row in bottom_stocks.iterrows():
                    stock_id = row['stock_id']
                    stock_mcap = self.market_simulator.stock_data[
                        (self.market_simulator.stock_data['stock_id'] == stock_id) & 
                        (self.market_simulator.stock_data['date'] == current_date)
                    ]['market_cap'].values[0]
                    
                    # Weight by market cap (negative for short)
                    weight = stock_mcap / bottom_total_mcap if bottom_total_mcap > 0 else 1/num_bottom
                    position_value = -short_budget * weight * (1 - self.transaction_cost)
                    current_holdings[stock_id] = position_value
            
            # Update portfolio value for the next day
            next_date_idx = np.where(dates == current_date)[0][0] + 1
            if next_date_idx < len(dates):
                next_date = dates[next_date_idx]
                
                # Calculate new portfolio value based on stock returns
                new_value = 0
                for stock_id, position_value in current_holdings.items():
                    try:
                        next_return = self.market_simulator.stock_data[
                            (self.market_simulator.stock_data['stock_id'] == stock_id) & 
                            (self.market_simulator.stock_data['date'] == next_date)
                        ]['stock_return'].values[0]
                        
                        # For long positions, we gain when returns are positive
                        # For short positions (negative position_value), we gain when returns are negative
                        new_position_value = position_value * (1 + next_return * np.sign(position_value))
                        new_value += new_position_value
                    except:
                        # If we can't find the stock return, assume no change
                        new_value += position_value
                
                daily_return = (new_value / current_value) - 1 if current_value > 0 else 0
                current_value = new_value
            else:
                daily_return = 0
            
            portfolio_values.append({
                'date': current_date,
                'portfolio_value': current_value,
                'daily_return': daily_return
            })
        
        # Convert to DataFrame
        portfolio_df = pd.DataFrame(portfolio_values)
        
        # Calculate performance metrics
        daily_returns = portfolio_df['daily_return'].values
        daily_returns = daily_returns[~np.isnan(daily_returns)]
        
        sharpe_ratio = np.sqrt(252) * np.mean(daily_returns) / np.std(daily_returns) if np.std(daily_returns) > 0 else 0
        mean_daily_return = np.mean(daily_returns) * 100  # as percentage
        std_daily_return = np.std(daily_returns) * 100  # as percentage
        
        # Calculate max drawdown
        portfolio_df['cumulative_return'] = (1 + portfolio_df['daily_return']).cumprod()
        portfolio_df['running_max'] = portfolio_df['cumulative_return'].cummax()
        portfolio_df['drawdown'] = portfolio_df['cumulative_return'] / portfolio_df['running_max'] - 1
        max_drawdown = portfolio_df['drawdown'].min() * 100  # as percentage
        
        # Final portfolio value
        final_value = portfolio_df.iloc[-1]['portfolio_value'] if len(portfolio_df) > 0 else initial_value
        total_return = (final_value / initial_value - 1) * 100  # as percentage
        
        results = {
            'portfolio_values': portfolio_df,
            'sharpe_ratio': sharpe_ratio,
            'mean_daily_return': mean_daily_return,
            'std_daily_return': std_daily_return,
            'max_drawdown': max_drawdown,
            'total_return': total_return
        }
        
        return results


