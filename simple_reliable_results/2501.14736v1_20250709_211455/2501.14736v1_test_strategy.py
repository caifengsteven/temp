def evaluate_genome(genome, config):
    # Create neural network from genome
    net = neat.nn.FeedForwardNetwork.create(genome, config)
    
    # Generate random 90-day data for faster evaluation
    data = generate_stock_data(days=90)
    data_with_indicators = prepare_data(data)
    
    # Run backtest
    backtest = Backtest(data_with_indicators)
    
    # Get a random ticker
    tickers = data_with_indicators['Ticker'].unique()
    ticker = random.choice(tickers)
    
    stats = backtest.run(net, ticker)
    
    # Calculate fitness based on the paper's Option 3 formula
    fitness = (stats['pnl'] + 
               1.5 * stats['pnl_relative'] - 
               0.5 * stats['max_drawdown'] + 
               0.0005 * stats['num_trades'] - 
               stats['avg_duration'])
    
    return fitness

