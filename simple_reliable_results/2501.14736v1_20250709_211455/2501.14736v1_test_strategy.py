# Define technical indicators calculation functions
def calculate_sma(prices, window):
    return prices.rolling(window=window).mean()

def calculate_stochastic(high, low, close, k_window=14, d_window=3):
    lowest_low = low.rolling(window=k_window).min()
    highest_high = high.rolling(window=k_window).max()
    
    k = 100 * ((close - lowest_low) / (highest_high - lowest_low))
    d = k.rolling(window=d_window).mean()
    
    return k, d

def calculate_willr(high, low, close, window=14):
    highest_high = high.rolling(window=window).max()
    lowest_low = low.rolling(window=window).min()
    
    willr = -100 * ((highest_high - close) / (highest_high - lowest_low))
    return willr

def calculate_macd(close, fast=12, slow=26, signal=9):
    exp1 = close.ewm(span=fast, adjust=False).mean()
    exp2 = close.ewm(span=slow, adjust=False).mean()
    macd = exp1 - exp2
    signal_line = macd.ewm(span=signal, adjust=False).mean()
    macd_diff = macd - signal_line
    return macd_diff / close

def calculate_cci(high, low, close, window=20):
    tp = (high + low + close) / 3
    sma_tp = tp.rolling(window=window).mean()
    mad = tp.rolling(window=window).apply(lambda x: np.mean(np.abs(x - np.mean(x))))
    cci = (tp - sma_tp) / (0.015 * mad)
    return cci

def calculate_rsi(close, window=14):
    delta = close.diff()
    gain = delta.clip(lower=0)
    loss = -delta.clip(upper=0)
    
    avg_gain = gain.rolling(window=window).mean()
    avg_loss = loss.rolling(window=window).mean()
    
    rs = avg_gain / avg_loss
    rsi = 100 - (100 / (1 + rs))
    
    return rsi

def calculate_adosc(high, low, close, volume, fast=3, slow=10):
    mfm = ((close - low) - (high - close)) / (high - low)
    mfv = mfm * volume
    adl = mfv.cumsum()
    
    exp1 = adl.ewm(span=fast, adjust=False).mean()
    exp2 = adl.ewm(span=slow, adjust=False).mean()
    
    adosc = exp1 - exp2
    return adosc

