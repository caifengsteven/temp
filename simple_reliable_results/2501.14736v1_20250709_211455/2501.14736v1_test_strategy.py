# Prepare data with technical indicators
def prepare_data(data):
    # Group by ticker and calculate technical indicators
    result = []
    
    for ticker, group in data.groupby('Ticker'):
        # Sort by date
        group = group.sort_values('Date')
        
        # Calculate technical indicators
        group['sma5'] = calculate_sma(group['Close'], 5) / group['Close']
        group['sma10'] = calculate_sma(group['Close'], 10) / group['Close']
        
        k, d = calculate_stochastic(group['High'], group['Low'], group['Close'])
        group['slow_k'] = k
        group['slow_d'] = d
        
        group['willr'] = calculate_willr(group['High'], group['Low'], group['Close'])
        group['macd_diff'] = calculate_macd(group['Close'])
        group['cci'] = calculate_cci(group['High'], group['Low'], group['Close'])
        group['rsi'] = calculate_rsi(group['Close'])
        group['adosc'] = calculate_adosc(group['High'], group['Low'], group['Close'], group['Volume'])
        
        # Drop NaN values resulting from rolling windows
        group = group.dropna()
        
        result.append(group)
    
    return pd.concat(result)

# Create a simple backtesting class
class Backtest:
    def __init__(self, data):
        self.data = data
        self.reset()
    
    def reset(self):
        self.cash = 100000.0
        self.position = 0
        self.trades = []
        self.equity_curve = []
        self.current_trade = None
    
    def run(self, model, ticker):
        ticker_data = self.data[self.data['Ticker'] == ticker].copy()
        
        # Add position columns (initially zero)
        ticker_data['long_position'] = 0.0
        ticker_data['short_position'] = 0.0
        
        for i in range(len(ticker_data)):
            if i < 20:  # Skip the first few days to avoid index errors
                continue
                
            # Update position values for input
            if self.position > 0:
                ticker_data.iloc[i, ticker_data.columns.get_loc('long_position')] = self.position / self.cash
            elif self.position < 0:
                ticker_data.iloc[i, ticker_data.columns.get_loc('short_position')] = abs(self.position) / self.cash
            
            # Extract features for the model
            features = ticker_data.iloc[i][['long_position', 'short_position', 'sma5', 'sma10', 
                                       'slow_k', 'slow_d', 'willr', 'macd_diff', 
                                       'cci', 'rsi', 'adosc']].values
            
            # Get model decision
            output = model.activate(features)
            buy_signal = output[0] > 0.5
            sell_signal = output[1] > 0.5
            volume_signal = max(min(output[2], 1.0), 0.0)  # Bound between 0 and 1
            
            current_price = ticker_data.iloc[i]['Close']
            
            # Execute trades based on signals
            if buy_signal and not sell_signal and self.position <= 0:
                # Buy
                amount = self.cash * volume_signal
                shares = amount / current_price
                self.cash -= amount
                self.position = shares
                
                self.current_trade = {
                    'entry_date': ticker_data.iloc[i]['Date'],
                    'entry_price': current_price,
                    'shares': shares,
                    'type': 'long'
                }
                
            elif sell_signal and not buy_signal and self.position >= 0:
                # Sell
                if self.position > 0:
                    # Close long position
                    amount = self.position * current_price
                    self.cash += amount
                    
                    if self.current_trade:
                        self.current_trade['exit_date'] = ticker_data.iloc[i]['Date']
                        self.current_trade['exit_price'] = current_price
                        self.current_trade['pnl'] = (current_price - self.current_trade['entry_price']) * self.current_trade['shares']
                        self.trades.append(self.current_trade)
                        self.current_trade = None
                
                # Short position
                amount = self.cash * volume_signal
                shares = amount / current_price
                self.position = -shares
                
                self.current_trade = {
                    'entry_date': ticker_data.iloc[i]['Date'],
                    'entry_price': current_price,
                    'shares': shares,
                    'type': 'short'
                }
            
            # Record equity
            equity = self.cash + (self.position * current_price if self.position > 0 else self.position * current_price)
            self.equity_curve.append((ticker_data.iloc[i]['Date'], equity))
        
        # Close any open position at the end
        if self.position != 0:
            final_price = ticker_data.iloc[-1]['Close']
            if self.position > 0:
                amount = self.position * final_price
                self.cash += amount
                
                if self.current_trade:
                    self.current_trade['exit_date'] = ticker_data.iloc[-1]['Date']
                    self.current_trade['exit_price'] = final_price
                    self.current_trade['pnl'] = (final_price - self.current_trade['entry_price']) * self.current_trade['shares']
                    self.trades.append(self.current_trade)
            else:
                amount = -self.position * final_price
                self.cash += amount
                
                if self.current_trade:
                    self.current_trade['exit_date'] = ticker_data.iloc[-1]['Date']
                    self.current_trade['exit_price'] = final_price
                    self.current_trade['pnl'] = (self.current_trade['entry_price'] - final_price) * self.current_trade['shares']
                    self.trades.append(self.current_trade)
            
            self.position = 0
            self.current_trade = None
        
        return self.calculate_statistics()
    
    def calculate_statistics(self):
        # Calculate performance metrics
        if not self.trades:
            return {
                'pnl': 0,
                'pnl_relative': 0,
                'max_drawdown': 0,
                'num_trades': 0,
                'avg_duration': 0,
                'win_rate': 0,
                'exposure_time': 0,
                'sqn': 0
            }
        
        pnl = sum(trade['pnl'] for trade in self.trades)
        
        # Calculate relative PnL to Buy & Hold
        start_price = self.data.iloc[0]['Close']
        end_price = self.data.iloc[-1]['Close']
        buy_hold_return = (end_price - start_price) / start_price
        pnl_relative = pnl / (100000 * buy_hold_return) if buy_hold_return != 0 else 0
        
        # Calculate max drawdown
        equity_values = [value for _, value in self.equity_curve]
        max_drawdown = 0
        peak = equity_values[0]
        
        for value in equity_values:
            if value > peak:
                peak = value
            
            drawdown = (peak - value) / peak
            max_drawdown = max(max_drawdown, drawdown)
        
        # Calculate other statistics
        num_trades = len(self.trades)
        
        durations = []
        for trade in self.trades:
            if 'exit_date' in trade and 'entry_date' in trade:
                duration = (trade['exit_date'] - trade['entry_date']).days
                durations.append(duration)
        
        avg_duration = sum(durations) / len(durations) if durations else 0
        
        win_count = sum(1 for trade in self.trades if trade.get('pnl', 0) > 0)
        win_rate = win_count / num_trades if num_trades > 0 else 0
        
        # Calculate exposure time
        total_days = (self.equity_curve[-1][0] - self.equity_curve[0][0]).days
        exposure_days = sum(durations)
        exposure_time = exposure_days / total_days if total_days > 0 else 0
        
        # Calculate SQN
        if num_trades > 0:
            pnls = [trade.get('pnl', 0) for trade in self.trades]
            avg_pnl = sum(pnls) / num_trades
            std_pnl = np.std(pnls) if len(pnls) > 1 else 1
            sqn = np.sqrt(num_trades) * avg_pnl / std_pnl if std_pnl != 0 else 0
        else:
            sqn = 0
        
        return {
            'pnl': pnl,
            'pnl_relative': pnl_relative,
            'max_drawdown': max_drawdown,
            'num_trades': num_trades,
            'avg_duration': avg_duration,
            'win_rate': win_rate,
            'exposure_time': exposure_time,
            'sqn': sqn
        }

