class StockFactorAnalysis:
    def __init__(self, n_stocks=100, n_days=1000, seed=42):
        """
        Initialize the analysis with simulated data parameters
        """
        self.n_stocks = n_stocks
        self.n_days = n_days
        self.seed = seed
        self.data = None
        self.factors = None
        self.models = {}
        self.best_factors = []
        np.random.seed(seed)
        
    def generate_simulated_data(self):
        """
        Generate simulated stock data with realistic properties
        """
        print("Generating simulated stock data...")
        
        # Generate dates
        end_date = dt.datetime.now()
        start_date = end_date - dt.timedelta(days=self.n_days)
        dates = pd.date_range(start=start_date, end=end_date, periods=self.n_days)
        
        # Create empty dataframe
        columns = ['permno', 'date', 'price', 'volume', 'shares_outstanding', 'ret']
        data = pd.DataFrame(columns=columns)
        
        # Generate data for each stock
        for stock_id in range(1, self.n_stocks + 1):
            # Base price between $10 and $500
            base_price = np.random.uniform(10, 500)
            
            # Generate price series with realistic volatility
            volatility = np.random.uniform(0.01, 0.05)
            price_series = base_price * np.exp(np.cumsum(np.random.normal(0.0002, volatility, self.n_days)))
            
            # Generate volume with realistic properties
            base_volume = np.random.uniform(100000, 10000000)
            volume_series = np.random.lognormal(mean=np.log(base_volume), sigma=0.5, size=self.n_days)
            
            # Shares outstanding (relatively stable)
            shares_outstanding = np.random.uniform(1000000, 1000000000)
            shares_series = np.ones(self.n_days) * shares_outstanding
            
            # Calculate returns
            returns = np.zeros(self.n_days)
            returns[1:] = (price_series[1:] / price_series[:-1]) - 1
            
            # Create dataframe for this stock
            stock_data = pd.DataFrame({
                'permno': stock_id,
                'date': dates,
                'price': price_series,
                'volume': volume_series,
                'shares_outstanding': shares_series,
                'ret': returns
            })
            
            # Append to main dataframe
            data = pd.concat([data, stock_data], ignore_index=True)
        
        self.data = data
        print(f"Generated data for {self.n_stocks} stocks over {self.n_days} days.")
        return data
    
    def calculate_factors(self):
        """
        Calculate factors based on the paper's methodology
        """
        print("Calculating factors...")
        
        # Ensure data exists
        if self.data is None:
            self.generate_simulated_data()
        
        # Group by stock ID
        grouped = self.data.groupby('permno')
        
        # Initialize factors dataframe
        factors = self.data[['permno', 'date', 'price', 'ret']].copy()
        
        # Calculate factors for each stock
        for permno, group in grouped:
            # Ensure group is sorted by date
            group = group.sort_values('date')
            
            # Market Capitalization
            factors.loc[group.index, 'Market_Capitalization'] = group['price'] * group['shares_outstanding']
            
            # Log of Market Capitalization
            factors.loc[group.index, 'Log_Market_Cap'] = np.log1p(factors.loc[group.index, 'Market_Capitalization'])
            
            # Momentum (12-month/60-day)
            factors.loc[group.index, 'Momentum'] = group['price'] / group['price'].shift(60) - 1
            
            # Short Momentum (10-day)
            factors.loc[group.index, 'Short_Momentum'] = group['price'] / group['price'].shift(10) - 1
            
            # Long Momentum (30-day)
            factors.loc[group.index, 'Long_Momentum'] = group['price'] / group['price'].shift(30) - 1
            
            # Multi Period Momentum
            factors.loc[group.index, 'Multi_Period_Momentum'] = factors.loc[group.index, 'Short_Momentum'] * factors.loc[group.index, 'Long_Momentum']
            
            # Momentum Change
            factors.loc[group.index, 'Momentum_Change'] = factors.loc[group.index, 'Momentum'] - factors.loc[group.index, 'Momentum'].shift(1)
            
            # Momentum Moving Average
            factors.loc[group.index, 'Momentum_MA'] = factors.loc[group.index, 'Momentum'].rolling(10).mean()
            
            # Turnover Ratio
            factors.loc[group.index, 'Turnover_Ratio'] = group['volume'] / group['shares_outstanding']
            
            # Amihud Illiquidity
            factors.loc[group.index, 'Amihud_Illiquidity'] = abs(group['ret']) / group['volume']
            
            # Rolling Volatility (20-day)
            factors.loc[group.index, 'Rolling_Volatility'] = group['ret'].rolling(20).std()
            
            # High-Low Spread
            factors.loc[group.index, 'High_Low_Spread'] = group['price'] - group['price'].rolling(20).min()
            
            # Normalized High-Low Spread
            factors.loc[group.index, 'Normalized_High_Low_Spread'] = factors.loc[group.index, 'High_Low_Spread'] / group['price']
            
            # RSI (14-day)
            delta = group['price'].diff()
            gain = (delta.where(delta > 0, 0)).rolling(window=14).mean()
            loss = (-delta.where(delta < 0, 0)).rolling(window=14).mean()
            rs = gain / loss
            factors.loc[group.index, 'RSI'] = 100 - (100 / (1 + rs))
            
            # Moving Average (20-day)
            factors.loc[group.index, 'MA_20'] = group['price'].rolling(20).mean()
            
            # Volatility Dynamics
            vol_slope = factors.loc[group.index, 'Rolling_Volatility'].diff() / 1
            factors.loc[group.index, 'Volatility_Dynamics'] = factors.loc[group.index, 'Rolling_Volatility'] * vol_slope
            
            # Liquidity Stress
            factors.loc[group.index, 'Liquidity_Stress'] = (factors.loc[group.index, 'Turnover_Ratio'] * abs(group['ret'])) / factors.loc[group.index, 'Market_Capitalization']
            
            # Momentum Liquidity
            factors.loc[group.index, 'Momentum_Liquidity'] = factors.loc[group.index, 'Momentum'] * factors.loc[group.index, 'Amihud_Illiquidity']
            
            # Smoothed Return
            factors.loc[group.index, 'Smoothed_Return'] = group['ret'].rolling(10).mean()
            
            # Volatility Adjusted Return
            factors.loc[group.index, 'Volatility_Adjusted_Return'] = group['ret'] / factors.loc[group.index, 'Rolling_Volatility']
        
        # Drop NA values after calculating all factors
        factors = factors.dropna()
        
        self.factors = factors
        print(f"Calculated {factors.shape[1] - 4} factors for analysis.")
        return factors
    
    def filter_factors(self, corr_threshold=0.1, max_factors=10):
        """
        Filter factors based on correlation with target and mutual correlation
        """
        print("Filtering factors...")
        
        if self.factors is None:
            self.calculate_factors()
        
        # Exclude non-factor columns
        factor_cols = [col for col in self.factors.columns if col not in ['permno', 'date', 'price', 'ret']]
        
        # First layer: Filter based on correlation with target
        correlations = self.factors[factor_cols + ['ret']].corr()['ret'].abs()
        selected_factors = correlations[correlations > corr_threshold].index.tolist()
        selected_factors.remove('ret')  # Remove target variable from factors
        
        print(f"After correlation filtering, {len(selected_factors)} factors remain.")
        
        # Second layer: Filter based on mutual correlation
        factor_corr = self.factors[selected_factors].corr().abs()
        
        # Initialize list for filtered factors
        low_corr_factors = []
        
        # Start with the factor most correlated with the target
        remaining_factors = selected_factors.copy()
        corr_with_target = correlations[selected_factors].sort_values(ascending=False)
        
        # Add factors one by one, ensuring low correlation with already selected factors
        for factor in corr_with_target.index:
            if factor in remaining_factors:
                low_corr_factors.append(factor)
                remaining_factors.remove(factor)
                
                # Remove highly correlated factors
                for other_factor in remaining_factors.copy():
                    if factor_corr.loc[factor, other_factor] > 0.75:
                        remaining_factors.remove(other_factor)
                        
                # Stop when we reach max_factors
                if len(low_corr_factors) >= max_factors:
                    break
        
        self.best_factors = low_corr_factors
        print(f"Final selected factors: {', '.join(low_corr_factors)}")
        return low_corr_factors
    
    def train_models(self):
        """
        Train different models on the filtered factors
        """
        print("Training models...")
        
        if not self.best_factors:
            self.filter_factors()
        
        # Prepare data
        X = self.factors[self.best_factors]
        y = self.factors['ret']
        
        # Split data
        X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.2, random_state=self.seed)
        
        # Define models
        models = {
            'Linear Regression': LinearRegression(),
            'Ridge Regression': Ridge(alpha=1.0),
            'Random Forest': RandomForestRegressor(n_estimators=100, max_depth=5, random_state=self.seed),
            'Gradient Boosting': GradientBoostingRegressor(n_estimators=100, max_depth=3, random_state=self.seed)
        }
        
        # Train and evaluate models
        results = {}
        for name, model in models.items():
            model.fit(X_train, y_train)
            y_pred_train = model.predict(X_train)
            y_pred_test = model.predict(X_test)
            
            # Calculate metrics
            train_r2 = r2_score(y_train, y_pred_train)
            test_r2 = r2_score(y_test, y_pred_test)
            train_mse = mean_squared_error(y_train, y_pred_train)
            test_mse = mean_squared_error(y_test, y_pred_test)
            
            results[name] = {
                'model': model,
                'train_r2': train_r2,
                'test_r2': test_r2,
                'train_mse': train_mse,
                'test_mse': test_mse
            }
            
            print(f"{name} - Train R²: {train_r2:.4f}, Test R²: {test_r2:.4f}, Train MSE: {train_mse:.6f}, Test MSE: {test_mse:.6f}")
        
        self.models = results
        return results
    
    def backtest_strategy(self, window_size=252, test_window=21, top_n=100):
        """
        Backtest the strategy using a rolling window approach
        """
        print("Running backtest simulation...")
        
        if not self.models:
            self.train_models()
        
        # Use the best performing model (GBR based on the paper)
        model = self.models['Gradient Boosting']['model']
        
        # Prepare data for backtesting
        data = self.factors.sort_values(['date', 'permno'])
        unique_dates = data['date'].unique()
        
        # Need at least window_size + test_window days
        if len(unique_dates) < window_size + test_window:
            raise ValueError("Not enough data for backtesting")
        
        # Initialize results
        portfolio_returns = []
        benchmark_returns = []
        dates = []
        
        # Rolling window backtest
        for i in range(window_size, len(unique_dates) - test_window, test_window):
            # Training window
            train_dates = unique_dates[i-window_size:i]
            test_dates = unique_dates[i:i+test_window]
            
            # Extract data
            train_data = data[data['date'].isin(train_dates)]
            test_data = data[data['date'].isin(test_dates)]
            
            # Train the model
            X_train = train_data[self.best_factors]
            y_train = train_data['ret']
            model.fit(X_train, y_train)
            
            # Test window (first day)
            first_test_day = test_data[test_data['date'] == test_dates[0]]
            X_test = first_test_day[self.best_factors]
            
            # Predict returns
            predicted_returns = model.predict(X_test)
            
            # Create a DataFrame for selection
            selection_df = pd.DataFrame({
                'permno': first_test_day['permno'].values,
                'predicted_return': predicted_returns
            })
            
            # Select top N stocks
            selected_stocks = selection_df.nlargest(min(top_n, len(selection_df)), 'predicted_return')['permno'].values
            
            # Calculate portfolio return for the test window
            portfolio_data = test_data[test_data['permno'].isin(selected_stocks)]
            portfolio_daily_returns = portfolio_data.groupby('date')['ret'].mean()
            
            # Calculate benchmark return (all stocks)
            benchmark_daily_returns = test_data.groupby('date')['ret'].mean()
            
            # Store results
            portfolio_returns.extend(portfolio_daily_returns.values)
            benchmark_returns.extend(benchmark_daily_returns.values)
            dates.extend(portfolio_daily_returns.index)
        
        # Calculate cumulative returns
        portfolio_cumulative = np.cumprod(1 + np.array(portfolio_returns)) - 1
        benchmark_cumulative = np.cumprod(1 + np.array(benchmark_returns)) - 1
        
        # Calculate Sharpe Ratio (assuming risk-free rate of 0 for simplicity)
        portfolio_sharpe = np.mean(portfolio_returns) / np.std(portfolio_returns) * np.sqrt(252)
        benchmark_sharpe = np.mean(benchmark_returns) / np.std(benchmark_returns) * np.sqrt(252)
        
        print(f"Backtest Results:")
        print(f"Portfolio Cumulative Return: {portfolio_cumulative[-1]:.4f}")
        print(f"Benchmark Cumulative Return: {benchmark_cumulative[-1]:.4f}")
        print(f"Portfolio Sharpe Ratio: {portfolio_sharpe:.4f}")
        print(f"Benchmark Sharpe Ratio: {benchmark_sharpe:.4f}")
        
        # Plot results
        plt.figure(figsize=(12, 6))
        plt.plot(portfolio_cumulative, label='Portfolio Strategy')
        plt.plot(benchmark_cumulative, label='Benchmark', linestyle='--')
        plt.title('Backtest Results: Cumulative Returns')
        plt.xlabel('Trading Days')
        plt.ylabel('Cumulative Return')
        plt.legend()
        plt.grid(True)
        plt.tight_layout()
        plt.show()
        
        return {
            'portfolio_returns': portfolio_returns,
            'benchmark_returns': benchmark_returns,
            'portfolio_cumulative': portfolio_cumulative,
            'benchmark_cumulative': benchmark_cumulative,
            'portfolio_sharpe': portfolio_sharpe,
            'benchmark_sharpe': benchmark_sharpe
        }
    
