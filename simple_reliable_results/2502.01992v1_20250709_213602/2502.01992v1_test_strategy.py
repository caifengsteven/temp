class BaselineLlamaModel(SentimentModel):
    """Simulates a baseline Llama-3.2-3B model without market feedback"""
    def __init__(self, signal_strength: int = 10):
        self.signal_strength = signal_strength
        
        # Keywords with associated sentiment values for simulation
        self.positive_keywords = {
            "record": 5, "growth": 4, "profit": 5, "success": 4, 
            "positive": 3, "launch": 3, "upgrade": 4, "beat": 4,
            "innovation": 3, "partnership": 2
        }
        
        self.negative_keywords = {
            "layoff": -5, "downturn": -4, "decline": -4, "loss": -5,
            "negative": -3, "cut": -3, "downgrade": -4, "miss": -4,
            "lawsuit": -3, "recall": -3
        }
    
    def predict_sentiment(self, headline: FinancialHeadline) -> float:
        """Simple keyword-based sentiment analysis"""
        text = headline.text.lower()
        score = 0
        
        # Check for positive keywords
        for keyword, value in self.positive_keywords.items():
            if keyword in text:
                score += value
        
        # Check for negative keywords
        for keyword, value in self.negative_keywords.items():
            if keyword in text:
                score += value
        
        # Normalize score to be within signal bounds
        score = max(min(score, self.signal_strength), -self.signal_strength)
        
        return score

