def evaluate_model(model: SentimentModel, headlines: List[FinancialHeadline], 
                  price_data: Dict, simulator: TradingSimulator) -> pd.DataFrame:
    """Evaluate model performance on test data"""
    results = []
    
    for headline in headlines:
        ticker = headline.ticker
        date = headline.date
        
        # Skip if we don't have price data for this day or 3 days later
        if date not in price_data[ticker] or date + timedelta(days=3) not in price_data[ticker]:
            continue
        
        # Get sentiment prediction
        sentiment_score = model.predict_sentiment(headline)
        
        # Get current price and future price (3 days later)
        current_price = price_data[ticker][date]
        future_price = price_data[ticker][date + timedelta(days=3)]
        
        # Calculate actual return
        actual_return = (future_price / current_price) - 1
        
        # Execute trade based on sentiment
        trade_result = simulator.execute_trades(date, ticker, current_price, sentiment_score)
        
        # Store result
        result = {
            "date": date,
            "ticker": ticker,
            "headline": headline.text,
            "sentiment_score": sentiment_score,
            "current_price": current_price,
            "future_price": future_price,
            "actual_return": actual_return,
            "trade_action": trade_result["action"],
            "portfolio_value": trade_result["portfolio_value"]
        }
        results.append(result)
    
    return pd.DataFrame(results)

