class TradingSimulator:
    """Simulates trading based on sentiment signals"""
    def __init__(self, initial_capital: float = 10000.0, threshold: float = 3.0):
        self.initial_capital = initial_capital
        self.capital = initial_capital
        self.threshold = threshold
        self.positions = {}
        self.trade_history = []
        
    def execute_trades(self, date: datetime, ticker: str, price: float, 
                       sentiment_score: float) -> Dict:
        """Execute trades based on sentiment score"""
        action = "HOLD"
        position_value = 0
        
        # Decide action based on sentiment threshold
        if sentiment_score > self.threshold:
            action = "BUY"
        elif sentiment_score < -self.threshold:
            action = "SELL"
            
        # Execute the trade
        if action == "BUY" and ticker not in self.positions:
            # Buy position with 10% of capital
            shares = (self.capital * 0.1) / price
            cost = shares * price
            self.capital -= cost
            self.positions[ticker] = {"shares": shares, "price": price}
            position_value = shares * price
            
        elif action == "SELL" and ticker in self.positions:
            # Sell existing position
            position = self.positions[ticker]
            proceeds = position["shares"] * price
            self.capital += proceeds
            position_value = -proceeds  # Negative for selling
            del self.positions[ticker]
            
        # Record the trade
        trade_record = {
            "date": date,
            "ticker": ticker,
            "action": action,
            "price": price,
            "sentiment_score": sentiment_score,
            "position_value": position_value,
            "capital": self.capital,
            "portfolio_value": self.get_portfolio_value({"ticker": price})
        }
        
        self.trade_history.append(trade_record)
        return trade_record
    
    def get_portfolio_value(self, current_prices: Dict[str, float]) -> float:
        """Calculate total portfolio value"""
        position_value = 0
        for ticker, position in self.positions.items():
            if ticker in current_prices:
                position_value += position["shares"] * current_prices[ticker]
        return self.capital + position_value
    
    def calculate_returns(self) -> pd.DataFrame:
        """Calculate returns based on trade history"""
        if not self.trade_history:
            return pd.DataFrame()
            
        df = pd.DataFrame(self.trade_history)
        df["cumulative_return"] = (df["portfolio_value"] / self.initial_capital) - 1
        return df

