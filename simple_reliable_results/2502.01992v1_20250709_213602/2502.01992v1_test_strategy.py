def calculate_sentiment_accuracy(results: pd.DataFrame) -> float:
    """Calculate how often sentiment direction matches actual return direction"""
    if results.empty:
        return 0.0
        
    # Determine if sentiment direction matches return direction
    sentiment_direction = np.sign(results["sentiment_score"])
    return_direction = np.sign(results["actual_return"])
    
    # Calculate accuracy
    matches = (sentiment_direction == return_direction).sum()
    return matches / len(results)

