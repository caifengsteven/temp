class TradingStrategy:
    """
    A simple trading strategy that can be optimized using FWT simulations
    """
    
    def __init__(self, lookback: int = 10, threshold: float = 0.01):
        """
        Initialize strategy with parameters
        
        Args:
            lookback: Number of days to look back for trend analysis
            threshold: Return threshold to trigger position change
        """
        self.lookback = lookback
        self.threshold = threshold
        
    def generate_signals(self, returns: np.ndarray) -> List[int]:
        """
        Generate trading signals based on returns
        
        Args:
            returns: Historical returns
            
        Returns:
            List of signals (1 for long, -1 for short, 0 for no position)
        """
        signals = [0] * len(returns)
        
        for i in range(self.lookback, len(returns)):
            # Calculate trend based on lookback period
            trend = np.mean(returns[i-self.lookback:i])
            
            # Generate signal based on trend and threshold
            if trend > self.threshold:
                signals[i] = 1  # Long
            elif trend < -self.threshold:
                signals[i] = -1  # Short
            else:
                signals[i] = 0  # No position
                
        return signals
    
    def backtest(self, returns: np.ndarray) -> Dict:
        """
        Backtest strategy on returns data
        
        Args:
            returns: Historical returns
            
        Returns:
            Dictionary of performance metrics
        """
        signals = self.generate_signals(returns)
        
        # Calculate strategy returns
        strategy_returns = np.zeros_like(returns)
        for i in range(1, len(returns)):
            strategy_returns[i] = signals[i-1] * returns[i]
            
        # Calculate performance metrics
        total_return = np.sum(strategy_returns)
        sharpe_ratio = np.mean(strategy_returns) / np.std(strategy_returns) * np.sqrt(252)  # Annualized
        max_drawdown = 0
        peak = 0
        
        for return_val in np.cumsum(strategy_returns):
            if return_val > peak:
                peak = return_val
            drawdown = peak - return_val
            max_drawdown = max(max_drawdown, drawdown)
            
        return {
            'total_return': total_return,
            'sharpe_ratio': sharpe_ratio,
            'max_drawdown': max_drawdown
        }
    
    def optimize(self, returns: np.ndarray, fwt: FinancialWindTunnel, 
                 stock_universe: pd.DataFrame, num_simulations: int = 10) -> Dict:
        """
        Optimize strategy parameters using FWT simulations
        
        Args:
            returns: Historical returns
            fwt: FinancialWindTunnel instance
            stock_universe: Historical returns of all stocks in the universe
            num_simulations: Number of simulations to run
            
        Returns:
            Dictionary of optimized parameters
        """
        best_params = {'lookback': self.lookback, 'threshold': self.threshold}
        best_sharpe = 0
        
        # Define parameter search space
        lookback_range = range(5, 30, 5)
        threshold_range = [0.001, 0.005, 0.01, 0.015, 0.02]
        
        for lookback in lookback_range:
            for threshold in threshold_range:
                avg_sharpe = 0
                
                # Test on multiple simulated scenarios
                for _ in range(num_simulations):
                    # Generate simulated returns
                    target_series = pd.Series(returns)
                    simulated_returns, _ = fwt.generate(target_series, stock_universe)
                    
                    # Test strategy with current parameters
                    self.lookback = lookback
                    self.threshold = threshold
                    results = self.backtest(simulated_returns)
                    avg_sharpe += results['sharpe_ratio']
                
                avg_sharpe /= num_simulations
                
                # Update best parameters if better performance
                if avg_sharpe > best_sharpe:
                    best_sharpe = avg_sharpe
                    best_params = {'lookback': lookback, 'threshold': threshold}
                    
        # Set strategy to best parameters
        self.lookback = best_params['lookback']
        self.threshold = best_params['threshold']
        
        return best_params


