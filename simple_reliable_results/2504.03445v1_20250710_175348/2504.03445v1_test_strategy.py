def check_criticality(params):
    """Check if the criticality condition is satisfied"""
    return np.isclose(params.alpha, params.f_prime_0 * (1 + params.beta * params.gamma))


def simulate_limit_model(params):
    """
    Simulate the limit model (continuous-time) as derived in the paper
    
    dy(t) = (beta_y + alpha_y * f''(0) * y^2(t))dt + sigma_y * sqrt(f'(0) * y(t)) * dB(t)
    dπ(t) = beta_π * dt + sigma_π * sqrt(f'(0) * y(t)) * dW(t)
    
    with correlation between B and W
    """
    # Calculate the derived constants based on the paper
    beta_pi = (1 - params.gamma) / (params.gamma * (1 + params.beta)) * (params.b_plus - params.b_minus)
    sigma_pi = np.sqrt(2 * (1 + params.beta * params.gamma) / (params.gamma * (1 + params.beta)))
    
    beta_y = ((2 / (1 + params.beta)) + (2 * params.beta / (1 + params.beta)) * params.gamma) * params.b_plus + \
             ((2 * params.beta / (1 + params.beta)) * (1 - params.gamma) + 2 * params.beta * params.gamma) * params.b_minus
    alpha_y = 0.5 * (1 + params.beta * params.gamma)
    sigma_y = np.sqrt((1 + params.beta**2) * (1 + params.beta * params.gamma)) / (1 + params.beta)
    
    # Initial conditions from the paper
    y0 = ((2 / (1 + params.beta)) + (2 * params.beta / (1 + params.beta)) * params.gamma) * params.a_plus + \
         ((2 * params.beta / (1 + params.beta)) * (1 - params.gamma) + 2 * params.beta * params.gamma) * params.a_minus
    pi0 = (1 - params.gamma) / (params.gamma * (1 + params.beta)) * (params.a_plus - params.a_minus)
    
    # Correlation between the Brownian motions
    rho = (1 + params.beta) * params.gamma * (1 - params.beta) / \
          ((1 + params.beta * params.gamma) * np.sqrt(2 * (1 + params.beta**2)))
    
    # Number of steps
    n_steps = int(params.T / params.dt)
    
    # Initialize arrays
    times = np.linspace(0, params.T, n_steps + 1)
    y = np.zeros(n_steps + 1)
    pi = np.zeros(n_steps + 1)
    
    # Set initial values
    y[0] = y0
    pi[0] = pi0
    
    # Generate correlated Brownian increments
    dW1 = np.random.normal(0, np.sqrt(params.dt), n_steps)
    dW2 = rho * dW1 + np.sqrt(1 - rho**2) * np.random.normal(0, np.sqrt(params.dt), n_steps)
    
    # Euler-Maruyama scheme
    for i in range(n_steps):
        if y[i] < 0:  # Ensure non-negativity of y
            y[i] = 0
            
        # Volatility process update
        drift_y = (beta_y + alpha_y * params.f_double_prime_0 * y[i]**2) * params.dt
        diffusion_y = sigma_y * np.sqrt(params.f_prime_0 * y[i]) * dW2[i]
        y[i+1] = y[i] + drift_y + diffusion_y
        
        # Price process update
        drift_pi = beta_pi * params.dt
        diffusion_pi = sigma_pi * np.sqrt(params.f_prime_0 * y[i]) * dW1[i]
        pi[i+1] = pi[i] + drift_pi + diffusion_pi
    
    return times, y, pi


def simulate_hawkes_processes(params):
    """
    Simulate the microscopic Hawkes processes model with N agents
    as described in the paper.
    
    This is a simplified implementation focusing on the key aspects.
    """
    # Number of time steps
    n_steps = int(params.T / params.dt)
    
    # Initialize intensity and price processes
    lambda_plus = np.zeros((params.N, n_steps + 1))
    lambda_minus = np.zeros((params.N, n_steps + 1))
    X_plus = np.zeros((params.N, n_steps + 1))
    X_minus = np.zeros((params.N, n_steps + 1))
    
    # Initial values based on a_N parameters
    a_plus_N = params.a_plus / np.sqrt(params.N)
    a_minus_N = params.a_minus / np.sqrt(params.N)
    X_plus[:, 0] = a_plus_N
    X_minus[:, 0] = a_minus_N
    
    # Parameter for the external signal
    b_plus_N = params.b_plus / np.sqrt(params.N)
    b_minus_N = params.b_minus / np.sqrt(params.N)
    
    # Memory decay factor for exponential kernel
    phi = np.exp(-params.alpha * params.dt)
    
    # Initialize aggregated price process
    Pi = np.zeros(n_steps + 1)
    
    # A simplified concave function f (as described in the paper)
    def f(x):
        if x < 0:
            return 0
        return params.f_prime_0 * x + 0.5 * params.f_double_prime_0 * x**2
    
    # Simulation
    for i in range(n_steps):
        # Calculate empirical means
        m_plus = np.mean(X_plus[:, i])
        m_minus = np.mean(X_minus[:, i])
        
        # Calculate intensities for each agent
        for j in range(params.N):
            lambda_plus[j, i] = f(m_plus + params.beta * params.gamma * m_minus)
            lambda_minus[j, i] = f(params.gamma * m_plus + (1 + (params.beta - 1) * params.gamma) * m_minus)
        
        # Generate jumps
        jumps_plus = np.random.poisson(lambda_plus[:, i] * params.dt)
        jumps_minus = np.random.poisson(lambda_minus[:, i] * params.dt)
        
        # Update X processes
        for j in range(params.N):
            # Self-excitation with memory decay
            X_plus[j, i+1] = phi * X_plus[j, i] + jumps_plus[j] + b_plus_N * params.dt
            X_minus[j, i+1] = phi * X_minus[j, i] + jumps_minus[j] + b_minus_N * params.dt
        
        # Update price process
        Pi[i+1] = Pi[i] + np.sum(jumps_plus - jumps_minus) / np.sqrt(params.N)
    
    # Calculate Y_N and Z_N as defined in the paper
    times = np.linspace(0, params.T, n_steps + 1)
    Y_N = np.zeros(n_steps + 1)
    Z_N = np.zeros(n_steps + 1)
    
    for i in range(n_steps + 1):
        m_plus_i = np.mean(X_plus[:, i])
        m_minus_i = np.mean(X_minus[:, i])
        
        Y_N[i] = (np.sqrt(params.N) / 2) * (
            ((2 / (1 + params.beta)) + (2 * params.beta / (1 + params.beta)) * params.gamma) * m_plus_i +
            ((2 * params.beta / (1 + params.beta)) * (1 - params.gamma) + 2 * params.beta * params.gamma) * m_minus_i
        )
        
        Z_N[i] = ((1 - params.gamma) * np.sqrt(params.N) / 2) * (m_plus_i - m_minus_i)
    
    return times, Pi, Y_N, Z_N


