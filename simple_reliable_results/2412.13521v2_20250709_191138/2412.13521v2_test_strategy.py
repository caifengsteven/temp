    plt.figure(figsize=(12, 6))
    
    # Sample paths
    plt.subplot(1, 2, 1)
    for i in range(10):
        plt.plot(model.time_grid, X_cnec[i], 'b-', alpha=0.3)
    plt.plot(model.time_grid, np.mean(X_cnec, axis=0), 'b-', linewidth=2)
    plt.title('CNEC Sample Paths')
    plt.xlabel('Time')
    plt.ylabel('State')
    
    # Controls
    plt.subplot(1, 2, 2)
    # Create a time grid for evaluating the control function
    t_grid = np.linspace(0, T, 100)
    control_values = [cnec_func(t, 1.0) for t in t_grid]  # Evaluate at x=1.0
    
    plt.plot(t_grid, control_values, 'b-', linewidth=2)
    plt.title('CNEC Control Function')
    plt.xlabel('Time')
    plt.ylabel('Control Value at x=1.0')
    
