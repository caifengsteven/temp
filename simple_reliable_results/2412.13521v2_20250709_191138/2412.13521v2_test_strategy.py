def exponential_utility_test():
    """Test the model with mean-exponential utility objective function from Section 5.3.1."""
    # Define model parameters
    A = 0.05  # Interest rate
    B = 0.3   # Market price of risk * volatility
    C = 0.1   # Income rate
    D = 0.4   # Volatility
    F = 0.0   # Additive noise
    T = 1.0   # Time horizon
    
    # Create model
    model = LinearControlModel(A, B, C, D, F, T=T)
    
    # Define objective function parameters
    kappa = 1.0  # Weight for mean
    c = 2.0      # CARA coefficient
    
    # Define CNEC function based on Equation (47)
    def cnec_func(t, x):
        theta_t = model._theta(t)
        beta_t = kappa * model.B(t) / (c * model.D(t)**2 * np.sqrt(1 + kappa**2 * theta_t))
        return model.cnec(t, x, beta_t)
    
    # Define a simple benchmark strategy
    def benchmark_func(t, x):
        return 0.5 * x - model.F(t) / model.D(t)
    
    # Simulate paths using both strategies
    X_cnec, U_cnec = model.simulate(cnec_func)
    X_bench, U_bench = model.simulate(benchmark_func)
    
    # Compute mean-exponential utility objective
    def compute_exp_objective(X, kappa, c):
        X_T = X[:, -1]
        mean = np.mean(X_T)
        
        # Compute E[e^(-c(X-E[X]))]
        exp_term = np.mean(np.exp(-c * (X_T - mean)))
        
        return kappa * mean - (1/c) * exp_term + (1/c)
    
    obj_cnec = compute_exp_objective(X_cnec, kappa, c)
    obj_bench = compute_exp_objective(X_bench, kappa, c)
    
    # Print results
    print("\nMean-Exponential Utility Test Results:")
    print(f"CNEC objective value: {obj_cnec:.4f}")
    print(f"Benchmark objective value: {obj_bench:.4f}")
    
