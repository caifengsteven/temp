    def _compute_alpha(self, j, y):
        """
        Compute α_j(y) as defined in the paper.
        For even j, α_j(y) = (j-1)!! * y^(j/2)
        For odd j, α_j(y) = 0
        """
        if j % 2 == 0:
            # Calculate double factorial (j-1)!!
            double_fact = 1
            for k in range(j-1, 0, -2):
                if k > 0:
                    double_fact *= k
            return double_fact * (y**(j/2))
        else:
            return 0
        
