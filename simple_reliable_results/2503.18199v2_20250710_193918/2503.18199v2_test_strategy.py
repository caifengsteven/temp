def bin_data_for_plot(x: np.ndarray, y: np.ndarray, num_bins: int = 20) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Bin the data for clearer visualization"""
    # Sort data by x values
    sorted_indices = np.argsort(x)
    x_sorted = x[sorted_indices]
    y_sorted = y[sorted_indices]
    
    # Create bins (logarithmic binning for x)
    log_x_min, log_x_max = np.log10(x_sorted.min()), np.log10(x_sorted.max())
    log_bin_edges = np.logspace(log_x_min, log_x_max, num_bins+1)
    
    bin_centers = []
    bin_means = []
    bin_stds = []
    
    for i in range(num_bins):
        mask = (x_sorted >= log_bin_edges[i]) & (x_sorted < log_bin_edges[i+1])
        if np.sum(mask) > 0:
            bin_centers.append(np.sqrt(log_bin_edges[i] * log_bin_edges[i+1]))
            bin_means.append(np.mean(y_sorted[mask]))
            bin_stds.append(np.std(y_sorted[mask]) / np.sqrt(np.sum(mask)))
    
    return np.array(bin_centers), np.array(bin_means), np.array(bin_stds)


def plot_square_root_law(volumes: np.ndarray, impacts: np.ndarray, title: str = "Square Root Law"):
    """Plot the Square Root Law"""
    plt.figure(figsize=(10, 6))
    
    # Plot raw data with low alpha
    plt.scatter(volumes, impacts, alpha=0.05, color='gray', label='Raw data')
    
    # Bin the data for clearer visualization
    bin_centers, bin_means, bin_stds = bin_data_for_plot(volumes, impacts)
    
    # Plot binned data
    plt.errorbar(bin_centers, bin_means, yerr=bin_stds, fmt='o', color='blue', 
                 label='Binned data', markersize=8)
    
    # Fit a power law to the binned data
    mask = ~np.isnan(bin_means)
    log_x = np.log10(bin_centers[mask])
    log_y = np.log10(bin_means[mask])
    slope, intercept, r_value, p_value, std_err = linregress(log_x, log_y)
    
    # Plot the fit
    x_fit = np.logspace(log_x.min(), log_x.max(), 100)
    y_fit = 10**intercept * x_fit**slope
    plt.plot(x_fit, y_fit, 'r-', linewidth=2, 
             label=f'Fit: y = {10**intercept:.2f} * x^{slope:.2f}, R² = {r_value**2:.2f}')
    
    # Square root reference
    y_sqrt = 0.5 * np.sqrt(x_fit)
    plt.plot(x_fit, y_sqrt, 'g--', linewidth=2, label='Square Root: y = 0.5 * √x')
    
    plt.xscale('log')
    plt.yscale('log')
    plt.xlabel('Normalized Volume (Q/VD)')
    plt.ylabel('Normalized Impact (I/σD)')
    plt.title(title)
    plt.legend()
    plt.grid(True, which='both', linestyle='--', alpha=0.7)
    
    return slope, 10**intercept, r_value**2


