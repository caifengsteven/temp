def assign_trades_to_traders(trades: List[Trade], 
                            num_traders: int = 20, 
                            distribution: str = 'homogeneous',
                            power_law_exponent: float = 2.0) -> List[Trade]:
    """
    Assign trader IDs to trades using the mapping function described in the paper
    
    Args:
        trades: List of trades
        num_traders: Number of traders in the market
        distribution: 'homogeneous' or 'power_law'
        power_law_exponent: Exponent for power law distribution
    """
    if distribution == 'homogeneous':
        frequencies = np.ones(num_traders)
    elif distribution == 'power_law':
        # Generate trader frequencies following a power law
        frequencies = np.array([1/(i+1)**power_law_exponent for i in range(num_traders)])
    else:
        raise ValueError("Distribution must be 'homogeneous' or 'power_law'")
    
    # Normalize to probabilities
    probabilities = frequencies / frequencies.sum()
    
    # Cumulative probabilities for efficient sampling
    cumulative_probs = np.cumsum(probabilities)
    
    # Assign trader IDs
    for trade in trades:
        u = np.random.random()
        trader_id = np.searchsorted(cumulative_probs, u)
        trade.trader_id = trader_id
    
    return trades


def create_metaorders(trades: List[Trade]) -> List[Metaorder]:
    """Create metaorders from assigned trades"""
    
    # Sort trades by trader ID and timestamp
    sorted_trades = sorted(trades, key=lambda x: (x.trader_id, x.timestamp))
    
    metaorders = []
    current_metaorder = None
    
    for trade in sorted_trades:
        if current_metaorder is None:
            # Start a new metaorder
            current_metaorder = Metaorder(
                trader_id=trade.trader_id,
                direction=trade.direction,
                child_orders=[trade],
                start_time=trade.timestamp,
                end_time=trade.timestamp
            )
        elif (trade.trader_id == current_metaorder.trader_id and 
              trade.direction == current_metaorder.direction):
            # Continue the current metaorder
            current_metaorder.child_orders.append(trade)
            current_metaorder.end_time = trade.timestamp
        else:
            # End the current metaorder and start a new one
            if len(current_metaorder.child_orders) > 1:  # Only keep metaorders with multiple child orders
                metaorders.append(current_metaorder)
            
            current_metaorder = Metaorder(
                trader_id=trade.trader_id,
                direction=trade.direction,
                child_orders=[trade],
                start_time=trade.timestamp,
                end_time=trade.timestamp
            )
    
    # Add the last metaorder if it exists and has multiple child orders
    if current_metaorder is not None and len(current_metaorder.child_orders) > 1:
        metaorders.append(current_metaorder)
    
    return metaorders


def calculate_metaorder_impact(metaorder: Metaorder, 
                              price_series: Dict[dt.datetime, float]) -> float:
    """
    Calculate the price impact of a metaorder.
    Impact = ε * (pe - ps) where ε is the metaorder sign, ps is the price at start,
    and pe is the price at the end of the metaorder.
    """
