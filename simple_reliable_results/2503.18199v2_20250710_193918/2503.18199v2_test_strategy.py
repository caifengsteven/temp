@dataclass
class Trade:
    """Represents a single trade in the market"""
    timestamp: dt.datetime
    price: float
    volume: float
    direction: int  # 1 for buy, -1 for sell
    trader_id: Optional[int] = None

@dataclass
class Metaorder:
    """Represents a metaorder composed of multiple child orders"""
    trader_id: int
    direction: int
    child_orders: List[Trade]
    start_time: dt.datetime
    end_time: dt.datetime
    
    @property
    def duration(self) -> float:
        """Duration in minutes"""
        return (self.end_time - self.start_time).total_seconds() / 60
    
    @property
    def total_volume(self) -> float:
        """Total volume of the metaorder"""
        return sum(trade.volume for trade in self.child_orders)
    
    @property
    def num_child_orders(self) -> int:
        """Number of child orders in the metaorder"""
        return len(self.child_orders)


