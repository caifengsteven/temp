class TrendLine:
    """Implements support and resistance line fitting for the Delta Engine."""
    
    def __init__(self, lookback: int = 5):
        self.lookback = lookback
        
    def fit_line(self, events: List[Dict], direction: str) -> Tuple[float, float]:
        """
        Fit a trend line to the events.
        Returns (slope, intercept)
        """
        if not events:
            return 0, 0
            
        filtered_events = [e for e in events if e['direction'] == direction]
        if len(filtered_events) < 2:
            return 0, 0
            
        # Use only the most recent events based on lookback
        points = filtered_events[-self.lookback:]
        
        # Convert timestamp to numeric format for fitting
        x = [i for i in range(len(points))]
        y = [p['price'] for p in points]
        
        if len(x) < 2:
            return 0, 0
            
        # Simple linear regression
        mean_x = sum(x) / len(x)
        mean_y = sum(y) / len(y)
        
        numerator = sum((x[i] - mean_x) * (y[i] - mean_y) for i in range(len(x)))
        denominator = sum((x[i] - mean_x) ** 2 for i in range(len(x)))
        
        if denominator == 0:
            slope = 0
        else:
            slope = numerator / denominator
            
        intercept = mean_y - slope * mean_x
        
        return slope, intercept
    
    def predict(self, slope: float, intercept: float, x: int) -> float:
        """Predict y value for a given x using the fitted line."""
        return slope * x + intercept


class Agent:
    """Agent representing a single threshold in the Delta Engine."""
    
    def __init__(self, threshold: float, lookback: int = 5):
        self.threshold = threshold
        self.intrinsic_time = IntrinsicTime(threshold)
        self.trend_fitter = TrendLine(lookback)
        self.last_signal = None
        self.is_active = True
        
    def process_tick(self, timestamp, price):
        """Process a price tick and return a trading signal if applicable."""
        event = self.intrinsic_time.process_tick(timestamp, price)
        
        if not event or not self.is_active:
            return None
            
        events = self.intrinsic_time.get_events()
        
        # Only generate signals for directional change events
        if event['type'] == 'dc':
            up_events = [e for e in events if e['direction'] == 'up']
            down_events = [e for e in events if e['direction'] == 'down']
            
            # Fit trend lines
            up_slope, up_intercept = self.trend_fitter.fit_line(up_events, 'up')
            down_slope, down_intercept = self.trend_fitter.fit_line(down_events, 'down')
            
            # Check for breakouts
            if event['direction'] == 'up':
                # Price broke above resistance line
                if len(down_events) >= self.trend_fitter.lookback:
                    x_position = len(down_events)
                    resistance = self.trend_fitter.predict(down_slope, down_intercept, x_position)
                    if price > resistance:
                        self.last_signal = {'direction': 'long', 'threshold': self.threshold, 
                                          'timestamp': timestamp, 'price': price}
                        return self.last_signal
            else:  # down direction
                # Price broke below support line
                if len(up_events) >= self.trend_fitter.lookback:
                    x_position = len(up_events)
                    support = self.trend_fitter.predict(up_slope, up_intercept, x_position)
                    if price < support:
                        self.last_signal = {'direction': 'short', 'threshold': self.threshold, 
                                          'timestamp': timestamp, 'price': price}
                        return self.last_signal
                        
        return None
    
    def update_activity(self, volatility_measure: float, threshold_multiplier: float = 2.0):
        """Update agent activity based on current market volatility."""
        # If volatility is too high for this threshold, deactivate the agent
        if volatility_measure > self.threshold * threshold_multiplier:
            self.is_active = False
        else:
            self.is_active = True


class DeltaEngine:
    """Implementation of the Delta Engine algorithm."""
    
    def __init__(self, thresholds: List[float], lookback: int = 5, unit_size: float = 1.0):
        self.agents = [Agent(t, lookback) for t in thresholds]
        self.position = 0
        self.unit_size = unit_size
        self.trades = []
        self.pnl = []
        self.total_pnl = 0
        
    def process_tick(self, timestamp, price):
        """Process a price tick through all agents and generate aggregated signals."""
        signals = []
        
        # Update volatility measure based on number of directional changes
        volatility = self._calculate_volatility()
        
        # Update agent activity based on volatility
        for agent in self.agents:
            agent.update_activity(volatility)
            signal = agent.process_tick(timestamp, price)
            if signal:
                signals.append(signal)
                
        # If we have signals, check for contrarian pattern
        if signals:
            # If we have no position, take the first signal
            if self.position == 0:
                best_signal = signals[0]
                if best_signal['direction'] == 'long':
                    self._execute_trade(timestamp, price, self.unit_size, best_signal)
                else:
                    self._execute_trade(timestamp, price, -self.unit_size, best_signal)
            # If we have a position, look for contrarian signals
            elif self.position > 0:  # We're long
                # Look for short signals
                short_signals = [s for s in signals if s['direction'] == 'short']
                if short_signals:
                    # Execute contrarian trade (double size to flip position)
                    self._execute_trade(timestamp, price, -2 * self.unit_size, short_signals[0])
            elif self.position < 0:  # We're short
                # Look for long signals
                long_signals = [s for s in signals if s['direction'] == 'long']
                if long_signals:
                    # Execute contrarian trade (double size to flip position)
                    self._execute_trade(timestamp, price, 2 * self.unit_size, long_signals[0])
                    
    def _execute_trade(self, timestamp, price, size, signal):
        """Execute a trade and update position."""
        self.position += size
        trade = {
            'timestamp': timestamp,
            'price': price,
            'size': size,
            'signal': signal,
            'position_after': self.position
        }
        self.trades.append(trade)
        
        # Update PnL
        if len(self.trades) > 1:
            last_trade = self.trades[-2]
            pnl = (price - last_trade['price']) * (-last_trade['position_after'])
            self.total_pnl += pnl
            self.pnl.append({
                'timestamp': timestamp,
                'pnl': pnl,
                'total_pnl': self.total_pnl
            })
    
    def _calculate_volatility(self):
        """Calculate volatility proxy based on number of directional changes."""
        dc_counts = [agent.intrinsic_time.count_directional_changes() for agent in self.agents]
        if not dc_counts:
            return 0
        return sum(dc_counts) / len(dc_counts)


def generate_simulated_prices(days: int = 30, points_per_day: int = 1440, 
                             initial_price: float = 100.0, 
                             volatility: float = 0.15) -> pd.DataFrame:
    """Generate simulated price data with GBM plus occasional jumps."""
    num_points = days * points_per_day
    
    # Create timestamps
    start_date = datetime.now() - timedelta(days=days)
    timestamps = [start_date + timedelta(minutes=i) for i in range(num_points)]
    
    # Parameters for geometric Brownian motion
    dt = 1.0 / points_per_day
    mu = 0.05  # drift
    sigma = volatility  # volatility
    
    # Generate log returns
    returns = np.random.normal(
        (mu - 0.5 * sigma**2) * dt,
        sigma * np.sqrt(dt),
        num_points
    )
    
    # Add occasional jumps
    jump_prob = 0.005
    jump_size_mean = 0.02
    jump_size_std = 0.01
    
    jumps = np.random.choice(
        [0, 1],
        size=num_points,
        p=[1 - jump_prob, jump_prob]
    )
    
    jump_sizes = np.random.normal(jump_size_mean, jump_size_std, num_points)
    jump_directions = np.random.choice([-1, 1], size=num_points)
    
    jump_returns = jumps * jump_sizes * jump_directions
    returns = returns + jump_returns
    
    # Calculate price series
    log_prices = np.cumsum(returns)
    prices = initial_price * np.exp(log_prices)
    
    # Create DataFrame
    df = pd.DataFrame({
        'timestamp': timestamps,
        'price': prices
    })
    
    return df


