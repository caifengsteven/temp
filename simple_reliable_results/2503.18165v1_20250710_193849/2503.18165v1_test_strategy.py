def generate_gbm_data(n_days=50, dt=1, mu1=0, sigma1=0.01, mu2=0, sigma2=0.02, s1_0=100, s2_0=100, s0_0=1):
    """
    Generate geometric Brownian motion data for two assets and a numeraire
    
    Parameters:
    n_days (int): Number of days to simulate
    dt (float): Time step
    mu1, mu2 (float): Drift parameters
    sigma1, sigma2 (float): Volatility parameters
    s1_0, s2_0, s0_0 (float): Initial prices
    
    Returns:
    dict: Dictionary with simulated price data
    """
    n_steps = n_days * 130  # 130 time steps per day
    times = np.arange(0, n_steps)
    
    # Generate Brownian motion
    dW1 = np.random.normal(0, np.sqrt(dt), n_steps)
    dW2 = np.random.normal(0, np.sqrt(dt), n_steps)
    
    # Generate GBM paths
    s0 = np.ones(n_steps) * s0_0  # Numeraire
    s1 = np.zeros(n_steps)
    s2 = np.zeros(n_steps)
    
    s1[0] = s1_0
    s2[0] = s2_0
    
    for i in range(1, n_steps):
        s1[i] = s1[i-1] * np.exp((mu1 - 0.5 * sigma1**2) * dt + sigma1 * dW1[i])
        s2[i] = s2[i-1] * np.exp((mu2 - 0.5 * sigma2**2) * dt + sigma2 * dW2[i])
    
    # Calculate discounted prices
    x1 = s1 / s0
    x2 = s2 / s0
    
    return {'x1': x1, 'x2': x2, 'time': times, 's0': s0, 's1': s1, 's2': s2}

