        # Initialize values for superhedging calculation
        # U_i in the paper (Definition A.10)
        U_values = {}
        
        # Start from terminal nodes
        for i in range(self.max_rebalances, -1, -1):
            for idx in nodes_by_level.get(i, []):
                if i == self.max_rebalances:
                    # Terminal node - payoff is X2
                    U_values[idx] = self.trajectory_set[idx][1]  # X2 value
                else:
                    # Skip type II arbitrage nodes
                    if arbitrage_nodes.get(idx, 0) == 2:
                        U_values[idx] = float('inf')
                        continue
                        
                    # Find children nodes
                    children = []
                    for next_idx in nodes_by_level.get(i + 1, []):
                        next_node = self.trajectory_set[next_idx]
                        if next_node[2] == i + 1:
                            # Check if this is a child of the current node
                            m1 = round((next_node[0] - self.trajectory_set[idx][0]) / self.delta_eps1)
                            m2 = round((next_node[1] - self.trajectory_set[idx][1]) / self.delta_eps2)
                            if any(ne[0] == m1 and ne[1] == m2 for ne in self.NE):
                                # Skip type II arbitrage children
                                if arbitrage_nodes.get(next_idx, 0) != 2:
                                    children.append(next_idx)
                    
                    if not children:
                        U_values[idx] = float('inf')
                        continue
                        
                    # Calculate superhedging value according to Definition A.10
                    # U_i(X) = inf_H sup_{X' in X(X,i)} [U_{i+1}(X') - H_i(X) · ΔX'_1]
                    
