def build_cnn_model(input_shape):
    """Build a simple CNN model."""
    inputs = Input(shape=input_shape)
    x = Conv1D(64, 3, activation='relu', padding='same')(inputs)
    x = MaxPooling1D(2)(x)
    x = Conv1D(128, 3, activation='relu', padding='same')(x)
    x = MaxPooling1D(2)(x)
    x = Flatten()(x)
    x = Dense(64, activation='relu')(x)
    x = Dropout(0.3)(x)
    outputs = Dense(1, activation='sigmoid')(x)
    
    model = Model(inputs, outputs)
    model.compile(optimizer=tf.keras.optimizers.Adam(learning_rate=0.001),
                 loss='binary_crossentropy',
                 metrics=['accuracy', tf.keras.metrics.AUC()])
    
    return model

def build_transformer_model(input_shape):
    """Build a simple Transformer model."""
    inputs = Input(shape=input_shape)
    x = Conv1D(64, 1, activation='relu')(inputs)  # Embedding layer
    
    # Transformer block
    attention_output = MultiHeadAttention(num_heads=4, key_dim=16)(x, x)
    x = LayerNormalization(epsilon=1e-6)(attention_output + x)
    
    # Feed-forward network
    x = Dense(128, activation='relu')(x)
    x = Dense(64, activation='relu')(x)
    
    # Global pooling
    x = GlobalAveragePooling1D()(x)
    x = Dropout(0.3)(x)
    outputs = Dense(1, activation='sigmoid')(x)
    
    model = Model(inputs, outputs)
    model.compile(optimizer=tf.keras.optimizers.Adam(learning_rate=0.001),
                 loss='binary_crossentropy',
                 metrics=['accuracy', tf.keras.metrics.AUC()])
    
    return model

def build_cnn_transformer_model(input_shape):
    """Build a CNN+Transformer model as described in the paper."""
    inputs = Input(shape=input_shape)
    
    # CNN branch
    cnn = Conv1D(64, 3, activation='relu', padding='same')(inputs)
    cnn = MaxPooling1D(2)(cnn)
    cnn = Conv1D(128, 3, activation='relu', padding='same')(cnn)
    cnn = MaxPooling1D(2)(cnn)
    
    # Transformer branch
    transformer = Conv1D(64, 1, activation='relu')(inputs)  # Embedding layer
    attention_output = MultiHeadAttention(num_heads=4, key_dim=16)(transformer, transformer)
    transformer = LayerNormalization(epsilon=1e-6)(attention_output + transformer)
    
    # Flatten and merge branches
    cnn_flat = Flatten()(cnn)
    transformer_flat = GlobalAveragePooling1D()(transformer)
    
    merged = Concatenate()([cnn_flat, transformer_flat])
    
    # Fully connected layers
    x = Dense(128, activation='relu')(merged)
    x = Dropout(0.3)(x)
    x = Dense(64, activation='relu')(x)
    x = Dropout(0.3)(x)
    outputs = Dense(1, activation='sigmoid')(x)
    
    model = Model(inputs, outputs)
    model.compile(optimizer=tf.keras.optimizers.Adam(learning_rate=0.001),
                 loss='binary_crossentropy',
                 metrics=['accuracy', tf.keras.metrics.AUC()])
    
    return model

def calculate_ks_score(y_true, y_pred_proba):
    """Calculate Kolmogorov-Smirnov (KS) statistic."""
    fpr, tpr, thresholds = roc_curve(y_true, y_pred_proba)
    return max(abs(tpr - fpr))

