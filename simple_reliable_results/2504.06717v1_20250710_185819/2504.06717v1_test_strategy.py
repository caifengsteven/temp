class OptimalExecutor:
    """Implementation of optimal executor agent based on Almgren-Chriss model"""
    
    def __init__(self, params: ExecutorParams):
        self.params = params
        self.inventory = params.initial_inventory
        self.cash = 0.0
        self.trading_rate_history = []
        self.inventory_history = []
        self.time_history = []
        
    def optimal_trading_rate(self, market_state: MarketState, mm_adjoint: float) -> float:
        """
        Calculate optimal trading rate v^{i,e} based on Equation (17)
        
        Args:
            market_state: Current market state
            mm_adjoint: Adjoint process value Y^{i,m} from market maker
            
        Returns:
            Optimal trading rate
        """
        # For buy program (negative initial inventory)
        if self.params.initial_inventory < 0:
            # Based on equation (17) in Section 4
            return max(1/(2 * self.params.temp_impact) * 
                       (self.adjoint_process(market_state.time) - mm_adjoint - 1/self.params.intensity_param), 
                       0.001)  # ε truncation
        else:
            # For sell program (positive initial inventory)
            return min(1/(2 * self.params.temp_impact) * 
                       (self.adjoint_process(market_state.time) - mm_adjoint - 1/self.params.intensity_param),
                       -0.001)  # ε truncation
    
    def adjoint_process(self, t: float) -> float:
        """
        Simplified adjoint process Y^{i,e} calculation
        
        Args:
            t: Current time
        
        Returns:
            Value of adjoint process
        """
        # In the simplified model, Y^{i,e} is related to inventory and penalties
        # This is a simplified version of the adjoint process from Equation (19)
        remaining_time = 1.0 - t
        return -2 * self.params.penalty_terminal * self.inventory * np.exp(-self.params.penalty_running * remaining_time)
    
    def update(self, market_state: MarketState, mm_adjoint: float, dt: float):
        """
        Update executor state based on optimal trading
        
        Args:
            market_state: Current market state
            mm_adjoint: Adjoint process value from market maker
            dt: Time step
        """
        # Calculate optimal trading rate
        trading_rate = self.optimal_trading_rate(market_state, mm_adjoint)
        
        # Update inventory: dQ^{i,e} = v^{i,e} dt (simplified from Equation 19)
        self.inventory += trading_rate * dt
        
        # Update cash: using transaction price with temporary impact
        transaction_price = market_state.ask_price if self.params.initial_inventory < 0 else market_state.bid_price
        temporary_impact = self.params.temp_impact * trading_rate
        
        # For buy: negative trading_rate (spend cash)
        # For sell: positive trading_rate (gain cash)
        self.cash -= (transaction_price + temporary_impact) * trading_rate * dt
        
        # Record history
        self.trading_rate_history.append(trading_rate)
        self.inventory_history.append(self.inventory)
        self.time_history.append(market_state.time)
    
    def get_pnl(self, current_price: float) -> float:
        """Calculate mark-to-market P&L"""
        return self.cash + self.inventory * current_price


class MarketMaker:
    """Implementation of market maker agent based on Avellaneda-Stoikov model"""
    
    def __init__(self, params: MarketMakerParams):
        self.params = params
        self.inventory = params.initial_inventory
        self.cash = 0.0
        self.bid_history = []
        self.ask_history = []
        self.inventory_history = []
        self.time_history = []
    
    def optimal_quotes(self, market_state: MarketState) -> Tuple[float, float]:
        """
        Calculate optimal bid and ask quotes based on Equation (17)
        
        Args:
            market_state: Current market state
            
        Returns:
            (bid_quote, ask_quote) as offset from reference price
        """
        # Based on equation (17) in Section 4
        adjoint = self.adjoint_process(market_state.time)
        
        # δ^{i,a} and δ^{i,b} from Equation (17)
        ask_offset = 1/self.params.intensity_param + adjoint
        bid_offset = 1/self.params.intensity_param - adjoint
        
        # Ensure quotes are reasonable (truncation)
        ask_offset = min(max(ask_offset, 0.01), 2.0)
        bid_offset = min(max(bid_offset, 0.01), 2.0)
        
        return bid_offset, ask_offset
    
    def adjoint_process(self, t: float) -> float:
        """
        Simplified adjoint process Y^{i,m} calculation
        
        Args:
            t: Current time
            
        Returns:
            Value of adjoint process
        """
        # In the simplified model, Y^{i,m} is related to inventory and penalties
        # This is a simplified version of the adjoint process from Equation (18)
        remaining_time = 1.0 - t
        return -2 * self.params.penalty_terminal * self.inventory * np.exp(-self.params.penalty_running * remaining_time)
    
    def fill_probability(self, spread: float) -> float:
        """
        Calculate fill probability based on exponential intensity function
        
        Args:
            spread: Spread from best price
            
        Returns:
            Probability of fill
        """
        # Λ(δ) = exp(-γ*δ) from Section 4
        return np.exp(-self.params.intensity_param * spread)
    
    def update(self, market_state: MarketState, exec_trading_rate: float, dt: float):
        """
        Update market maker state based on quotes and fills
        
        Args:
            market_state: Current market state
            exec_trading_rate: Trading rate from executor
            dt: Time step
        """
        # Calculate optimal quotes
        bid_offset, ask_offset = self.optimal_quotes(market_state)
        
        # Calculate absolute prices
        bid_price = market_state.reference_price - bid_offset
        ask_price = market_state.reference_price + ask_offset
        
        # Record quotes
        self.bid_history.append(bid_price)
        self.ask_history.append(ask_price)
        self.time_history.append(market_state.time)
        
        # Determine fills based on executor trading rate and noise trader activity
        noise_buy_rate = 0.5  # Simplified κ^b from the paper
        noise_sell_rate = 0.5  # Simplified κ^a from the paper
        
        # Calculate fill probabilities
        bid_fill_prob = self.fill_probability(market_state.bid_price - bid_price) if bid_price < market_state.bid_price else 0
        ask_fill_prob = self.fill_probability(ask_price - market_state.ask_price) if ask_price > market_state.ask_price else 0
        
        # Process executor trades
        if exec_trading_rate > 0:  # Executor is selling
            ask_volume = min(exec_trading_rate * dt, 0) * ask_fill_prob  # Negative for buy
        else:  # Executor is buying
            bid_volume = min(-exec_trading_rate * dt, 0) * bid_fill_prob  # Positive for sell
        
        # Process noise trades
        ask_volume = noise_sell_rate * ask_fill_prob * dt
        bid_volume = noise_buy_rate * bid_fill_prob * dt
        
        # Update inventory and cash
        self.inventory += bid_volume - ask_volume
        self.cash += ask_price * ask_volume - bid_price * bid_volume
        
        # Record inventory
        self.inventory_history.append(self.inventory)
    
    def get_pnl(self, current_price: float) -> float:
        """Calculate mark-to-market P&L"""
        return self.cash + self.inventory * current_price


def simulate_market_price(steps: int, dt: float, initial_price: float, volatility: float) -> np.ndarray:
    """
    Simulate reference price process as a martingale
    
    Args:
        steps: Number of simulation steps
        dt: Time step
        initial_price: Starting price
        volatility: Price volatility
        
    Returns:
        Array of simulated prices
    """
    prices = np.zeros(steps)
    prices[0] = initial_price
    
    for i in range(1, steps):
        # dP_t is a martingale
        prices[i] = prices[i-1] + np.random.normal(0, volatility * np.sqrt(dt))
    
    return prices


