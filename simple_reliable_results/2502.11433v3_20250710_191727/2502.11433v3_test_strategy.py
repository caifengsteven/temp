        # Create date range for one year of trading days
        start_date = datetime.now() - timedelta(days=365)
        dates = pd.date_range(start=start_date, periods=self.max_steps, freq='B')
        
        # Generate price series with random walk
        initial_price = 100.0
        returns = np.random.normal(0.0005, volatility, self.max_steps)
        prices = [initial_price]
        
        for ret in returns:
            prices.append(prices[-1] * (1 + ret))
            
        # Create additional technical indicators
        self.price_data = pd.DataFrame({
            'date': dates,
            'price': prices[:-1],
            'volume': np.random.randint(100000, 1000000, size=self.max_steps),
        })
        
