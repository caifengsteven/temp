def test_trading_strategy(ticker='TEST', use_rl=False, episodes=5):
    """Test a trading strategy with the simulated environment."""
    env = MarketEnvironment(ticker=ticker)
    policy = SimpleLLMTradingPolicy(use_rl_optimization=use_rl)
    
    best_metrics = None
    best_env = None
    
    for episode in range(episodes):
        state = env.reset()
        done = False
        total_reward = 0
        
        while not done:
            # Get action from policy
            action = policy.predict(state)
            
            # Take action in environment
            next_state, reward, done, info = env.step(action)
            
            # Update policy if using RL
            if use_rl:
                policy.update_weights(state, action, reward, next_state)
            
            # Update state and total reward
            state = next_state
            total_reward += reward
        
        # Calculate metrics for this episode
        metrics = calculate_metrics(env)
        
        # Save best result
        if best_metrics is None or metrics["Sharpe Ratio"] > best_metrics["Sharpe Ratio"]:
            best_metrics = metrics
            best_env = env
        
        print(f"Episode {episode+1}/{episodes} - Total Reward: {total_reward:.2f}")
        print(f"  Cumulative Return: {metrics['Cumulative Return (%)']:.2f}%")
        print(f"  Sharpe Ratio: {metrics['Sharpe Ratio']:.2f}")
        print(f"  Annualized Volatility: {metrics['Annualized Volatility (%)']:.2f}%")
        print(f"  Maximum Drawdown: {metrics['Maximum Drawdown (%)']:.2f}%")
        print()
    
    # Return the best result for visualization
    return best_env, best_metrics, policy

