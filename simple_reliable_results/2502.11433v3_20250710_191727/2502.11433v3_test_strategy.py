def calculate_metrics(env):
    """Calculate and return financial metrics based on environment history."""
    total_values = env.total_value_history
    initial_value = total_values[0]
    final_value = total_values[-1]
    
    # Calculate daily returns
    returns = np.diff(total_values) / total_values[:-1]
    
    # Cumulative Return
    cumulative_return = (final_value / initial_value - 1) * 100
    
    # Annualized Volatility
    daily_volatility = np.std(returns)
    annualized_volatility = daily_volatility * np.sqrt(252) * 100
    
    # Sharpe Ratio (assuming risk-free rate of 0 for simplicity)
    mean_daily_return = np.mean(returns)
    sharpe_ratio = (mean_daily_return / daily_volatility) * np.sqrt(252) if daily_volatility > 0 else 0
    
    # Maximum Drawdown
    peak = total_values[0]
    max_drawdown = 0
    
    for value in total_values:
        if value > peak:
            peak = value
        drawdown = (peak - value) / peak
        max_drawdown = max(max_drawdown, drawdown)
    
    max_drawdown *= 100  # Convert to percentage
    
    return {
        "Cumulative Return (%)": cumulative_return,
        "Sharpe Ratio": sharpe_ratio,
        "Annualized Volatility (%)": annualized_volatility,
        "Maximum Drawdown (%)": max_drawdown
    }

