    def run_day(self):
        """Run a single trading day simulation"""
        self.day += 1
        self.update_prices()
        
        # Store initial values for calculating daily returns
        initial_values = {name: agent.calculate_portfolio_value(self.stocks) 
                         for name, agent in self.agents.items()}
        
        # Each agent makes a trading decision
        for name, agent in self.agents.items():
            use_visual = "visual" in name.lower()
