class Stock:
    """Stock model with price history and attributes"""
    def __init__(self, name: str, initial_price: float, dps: float, quantity: int):
        self.name = name
        self.current_price = initial_price
        self.dps = dps  # Dividend Per Share
        self.quantity = quantity
        self.historical_prices = [initial_price]
        self.volume = random.randint(500000, 5000000)
        
    def update_price(self, new_price: float):
        self.current_price = new_price
        self.historical_prices.append(new_price)
        
    def get_price_history(self, days: int = 10) -> List[float]:
        """Get last n days of price history"""
        return self.historical_prices[-days:]
    
    def get_intraday_range(self) -> Tuple[float, float, float]:
        """Return intraday high, low, mean"""
        base = self.current_price
        high = round(base * (1 + random.uniform(0.01, 0.03)), 2)
        low = round(base * (1 - random.uniform(0.01, 0.03)), 2)
        mean = round((high + low) / 2, 2)
        return high, low, mean
    
    def get_price_change(self) -> float:
        """Get percentage price change from previous day"""
        if len(self.historical_prices) < 2:
            return 0.0
        prev = self.historical_prices[-2]
        return round((self.current_price - prev) / prev * 100, 2)


class Agent:
    """Trading agent with portfolio and strategies"""
    def __init__(self, name: str, cash: float, years: int, occupation: str):
        self.name = name
        self.cash = cash
        self.years = years  # investment duration
        self.occupation = occupation
        self.portfolio: Dict[str, Tuple[int, float]] = {}  # {stock_name: (quantity, avg_price)}
        self.history = []
        self.total_return = 0.0
        self.daily_returns = []
        
    def buy(self, stock_name: str, quantity: int, price: float) -> bool:
        """Buy a stock and update portfolio"""
        cost = quantity * price
        if cost > self.cash:
            return False
        
        self.cash -= cost
        if stock_name in self.portfolio:
            curr_qty, avg_price = self.portfolio[stock_name]
            total_qty = curr_qty + quantity
            total_cost = (curr_qty * avg_price) + (quantity * price)
            new_avg_price = total_cost / total_qty
            self.portfolio[stock_name] = (total_qty, new_avg_price)
        else:
            self.portfolio[stock_name] = (quantity, price)
            
        self.history.append(("buy", stock_name, quantity, price, datetime.now()))
        return True
    
    def sell(self, stock_name: str, quantity: int, price: float) -> bool:
        """Sell a stock and update portfolio"""
        if stock_name not in self.portfolio:
            return False
        
        curr_qty, avg_price = self.portfolio[stock_name]
        if quantity > curr_qty:
            return False
        
        self.cash += quantity * price
        if quantity == curr_qty:
            del self.portfolio[stock_name]
        else:
            self.portfolio[stock_name] = (curr_qty - quantity, avg_price)
            
        self.history.append(("sell", stock_name, quantity, price, datetime.now()))
        return True
    
    def calculate_portfolio_value(self, stocks: Dict[str, Stock]) -> float:
        """Calculate current portfolio value"""
        value = self.cash
        for stock_name, (quantity, _) in self.portfolio.items():
            if stock_name in stocks:
                value += quantity * stocks[stock_name].current_price
        return value
    
    def update_performance(self, stocks: Dict[str, Stock], initial_value: float):
        """Update agent performance metrics"""
        current_value = self.calculate_portfolio_value(stocks)
        daily_return = (current_value - initial_value) / initial_value * 100
        self.daily_returns.append(daily_return)
        self.total_return = (current_value / initial_value - 1) * 100
    
    def get_sharpe_ratio(self) -> float:
        """Calculate Sharpe ratio (without risk-free rate)"""
        if not self.daily_returns or np.std(self.daily_returns) == 0:
            return 0.0
        return np.mean(self.daily_returns) / np.std(self.daily_returns)
    
    def get_win_rate(self) -> float:
        """Calculate percentage of profitable trades"""
        if not self.history:
            return 0.0
        profitable = sum(1 for op, _, _, price, _ in self.history if op == "sell" and price > 0)
        return profitable / len(self.history) * 100


class TradingArena:
    """Simulation environment for agent trading"""
    def __init__(self):
        self.stocks = {}
        self.agents = {}
        self.day = 0
        self.market_index = 100.0
        self.initial_values = {}
        
    def add_stock(self, name: str, initial_price: float, dps: float, quantity: int):
        """Add a stock to the market"""
        self.stocks[name] = Stock(name, initial_price, dps, quantity)
        
    def add_agent(self, name: str, cash: float, years: int, occupation: str):
        """Add an agent to the simulation"""
        self.agents[name] = Agent(name, cash, years, occupation)
        self.initial_values[name] = cash
        
    def update_prices(self):
        """Update stock prices for the next day"""
        for stock in self.stocks.values():
            # Generate a random price movement
            change = random.uniform(-0.03, 0.03)
            new_price = round(stock.current_price * (1 + change), 2)
            stock.update_price(new_price)
        
        # Update market index
        self.market_index *= (1 + random.uniform(-0.01, 0.02))
    
    def generate_text_data(self, stock_name: str) -> str:
        """Generate textual representation of stock data"""
        stock = self.stocks[stock_name]
        high, low, mean = stock.get_intraday_range()
        
        text = f"- {stock_name}:\n"
        text += f"  - The closing prices in the past 10 days are: {stock.get_price_history()}\n"
        text += f"  - Volume: {stock.volume}\n"
        text += f"  - Current price change: {stock.get_price_change()}%\n"
        text += f"  - Current price: ${stock.current_price}\n"
        text += f"  - Intraday High: ${high}\n"
        text += f"  - Intraday Low: ${low}\n"
        text += f"  - Intraday Mean: ${mean}\n"
        
        return text
    
    def generate_visual_data(self, stock_name: str) -> str:
        """Generate K-line chart of stock data (returns base64 image string)"""
        stock = self.stocks[stock_name]
        prices = stock.get_price_history(10)
        dates = [(datetime.now() - timedelta(days=9-i)).strftime('%m/%d') for i in range(10)]
        
        # Create figure
        fig, ax = plt.subplots(figsize=(8, 4))
        ax.plot(dates, prices, marker='o')
        ax.set_title(f"{stock_name} Price Chart")
        ax.set_xlabel("Date")
        ax.set_ylabel("Price ($)")
        ax.grid(True, linestyle='--', alpha=0.7)
        
        # Convert plot to base64 string
        buffer = io.BytesIO()
        plt.savefig(buffer, format='png')
        buffer.seek(0)
        img_str = base64.b64encode(buffer.getvalue()).decode()
        plt.close(fig)
        
        return f"data:image/png;base64,{img_str}"
    
