def train_model(model, data, optimizer, criterion, num_epochs=100):
    """Train the GNN model"""
    model.train()
    
    # Split edges for training and testing
    edge_index = data.edge_index
    edge_attr = data.edge_attr
    y = data.y
    
    num_edges = edge_index.size(1)
    perm = torch.randperm(num_edges)
    
    train_idx = perm[:int(0.8 * num_edges)]
    test_idx = perm[int(0.8 * num_edges):]
    
    train_edge_index = edge_index[:, train_idx]
    train_edge_attr = edge_attr[train_idx]
    train_y = y[train_idx]
    
    test_edge_index = edge_index[:, test_idx]
    test_edge_attr = edge_attr[test_idx]
    test_y = y[test_idx]
    
    for epoch in range(num_epochs):
        optimizer.zero_grad()
        out = model(data.x, train_edge_index, train_edge_attr)
        loss = criterion(out, train_y)
        loss.backward()
        optimizer.step()
        
        if (epoch + 1) % 10 == 0:
            print(f'Epoch {epoch+1}/{num_epochs}, Loss: {loss.item():.4f}')
    
    # Evaluate on test set
    model.eval()
    with torch.no_grad():
        test_out = model(data.x, test_edge_index, test_edge_attr)
        test_pred = test_out.argmax(dim=1)
        
        # Calculate accuracy
        accuracy = (test_pred == test_y).sum().item() / test_y.size(0)
        
        # Generate classification report
        y_true = test_y.cpu().numpy()
        y_pred = test_pred.cpu().numpy()
        
        print("\nTest Results:")
        print(f"Accuracy: {accuracy:.4f}")
        print("\nClassification Report:")
        print(classification_report(y_true, y_pred))
        
        # Confusion Matrix
        cm = confusion_matrix(y_true, y_pred)
        print("\nConfusion Matrix:")
        print(cm)
    
    return model, accuracy, y_true, y_pred

def visualize_graph(G, fraud_edges=None):
    """Visualize the transaction graph with fraud highlighted"""
    plt.figure(figsize=(12, 10))
    
    # Create position layout
    pos = nx.spring_layout(G, seed=42)
    
    # Draw nodes
    nx.draw_networkx_nodes(G, pos, node_size=50, node_color='blue', alpha=0.6)
    
    # Draw normal edges
    normal_edges = [(u, v) for u, v, d in G.edges(data=True) if d['is_fraud'] == 0]
    nx.draw_networkx_edges(G, pos, edgelist=normal_edges, width=1, alpha=0.5, edge_color='gray')
    
    # Draw fraud edges if provided
    if fraud_edges:
        nx.draw_networkx_edges(G, pos, edgelist=fraud_edges, width=2, alpha=1.0, edge_color='red')
    
    plt.title("Transaction Network (Red = Fraudulent Transactions)")
    plt.axis('off')
    plt.tight_layout()
    plt.savefig("transaction_network.png")
    print("Graph visualization saved as 'transaction_network.png'")

