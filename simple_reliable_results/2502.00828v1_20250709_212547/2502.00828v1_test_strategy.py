def test_gradient_sensitivity(model: nn.Module, test_dataset: TensorDataset) -> None:
    """
    Test the paper's hypothesis that assets with higher gradient sensitivities
    have lower prediction errors.
    """
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    model = model.to(device)
    model.eval()
    
    # Extract test data
    test_returns, test_macro, test_actual = test_dataset.tensors
    
    # Use a subset for analysis
    n_samples = 50
    test_returns = test_returns[:n_samples].to(device)
    test_macro = test_macro[:n_samples].to(device)
    test_actual = test_actual[:n_samples].to(device)
    
    # Enable gradient computation
    with torch.set_grad_enabled(True):
        # Historical returns for covariance
        hist_returns = test_returns[:, -30:, :]
        
        # Forward pass
        predicted_returns, predicted_weights = model(test_returns, test_macro, hist_returns)
        
        # Compute gradient sensitivities (manually simplified from the paper)
        n_assets = predicted_returns.shape[1]
        sensitivities = torch.zeros(n_samples, n_assets, device=device)
        
        for i in range(n_samples):
            for j in range(n_assets):
                # Create a one-hot vector for the gradient
                grad_output = torch.zeros_like(predicted_weights)
                grad_output[i, j] = 1.0
                
                # Get gradient of weights with respect to predicted returns
                predicted_weights.backward(grad_output, retain_graph=True)
                
                # Store the gradient magnitude
                param_grad = next(model.parameters()).grad
                sensitivities[i, j] = torch.norm(param_grad)
                
                # Reset gradients
                model.zero_grad()
    
    # Convert to numpy
    sensitivities = sensitivities.cpu().numpy().mean(axis=0)
    predicted_returns = predicted_returns.detach().cpu().numpy()
    actual_returns = test_actual.cpu().numpy()
    
    # Calculate prediction errors
    mse_errors = np.mean((predicted_returns - actual_returns)**2, axis=0)
    
    # Sort assets by sensitivity
    sorted_indices = np.argsort(sensitivities)
    top_10_pct = sorted_indices[-int(n_assets*0.1):]
    bottom_10_pct = sorted_indices[:int(n_assets*0.1)]
    
    # Calculate error differences
    top_mse = np.mean(mse_errors[top_10_pct])
    bottom_mse = np.mean(mse_errors[bottom_10_pct])
    
    print("\nGradient Sensitivity Analysis:")
    print(f"MSE for top 10% sensitivity assets: {top_mse:.6f}")
    print(f"MSE for bottom 10% sensitivity assets: {bottom_mse:.6f}")
    print(f"Difference (Bottom - Top): {bottom_mse - top_mse:.6f}")
    
