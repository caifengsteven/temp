    plt.figure(figsize=(10, 6))
    plt.scatter(sensitivities, mse_errors)
    plt.title('Gradient Sensitivity vs. Prediction Error')
    plt.xlabel('Gradient Sensitivity')
    plt.ylabel('Mean Squared Error')
    
    # Highlight top and bottom 10%
    plt.scatter(sensitivities[top_10_pct], mse_errors[top_10_pct], color='green', 
                label='Top 10% Sensitivity')
    plt.scatter(sensitivities[bottom_10_pct], mse_errors[bottom_10_pct], color='red', 
                label='Bottom 10% Sensitivity')
    
    # Add trend line
    z = np.polyfit(sensitivities, mse_errors, 1)
    p = np.poly1d(z)
    plt.plot(np.sort(sensitivities), p(np.sort(sensitivities)), "r--", 
             label=f'Trend: y={z[0]:.4f}x+{z[1]:.4f}')
    
    plt.legend()
    plt.show()


