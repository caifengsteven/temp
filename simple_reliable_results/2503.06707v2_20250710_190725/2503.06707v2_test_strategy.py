def test_differential_regression():
    """
    Test Differential Regression as described in the paper.
    """
    print("\n=== Testing Differential Regression ===")
    
    # Setup simulation parameters
    n_assets = 3
    correlation = 0.3
    volatility = 0.2
    risk_free_rate = 0.05
    time_to_maturity = 1.0
    
    # Create simulator
    simulator = BasketOptionSimulator(
        n_assets=n_assets,
        correlation=correlation,
        volatility=volatility,
        risk_free_rate=risk_free_rate,
        time_to_maturity=time_to_maturity
    )
    
    # Simulate data
    n_samples = 5000
    X = simulator.simulate_states(n_samples)
    
    # Define basket weights and strike
    weights = np.array([0.4, 0.3, 0.3])
    strike = 110.0
    
    # Compute payoffs and pathwise differentials
    Y, Z = simulator.basket_payoff(X, weights, strike)
    
    # Split data into training and test sets
    n_train = 4000
    X_train, X_test = X[:n_train], X[n_train:]
    Y_train, Y_test = Y[:n_train], Y[n_train:]
    Z_train, Z_test = Z[:n_train], Z[n_train:]
    
    # First apply Differential PCA to reduce dimensions
    dpca = DifferentialPCA(n_components=1)
    dpca.fit(X_train, Z_train)
    
    # Transform data to reduced feature space
    L_train = dpca.transform(X_train)
    L_test = dpca.transform(X_test)
    
    # Create basis functions (polynomials up to degree 3)
    def create_basis_functions(L, degree=3):
        features = []
        for d in range(degree + 1):
            if d == 0:
                features.append(np.ones(L.shape[0]))
            else:
                features.append(L[:, 0] ** d)
        return np.column_stack(features)
    
    phi_train = create_basis_functions(L_train)
    phi_test = create_basis_functions(L_test)
    
    # Compute derivatives of basis functions
    def compute_basis_derivatives(L, degree=3):
        derivatives = []
        for d in range(degree + 1):
            if d == 0:
                derivatives.append(np.zeros(L.shape[0]))
            else:
                derivatives.append(d * L[:, 0] ** (d - 1))
        return np.column_stack(derivatives)
    
    dphi_train = compute_basis_derivatives(L_train)
    dphi_test = compute_basis_derivatives(L_test)
    
    # Project pathwise differentials to the reduced feature space
    S_train = Z_train @ dpca.eigenvectors
    S_test = Z_test @ dpca.eigenvectors
    
    # Standard linear regression
    Cphi = phi_train.T @ phi_train / n_train
    Cphi_Y = phi_train.T @ Y_train / n_train
    
    # Regularization parameter
    lambda_reg = 1e-6
    
    # Standard linear regression with Tikhonov regularization
    beta_standard = np.linalg.solve(Cphi + lambda_reg * np.eye(phi_train.shape[1]), Cphi_Y)
    
    # Differential linear regression
    lambda_diff = np.mean(Y_train**2) / np.mean(S_train**2)  # Scaling factor
    
    Cdphi = dphi_train.T @ dphi_train / n_train
    Cdphi_S = dphi_train.T @ S_train / n_train
    
    beta_differential = np.linalg.solve(
        Cphi + lambda_diff * Cdphi + lambda_reg * np.eye(phi_train.shape[1]),
        Cphi_Y + lambda_diff * Cdphi_S
    )
    
    # Make predictions
    Y_pred_standard = phi_test @ beta_standard
    Y_pred_differential = phi_test @ beta_differential
    
    # Compute mean squared errors
    mse_standard = np.mean((Y_test - Y_pred_standard) ** 2)
    mse_differential = np.mean((Y_test - Y_pred_differential) ** 2)
    
    print(f"Standard regression MSE: {mse_standard:.6f}")
    print(f"Differential regression MSE: {mse_differential:.6f}")
    print(f"Improvement: {(1 - mse_differential/mse_standard) * 100:.2f}%")
    
    # Plot results
    plt.figure(figsize=(12, 5))
    
    plt.subplot(1, 2, 1)
    plt.scatter(L_test, Y_test, alpha=0.3, label='True')
    
    # Sort for smooth curve plotting
    idx = np.argsort(L_test.flatten())
    L_sorted = L_test[idx]
    
    plt.plot(L_sorted, phi_test[idx] @ beta_standard, 'r-', 
             linewidth=2, label='Standard Regression')
    plt.plot(L_sorted, phi_test[idx] @ beta_differential, 'g-', 
             linewidth=2, label='Differential Regression')
    
    plt.xlabel('Reduced Feature')
    plt.ylabel('Option Payoff')
    plt.title('Regression Results')
    plt.legend()
    
    plt.subplot(1, 2, 2)
    plt.scatter(Y_test, Y_pred_standard, alpha=0.3, label='Standard')
    plt.scatter(Y_test, Y_pred_differential, alpha=0.3, label='Differential')
    
    # Add diagonal line
    min_val = min(np.min(Y_test), np.min(Y_pred_standard), np.min(Y_pred_differential))
    max_val = max(np.max(Y_test), np.max(Y_pred_standard), np.max(Y_pred_differential))
    plt.plot([min_val, max_val], [min_val, max_val], 'k--')
    
    plt.xlabel('True Payoff')
    plt.ylabel('Predicted Payoff')
    plt.title('Predicted vs True')
    plt.legend()
    
    plt.tight_layout()
    plt.show()
    
    return {
        'mse_standard': mse_standard,
        'mse_differential': mse_differential,
        'beta_standard': beta_standard,
        'beta_differential': beta_differential
    }


