class DifferentialPCA:
    """
    Implementation of Differential PCA as described in the paper
    "Axes that matter: PCA with a difference" by Brian Huge and Antoine Savine.
    """
    def __init__(self, n_components=None, tolerance=None):
        """
        Initialize Differential PCA.
        
        Parameters:
        -----------
        n_components : int, optional
            Number of components to keep.
        tolerance : float, optional
            Tolerance level for eigenvalues. Components with cumulative eigenvalues
            below this threshold will be kept.
        """
        self.n_components = n_components
        self.tolerance = tolerance
        self.projector = None
        self.eigenvectors = None
        self.eigenvalues = None
        
    def fit(self, X, Z):
        """
        Fit the Differential PCA model.
        
        Parameters:
        -----------
        X : array-like, shape (n_samples, n_features)
            The input data (market states).
        Z : array-like, shape (n_samples, n_features)
            The pathwise differentials (derivatives of payoffs w.r.t. input state).
        
        Returns:
        --------
        self : object
            Returns self.
        """
        # Compute covariance matrix of pathwise differentials
        cov_Z = np.cov(Z, rowvar=False)
        
        # Perform eigenvalue decomposition
        eigenvalues, eigenvectors = np.linalg.eigh(cov_Z)
        
        # Sort eigenvalues and eigenvectors in descending order
        idx = eigenvalues.argsort()[::-1]
        eigenvalues = eigenvalues[idx]
        eigenvectors = eigenvectors[:, idx]
        
        # Determine number of components to keep
        if self.n_components is not None:
            n_components = min(self.n_components, X.shape[1])
        elif self.tolerance is not None:
            total_eigenvalue = np.sum(eigenvalues)
            cumulative_eigenvalues = np.cumsum(eigenvalues) / total_eigenvalue
            n_components = np.searchsorted(cumulative_eigenvalues, 1 - self.tolerance) + 1
        else:
            n_components = X.shape[1]
            
        # Store the results
        self.eigenvectors = eigenvectors[:, :n_components]
        self.eigenvalues = eigenvalues[:n_components]
        self.projector = self.eigenvectors @ self.eigenvectors.T
        
        return self
    
    def transform(self, X):
        """
        Transform X to the reduced feature space.
        
        Parameters:
        -----------
        X : array-like, shape (n_samples, n_features)
            The input data to transform.
            
        Returns:
        --------
        L : array-like, shape (n_samples, n_components)
            The reduced representation of X.
        """
        return X @ self.eigenvectors
    
    def inverse_transform(self, L):
        """
        Transform from feature space back to original space.
        
        Parameters:
        -----------
        L : array-like, shape (n_samples, n_components)
            The data in the reduced feature space.
            
        Returns:
        --------
        X_approx : array-like, shape (n_samples, n_features)
            The reconstructed data in the original space.
        """
        return L @ self.eigenvectors.T
    
    def reconstruction_error(self, X, Z):
        """
        Compute the differential reconstruction error.
        
        Parameters:
        -----------
        X : array-like, shape (n_samples, n_features)
            The input data.
        Z : array-like, shape (n_samples, n_features)
            The pathwise differentials.
            
        Returns:
        --------
        error : float
            The differential reconstruction error.
        """
        Z_approx = Z @ self.projector
        return np.mean(np.sum((Z - Z_approx) ** 2, axis=1))


class BasketOptionSimulator:
    """
    Simulator for basket options in a multi-asset Black-Scholes model.
    """
    def __init__(self, n_assets, correlation, volatility, risk_free_rate, time_to_maturity):
        """
        Initialize the simulator.
        
        Parameters:
        -----------
        n_assets : int
            Number of assets in the basket.
        correlation : float
            Correlation between assets.
        volatility : float or array-like
            Volatility of assets.
        risk_free_rate : float
            Risk-free interest rate.
        time_to_maturity : float
            Time to maturity in years.
        """
        self.n_assets = n_assets
        self.correlation = correlation
        self.volatility = volatility if isinstance(volatility, np.ndarray) else np.ones(n_assets) * volatility
        self.risk_free_rate = risk_free_rate
        self.time_to_maturity = time_to_maturity
        
        # Create correlation matrix
        self.correlation_matrix = np.ones((n_assets, n_assets)) * correlation
        np.fill_diagonal(self.correlation_matrix, 1.0)
        
        # Create covariance matrix
        vol_matrix = np.diag(self.volatility)
        self.covariance_matrix = vol_matrix @ self.correlation_matrix @ vol_matrix
        
        # Cholesky decomposition for correlated random variables
        self.cholesky_matrix = np.linalg.cholesky(self.correlation_matrix)
        
    def simulate_states(self, n_samples, initial_prices=None):
        """
        Simulate market states (asset prices).
        
        Parameters:
        -----------
        n_samples : int
            Number of samples to simulate.
        initial_prices : array-like, optional
            Initial prices of assets.
            
        Returns:
        --------
        X : array-like, shape (n_samples, n_assets)
            Simulated asset prices.
        """
        if initial_prices is None:
            initial_prices = np.ones(self.n_assets) * 100.0
            
        # Generate correlated normal random variables
        Z = np.random.normal(size=(n_samples, self.n_assets))
        correlated_Z = Z @ self.cholesky_matrix.T
        
        # Simulate log-normal asset prices
        drift = (self.risk_free_rate - 0.5 * self.volatility**2) * self.time_to_maturity
        diffusion = self.volatility * np.sqrt(self.time_to_maturity) * correlated_Z
        
        X = initial_prices * np.exp(drift + diffusion)
        return X
    
    def basket_payoff(self, X, weights, strike):
        """
        Compute basket option payoff.
        
        Parameters:
        -----------
        X : array-like, shape (n_samples, n_assets)
            Asset prices.
        weights : array-like, shape (n_assets,)
            Basket weights.
        strike : float
            Strike price.
            
        Returns:
        --------
        Y : array-like, shape (n_samples,)
            Option payoffs.
        Z : array-like, shape (n_samples, n_assets)
            Pathwise differentials.
        """
        # Normalize weights
        weights = weights / np.sum(weights)
        
        # Compute basket values
        basket_values = X @ weights
        
        # Compute payoffs (max(basket - strike, 0))
        Y = np.maximum(basket_values - strike, 0)
        
        # Compute pathwise differentials
        Z = np.zeros_like(X)
        in_the_money = basket_values > strike
        Z[in_the_money] = weights * in_the_money[:, np.newaxis]
        
        return Y, Z
    
    def spread_option_payoff(self, X, strike=0.0):
        """
        Compute spread option payoff.
        
        Parameters:
        -----------
        X : array-like, shape (n_samples, n_assets)
            Asset prices.
        strike : float, optional
            Strike price.
            
        Returns:
        --------
        Y : array-like, shape (n_samples,)
            Option payoffs.
        Z : array-like, shape (n_samples, n_assets)
            Pathwise differentials.
        """
        if X.shape[1] < 2:
            raise ValueError("Spread option requires at least 2 assets")
            
        # Compute spread values (asset2 - asset1)
        spread_values = X[:, 1] - X[:, 0]
        
        # Compute payoffs (max(spread - strike, 0))
        Y = np.maximum(spread_values - strike, 0)
        
        # Compute pathwise differentials
        Z = np.zeros_like(X)
        in_the_money = spread_values > strike
        
        # For in-the-money scenarios, derivative w.r.t. first asset is -1, w.r.t. second asset is 1
        Z[in_the_money, 0] = -1.0
        Z[in_the_money, 1] = 1.0
        
        return Y, Z


def test_classic_vs_differential_pca():
    """
    Test and compare classic PCA vs Differential PCA on a spread option example.
    This recreates the example mentioned in the paper where classic PCA fails.
    """
    print("\n=== Testing Classic PCA vs Differential PCA on Spread Option ===")
    
    # Setup simulation parameters
    n_assets = 2
    correlation = 0.95  # High correlation between assets
    volatility = 0.2
    risk_free_rate = 0.05
    time_to_maturity = 1.0
    
    # Create simulator
    simulator = BasketOptionSimulator(
        n_assets=n_assets,
        correlation=correlation,
        volatility=volatility,
        risk_free_rate=risk_free_rate,
        time_to_maturity=time_to_maturity
    )
    
    # Simulate data
    n_samples = 10000
    X = simulator.simulate_states(n_samples)
    Y, Z = simulator.spread_option_payoff(X)
    
    # Apply classic PCA
    pca = PCA(n_components=1)
    X_pca = pca.fit_transform(X)
    X_reconstructed = pca.inverse_transform(X_pca)
    
    # Apply Differential PCA
    dpca = DifferentialPCA(n_components=1)
    dpca.fit(X, Z)
    L = dpca.transform(X)
    X_dpca_reconstructed = dpca.inverse_transform(L)
    
    # Compute reconstruction errors for X
    pca_recon_error = np.mean(np.sum((X - X_reconstructed) ** 2, axis=1))
    dpca_recon_error = np.mean(np.sum((X - X_dpca_reconstructed) ** 2, axis=1))
    
    print(f"Classic PCA X reconstruction error: {pca_recon_error:.4f}")
    print(f"Differential PCA X reconstruction error: {dpca_recon_error:.4f}")
    
    # Compute option payoffs and pathwise differentials on reconstructed states
    Y_pca, Z_pca = simulator.spread_option_payoff(X_reconstructed)
    Y_dpca, Z_dpca = simulator.spread_option_payoff(X_dpca_reconstructed)
    
