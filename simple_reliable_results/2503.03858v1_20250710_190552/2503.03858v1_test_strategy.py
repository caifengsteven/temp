    mm_metrics = mm_sim['daily_metrics']
    
    # Ensure we're comparing the same days
    common_days = sorted(set(normal_metrics.keys()) & set(mm_metrics.keys()))
    
    analysis = {
        'days': common_days,
        'normal_spreads': [normal_metrics[day]['spread'] if normal_metrics[day]['spread'] is not None else 0 for day in common_days],
        'mm_spreads': [mm_metrics[day]['spread'] if mm_metrics[day]['spread'] is not None else 0 for day in common_days],
        'normal_rel_spreads': [normal_metrics[day]['relative_spread'] if normal_metrics[day]['relative_spread'] is not None else 0 for day in common_days],
        'mm_rel_spreads': [mm_metrics[day]['relative_spread'] if mm_metrics[day]['relative_spread'] is not None else 0 for day in common_days],
        'normal_execution_ratios': [normal_metrics[day]['execution_ratio'] for day in common_days],
        'mm_execution_ratios': [mm_metrics[day]['execution_ratio'] for day in common_days],
        'normal_mid_prices': [normal_metrics[day]['mid_price'] if normal_metrics[day]['mid_price'] is not None else 0 for day in common_days],
        'mm_mid_prices': [mm_metrics[day]['mid_price'] if mm_metrics[day]['mid_price'] is not None else 0 for day in common_days]
    }
    
    # Calculate average improvements
    if len(common_days) > 0:
        # Filter out None values for valid comparisons
        valid_spreads = [(n, m) for n, m in zip(analysis['normal_spreads'], analysis['mm_spreads']) if n is not None and m is not None]
        valid_rel_spreads = [(n, m) for n, m in zip(analysis['normal_rel_spreads'], analysis['mm_rel_spreads']) if n is not None and m is not None]
        
        spread_improvements = [n - m for n, m in valid_spreads]
        rel_spread_improvements = [n - m for n, m in valid_rel_spreads]
