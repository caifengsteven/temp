        if order.epsilon == 1:  # Buy order
            # Sort sell orders by price (ascending)
            self.sell_orders.sort(key=lambda x: x.price)
            
            # Match with sell orders
            remaining_volume = order.volume
            while remaining_volume > 0 and len(self.sell_orders) > 0:
                sell_order = self.sell_orders[0]
                
                if sell_order.price <= order.price:  # Match is possible
                    executed_volume = min(remaining_volume, sell_order.volume)
                    execution_price = sell_order.price  # Price is set by the resting order
                    
                    # Record execution
                    execution = (order, sell_order, execution_price, order.timestamp)
                    self.executed_orders.append(execution)
                    executions.append(execution)
                    
                    if from_market_maker:
                        self.market_maker_executions.append(execution)
                    
                    # Update volumes
                    remaining_volume -= executed_volume
                    sell_order.volume -= executed_volume
                    
                    # Remove filled sell order
                    if sell_order.volume <= 0:
                        self.sell_orders.pop(0)
                else:
                    break  # No more matches possible
            
