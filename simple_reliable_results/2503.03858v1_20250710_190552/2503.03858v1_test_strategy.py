def generate_simulated_data(
    start_date: datetime,
    end_date: datetime,
    orders_per_day: int = 100,
    initial_price: float = 300.0,
    price_volatility: float = 2.38,
    volume_scale: float = 1000
) -> List[Order]:
    """Generate simulated order data for the informal currency market."""
    orders = []
    current_date = start_date
    price = initial_price
    
    # Define an exponential distribution for order sizes (as observed in the paper)
    volume_param = 1 / volume_scale
    
    while current_date <= end_date:
        # Daily price drift - small random walk
        price = max(price * (1 + np.random.normal(0, price_volatility / 100)), 50.0)
        
        # Generate orders for the day
        for _ in range(orders_per_day):
            # Order timestamp within the day
            hour = np.random.randint(8, 20)  # Business hours
            minute = np.random.randint(0, 60)
            second = np.random.randint(0, 60)
            order_time = current_date.replace(hour=hour, minute=minute, second=second)
            
            # Order side (buy or sell)
            epsilon = np.random.choice([1, -1])
            
            # Order price with some random spread around the mid price
            spread_pct = np.random.exponential(0.03)  # 3% average spread
            if epsilon == 1:  # Buy order
                order_price = price * (1 - spread_pct)
            else:  # Sell order
                order_price = price * (1 + spread_pct)
            
            # Order volume - exponentially distributed
            volume = max(10, np.random.exponential(1/volume_param))
            
            orders.append(Order(
                epsilon=epsilon,
                price=order_price,
                volume=volume,
                timestamp=order_time
            ))
        
        current_date += timedelta(days=1)
    
    return orders


def run_lob_simulation(orders: List[Order], with_market_maker: bool = False) -> Dict:
    """Run a simulation of the limit order book with the given orders."""
    lob = LimitOrderBook()
    mm = MarketMaker() if with_market_maker else None
    
    # Group orders by day for analysis
    orders_by_day = {}
    for order in orders:
        day = order.timestamp.date()
        if day not in orders_by_day:
            orders_by_day[day] = []
        orders_by_day[day].append(order)
    
    # Process orders day by day
    daily_metrics = {}
    for day, day_orders in sorted(orders_by_day.items()):
        # Sort orders by timestamp
        day_orders.sort(key=lambda x: x.timestamp)
        
        # Process each order
        for order in day_orders:
            # If using market maker, let it place orders first
            if with_market_maker and mm:
                mid_price = lob.get_mid_price()
                if mid_price is not None:
                    mm.place_orders(lob, mid_price, order.timestamp)
            
            # Process the regular order
            executions = lob.add_order(order)
            
            # Update market maker if it was involved in any executions
            if with_market_maker and mm:
                for execution in executions:
                    mm.update_inventory_and_cash(execution)
        
        # Calculate daily metrics
        start_time = datetime.combine(day, datetime.min.time())
        end_time = datetime.combine(day, datetime.max.time())
        
        bid_price = lob.get_bid_price()
        ask_price = lob.get_ask_price()
        mid_price = lob.get_mid_price()
        spread = lob.get_spread()
        relative_spread = lob.get_relative_spread()
        execution_ratio = lob.get_execution_ratio(start_time, end_time)
        
        daily_metrics[day] = {
            'bid_price': bid_price,
            'ask_price': ask_price,
            'mid_price': mid_price,
            'spread': spread,
            'relative_spread': relative_spread,
            'execution_ratio': execution_ratio,
            'bid_volume': lob.get_bid_volume(),
            'ask_volume': lob.get_ask_volume()
        }
    
    return {
        'lob': lob,
        'market_maker': mm,
        'daily_metrics': daily_metrics
    }


def analyze_results(normal_sim: Dict, mm_sim: Dict) -> Dict:
    """Compare and analyze results from simulations with and without market maker."""
