@dataclass
class MarketParameters:
    """Parameters defining the market dynamics and execution costs"""
    T: float = 1.0                  # Trading horizon (days)
    dt: float = 1/100               # Time step
    S0: float = 500_000             # Initial price ($/lot)
    sigma: float = 10_000           # Price volatility ($/lot/day^0.5)
    nu: float = 10                  # Trade flow std dev (lot/day^0.5)
    psi: float = 250                # Bid-ask spread ($/lot)
    eta: float = 5                  # Quadratic cost coefficient ($/lot^2/day)
    phi: float = 1                  # Execution cost exponent
    gamma: float = 2e-6             # Risk aversion (1/$)
    K: float = 500                  # Terminal inventory penalty ($/lot^2)
    rho: float = 0.0                # Correlation between price and flow

@dataclass
class State:
    """Current state of the system"""
    t: float          # Current time
    q: float          # Current inventory
    S: float          # Current price


class StochasticTradeFlowSimulator:
    """Simulates stochastic trade flows and implements different execution strategies"""
    
    def __init__(self, params=None):
        """Initialize with default or provided parameters"""
        self.params = params if params else MarketParameters()
        self.reset()
        
    def reset(self):
        """Reset the simulation state"""
        self.time_points = np.arange(0, self.params.T + self.params.dt, self.params.dt)
        self.n_steps = len(self.time_points) - 1
        
        # Initialize paths
        self.inventory_path = np.zeros(len(self.time_points))
        self.price_path = np.zeros(len(self.time_points))
        self.cash_path = np.zeros(len(self.time_points))
        self.control_path = np.zeros(len(self.time_points))
        
        # Set initial values
        self.inventory_path[0] = 0
        self.price_path[0] = self.params.S0
        self.cash_path[0] = 0
        
        # Pre-generate Brownian increments for reproducibility
        np.random.seed(42)
        self.dW = np.random.normal(0, np.sqrt(self.params.dt), (2, self.n_steps))
        if self.params.rho != 0:
            # Apply correlation
            self.dW[1] = self.params.rho * self.dW[0] + np.sqrt(1 - self.params.rho**2) * self.dW[1]
    
    def execution_cost(self, v):
        """Calculate execution costs L(v)"""
        if self.params.phi == 1:  # Linear + quadratic
            return 0.5 * self.params.psi * np.abs(v) + self.params.eta * v**2
        elif self.params.phi == 2:  # Pure quadratic
            return self.params.eta * v**2
        else:  # More general form
            return 0.5 * self.params.psi * np.abs(v) + self.params.eta * np.abs(v)**(1 + self.params.phi)
    
    def rule_based_strategy(self, state, threshold=5):
        """Simple rule-based strategy: trade at constant speed if inventory exceeds threshold"""
        if abs(state.q) > threshold:
            return -np.sign(state.q) * 100  # Trade at 100 lots/day
        return 0
    
    def closed_form_strategy(self, state):
        """Optimal strategy for pure quadratic execution costs (η > 0, ψ = 0)"""
        # Remaining time
        tau = self.params.T - state.t
        
        # Calculate a(t) from equation (10) in the paper
        gamma_sigma2_eta = np.sqrt(self.params.gamma * self.params.sigma**2 * self.params.eta / 2)
        K_term = (self.params.K - gamma_sigma2_eta) / (self.params.K + gamma_sigma2_eta)
        exp_term = np.exp(-2 * gamma_sigma2_eta * tau)
        
        # Handle potential numerical issues
        if np.isnan(K_term) or np.isnan(exp_term):
            return -state.q / (tau + 1e-10)
        
        a_t = gamma_sigma2_eta * (1 + K_term * exp_term) / (1 - K_term * exp_term)
        return -a_t * state.q / self.params.eta
    
    def numerical_pde_strategy(self, state):
        """
        Simulate the optimal strategy derived from numerical PDE solution
        This is a simplified approximation of what would be obtained from solving the HJB equation
        """
        # Remaining time
        tau = self.params.T - state.t
        if tau < 1e-10:
            return -state.q / 1e-10  # Avoid division by zero
        
        if self.params.psi == 0:  # Pure quadratic case
            return self.closed_form_strategy(state)
        
        # For the case with bid-ask spread (ψ > 0)
        # Define no-trading zone which shrinks as we approach terminal time
        no_trade_threshold = max(0.5, self.params.psi / (4 * self.params.eta)) * np.exp(-2 * tau)
        
        if abs(state.q) <= no_trade_threshold:
            return 0  # No trading inside the no-trading zone
        else:
            # Trade towards the boundary of no-trading zone
            direction = -np.sign(state.q)
            intensity = min(50 * abs(state.q), 200)  # Limit max trading speed
            return direction * intensity
    
    def simulate_episode(self, strategy_fn):
        """
        Simulate a complete trading episode using the provided strategy function
        Returns the accumulated reward (negative costs)
        """
        for i in range(self.n_steps):
            t = self.time_points[i]
            q = self.inventory_path[i]
            S = self.price_path[i]
            
            # Get control from strategy
            current_state = State(t=t, q=q, S=S)
            v = strategy_fn(current_state)
            self.control_path[i] = v
            
            # Apply control and update state
            # Inventory: dq = v*dt + ν*dB
            self.inventory_path[i+1] = q + v * self.params.dt + self.params.nu * self.dW[0, i]
            
            # Price: dS = k*v*dt + σ*dW
            self.price_path[i+1] = S + 0 * v * self.params.dt + self.params.sigma * self.dW[1, i]
            
            # Cash: dX = -v*S*dt - L(v)*dt
            self.cash_path[i+1] = self.cash_path[i] - v * S * self.params.dt - self.execution_cost(v) * self.params.dt
        
        # Calculate terminal reward components
        final_q = self.inventory_path[-1]
        final_S = self.price_path[-1]
        
        # PnL components
        execution_costs = np.sum([self.execution_cost(v) * self.params.dt for v in self.control_path])
        inventory_risk_penalty = 0.5 * self.params.gamma * self.params.sigma**2 * np.sum(self.inventory_path[:-1]**2) * self.params.dt
        price_risk_penalty = 0.5 * self.params.gamma * self.params.nu**2 * np.sum(self.price_path[:-1]**2) * self.params.dt
        terminal_penalty = 0.5 * self.params.K * final_q**2
        
        # Total reward (negative cost)
        total_reward = -(execution_costs + inventory_risk_penalty + price_risk_penalty + terminal_penalty)
        
        return total_reward
    
