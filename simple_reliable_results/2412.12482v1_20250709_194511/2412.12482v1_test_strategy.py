        params = self.bin_params[range_bin]
        
        # Run Metropolis-Hastings
        accepted_volumes = []
        v_prev = stats.lognorm.rvs(params['shape'], loc=params['loc'], scale=params['scale'])
        
        for i in range(n_iterations):
            # Propose new volume
            v_proposal = stats.lognorm.rvs(params['shape'], loc=params['loc'], scale=params['scale'])
            
            # Calculate likelihood ratio (assuming independence of range and volume)
            # In this case, we're just comparing prior probabilities
            p_prev = stats.lognorm.pdf(v_prev, params['shape'], loc=params['loc'], scale=params['scale'])
            p_proposal = stats.lognorm.pdf(v_proposal, params['shape'], loc=params['loc'], scale=params['scale'])
            
            # Acceptance probability
            if p_prev == 0:  # Avoid division by zero
                acceptance = 1
