    def evaluate_prediction(self, predicted_range: float, predicted_volume: float, 
                           actual_range: float, actual_volume: float) -> Dict[str, float]:
        """
        Evaluate prediction accuracy.
        
        Parameters:
        -----------
        predicted_range : float
            Predicted range value
        predicted_volume : float
            Predicted volume value
        actual_range : float
            Actual range value
        actual_volume : float
            Actual volume value
            
        Returns:
        --------
        Dict[str, float]
            Dictionary with evaluation metrics
        """
        # Calculate MAPE for range
        range_mape = 100 * abs(actual_range - predicted_range) / actual_range if actual_range > 0 else float('inf')
        
        # Calculate MAPE for volume
        volume_mape = 100 * abs(actual_volume - predicted_volume) / actual_volume if actual_volume > 0 else float('inf')
        
        return {
            'range_mape': range_mape,
            'volume_mape': volume_mape
        }
    
    def run_rolling_window_test(self, df: pd.DataFrame, num_bins: int = 8) -> Dict:
        """
        Run rolling window test on the dataset.
        
        Parameters:
        -----------
        df : pd.DataFrame
            DataFrame with 5-minute interval data
        num_bins : int
            Number of bins for distribution identification
            
        Returns:
        --------
        Dict
            Dictionary with test results
        """
        # Aggregate to daily
        daily_df = self.aggregate_to_daily(df)
        
        # Initialize results
        results = {
            'predicted_ranges': [],
            'actual_ranges': [],
            'predicted_volumes': [],
            'actual_volumes': [],
            'range_mapes': [],
            'volume_mapes': []
        }
        
        # Run rolling window test
        for i in range(self.lookback_period, len(daily_df) - 1):
            # Get training data
            train_daily = daily_df.iloc[:i]
            train_df = df[df['DateTime'].dt.date.isin(train_daily['Date'])]
            
            # Identify distribution
            self.identify_distribution(train_df, num_bins)
            
            # Predict next day
            expected_range, predicted_volume = self.predict_next_day(train_df, train_daily)
            
            # Get actual values for next day
            next_day = daily_df.iloc[i]
            actual_range = next_day['Range']  # Average 5-minute range
            actual_volume = next_day['Volume'] / 78  # Average 5-minute volume (assuming 78 intervals per day)
            
            # Evaluate prediction
            metrics = self.evaluate_prediction(expected_range, predicted_volume, actual_range, actual_volume)
            
            # Store results
            results['predicted_ranges'].append(expected_range)
            results['actual_ranges'].append(actual_range)
            results['predicted_volumes'].append(predicted_volume)
            results['actual_volumes'].append(actual_volume)
            results['range_mapes'].append(metrics['range_mape'])
            results['volume_mapes'].append(metrics['volume_mape'])
        
        # Calculate average MAPE
        results['avg_range_mape'] = np.mean(results['range_mapes'])
        results['avg_volume_mape'] = np.mean(results['volume_mapes'])
        
        return results

