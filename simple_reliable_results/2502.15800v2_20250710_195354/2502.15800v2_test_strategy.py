class Market:
    def __init__(self, agents: List[Agent]):
        self.agents = agents
        self.current_round = 0
        self.price_history = [FUNDAMENTAL_VALUE]  # Start with fundamental value
        self.volume_history = [0]
        self.dividend_history = []
        
    def match_orders(self, all_orders: List[Dict]) -> Tuple[float, List[Dict]]:
        """Match buy and sell orders to determine price and executed trades"""
        if not all_orders:
            return self.price_history[-1], []
            
        # Separate buy and sell orders
        buy_orders = [order for order in all_orders if order["order_type"] == "BUY"]
        sell_orders = [order for order in all_orders if order["order_type"] == "SELL"]
        
        if not buy_orders or not sell_orders:
            return self.price_history[-1], []
        
        # Sort orders by price (buys descending, sells ascending)
        buy_orders.sort(key=lambda x: x["limit_price"], reverse=True)
        sell_orders.sort(key=lambda x: x["limit_price"])
        
        # Find clearing price
        clearing_price = None
        max_volume = 0
        
        # Get all unique prices from orders
        all_prices = sorted(set([o["limit_price"] for o in buy_orders + sell_orders]))
        
        for price in all_prices:
            # Calculate cumulative buy and sell quantities at this price
            buy_quantity = sum(o["quantity"] for o in buy_orders if o["limit_price"] >= price)
            sell_quantity = sum(o["quantity"] for o in sell_orders if o["limit_price"] <= price)
            
            # Volume at this price is the minimum of buy and sell quantities
            volume = min(buy_quantity, sell_quantity)
            
            if volume > max_volume:
                max_volume = volume
                clearing_price = price
        
        # If no trades possible, use previous price
        if clearing_price is None:
            return self.price_history[-1], []
        
        # Execute trades at clearing price
        executed_trades = []
        remaining_volume = max_volume
        
        # Execute buy orders
        for buy_order in buy_orders:
            if buy_order["limit_price"] >= clearing_price and remaining_volume > 0:
                # Determine quantity to execute
                exec_quantity = min(buy_order["quantity"], remaining_volume)
                remaining_volume -= exec_quantity
                
                executed_trades.append({
                    "agent_id": buy_order["agent_id"],
                    "order_type": "BUY",
                    "quantity": exec_quantity,
                    "price": clearing_price
                })
                
                if remaining_volume == 0:
                    break
        
        # Reset remaining volume for sell orders
        remaining_volume = max_volume
        
        # Execute sell orders
        for sell_order in sell_orders:
            if sell_order["limit_price"] <= clearing_price and remaining_volume > 0:
                # Determine quantity to execute
                exec_quantity = min(sell_order["quantity"], remaining_volume)
                remaining_volume -= exec_quantity
                
                executed_trades.append({
                    "agent_id": sell_order["agent_id"],
                    "order_type": "SELL",
                    "quantity": exec_quantity,
                    "price": clearing_price
                })
                
                if remaining_volume == 0:
                    break
        
        return clearing_price, executed_trades
    
    def run_round(self) -> Dict:
        """Run a single round of trading"""
        self.current_round += 1
        current_price = self.price_history[-1]
        
        # 1. Collect orders from all agents
        all_orders = []
        for agent in self.agents:
            agent_orders = agent.decide_orders(self.current_round, current_price)
            for order in agent_orders:
                order["agent_id"] = agent.id
            all_orders.extend(agent_orders)
        
        # 2. Match orders and determine price
        market_price, executed_trades = self.match_orders(all_orders)
        
        # 3. Generate random dividend
        dividend = random.choice(POSSIBLE_DIVIDENDS)
        self.dividend_history.append(dividend)
        
        # 4. Update agent portfolios
        for agent in self.agents:
            agent_trades = [t for t in executed_trades if t["agent_id"] == agent.id]
            agent.update_portfolio(dividend, agent_trades)
            agent.portfolio_values.append(agent.get_portfolio_value(market_price))
        
        # 5. Update market history
        self.price_history.append(market_price)
        self.volume_history.append(sum(t["quantity"] for t in executed_trades))
        
        return {
            "round": self.current_round,
            "price": market_price,
            "volume": self.volume_history[-1],
            "dividend": dividend,
            "trades": executed_trades
        }
    
    def run_simulation(self) -> Dict:
        """Run the full market simulation"""
        results = []
        for _ in range(TOTAL_ROUNDS):
            round_result = self.run_round()
            results.append(round_result)
        
        # Calculate final portfolio values and market metrics
        final_values = {}
        for agent in self.agents:
            final_values[agent.id] = {
                "model_type": agent.model_type.value,
                "final_cash": agent.cash,
                "final_stocks": agent.stocks,
                "final_portfolio_value": agent.get_portfolio_value(self.price_history[-1]),
                "portfolio_variance": np.var(agent.portfolio_values) if len(agent.portfolio_values) > 1 else 0
            }
        
        market_metrics = {
            "mse_vs_fundamental": np.mean([(p - FUNDAMENTAL_VALUE)**2 for p in self.price_history]),
            "max_price": max(self.price_history),
            "min_price": min(self.price_history),
            "price_variance": np.var(self.price_history),
            "avg_volume": np.mean(self.volume_history),
            "price_history": self.price_history,
            "volume_history": self.volume_history
        }
        
        return {
            "round_results": results,
            "agent_results": final_values,
            "market_metrics": market_metrics
        }

