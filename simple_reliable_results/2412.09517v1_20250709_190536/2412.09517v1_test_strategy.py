# ----- Utility Functions -----
def generate_spd_matrix(n, condition_number=10):
    """Generate a random Symmetric Positive Definite matrix."""
    A = np.random.randn(n, n)
    U, _, _ = np.linalg.svd(A @ A.T)
    D = np.diag(np.linspace(1, condition_number, n))
    return U @ D @ U.T

def matrix_log(X):
    """Compute the matrix logarithm of SPD matrix X."""
    eigvals, eigvecs = np.linalg.eigh(X)
    return eigvecs @ np.diag(np.log(eigvals)) @ eigvecs.T

def matrix_exp(X):
    """Compute the matrix exponential of a symmetric matrix X."""
    eigvals, eigvecs = np.linalg.eigh(X)
    return eigvecs @ np.diag(np.exp(eigvals)) @ eigvecs.T

def frechet_mean_log_euclidean(matrices):
    """Compute the Log-Euclidean Fréchet mean of SPD matrices."""
    log_matrices = [matrix_log(matrix) for matrix in matrices]
    mean_log = np.mean(log_matrices, axis=0)
    return matrix_exp(mean_log)

def frobenius_distance(A, B):
    """Compute the Frobenius distance between two matrices."""
    return np.linalg.norm(A - B, 'fro')

def log_euclidean_distance(A, B):
    """Compute the Log-Euclidean distance between two SPD matrices."""
    return frobenius_distance(matrix_log(A), matrix_log(B))

def procrustes_distance(A, B):
    """Compute an approximation of the Procrustes distance between SPD matrices."""
    LA = linalg.cholesky(A)
    LB = linalg.cholesky(B)
    U, _, Vt = linalg.svd(LA.T @ LB)
    R = U @ Vt
    return frobenius_distance(LA, LB @ R.T)

