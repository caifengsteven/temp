def create_block_diagonal_input(rcov_list):
    """
    Create a block diagonal matrix from a list of RCOV matrices.
    This implements the approach from the paper for handling multiple lags.
    """
    n = rcov_list[0].shape[0]  # Size of each RCOV matrix
    k = len(rcov_list)         # Number of lags
    block_matrix = np.zeros((k * n, k * n))
    
    for i, rcov in enumerate(rcov_list):
        start_idx = i * n
        end_idx = (i + 1) * n
        block_matrix[start_idx:end_idx, start_idx:end_idx] = rcov
        
    return block_matrix

def prepare_data_for_geohar(rcov_data, window_size=5, monthly_window=22):
    """
    Prepare data for the GeoHAR model using Fréchet means.
    """
    n_samples = len(rcov_data) - max(window_size, monthly_window)
    n_assets = rcov_data[0].shape[0]
    
    X = np.zeros((n_samples, 3 * n_assets, 3 * n_assets))
    y = np.zeros((n_samples, n_assets, n_assets))
    
    for i in range(n_samples):
        t = i + max(window_size, monthly_window)
        
        # Daily component
        daily = rcov_data[t-1]
        
        # Weekly component (Fréchet mean of last 5 days)
        weekly_matrices = rcov_data[t-window_size:t]
        weekly = frechet_mean_log_euclidean(weekly_matrices)
        
        # Monthly component (Fréchet mean of last 22 days)
        monthly_matrices = rcov_data[t-monthly_window:t]
        monthly = frechet_mean_log_euclidean(monthly_matrices)
        
        # Create block diagonal input
        X[i] = create_block_diagonal_input([daily, weekly, monthly])
        
        # Target is the next day's RCOV
        y[i] = rcov_data[t]
    
    return X, y

def train_model(model, train_loader, criterion, optimizer, device, epochs=100):
    """Train the model."""
    model.train()
    losses = []
    
    for epoch in range(epochs):
        epoch_loss = 0
        for X_batch, y_batch in train_loader:
            X_batch, y_batch = X_batch.to(device), y_batch.to(device)
            
            # Zero gradients
            optimizer.zero_grad()
            
            # Forward pass
            outputs = model(X_batch)
            
            # Compute loss
            loss = criterion(outputs, y_batch)
            
            # Backward pass and optimize
            loss.backward()
            optimizer.step()
            
            epoch_loss += loss.item()
            
        losses.append(epoch_loss / len(train_loader))
        if epoch % 10 == 0:
            print(f"Epoch {epoch}/{epochs}, Loss: {losses[-1]:.6f}")
    
    return losses

def evaluate_model(model, test_loader, device):
    """Evaluate the model on test data."""
    model.eval()
    predictions = []
    actuals = []
    
    with torch.no_grad():
        for X_batch, y_batch in test_loader:
            X_batch = X_batch.to(device)
            outputs = model(X_batch)
            predictions.append(outputs.cpu().numpy())
            actuals.append(y_batch.numpy())
    
    predictions = np.vstack(predictions)
    actuals = np.vstack(actuals)
    
    return predictions, actuals

def log_euclidean_loss(output, target):
    """
    Compute the Log-Euclidean loss between predicted and target SPD matrices.
    Designed for PyTorch tensors.
    """
    batch_size = output.size(0)
    loss = 0
    
    for i in range(batch_size):
        # Ensure outputs are SPD by using eigenvalue decomposition
        eigvals, eigvecs = torch.linalg.eigh(output[i])
        eigvals = torch.clamp(eigvals, min=1e-6)  # Ensure positive eigenvalues
        output_spd = eigvecs @ torch.diag(eigvals) @ eigvecs.t()
        
        # Compute matrix logarithms
        log_output = torch.matrix_exp(torch.linalg.logm(output_spd))
        log_target = torch.matrix_exp(torch.linalg.logm(target[i]))
        
        # Compute Frobenius norm of difference
        loss += torch.norm(log_output - log_target, p='fro')**2
    
    return loss / batch_size

