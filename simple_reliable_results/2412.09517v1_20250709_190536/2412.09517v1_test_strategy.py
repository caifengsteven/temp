class BiMapLayer(nn.Module):
    """Bilinear Mapping Layer for SPD matrices as described in the paper."""
    def __init__(self, in_dim, out_dim):
        super(BiMapLayer, self).__init__()
        # Initialize W as semi-orthogonal (using nn.init after parameter creation)
        self.W = nn.Parameter(torch.Tensor(out_dim, in_dim))
        nn.init.orthogonal_(self.W)
        
    def forward(self, X):
        # X is batch of SPD matrices
        # Implement the bilinear mapping: W * X * W^T
        return torch.bmm(torch.bmm(self.W.expand(X.size(0), -1, -1), X), 
                         self.W.expand(X.size(0), -1, -1).transpose(1, 2))

class ReEigLayer(nn.Module):
    """Eigenvalue Rectification Layer for SPD matrices."""
    def __init__(self, epsilon=1e-4):
        super(ReEigLayer, self).__init__()
        self.epsilon = epsilon
        
    def forward(self, X):
        # For each matrix in the batch
        batch_size = X.size(0)
        n = X.size(1)  # Matrix dimension
        output = torch.zeros_like(X)
        
        for i in range(batch_size):
            # Eigenvalue decomposition
            eigvals, eigvecs = torch.linalg.eigh(X[i])
            # Apply ReLU-like operation to eigenvalues
            eigvals = torch.clamp(eigvals, min=self.epsilon)
            # Reconstruct the matrix
            output[i] = eigvecs @ torch.diag(eigvals) @ eigvecs.t()
        
        return output

class ReSPDNet(nn.Module):
    """Simplified SPDNet for Realized Covariance Matrix Forecasting."""
    def __init__(self, input_dim, hidden_dim, output_dim):
        super(ReSPDNet, self).__init__()
        self.bimap1 = BiMapLayer(input_dim, hidden_dim)
        self.reeig1 = ReEigLayer()
        self.bimap2 = BiMapLayer(hidden_dim, output_dim)
        
    def forward(self, X):
        X = self.bimap1(X)
        X = self.reeig1(X)
        X = self.bimap2(X)
        return X

