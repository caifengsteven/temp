@dataclass
class Agent:
    """Represents a trading agent in the market simulation"""
    id: int
    model_type: ModelType
    cash: float = 100.0
    shares: int = 4
    portfolio_value: float = 0.0
    
    # Forecasting data
    forecasts: Dict[int, Dict[int, float]] = None
    
    def __post_init__(self):
        if self.forecasts is None:
            self.forecasts = {}
    
    def calculate_portfolio_value(self, current_price: float) -> float:
        """Calculate total portfolio value based on current market price"""
        self.portfolio_value = self.cash + (self.shares * current_price)
        return self.portfolio_value
    
    def generate_forecast(self, current_round: int, current_price: float, fundamental_value: float,
                          horizon_rounds: List[int]) -> Dict[int, float]:
        """Generate price forecasts for current and future rounds"""
        model_chars = MODEL_CHARACTERISTICS[self.model_type]
        rationality = model_chars["rationality"]
        bubble_tendency = model_chars["bubble_tendency"]
        
        # Initialize forecast dictionary for this round
        round_forecasts = {}
        
        # Base noise level
        noise_level = 0.1 if self.model_type != ModelType.HUMAN else 0.3
        
        for horizon in horizon_rounds:
            target_round = current_round + horizon
            
            # How much the forecast favors fundamental value vs bubble behavior
            fundamental_weight = rationality * (1 - 0.05 * horizon)  # Rationality decreases slightly with horizon
            bubble_weight = bubble_tendency * (1 + 0.1 * horizon)    # Bubble tendency increases with horizon
            
            # Calculate forecast as weighted sum of fundamental and bubble components
            fundamental_component = fundamental_value
            
            # For erratic models, occasionally go below fundamental value
            if model_chars["hypothesis"] == HypothesisType.ERRATIC and random.random() < 0.5:
                bubble_component = fundamental_value * (1 - random.random() * 0.3)
            else:
                # Bubble component increases with round number (up to a peak)
                max_bubble = 3.0 if self.model_type == ModelType.HUMAN else 2.0
                bubble_factor = min(1 + (current_round / 20), max_bubble)
                bubble_component = fundamental_value * bubble_factor
            
            # Add some randomness
            noise = np.random.normal(0, noise_level * current_price)
            
            # Combine components
            forecast = (fundamental_component * fundamental_weight + 
                       bubble_component * bubble_weight + noise) / (fundamental_weight + bubble_weight)
            
            # Ensure forecast is positive and round to nearest 0.5
            forecast = max(0.5, round(forecast * 2) / 2)
            
            round_forecasts[target_round] = forecast
            
        self.forecasts[current_round] = round_forecasts
        return round_forecasts
    
    def decide_trade(self, current_price: float, fundamental_value: float) -> Tuple[str, int, float]:
        """Decide whether to buy, sell, or hold based on model characteristics"""
        model_chars = MODEL_CHARACTERISTICS[self.model_type]
        rationality = model_chars["rationality"]
        
        # Price threshold is weighted between fundamental value and current price
        price_threshold = fundamental_value * rationality + current_price * (1 - rationality)
        
        # Add some randomness to decision
        noise = np.random.normal(0, 0.1 * fundamental_value)
        adjusted_threshold = price_threshold + noise
        
        # Decide action based on comparison
        if current_price < adjusted_threshold - 0.5:
            # Buy if price is below threshold
            max_affordable = min(5, int(self.cash / current_price))  # Limit to 5 shares max per trade
            quantity = max(1, int(max_affordable * random.random()))
            if quantity > 0 and self.cash >= quantity * current_price:
                return "BUY", quantity, current_price
        
        elif current_price > adjusted_threshold + 0.5:
            # Sell if price is above threshold
            max_sellable = min(self.shares, 5)  # Limit to 5 shares max per trade
            quantity = max(1, int(max_sellable * random.random()))
            if quantity > 0 and self.shares >= quantity:
                return "SELL", quantity, current_price
        
        # Hold otherwise
        return "HOLD", 0, current_price

@dataclass
class Market:
    """Represents an experimental asset market simulation"""
    agents: List[Agent]
    fundamental_value: float = 14.0
    interest_rate: float = 0.05
    possible_dividends: List[float] = None
    current_price: float = 14.0
    current_round: int = 0
    max_rounds: int = 30
    price_history: List[float] = None
    volume_history: List[int] = None
    
    def __post_init__(self):
        if self.possible_dividends is None:
            self.possible_dividends = [0.4, 1.0]
        if self.price_history is None:
            self.price_history = [self.current_price]
        if self.volume_history is None:
            self.volume_history = [0]
    
    def run_round(self) -> Dict:
        """Simulate a single trading round"""
        self.current_round += 1
        if self.current_round > self.max_rounds:
            return {"completed": True}
        
        # Collect all orders
        buy_orders = []
        sell_orders = []
        
        # Generate forecasts for all agents
        forecast_horizons = [0, 2, 5, 10]  # Current, 2 rounds, 5 rounds, 10 rounds ahead
        for agent in self.agents:
            agent.generate_forecast(
                self.current_round, 
                self.current_price, 
                self.fundamental_value,
                forecast_horizons
            )
        
        # Collect trade decisions
        for agent in self.agents:
            action, quantity, price = agent.decide_trade(self.current_price, self.fundamental_value)
            
            if action == "BUY" and quantity > 0:
                buy_orders.append({"agent": agent, "quantity": quantity, "price": price})
            elif action == "SELL" and quantity > 0:
                sell_orders.append({"agent": agent, "quantity": quantity, "price": price})
        
        # Sort orders by price (buy highest first, sell lowest first)
        buy_orders.sort(key=lambda x: x["price"], reverse=True)
        sell_orders.sort(key=lambda x: x["price"])
        
        # Execute trades
        volume = 0
        while buy_orders and sell_orders:
            buy = buy_orders[0]
            sell = sell_orders[0]
            
            # Check if trade can be executed
            if buy["price"] >= sell["price"]:
                # Determine trade quantity
                trade_quantity = min(buy["quantity"], sell["quantity"])
                trade_price = (buy["price"] + sell["price"]) / 2
                
                # Update agent positions
                buy["agent"].cash -= trade_quantity * trade_price
                buy["agent"].shares += trade_quantity
                sell["agent"].cash += trade_quantity * trade_price
                sell["agent"].shares -= trade_quantity
                
                # Update order quantities
                buy["quantity"] -= trade_quantity
                sell["quantity"] -= trade_quantity
                volume += trade_quantity
                
                # Remove fulfilled orders
                if buy["quantity"] == 0:
                    buy_orders.pop(0)
                if sell["quantity"] == 0:
                    sell_orders.pop(0)
            else:
                # No more trades possible
                break
        
        # Update market price based on executed trades
        if volume > 0:
            # Simple price update based on supply/demand balance
            buy_pressure = sum(order["quantity"] for order in buy_orders)
            sell_pressure = sum(order["quantity"] for order in sell_orders)
            
            if buy_pressure > sell_pressure:
                self.current_price *= 1 + min(0.1, (buy_pressure - sell_pressure) / 100)
            elif sell_pressure > buy_pressure:
                self.current_price *= 1 - min(0.1, (sell_pressure - buy_pressure) / 100)
        
        # Ensure price doesn't go too far below fundamental in most cases
        if self.current_price < self.fundamental_value * 0.5:
            self.current_price = self.fundamental_value * 0.5 + random.random()
        
        # Round price to nearest 0.5
        self.current_price = round(self.current_price * 2) / 2
        
        # Draw dividend for this round
        dividend = random.choice(self.possible_dividends)
        
        # Pay dividends and interest
        for agent in self.agents:
            # Dividend payment
            dividend_payment = agent.shares * dividend
            agent.cash += dividend_payment
            
            # Interest payment
            interest_payment = agent.cash * self.interest_rate
            agent.cash += interest_payment
            
            # Update portfolio value
            agent.calculate_portfolio_value(self.current_price)
        
        # Record price and volume history
        self.price_history.append(self.current_price)
        self.volume_history.append(volume)
        
        return {
            "completed": False,
            "round": self.current_round,
            "price": self.current_price,
            "volume": volume,
            "dividend": dividend
        }
    
    def run_simulation(self) -> Dict:
        """Run the complete market simulation"""
        results = {"rounds": []}
        
        while self.current_round < self.max_rounds:
            round_result = self.run_round()
            results["rounds"].append(round_result)
            
            if round_result.get("completed", False):
                break
        
        # Calculate final portfolio values and market metrics
        for agent in self.agents:
            # Convert shares to cash at buyback price
            agent.cash += agent.shares * self.fundamental_value
            agent.shares = 0
            agent.portfolio_value = agent.cash
        
        # Calculate market metrics
        mse_fundamental = np.mean([(p - self.fundamental_value)**2 for p in self.price_history[1:]])
        
        results["final_price"] = self.current_price
        results["mse_fundamental"] = mse_fundamental
        results["price_history"] = self.price_history
        results["volume_history"] = self.volume_history
        
        # Portfolio statistics
        portfolio_values = [agent.portfolio_value for agent in self.agents]
        results["portfolio_stats"] = {
            "mean": np.mean(portfolio_values),
            "median": np.median(portfolio_values),
            "min": np.min(portfolio_values),
            "max": np.max(portfolio_values),
            "std": np.std(portfolio_values),
            "variance": np.var(portfolio_values)
        }
        
        return results

def run_single_model_market(model_type: ModelType, num_agents: int = 20) -> Dict:
    """Run a market simulation with agents of a single model type"""
    agents = [Agent(id=i, model_type=model_type) for i in range(num_agents)]
    market = Market(agents=agents)
    results = market.run_simulation()
    
    # Add model-specific information
    results["model_type"] = model_type.value
