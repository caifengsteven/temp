def analyze_forecasts(results: Dict, model_type: ModelType) -> Dict:
    """Analyze the forecasting behavior of agents"""
    agents = results.get("agents", [])
    agents_of_type = [a for a in agents if a.model_type == model_type]
    
    if not agents_of_type:
        return {"error": f"No agents of type {model_type.value} found"}
    
    forecast_data = {}
    for horizon in [0, 2, 5, 10]:
        errors = []
        for agent in agents_of_type:
            for round_num, forecasts in agent.forecasts.items():
                target_round = round_num + horizon
                if target_round in forecasts and target_round < len(results["price_history"]):
                    actual_price = results["price_history"][target_round]
                    forecast_price = forecasts[target_round]
                    error = actual_price - forecast_price
                    errors.append(error)
        
        if errors:
            forecast_data[f"horizon_{horizon}"] = {
                "mean_error": np.mean(errors),
                "std_error": np.std(errors),
                "abs_mean_error": np.mean(np.abs(errors)),
                "min_error": np.min(errors),
                "max_error": np.max(errors)
            }
    
    return forecast_data

