def generate_synthetic_stock_data(n_points=3500, volatility=0.01, drift=0.0001, seed=42):
    """Generate synthetic stock price data with trends"""
    np.random.seed(seed)
    
    # Base price starts at 100
    price = 100
    prices = [price]
    
    # Generate prices with random walk + drift
    for _ in range(n_points - 1):
        # Random component
        random_component = np.random.normal(0, volatility)
        
        # Add some regime changes to create more realistic trends
        if np.random.random() < 0.01:  # 1% chance of regime change
            drift = np.random.normal(0, 0.0005)
        
        # Update price
        price = price * (1 + drift + random_component)
        prices.append(price)
    
    return np.array(prices)

def calculate_trends(prices):
    """Calculate the actual trend directions (1 for up, -1 for down)"""
    return np.array([1 if prices[i] >= prices[i-1] else -1 for i in range(1, len(prices))])

def calculate_sharpe_ratio(returns, risk_free_rate=0):
    """Calculate Sharpe ratio from returns"""
    excess_returns = returns - risk_free_rate
    return np.mean(excess_returns) / np.std(excess_returns)

def evaluate_model(model, test_data, test_trends):
    """Evaluate model performance with metrics"""
    predictions = []
    for i in range(len(test_trends)):
        pred = model.predict(test_data[:len(test_data) - len(test_trends) + i + 1])
        predictions.append(pred)
    
    # Calculate metrics
    acc = accuracy_score(test_trends, predictions)
    f1 = f1_score(test_trends, predictions, pos_label=1)
    
    # For AUC, we need probabilities
    probas = []
    for i in range(len(test_trends)):
        prob = model.predict_proba(test_data[:len(test_data) - len(test_trends) + i + 1])
        probas.append(prob)
    
    auc = roc_auc_score(test_trends, probas)
    
    # Calculate Sharpe ratio
    # 1 means buy/hold, -1 means sell/no position
    returns = []
    price_changes = np.diff(test_data[-len(test_trends)-1:])
    for i, pred in enumerate(predictions):
        if pred == 1:  # If predicted up, we gain/lose based on actual change
            returns.append(price_changes[i] / test_data[-len(test_trends)-1+i])
        else:  # If predicted down, no position (or could implement shorting)
            returns.append(0)
    
    sharpe = calculate_sharpe_ratio(np.array(returns))
    
    return {
        'accuracy': acc,
        'f1_score': f1,
        'auc': auc,
        'sharpe_ratio': sharpe
    }

