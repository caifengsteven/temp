def simulate_hierarchical_returns(n_days: int, n_stocks: int, n_scales: int = 3, 
                                 class_type: str = "wishart", seed: int = 42) -> Tuple[pd.DataFrame, pd.DataFrame]:
    """
    Simulate hierarchical stock returns based on Matrix H-theory
    
    Parameters:
    -----------
    n_days: int
        Number of days to simulate
    n_stocks: int
        Number of stocks to simulate
    n_scales: int
        Number of hierarchical scales
    class_type: str
        'wishart' or 'inverse_wishart'
    seed: int
        Random seed
        
    Returns:
    --------
    tuple: (returns DataFrame, background variance DataFrame)
    """
    np.random.seed(seed)
    
    # Parameters
    beta_params = np.ones(n_scales) * 5.0  # Same beta for all scales
    epsilon0 = 1.0  # Base variance
    
    # Initialize arrays
    epsilon = np.zeros((n_days, n_scales))
    epsilon[:, 0] = epsilon0  # Largest scale is constant
    
    # Correlation structure
    # Create a block correlation matrix to simulate sector correlations
    n_sectors = 5
    stocks_per_sector = n_stocks // n_sectors
    
    # Generate hierarchical background process
    for i in range(1, n_scales):
        if class_type == "wishart":
            # Simulate from gamma distribution
            for t in range(1, n_days):
                # Simple AR(1) process with gamma innovations
                prev_epsilon = epsilon[t-1, i-1]
                scale = prev_epsilon / beta_params[i-1]
                epsilon[t, i] = stats.gamma.rvs(a=beta_params[i-1], scale=scale)
        else:
            # Simulate from inverse gamma distribution
            for t in range(1, n_days):
                # Simple AR(1) process with inverse gamma innovations
                prev_epsilon = epsilon[t-1, i-1]
                scale = beta_params[i-1] * prev_epsilon
                epsilon[t, i] = stats.invgamma.rvs(a=beta_params[i-1]+1, scale=scale)
    
    # Background volatility is the last scale
    background = epsilon[:, -1]
    
    # Create correlation matrix with block structure
    correlation = np.eye(n_stocks)
    block_size = n_stocks // n_sectors
    
    # Fill blocks with higher correlation to simulate sectors
    for i in range(n_sectors):
        start_idx = i * block_size
        end_idx = (i + 1) * block_size
        
        # Set correlations within sector
        correlation[start_idx:end_idx, start_idx:end_idx] = 0.7
        
        # Ensure diagonal is 1
        np.fill_diagonal(correlation, 1.0)
    
    # Generate returns
    returns = np.zeros((n_days, n_stocks))
    
    # Generate multivariate normal returns with time-varying volatility
    for t in range(n_days):
        # Scale correlation to covariance using the background volatility
        vol = np.sqrt(background[t])
        cov_matrix = correlation * vol
        
        # Generate returns
        returns[t] = np.random.multivariate_normal(np.zeros(n_stocks), cov_matrix)
    
    # Convert to DataFrames
    stock_names = [f'Stock_{i+1}' for i in range(n_stocks)]
    dates = pd.date_range(start='2010-01-01', periods=n_days, freq='B')
    
    returns_df = pd.DataFrame(returns, index=dates, columns=stock_names)
    background_df = pd.DataFrame(background, index=dates, columns=['Background'])
    
    return returns_df, background_df


def estimate_background(returns: pd.DataFrame, window_size: int = 14) -> pd.DataFrame:
    """
    Estimate background variance from returns
    
    Parameters:
    -----------
    returns: pd.DataFrame
        DataFrame of returns
    window_size: int
        Window size for variance estimation
        
    Returns:
    --------
    pd.DataFrame: Estimated background variance
    """
    # Calculate rolling variance for each stock
    rolling_var = returns.rolling(window=window_size).var()
    
    # Aggregate across stocks
    aggregated_var = rolling_var.mean(axis=1)
    
    return pd.DataFrame(aggregated_var, columns=['Background'])


def calculate_aggregated_returns(returns: pd.DataFrame) -> np.ndarray:
    """
    Calculate aggregated returns as described in the paper
    
    Parameters:
    -----------
    returns: pd.DataFrame
        DataFrame of returns
        
    Returns:
    --------
    np.ndarray: Aggregated returns
    """
    # Normalize returns
    normalized_returns = (returns - returns.mean()) / returns.std()
    
    # Calculate correlation matrix
    corr_matrix = normalized_returns.corr()
    
    # Eigendecomposition
    eigenvalues, eigenvectors = np.linalg.eigh(corr_matrix)
    
    # Transform returns to uncorrelated basis
    rotated_returns = normalized_returns @ eigenvectors
    
    # Normalize by square root of eigenvalues
    for i in range(len(eigenvalues)):
        if eigenvalues[i] > 0:  # Avoid division by zero
            rotated_returns.iloc[:, i] = rotated_returns.iloc[:, i] / np.sqrt(eigenvalues[i])
    
    # Flatten to get aggregated returns
    aggregated_returns = rotated_returns.values.flatten()
    
    return aggregated_returns


