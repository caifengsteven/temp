class ScoreNetwork(nn.Module):
    """Neural network for score estimation with encoder-decoder architecture"""
    def __init__(self, d, k, hidden_dim=64):
        super().__init__()
        self.d = d  # Dimension of asset returns
        self.k = k  # Dimension of latent factors
        
        # Encoder (V^T in the paper)
        self.encoder = nn.Linear(d, k, bias=False)
        
        # Score approximation network (g_ζ in the paper)
        self.score_net = nn.Sequential(
            nn.Linear(k + 1, hidden_dim),  # +1 for time input
            nn.ReLU(),
            nn.Linear(hidden_dim, hidden_dim),
            nn.ReLU(),
            nn.Linear(hidden_dim, k)
        )
        
        # Decoder (V in the paper)
        self.decoder = nn.Linear(k, d, bias=False)
        
        # Initialize sigma parameters (c in the paper)
        self.log_sigmas = nn.Parameter(torch.zeros(d))
        
    def forward(self, r, t):
        # Time-dependent normalizing matrix D_t
        alpha_t = torch.exp(-0.5 * t)
        h_t = 1 - alpha_t**2
        D_t = 1.0 / (h_t + alpha_t**2 * torch.exp(self.log_sigmas).unsqueeze(0))
        
        # Normalized input
        D_t_r = D_t * r
        
        # Encoder
        z = self.encoder(D_t_r)
        
        # Score approximation with time
        t_expanded = t * torch.ones(z.shape[0], 1, device=z.device)
        g_output = self.score_net(torch.cat([z, t_expanded], dim=1))
        
        # Decoder with skip connection
        score = alpha_t * self.decoder(g_output) - D_t_r
        
        return score

class DiffusionFactorModel:
    """Implementation of the diffusion factor model from the paper"""
    def __init__(self, d, k, device='cpu'):
        self.d = d  # Dimension of asset returns
        self.k = k  # Dimension of latent factors
        self.device = device
        self.score_net = ScoreNetwork(d, k).to(device)
        self.optimizer = Adam(self.score_net.parameters(), lr=1e-3)
        
    def train(self, data, num_epochs=100, batch_size=64, T=1.0, t0=0.01):
        """Train the diffusion model using score matching"""
        dataset = torch.tensor(data, dtype=torch.float32).to(self.device)
        data_loader = torch.utils.data.DataLoader(
            dataset, batch_size=batch_size, shuffle=True
        )
        
        for epoch in range(num_epochs):
            total_loss = 0.0
            for batch in data_loader:
                self.optimizer.zero_grad()
                
                # Sample time uniformly
                t = torch.rand(batch.shape[0], 1, device=self.device) * (T - t0) + t0
                
                # Calculate alpha_t and h_t
                alpha_t = torch.exp(-0.5 * t)
                h_t = 1 - alpha_t**2
                
                # Sample noise
                epsilon = torch.randn_like(batch)
                
                # Perturb data
                r_t = alpha_t * batch + torch.sqrt(h_t) * epsilon
                
                # Calculate target
                target = -epsilon / torch.sqrt(h_t)
                
                # Compute score
                pred = self.score_net(r_t, t)
                
                # Score matching loss
                loss = F.mse_loss(pred, target)
                loss.backward()
                self.optimizer.step()
                
                total_loss += loss.item()
            
            if (epoch + 1) % 10 == 0:
                print(f"Epoch {epoch+1}, Loss: {total_loss / len(data_loader):.6f}")
                
    def generate_samples(self, num_samples, T=1.0, t0=0.01, num_steps=100):
        """Generate samples using the reverse diffusion process"""
        # Initialize from Gaussian
        r = torch.randn(num_samples, self.d, device=self.device)
        
        # Discretize time
        time_steps = torch.linspace(T, t0, num_steps, device=self.device)
        step_size = (T - t0) / num_steps
        
        # Reverse diffusion process
        for i in range(num_steps - 1):
            t = time_steps[i].unsqueeze(0)
            with torch.no_grad():
                score = self.score_net(r, t)
            
            # Update using reverse SDE
            noise = torch.randn_like(r)
            r = r + (0.5 * r + score) * step_size + np.sqrt(step_size) * noise
            
        return r.cpu().numpy()

def generate_synthetic_data(d, k, n_samples):
    """Generate synthetic data following a factor model structure"""
    # Generate factor loadings (beta)
    beta = np.random.randn(d, k)
    q, _ = np.linalg.qr(beta)
    beta = q[:, :k]  # Ensure orthonormal columns
    
    # Generate factor means and variances
    mu_F = np.random.uniform(0, 0.1, k)
    sigma_F = 1.5 * mu_F
    
    # Generate idiosyncratic noise variances
    sigma_eps = np.random.uniform(0, 0.4, d)
    sigma_eps = np.sort(sigma_eps)[::-1]  # Sort in descending order
    
    # Generate samples
    data = []
    for _ in range(n_samples):
        # Sample factors
        F = np.random.normal(mu_F, sigma_F)
        
        # Sample noise
        eps = np.random.normal(0, sigma_eps)
        
        # Generate return
        R = beta @ F + eps
        data.append(R)
    
    data = np.array(data)
    
    # Calculate true covariance matrix
    F_cov = np.diag(sigma_F**2)
    eps_cov = np.diag(sigma_eps**2)
    true_cov = beta @ F_cov @ beta.T + eps_cov
    
    return data, beta, true_cov

def evaluate_subspace_recovery(generated_data, true_data, true_cov, k):
    """Evaluate how well the generated data recovers the latent subspace"""
    # Compute covariance matrices
    gen_cov = np.cov(generated_data.T)
    emp_cov = np.cov(true_data.T)
    
    # Get top-k eigenvalues and eigenvectors
    eig_val_true, eig_vec_true = np.linalg.eigh(true_cov)
    eig_val_true, eig_vec_true = eig_val_true[-k:], eig_vec_true[:, -k:]
    
    eig_val_gen, eig_vec_gen = np.linalg.eigh(gen_cov)
    eig_val_gen, eig_vec_gen = eig_val_gen[-k:], eig_vec_gen[:, -k:]
    
    eig_val_emp, eig_vec_emp = np.linalg.eigh(emp_cov)
    eig_val_emp, eig_vec_emp = eig_val_emp[-k:], eig_vec_emp[:, -k:]
    
    # Compute relative eigenvalue error
    rel_err_gen = np.mean(np.abs(eig_val_gen / eig_val_true - 1))
    rel_err_emp = np.mean(np.abs(eig_val_emp / eig_val_true - 1))
    
    # Compute subspace recovery error
    U_true = eig_vec_true @ eig_vec_true.T
    U_gen = eig_vec_gen @ eig_vec_gen.T
    U_emp = eig_vec_emp @ eig_vec_emp.T
    
    frob_err_gen = np.linalg.norm(U_gen - U_true, 'fro') / np.linalg.norm(U_true, 'fro')
    frob_err_emp = np.linalg.norm(U_emp - U_true, 'fro') / np.linalg.norm(U_true, 'fro')
    
    return {
        'eigenvalue_error_diff': rel_err_gen,
        'eigenvalue_error_emp': rel_err_emp,
        'subspace_error_diff': frob_err_gen,
        'subspace_error_emp': frob_err_emp,
        'ratio_eigenvalue': rel_err_gen / rel_err_emp,
        'ratio_subspace': frob_err_gen / frob_err_emp
    }

def construct_portfolio(returns, cov_matrix, risk_aversion=3):
    """Construct a mean-variance optimal portfolio with constraints"""
    n_assets = returns.shape[1]
    
    def objective(w):
        return -w @ returns.mean(axis=0) + 0.5 * risk_aversion * w @ cov_matrix @ w
    
    constraints = [
        {'type': 'eq', 'fun': lambda w: np.sum(w) - 1},  # Sum of weights = 1
    ]
    
    bounds = [(0, 0.05) for _ in range(n_assets)]  # Max weight per asset = 5%
    
    # Initial guess: equal weights
    w0 = np.ones(n_assets) / n_assets
    
    result = minimize(objective, w0, method='SLSQP', bounds=bounds, constraints=constraints)
    
    return result.x

def evaluate_portfolio(weights, test_returns, risk_aversion=3):
    """Evaluate portfolio performance"""
    portfolio_returns = test_returns @ weights
    
    mean_return = np.mean(portfolio_returns)
    std_return = np.std(portfolio_returns)
    sharpe_ratio = mean_return / std_return
    cer = mean_return - 0.5 * risk_aversion * std_return**2
    
    # Compute maximum drawdown
    cumulative_returns = np.cumprod(1 + portfolio_returns)
    peak = np.maximum.accumulate(cumulative_returns)
    drawdown = (peak - cumulative_returns) / peak
    max_drawdown = np.max(drawdown)
    
    return {
        'mean': mean_return,
        'std': std_return,
        'sharpe_ratio': sharpe_ratio,
        'cer': cer,
        'max_drawdown': max_drawdown
    }

