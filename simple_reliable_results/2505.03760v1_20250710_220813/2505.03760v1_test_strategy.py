class StockMarketSimulator:
    """Generates simulated stock price data with different volatility profiles"""
    
    def __init__(self, n_stocks=30, n_days=1500, start_date="2010-01-01"):
        self.n_stocks = n_stocks
        self.n_days = n_days
        self.start_date = datetime.strptime(start_date, "%Y-%m-%d")
        
    def generate_data(self):
        """Generate stock prices with different volatility profiles"""
        dates = [self.start_date + timedelta(days=i) for i in range(self.n_days)]
        dates = [d for d in dates if d.weekday() < 5]  # Only business days
        
        # Create empty dataframe
        df = pd.DataFrame(index=dates)
        df.index = pd.to_datetime(df.index)
        
        # Generate stocks with different volatility profiles
        # Higher volatility for aggressive stocks (indices 0-9)
        # Medium volatility for moderate stocks (indices 10-19)
        # Lower volatility for conservative stocks (indices 20-29)
        for i in range(self.n_stocks):
            if i < 10:  # Aggressive stocks
                volatility = np.random.uniform(0.015, 0.025)
            elif i < 20:  # Moderate stocks
                volatility = np.random.uniform(0.008, 0.015)
            else:  # Conservative stocks
                volatility = np.random.uniform(0.003, 0.008)
                
            # Starting price
            start_price = np.random.uniform(50, 200)
            
            # Generate price series with random walk
            prices = [start_price]
            for _ in range(len(dates) - 1):
                # Random daily return based on volatility
                daily_return = np.random.normal(0.0005, volatility)  # Slight upward drift
                new_price = prices[-1] * (1 + daily_return)
                prices.append(new_price)
                
            df[f'Stock_{i+1}'] = prices
            
        # Split into training and test sets
        train_end_date = "2022-12-31"
        test_start_date = "2023-01-01"
        
        train_data = df[df.index <= train_end_date]
        test_data = df[df.index >= test_start_date]
        
        return train_data, test_data

class GARCHVolatilityClassifier:
    """Classifies stocks based on their GARCH volatility forecasts"""
    
    def __init__(self):
        self.volatilities = {}
        
    def calculate_volatility(self, stock_data):
        """Calculate GARCH volatility for each stock"""
        volatilities = {}
        
        for column in stock_data.columns:
            # Calculate log returns
            returns = np.log(stock_data[column] / stock_data[column].shift(1)).dropna()
            
            # Fit GARCH(1,1) model
            model = arch_model(returns, vol='GARCH', p=1, q=1)
            try:
                results = model.fit(disp='off')
                # Get the last forecasted volatility
                forecast = results.forecast(horizon=1)
                volatility = np.sqrt(forecast.variance.iloc[-1, 0])
                volatilities[column] = volatility
            except:
                # Fallback to standard deviation if GARCH fitting fails
                volatilities[column] = returns.std()
                
        self.volatilities = volatilities
        return volatilities
    
    def categorize_stocks(self, n_per_category=10):
        """Categorize stocks into aggressive, moderate, and conservative based on volatility"""
        sorted_stocks = sorted(self.volatilities.items(), key=lambda x: x[1], reverse=True)
        
        aggressive = [stock[0] for stock in sorted_stocks[:n_per_category]]
        moderate = [stock[0] for stock in sorted_stocks[n_per_category:2*n_per_category]]
        conservative = [stock[0] for stock in sorted_stocks[2*n_per_category:]]
        
        return {
            'aggressive': aggressive,
            'moderate': moderate,
            'conservative': conservative
        }

class PortfolioEnvironment(gym.Env):
    """Environment for portfolio optimization using reinforcement learning"""
    
    def __init__(self, stock_data, stocks_list, initial_capital=1000000, transaction_cost=0.0005):
        super(PortfolioEnvironment, self).__init__()
        
        self.stock_data = stock_data[stocks_list].copy()
        self.stocks_list = stocks_list
        self.n_stocks = len(stocks_list)
        
        self.initial_capital = initial_capital
        self.transaction_cost = transaction_cost
        
        # Define action and observation space
        self.action_space = spaces.Box(low=0, high=1, shape=(self.n_stocks,), dtype=np.float32)
        self.observation_space = spaces.Box(
            low=-np.inf, high=np.inf, shape=(self.n_stocks * 2 + 1,), dtype=np.float32
        )
        
        self.reset()
        
    def reset(self):
        self.current_step = 0
        self.current_value = self.initial_capital
        self.weights = np.zeros(self.n_stocks)
        self.portfolio_values = [self.initial_capital]
        
        return self._get_observation()
        
    def _get_observation(self):
        # Get normalized prices (normalized by the first day)
        if self.current_step == 0:
            normalized_prices = np.ones(self.n_stocks)
        else:
            prices_t = self.stock_data.iloc[self.current_step].values
            prices_tminus1 = self.stock_data.iloc[self.current_step-1].values
            normalized_prices = prices_t / prices_tminus1
            
        # Returns over the last 5 days (or fewer if at the beginning)
        if self.current_step < 5:
            past_returns = np.zeros(self.n_stocks)
        else:
            prices_t = self.stock_data.iloc[self.current_step].values
            prices_tminus5 = self.stock_data.iloc[self.current_step-5].values
            past_returns = prices_t / prices_tminus5 - 1
            
        # Current portfolio weights
        current_weights = self.weights
        
        # Combine everything into the observation
        observation = np.concatenate([normalized_prices, past_returns, [self.current_value / self.initial_capital]])
        
        return observation
        
    def step(self, action):
        # Ensure the action sums to 1 (normalize if necessary)
        action = np.array(action)
        action_sum = np.sum(action)
        if action_sum > 0:
            action = action / action_sum
        else:
            action = np.ones(self.n_stocks) / self.n_stocks
            
        # Calculate transaction costs
        cost = np.sum(np.abs(action - self.weights)) * self.transaction_cost * self.current_value
        
        # Update weights
        self.weights = action
        
        # Move to the next day
        self.current_step += 1
        
        if self.current_step >= len(self.stock_data) - 1:
            done = True
        else:
            done = False
            
        # Calculate portfolio return
        prev_prices = self.stock_data.iloc[self.current_step - 1].values
        curr_prices = self.stock_data.iloc[self.current_step].values
        
        # Element-wise return calculation
        element_returns = curr_prices / prev_prices
        
        # Portfolio return is the weighted sum of individual returns
        portfolio_return = np.sum(element_returns * self.weights) - cost / self.current_value
        
        # Update portfolio value
        self.current_value *= portfolio_return
        self.portfolio_values.append(self.current_value)
        
        # Calculate reward (log return)
        reward = np.log(portfolio_return) if portfolio_return > 0 else -1
        
        # Get new observation
        observation = self._get_observation()
        
        info = {
            'portfolio_value': self.current_value,
            'portfolio_return': portfolio_return - 1,  # Convert to percentage
            'weights': self.weights
        }
        
        return observation, reward, done, info

class SimplePPOAgent:
    """Simple implementation of Proximal Policy Optimization (PPO) agent"""
    
    def __init__(self, state_dim, action_dim):
        self.state_dim = state_dim
        self.action_dim = action_dim
        
        # Simple weight matrices for the policy network
        self.W1 = np.random.randn(state_dim, 64) * 0.1
        self.b1 = np.zeros(64)
        self.W2 = np.random.randn(64, 32) * 0.1
        self.b2 = np.zeros(32)
        self.W3 = np.random.randn(32, action_dim) * 0.1
        self.b3 = np.zeros(action_dim)
        
    def predict(self, state):
        """Forward pass through the network to predict action weights"""
        h1 = np.tanh(np.dot(state, self.W1) + self.b1)
        h2 = np.tanh(np.dot(h1, self.W2) + self.b2)
        out = np.tanh(np.dot(h2, self.W3) + self.b3)
        
        # Convert to portfolio weights (non-negative and sum to 1)
        weights = np.maximum(0, out)
        weights_sum = np.sum(weights)
        
        if weights_sum > 0:
            weights = weights / weights_sum
        else:
            weights = np.ones(self.action_dim) / self.action_dim
            
        return weights
    
    def train(self, env, episodes=10):
        """Simple training loop for the agent"""
        best_reward = -np.inf
        best_weights = self.predict(np.zeros(self.state_dim))
        
        for episode in range(episodes):
            state = env.reset()
            done = False
            total_reward = 0
            
            while not done:
                action = self.predict(state)
                next_state, reward, done, info = env.step(action)
                
                # Simple update rule (not a true PPO implementation)
                if reward > 0:
                    # Reinforce successful actions by small random adjustments
                    self.W3 += np.random.normal(0, 0.01, self.W3.shape) * reward
                    self.b3 += np.random.normal(0, 0.01, self.b3.shape) * reward
                
                state = next_state
                total_reward += reward
            
            if total_reward > best_reward:
                best_reward = total_reward
                best_weights = action
                
            print(f"Episode {episode+1}/{episodes}, Reward: {total_reward:.4f}, Final Value: {info['portfolio_value']:.2f}")
        
        return best_weights

