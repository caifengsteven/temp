class ExpectedShortfall:
    """
    Implementation of Expected Shortfall as an example of a signed Choquet integral
    to test the results from Section 6.
    """
    
    @staticmethod
    def calculate(samples: np.ndarray, alpha: float = 0.9) -> float:
        """
        Calculate Expected Shortfall (ES) at level alpha
        
        Args:
            samples: Sample data
            alpha: ES level (default: 0.9)
            
        Returns:
            ES value
        """
        sorted_samples = np.sort(samples)
        n = len(sorted_samples)
        k = int(np.ceil(n * (1 - alpha)))
        return np.mean(sorted_samples[-k:])
    
    @staticmethod
    def worst_case_quantile(
        reference_samples: np.ndarray, 
        alpha: float, 
        epsilon: float, 
        L: float
    ) -> np.ndarray:
        """
        Generate the worst-case quantile function for ES as per Proposition 8
        
        Args:
            reference_samples: Samples from reference distribution
            alpha: ES level
            epsilon: Tolerance distance for uncertainty sets
            L: Lipschitz constant
            
        Returns:
            Samples from the worst-case distribution
        """
        n_samples = len(reference_samples)
        sorted_ref = np.sort(reference_samples)
        
        # Create quantile points
        u = np.linspace(0, 1, n_samples)
        
        # Distortion weight function for ES (piecewise constant)
        phi = np.zeros(n_samples)
        phi[u > alpha] = 1/(1-alpha)
        
        # Calculate L2 norm of phi
        phi_norm = np.sqrt(np.mean(phi**2))
        
        # Generate worst-case quantile function
        worst_case = np.copy(sorted_ref)
        
        # Only modify points in the tail according to the paper's formula
        worst_case[u > alpha] += L * epsilon * phi_norm
        
        return worst_case


