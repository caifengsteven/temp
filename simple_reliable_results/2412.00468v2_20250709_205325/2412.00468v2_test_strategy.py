            weighted_mc = np.sum(weights * avg_market_caps)
            
            # Calculate average market cap
            avg_mc = np.mean(avg_market_caps)
            
            # Calculate normalized exposure
            normalized_exposure = weighted_mc / avg_mc
            
            # Calculate Gini coefficient of portfolio
            sorted_idx = np.argsort(avg_market_caps)[::-1]
            sorted_mc = avg_market_caps[sorted_idx]
            sorted_weights = weights[sorted_idx]
            
            # Calculate weighted Gini
