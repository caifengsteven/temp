class AMVPOptimizer:
    """
    Adaptive Minimum-Variance Portfolio (AMVP) Optimizer as described in the paper
    """
    def __init__(self, returns, max_iterations=15, convergence_threshold=1e-10):
        """
        Initialize the optimizer with a matrix of asset returns.
        
        Parameters:
        returns (numpy.ndarray): T x N matrix of T observations for N assets
        max_iterations (int): Maximum number of iterations for convergence
        convergence_threshold (float): Threshold for convergence of variance
        """
        self.returns = returns
        self.T, self.N = returns.shape
        self.max_iterations = max_iterations
        self.convergence_threshold = convergence_threshold
        self.convergence_history = []
        
    def calculate_covariance(self, data):
        """Calculate the sample covariance matrix"""
        return np.cov(data, rowvar=False)
    
    def calculate_mean_returns(self, data):
        """Calculate the mean returns vector"""
        return np.mean(data, axis=0)
    
    def minimum_variance_portfolio(self, cov_matrix):
        """
        Solve for the minimum variance portfolio with non-negative weights constraint
        
        Parameters:
        cov_matrix (numpy.ndarray): N x N covariance matrix
        
        Returns:
        tuple: (weights, portfolio variance)
        """
        n = cov_matrix.shape[0]
        
        # Define the objective function (portfolio variance)
        def objective(weights):
            return np.dot(weights.T, np.dot(cov_matrix, weights))
        
        # Define constraints: weights sum to 1
        constraints = ({'type': 'eq', 'fun': lambda x: np.sum(x) - 1})
        
        # Bounds: non-negative weights
        bounds = tuple((0, 1) for _ in range(n))
        
        # Initial guess: equal weights
        initial_weights = np.ones(n) / n
        
        # Solve the optimization problem
        result = minimize(objective, initial_weights, method='SLSQP', 
                          bounds=bounds, constraints=constraints)
        
        # Extract the optimal weights and portfolio variance
        weights = result['x']
        variance = result['fun']
        
        return weights, variance
    
    def optimize(self):
        """
        Perform the AMVP optimization process
        
        Returns:
        dict: Results containing weights, variance, and AMRR for each iteration
        """
        current_data = self.returns.copy()
        results = {
            'weights': [],
            'variance': [],
            'amrr': []
        }
        
        for i in range(self.max_iterations):
            # Calculate covariance matrix and mean returns
            cov_matrix = self.calculate_covariance(current_data)
            mean_returns = self.calculate_mean_returns(current_data)
            
