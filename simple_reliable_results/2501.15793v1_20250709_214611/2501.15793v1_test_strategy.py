def generate_simulated_returns(n_assets, n_days, mean_returns=None, volatilities=None, 
                               correlation=None, heavy_tailed=False):
    """
    Generate simulated return data with specified properties.
    
    Parameters:
    n_assets (int): Number of assets
    n_days (int): Number of days
    mean_returns (list, optional): Mean returns for each asset
    volatilities (list, optional): Volatilities for each asset
    correlation (float, optional): Base correlation between assets
    heavy_tailed (bool): Whether to use heavy-tailed distribution (NIG-like)
    
    Returns:
    numpy.ndarray: Matrix of simulated returns
    """
    if mean_returns is None:
        mean_returns = np.random.uniform(0.0001, 0.002, n_assets)
    
    if volatilities is None:
        volatilities = np.random.uniform(0.01, 0.05, n_assets)
    
    # Create correlation matrix (simplified)
    if correlation is None:
        correlation = 0.3
        
    corr_matrix = np.ones((n_assets, n_assets)) * correlation
    np.fill_diagonal(corr_matrix, 1)
    
    # Convert correlation matrix to covariance matrix
    cov_matrix = np.outer(volatilities, volatilities) * corr_matrix
    
    # Generate multivariate normal returns
    returns = np.random.multivariate_normal(mean_returns, cov_matrix, n_days)
    
    # If heavy-tailed, transform to approximate NIG distribution
    if heavy_tailed:
        # Simple approximation of NIG using t-distribution
        df = 3  # Degrees of freedom for t-distribution (smaller = heavier tails)
        t_random = np.random.standard_t(df, size=(n_days, n_assets))
        # Scale t-distribution to match desired volatility and add mean
        returns = (t_random * volatilities / np.std(t_random, axis=0)) + mean_returns
        
    return returns


def calculate_amrr_time_series(returns, window_size=252):
    """
    Calculate the AMRR time series using rolling windows
    
    Parameters:
    returns (numpy.ndarray): Asset returns
    window_size (int): Size of rolling window
    
    Returns:
    numpy.ndarray: Time series of AMRR values
    """
    T, N = returns.shape
    amrr_series = np.zeros(T - window_size + 1)
    
    for t in range(T - window_size + 1):
        window_returns = returns[t:t+window_size]
        optimizer = AMVPOptimizer(window_returns, max_iterations=3)
        results = optimizer.optimize()
        amrr_series[t] = results['amrr'][-1]  # Use the final AMRR value
    
    return amrr_series


def test_chow_test(amrr_series, breakpoint_idx):
    """
    Perform Chow test for structural breaks
    
    Parameters:
    amrr_series (numpy.ndarray): Time series of AMRR values
    breakpoint_idx (int): Index to test for structural break
    
    Returns:
    tuple: (F-statistic, p-value)
    """
    # Split data at breakpoint
    before = amrr_series[:breakpoint_idx]
    after = amrr_series[breakpoint_idx:]
    full = amrr_series
    
    # Create simple trend model
    X_before = np.column_stack((np.ones(len(before)), np.arange(len(before))))
    X_after = np.column_stack((np.ones(len(after)), np.arange(len(after))))
    X_full = np.column_stack((np.ones(len(full)), np.arange(len(full))))
    
    # Fit regression models
    beta_before = np.linalg.lstsq(X_before, before, rcond=None)[0]
    beta_after = np.linalg.lstsq(X_after, after, rcond=None)[0]
    beta_full = np.linalg.lstsq(X_full, full, rcond=None)[0]
    
    # Calculate residual sum of squares
    rss_before = np.sum((before - np.dot(X_before, beta_before))**2)
    rss_after = np.sum((after - np.dot(X_after, beta_after))**2)
    rss_pooled = rss_before + rss_after
    rss_full = np.sum((full - np.dot(X_full, beta_full))**2)
    
    # Calculate F-statistic
    n = len(full)
    k = 2  # Number of parameters in the model
    f_stat = ((rss_full - rss_pooled) / k) / (rss_pooled / (n - 2*k))
    
    # Calculate p-value (approximate using chi-square)
    p_value = 1 - chisquare.cdf(f_stat * k, k)
    
    return f_stat, p_value


