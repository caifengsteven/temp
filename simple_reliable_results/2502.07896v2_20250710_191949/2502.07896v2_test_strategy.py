            # Calculate first-order effect (Hulten's theorem)
            # Domar weight is column sum of Leontief inverse
            domar_weight = np.sum(L[:, shock_idx])
            
            # First-order effect
            first_order_effect = shock_size * domar_weight
            
            # Add non-linear effects for complementarity (simplified)
