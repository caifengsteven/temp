class EMVRSModel:
    def __init__(self, T=1, dt=0.1, x0=1.0, z=1.4, xi=0.5, r=(0.01, 0.05), 
                 Q=np.array([[-1, 1], [1, -1]]), action_constraint=3, 
                 allow_short_selling=True):
        """
        Initialize the EMVRS model with parameters
        
        Parameters:
        -----------
        T : float
            Investment horizon
        dt : float
            Time step for discretization
        x0 : float
            Initial portfolio value
        z : float
            Target terminal portfolio value
        xi : float
            Exploration weight
        r : tuple
            Risk-free interest rates for each regime
        Q : ndarray
            Generator matrix for the Markov chain
        action_constraint : float
            Maximum leverage allowed
        allow_short_selling : bool
            Whether short selling is allowed
        """
        self.T = T
        self.dt = dt
        self.K = int(T / dt)
        self.time_grid = np.linspace(0, T, self.K + 1)
        self.x0 = x0
        self.z = z
        self.xi = xi
        self.r = r
        self.Q = Q
        self.l = len(r)  # Number of regimes
        self.P_matrix = expm(dt * Q)  # Transition matrix
        self.action_constraint = action_constraint
        self.allow_short_selling = allow_short_selling
        
        # Initialize market parameters
        self.theta = np.array([0.2, 0.2, 0.95, -0.83])  # [sigma1, sigma2, rho1, rho2]
        self.true_theta = np.array([0.2, 0.3, 0.95, -0.83])  # Ground truth
        
        # Learning rates for the Orthogonality Condition (OC) learning
        self.eta_oc = np.array([1e4, 1e4, 1e4, 1e4])
        
        # For saving results
        self.theta_history = []

    def solve_odes(self, theta, alpha_path):
        """
        Solve the system of ODEs for P, H, C, D functions
        
        Parameters:
        -----------
        theta : ndarray
            Market parameters [sigma1, sigma2, rho1, rho2]
        alpha_path : ndarray
            Path of market regimes
            
        Returns:
        --------
        P_values, H_values, C_values, D_values : tuple of ndarrays
            Solutions to the ODEs at each time point
        """
        sigma1, sigma2, rho1, rho2 = theta
        sigma = np.array([sigma1, sigma2])
        rho = np.array([rho1, rho2])
        
        # Initialize arrays to store solutions
        P_values = np.zeros((self.K+1, self.l))
        H_values = np.zeros((self.K+1, self.l))
        C_values = np.zeros((self.K+1, self.l))
        D_values = np.zeros((self.K+1, self.l))
        
        # Terminal conditions
        P_values[self.K, :] = 1.0
        H_values[self.K, :] = 1.0
        
        # Solve ODEs backwards in time
        for k in range(self.K-1, -1, -1):
            t = self.time_grid[k]
            dt = self.time_grid[k+1] - t
            
            # Simple Euler scheme for ODE integration
            for i in range(self.l):
                # P(t, i) ODE
                P_dot = (rho[i]**2 - 2*self.r[i])*P_values[k+1, i]
                for j in range(self.l):
                    P_dot -= self.Q[i, j] * P_values[k+1, j]
                P_values[k, i] = P_values[k+1, i] - dt * P_dot
                
                # H(t, i) ODE
                H_dot = self.r[i] * H_values[k+1, i]
                for j in range(self.l):
                    H_dot -= (self.Q[i, j] * P_values[k+1, j] * (H_values[k+1, j] - H_values[k+1, i])) / P_values[k+1, i]
                H_values[k, i] = H_values[k+1, i] - dt * H_dot
                
                # C(t, i) ODE
                C_dot = 0
                for j in range(self.l):
                    C_dot -= self.Q[i, j] * (P_values[k+1, j] * (H_values[k+1, j] - H_values[k+1, i])**2 + C_values[k+1, j])
                C_values[k, i] = C_values[k+1, i] - dt * C_dot
                
                # D(t, i) ODE
                D_dot = (self.xi/2) * np.log(np.pi * self.xi / (sigma[i]**2 * P_values[k+1, i]))
                for j in range(self.l):
                    D_dot -= self.Q[i, j] * D_values[k+1, j]
                D_values[k, i] = D_values[k+1, i] - dt * D_dot
        
        return P_values, H_values, C_values, D_values

    def compute_value_function(self, t_idx, x, i, P, H, C, D, lambda_val):
        """
        Compute the value function at time t_idx with wealth x in regime i
        """
        return (P[t_idx, i] * (x + (lambda_val - self.z) * H[t_idx, i])**2 + 
                (lambda_val - self.z)**2 * C[t_idx, i] + 
                D[t_idx, i] - lambda_val**2/2)

    def optimal_policy(self, t_idx, x, i, P, H, theta, lambda_val):
        """
        Compute the optimal policy distribution parameters (mean and std)
        """
        sigma_i = theta[i] if i < 2 else theta[0]  # sigma1 or sigma2
        rho_i = theta[i+2] if i < 2 else theta[2]  # rho1 or rho2
        
        mean = -rho_i/sigma_i * (x + (lambda_val - self.z) * H[t_idx, i])
        std = np.sqrt(self.xi / (2 * sigma_i**2 * P[t_idx, i]))
        
        return mean, std

    def simulate_trajectory(self, theta, true_theta, seed=None):
        """
        Simulate a trajectory of portfolio values and regimes
        
        Parameters:
        -----------
        theta : ndarray
            Current estimate of market parameters
        true_theta : ndarray
            True market parameters for simulation
        seed : int, optional
            Random seed for reproducibility
            
        Returns:
        --------
        X_path : ndarray
            Path of portfolio values
        alpha_path : ndarray
            Path of market regimes
        W_path : ndarray
            Path of Brownian motion increments
        """
        if seed is not None:
            np.random.seed(seed)
            
        # Initialize paths
        X_path = np.zeros(self.K + 1)
        X_path[0] = self.x0
        alpha_path = np.zeros(self.K + 1, dtype=int)
        alpha_path[0] = np.random.randint(0, self.l)  # Random initial regime
        W_path = np.random.normal(0, np.sqrt(self.dt), self.K)
        
        # Solve ODEs for the current theta
        P, H, C, D = self.solve_odes(theta, alpha_path)
        
        # Compute optimal lambda
        i0 = alpha_path[0]
        lambda_val = (self.z - P[0, i0] * H[0, i0] * self.x0) / (P[0, i0] * H[0, i0]**2 + C[0, i0] - 1) + self.z
        
        # Simulate forward
        for k in range(self.K):
            # Current regime and wealth
            i = alpha_path[k]
            x = X_path[k]
            
            # Get policy parameters and sample action
            mean, std = self.optimal_policy(k, x, i, P, H, theta, lambda_val)
            
            # Simulate next regime
            if np.random.rand() < self.P_matrix[i, 0]:
                alpha_path[k+1] = 0
            else:
                alpha_path[k+1] = 1
                
            # Get true market parameters for the current regime
            sigma_true = true_theta[i] if i < 2 else true_theta[0]
            rho_true = true_theta[i+2] if i < 2 else true_theta[2]
            
            # Update portfolio value (discretized SDE)
            drift = (self.r[i] * x + rho_true * sigma_true * mean) * self.dt
            diffusion = sigma_true * np.sqrt(mean**2 + self.xi/(2*sigma_true**2 * P[k, i])) * W_path[k]
            X_path[k+1] = x + drift + diffusion
            
        return X_path, alpha_path, W_path

    def compute_oc_loss(self, theta, X_path, alpha_path):
        """
        Compute the Orthogonality Condition loss
        """
        P, H, C, D = self.solve_odes(theta, alpha_path)
        
        # Compute optimal lambda
        i0 = alpha_path[0]
        lambda_val = (self.z - P[0, i0] * H[0, i0] * self.x0) / (P[0, i0] * H[0, i0]**2 + C[0, i0] - 1) + self.z
        
        # Initialize OC losses
        oc_losses = np.zeros(4)
        
        # For each parameter
        for j in range(4):
            # Compute parameter gradients (simplified approximation)
            dtheta = 1e-5
            theta_plus = theta.copy()
            theta_plus[j] += dtheta
            
            P_plus, H_plus, C_plus, D_plus = self.solve_odes(theta_plus, alpha_path)
            
            # Compute value function derivatives w.r.t. parameters
            dV_dtheta = np.zeros(self.K)
            for k in range(self.K):
                i = alpha_path[k]
                x = X_path[k]
                V_plus = self.compute_value_function(k, x, i, P_plus, H_plus, C_plus, D_plus, lambda_val)
                V = self.compute_value_function(k, x, i, P, H, C, D, lambda_val)
                dV_dtheta[k] = (V_plus - V) / dtheta
            
            # Compute M increments
            M_increments = np.zeros(self.K)
            for k in range(self.K):
                i = alpha_path[k]
                x = X_path[k]
                i_next = alpha_path[k+1]
                x_next = X_path[k+1]
                
                V_next = self.compute_value_function(k+1, x_next, i_next, P, H, C, D, lambda_val)
                V_curr = self.compute_value_function(k, x, i, P, H, C, D, lambda_val)
                
                # Log term in M process
                log_term = -(self.xi/2) * np.log(np.pi * self.xi / (theta[i]**2 * P[k, i]))
                
                M_increments[k] = V_next - V_curr - log_term * self.dt
            
            # Compute OC loss for this parameter
            oc_losses[j] = np.sum(dV_dtheta * M_increments)
            
        return oc_losses

    def train_oc(self, num_epochs=1000, eval_freq=50):
        """
        Train the model using Orthogonality Condition learning
        """
        self.theta_history = [self.theta.copy()]
        
        for epoch in range(num_epochs):
            # Simulate trajectory
            X_path, alpha_path, W_path = self.simulate_trajectory(self.theta, self.true_theta, seed=epoch)
            
            # Compute OC loss
            oc_losses = self.compute_oc_loss(self.theta, X_path, alpha_path)
            
            # Update parameters
            self.theta += self.eta_oc * oc_losses
            
            # Apply constraints
            if not self.allow_short_selling:
                # Ensure positive sigma values
                self.theta[0:2] = np.clip(self.theta[0:2], 0.05, 1.0)
            else:
                # Bound sigma and rho values
                self.theta[0:2] = np.clip(self.theta[0:2], 0.05, 1.0)
                self.theta[2:4] = np.clip(self.theta[2:4], -2.0, 2.0)
            
            # Save history
            self.theta_history.append(self.theta.copy())
            
            # Display progress
            if epoch % eval_freq == 0 or epoch == num_epochs - 1:
                print(f"Epoch {epoch}: theta = {self.theta}, true = {self.true_theta}")
                
            # Reduce learning rate over time
            if epoch % 100 == 0 and epoch > 0:
                self.eta_oc *= 0.9
                
        return self.theta_history

