    def backtest(self, num_trials=5):
        """
        Backtest the trained model
        """
        terminal_values = []
        
        for trial in range(num_trials):
            X_path, _, _ = self.simulate_trajectory(self.theta, self.true_theta, seed=1000+trial)
            terminal_values.append(X_path[-1])
            
