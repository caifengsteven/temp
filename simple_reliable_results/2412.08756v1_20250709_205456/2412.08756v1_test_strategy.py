def plot_eigenvalue_distribution(model, p=100):
    """Plot eigenvalue distribution of a covariance matrix model."""
    if model == "nested":
        Sigma = CovarianceModels.nested_hierarchical_model(p)
        title = "Model 1: Nested Hierarchical Covariance"
    elif model == "factor":
        Sigma = CovarianceModels.one_factor_model(p)
        title = "Model 2: One-Factor Model"
    elif model == "diagonal":
        Sigma = CovarianceModels.diagonal_model(p)
        title = "Model 3: Diagonal Model"
    
    eigenvalues = np.linalg.eigvalsh(Sigma)
    eigenvalues = np.sort(eigenvalues)[::-1]  # Sort in descending order
    
    plt.figure(figsize=(10, 6))
    plt.plot(range(1, p+1), eigenvalues, marker='o', linestyle='-')
    plt.title(f"Eigenvalue Distribution - {title}")
    plt.xlabel("Eigenvalue Index")
    plt.ylabel("Eigenvalue Magnitude")
    plt.yscale('log')
    plt.grid(True)
    plt.tight_layout()
    plt.show()
    
    # Also plot dendrogram for hierarchical structure
    if model != "diagonal":
        plt.figure(figsize=(12, 6))
        # Create distance matrix from correlation
        corr = Sigma / np.sqrt(np.outer(np.diag(Sigma), np.diag(Sigma)))
        dist = np.sqrt(0.5 * (1 - corr))
        
        # Compute linkage
        link = linkage(dist[np.triu_indices(p, k=1)], method='single')
        
        # Plot dendrogram
        dendrogram(link, p=30)
        plt.title(f"Hierarchical Structure - {title}")
        plt.xlabel("Asset Index")
        plt.ylabel("Distance")
        plt.tight_layout()
        plt.show()


