            w_mvp = PortfolioStrategies.minimum_variance_portfolio(S_est)
            w_mvp_long = PortfolioStrategies.minimum_variance_portfolio_long_only(S_est)
            w_hrp = PortfolioStrategies.hierarchical_risk_parity(S_est)
            
            strategies = {
                "MVP": w_mvp,
                "MVP+": w_mvp_long,
                "HRP": w_hrp
            }
            
            for strat_name, w in strategies.items():
                # Calculate performance metrics
                hhi = PerformanceMetrics.hhi(w)
