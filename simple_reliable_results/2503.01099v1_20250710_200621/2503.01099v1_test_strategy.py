class PortfolioState:
    """Represents the state of the portfolio at a given time"""
    def __init__(self, 
                 t: int = 0, 
                 W: float = 1.0,  # Liquid wealth
                 P: float = 0.0,   # Illiquid wealth (PE NAV)
                 K: float = 0.0,   # Uncalled commitments
                 mu_P: float = 0.03,  # Expected PE return
                 s: int = 1):      # Macroeconomic state (1=recession, 2=expansion)
        self.t = t
        self.W = W
        self.P = P
        self.K = K
        self.mu_P = mu_P
        self.s = s  # 1-indexed (1=recession, 2=expansion)
        
    @property
    def w(self) -> float:
        """Liquid fraction of total wealth"""
        if self.W + self.P <= 0:
            return 1.0
        return self.W / (self.W + self.P)
    
    @property
    def k(self) -> float:
        """Uncalled commitments relative to total wealth"""
        if self.W + self.P <= 0:
            return 0.0
        return self.K / (self.W + self.P)
    
    @property
    def total_wealth(self) -> float:
        """Total wealth (liquid + illiquid)"""
        return self.W + self.P
    
    def __str__(self):
        return (f"t={self.t}, W={self.W:.2f}, P={self.P:.2f}, K={self.K:.2f}, "
                f"mu_P={self.mu_P:.4f}, s={self.s}, total={self.total_wealth:.2f}")


class PortfolioDecision:
    """Represents a portfolio decision at a given time"""
    def __init__(self, 
                 N: float = 0.0,   # New PE commitments
                 S: float = 0.0,   # Allocation to stocks
                 B: float = 0.0):  # Allocation to bonds
        self.N = N
        self.S = S
        self.B = B
    
    @property
    def is_valid(self) -> bool:
        """Check if the decision is valid (non-negative allocations)"""
        return self.N >= 0 and self.S >= 0 and self.B >= 0
    
    def __str__(self):
        return f"N={self.N:.2f}, S={self.S:.2f}, B={self.B:.2f}"


