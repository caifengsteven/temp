class OptimalAllocationStrategy(AllocationStrategy):
    """Implements the paper's optimal allocation strategy (approximated)"""
    def decide(self, state: PortfolioState, params: ModelParameters) -> PortfolioDecision:
        t, w, k, mu_P, s = state.t, state.w, state.k, state.mu_P, state.s
        total_wealth = state.total_wealth
        s_idx = s - 1  # Convert to 0-indexed
        
        # Determine life cycle phase
        if t < 4:  # Ramp-up phase (years 0-1)
            # Aggressive new commitments
            if t == 0:
                n_scaled = 1.0  # 100% of total wealth
            elif t == 1:
                n_scaled = 0.47  # 47% of total wealth
            elif t < 4:
                n_scaled = 0.10  # 10% of total wealth
            else:
                n_scaled = 0.05  # 5% of total wealth
                
            # Adjust for business cycle
            if s == 1:  # Recession
                n_scaled *= 0.9  # Reduce commitments by 10% in recession
                
            # Stock allocation depends on business cycle
            if s == 2:  # Expansion
                stock_pct = max(0.62 - 0.15 * t, 0.05)  # Starts high, decreases over time
            else:  # Recession
                stock_pct = max(0.38 - 0.10 * t, 0.03)  # Lower allocation in recession
                
        else:  # Maintenance phase (years 1+)
            # Maintain PE exposure
            expected_calls = (params.lambda_K[s_idx] * k + 
                             params.lambda_D[s_idx] * (1 - w)) * total_wealth
            
            # Target 62% PE allocation
            pe_target = 0.62
            current_pe = 1 - w
            
            # Adjust commitments to maintain target PE allocation
            if current_pe < pe_target * 0.9:  # Below target
                n_scaled = min(0.15, pe_target - current_pe + 0.05)
            elif current_pe > pe_target * 1.1:  # Above target
                n_scaled = 0.02  # Minimal new commitments
            else:  # Near target
                n_scaled = 0.05  # Maintenance level
                
            # Stock allocation in maintenance phase
            if s == 2:  # Expansion
                stock_pct = 0.05  # Low stock allocation in expansion
            else:  # Recession
                stock_pct = 0.03  # Even lower in recession
                
        # Calculate actual allocation amounts
        N = n_scaled * total_wealth
        S = stock_pct * total_wealth
        
        # Ensure liquidity constraint is satisfied
        gamma_N_cost = params.gamma_N * total_wealth * (n_scaled - params.n_bar)**2
        gamma_S_cost = params.gamma_S * total_wealth * (stock_pct)**2
        
        available_liquid = state.W - gamma_N_cost - gamma_S_cost
        
        # Adjust if not enough liquid wealth
        if available_liquid < S:
            S = max(0, available_liquid * 0.9)  # Leave some buffer
            
        B = available_liquid - S
        
        # Ensure non-negative allocations
        N = max(0, N)
        S = max(0, S)
        B = max(0, B)
        
        return PortfolioDecision(N=N, S=S, B=B)


