def run_simulation(
    strategy: AllocationStrategy,
    params: ModelParameters,
    initial_state: PortfolioState,
    n_trajectories: int = 100,
    seed: int = 42
) -> List[List[PortfolioState]]:
    """Run multiple simulation trajectories with the given strategy"""
    np.random.seed(seed)
    random.seed(seed)
    
    simulator = PrivateAssetSimulator(params)
    all_trajectories = []
    
    default_count = 0
    
    for i in range(n_trajectories):
        trajectory = [initial_state]
        has_defaulted = False
        
        for t in range(params.T):
            current_state = trajectory[-1]
            decision = strategy.decide(current_state, params)
            
            try:
                next_state = simulator.step(current_state, decision)
                trajectory.append(next_state)
                
                # Check if this step resulted in default
                if next_state.P == 0 and current_state.P > 0 and not has_defaulted:
                    has_defaulted = True
                    default_count += 1
                    
            except ValueError as e:
                print(f"Error in trajectory {i} at time {t}: {e}")
                break
                
        all_trajectories.append(trajectory)
    
    print(f"Completed {n_trajectories} trajectories. Default rate: {default_count/n_trajectories:.1%}")
    return all_trajectories


def analyze_trajectories(trajectories: List[List[PortfolioState]], params: ModelParameters) -> Dict:
    """Analyze the simulation results"""
    n_trajectories = len(trajectories)
    horizon_years = params.T / 4  # Convert quarters to years
    
    # Extract final wealth values
    final_total_wealth = [traj[-1].total_wealth for traj in trajectories]
    
    # Calculate annualized returns
    annualized_returns = [(np.log(traj[-1].total_wealth) / horizon_years) for traj in trajectories]
    
    # Count defaults
    default_count = sum(1 for traj in trajectories if any(state.P == 0 and state.t > 0 for state in traj))
    
    # Calculate aggregate statistics
    results = {
        "mean_final_wealth": np.mean(final_total_wealth),
        "std_final_wealth": np.std(final_total_wealth),
        "mean_annualized_return": np.mean(annualized_returns) * 100,  # Convert to percentage
        "std_annualized_return": np.std(annualized_returns) * 100,    # Convert to percentage
        "default_rate": default_count / n_trajectories,
        "p1_annualized_return": np.percentile(annualized_returns, 1) * 100,
        "p5_annualized_return": np.percentile(annualized_returns, 5) * 100,
        "p95_annualized_return": np.percentile(annualized_returns, 95) * 100,
    }
    
    return results


def calculate_certainty_equivalent(trajectories: List[List[PortfolioState]], gamma: float) -> float:
    """Calculate the certainty equivalent wealth"""
    final_wealth = [traj[-1].total_wealth for traj in trajectories]
    
    if gamma == 1:  # Log utility
        mean_log_wealth = np.mean([np.log(w) for w in final_wealth])
        ce = np.exp(mean_log_wealth)
    else:
        mean_utility = np.mean([(w**(1-gamma))/(1-gamma) for w in final_wealth])
        ce = ((1-gamma) * mean_utility)**(1/(1-gamma))
        
    return ce


