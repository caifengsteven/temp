class PrivateAssetSimulator:
    """Simulator for the private asset allocation model"""
    def __init__(self, params: ModelParameters):
        self.params = params
        
    def generate_returns(self, state: PortfolioState) -> Tuple[float, float]:
        """Generate returns for PE and stocks based on the current state"""
        s_idx = state.s - 1  # Convert to 0-indexed
        
        # Generate correlated normal random variables
        z = np.random.normal(0, 1, 2)
        
        # Apply correlation
        epsilon_S = z[0]
        epsilon_P = self.params.rho[s_idx] * z[0] + np.sqrt(1 - self.params.rho[s_idx]**2) * z[1]
        
        # Calculate log returns
        log_R_S = self.params.mu_S[s_idx] + self.params.sigma_S[s_idx] * epsilon_S
        log_R_P = state.mu_P + self.params.sigma_P[s_idx] * epsilon_P
        
        # Convert to actual returns
        R_S = np.exp(log_R_S)
        R_P = np.exp(log_R_P)
        
        return R_P, R_S
    
    def transition_state(self, state: PortfolioState) -> int:
        """Transition the macroeconomic state according to the Markov process"""
        s_idx = state.s - 1  # Convert to 0-indexed
        return np.random.choice([1, 2], p=self.params.p_transition[s_idx])
    
    def calculate_risk_weight(self, state: PortfolioState, decision: PortfolioDecision) -> float:
        """Calculate the risk weight of the portfolio"""
        total_wealth = state.total_wealth
        
        # Risk weight calculation
        numerator = (self.params.theta_S * (decision.S + self.params.gamma_S * total_wealth * 
                     (decision.S / total_wealth)**2) + 
                     self.params.theta_P * state.P)
        
        denominator = (decision.B + decision.S + self.params.gamma_S * total_wealth * 
                       (decision.S / total_wealth)**2 + state.P)
        
        if denominator <= 0:
            return 0
        
        return numerator / denominator
    
    def calculate_risk_cost(self, theta: float) -> float:
        """Calculate the risk cost based on the risk weight"""
        if theta <= self.params.theta:
            return 0
        return self.params.kappa * (theta - self.params.theta)**2
    
    def step(self, state: PortfolioState, decision: PortfolioDecision) -> PortfolioState:
        """Simulate one time step with the given decision"""
        if not decision.is_valid:
            raise ValueError("Invalid portfolio decision")
        
        # Current state values
        s_idx = state.s - 1  # Convert to 0-indexed
        W = state.W
        P = state.P
        K = state.K
        total_wealth = W + P
        
        # Generate returns
        R_P, R_S = self.generate_returns(state)
        R_f = np.exp(self.params.log_Rf[s_idx])
        
        # Transition to next state
        next_s = self.transition_state(state)
        next_s_idx = next_s - 1  # Convert to 0-indexed
        
        # Calculate risk weight and cost
        theta = self.calculate_risk_weight(state, decision)
        risk_cost = self.calculate_risk_cost(theta) * total_wealth
        
        # Calculate capital calls and distributions
        capital_call_new = self.params.lambda_N[next_s_idx] * decision.N
        capital_call_existing = self.params.lambda_K[next_s_idx] * K
        distributions = self.params.lambda_D[next_s_idx] * P * R_P
        
        # Update liquid wealth
        next_W = (distributions + 
                  R_S * decision.S + 
                  R_f * decision.B - 
                  capital_call_new - 
                  capital_call_existing - 
                  risk_cost)
        
        # Check for default
        if next_W < 0:
            # In default, PE holdings are liquidated at a discount
            liquidation_value = self.params.alpha[next_s_idx] * (1 - self.params.lambda_D[next_s_idx]) * P * R_P
            next_W = distributions + R_S * decision.S + R_f * decision.B + liquidation_value - risk_cost
            next_P = 0
            next_K = 0
            print(f"DEFAULT at t={state.t+1}: W={next_W:.2f}")
        else:
            # No default
            next_P = ((1 - self.params.lambda_D[next_s_idx]) * P * R_P + 
                      capital_call_new + 
                      capital_call_existing)
            next_K = ((1 - self.params.lambda_K[next_s_idx]) * K + 
                      (1 - self.params.lambda_N[next_s_idx]) * decision.N)
        
        # Update expected PE return
        next_mu_P = (self.params.rho_P_1 * state.mu_P + 
                     self.params.rho_P_2 * np.log(R_P) + 
                     self.params.nu_P[next_s_idx])
        
        return PortfolioState(
            t=state.t + 1,
            W=next_W,
            P=next_P,
            K=next_K,
            mu_P=next_mu_P,
            s=next_s
        )


