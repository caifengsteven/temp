class PCALayer(nn.Module):
    """
    Differentiable PCA Layer as described in the paper.
    """
    def __init__(self, input_dim, output_dim, freeze_after_init=False):
        super(PCALayer, self).__init__()
        self.input_dim = input_dim
        self.output_dim = output_dim
        self.freeze_after_init = freeze_after_init
        self.initialized = False
        self.projection = nn.Parameter(torch.randn(input_dim, output_dim) / np.sqrt(input_dim))
        
    def forward(self, x):
        # x shape: [batch_size, input_dim]
        if not self.initialized or not self.freeze_after_init:
            # Compute covariance matrix
            centered_x = x - x.mean(dim=0, keepdim=True)
            cov_matrix = torch.matmul(centered_x.t(), centered_x) / (x.size(0) - 1)
            
            # Add small noise for stability
            diag_mean = torch.mean(torch.diag(cov_matrix))
            noise = 1e-4 * diag_mean * torch.rand_like(cov_matrix)
            cov_matrix = cov_matrix + noise
            
            # Compute eigenvalues and eigenvectors
            eigenvalues, eigenvectors = torch.linalg.eigh(cov_matrix)
            
            # Sort eigenvalues in descending order
            _, indices = torch.sort(eigenvalues, descending=True)
            eigenvectors = eigenvectors[:, indices]
            
            # Select top k eigenvectors
            self.projection.data = eigenvectors[:, :self.output_dim] / np.sqrt(self.input_dim)
            self.initialized = True
            
            if self.freeze_after_init:
                self.projection.requires_grad = False
        
        # Project data
        return torch.matmul(x, self.projection)


class SoftPCALayer(nn.Module):
    """
    Soft PCA Layer that learns PCA-like projections.
    """
    def __init__(self, input_dim, output_dim):
        super(SoftPCALayer, self).__init__()
        self.projection = nn.Parameter(torch.randn(input_dim, output_dim) / np.sqrt(input_dim))
        self.input_dim = input_dim
        self.output_dim = output_dim
        
    def forward(self, x):
        # Project data
        output = torch.matmul(x, self.projection)
        return output
    
    def compute_regularization_loss(self, x):
        # Project data
        output = torch.matmul(x, self.projection)
        
        # Compute variance loss
        input_var = torch.var(x, dim=0).sum()
        output_var = torch.var(output, dim=0).sum()
        variance_loss = torch.abs(input_var - output_var)
        
        # Compute orthogonality loss
        centered_output = output - output.mean(dim=0, keepdim=True)
        cov_matrix = torch.matmul(centered_output.t(), centered_output) / (output.size(0) - 1)
        diag_cov = torch.diag(cov_matrix)
        orthogonality_loss = torch.norm(cov_matrix - torch.diag(diag_cov), 'fro')
        
        return variance_loss + orthogonality_loss


class AdditiveLayer(nn.Module):
    """
    Additive Layer that processes inputs through separate networks.
    """
    def __init__(self, input_dim_list, output_dim_list):
        super(AdditiveLayer, self).__init__()
        assert sum(input_dim_list) == sum(output_dim_list), "Input and output dimensions must match"
        
        self.input_dim_list = input_dim_list
        self.output_dim_list = output_dim_list
        self.n_subnn = len(input_dim_list)
        
        # Create subnetwork indices for splitting
        self.subnn_idx_in = [0]
        for dim in input_dim_list:
            self.subnn_idx_in.append(self.subnn_idx_in[-1] + dim)
            
        self.subnn_idx_out = [0]
        for dim in output_dim_list:
            self.subnn_idx_out.append(self.subnn_idx_out[-1] + dim)
        
        # Create linear layers for each subnetwork
        self.layers = nn.ModuleList([
            nn.Linear(input_dim_list[i], output_dim_list[i], bias=True)
            for i in range(self.n_subnn)
        ])
        
    def forward(self, x):
        outputs = []
        for i in range(self.n_subnn):
            start_in, end_in = self.subnn_idx_in[i], self.subnn_idx_in[i+1]
            outputs.append(self.layers[i](x[:, start_in:end_in]))
        
        return torch.cat(outputs, dim=1)


class GFADNN(nn.Module):
    """
    Generalized Factor Additive Deep Neural Network Model.
    """
    def __init__(self, input_dim, output_dim, factor_dim, hidden_dim=32, use_soft_pca=False):
        super(GFADNN, self).__init__()
        
        # First factor layer
        if use_soft_pca:
            self.factor_layer1 = SoftPCALayer(input_dim, factor_dim)
        else:
            self.factor_layer1 = PCALayer(input_dim, factor_dim, freeze_after_init=True)
        
        # Intermediate layer
        self.intermediate = nn.Sequential(
            nn.Linear(factor_dim, hidden_dim),
            nn.LeakyReLU(0.1),
            nn.BatchNorm1d(hidden_dim)
        )
        
        # Second factor layer
        if use_soft_pca:
            self.factor_layer2 = SoftPCALayer(hidden_dim, factor_dim)
        else:
            self.factor_layer2 = PCALayer(hidden_dim, factor_dim, freeze_after_init=True)
        
        # Split factor_dim into 3 parts for additive layers
        split_size = factor_dim // 3
        self.additive_layer1 = AdditiveLayer(
            [split_size, split_size, factor_dim - 2*split_size], 
            [hidden_dim//3, hidden_dim//3, hidden_dim - 2*(hidden_dim//3)]
        )
        
        # Final additive layer
        self.additive_layer2 = AdditiveLayer(
            [hidden_dim//3, hidden_dim//3, hidden_dim - 2*(hidden_dim//3)],
            [output_dim, output_dim, output_dim]
        )
        
        # Output aggregation
        self.output_layer = nn.Linear(3*output_dim, output_dim)
        
        self.use_soft_pca = use_soft_pca
        
    def forward(self, x):
        # First factor layer
        x = self.factor_layer1(x)
        
        # Intermediate processing
        x = self.intermediate(x)
        
        # Second factor layer
        x = self.factor_layer2(x)
        
        # Additive layers
        x = self.additive_layer1(x)
        x = self.additive_layer2(x)
        
        # Combine outputs
        x = self.output_layer(x)
        
        return x
    
    def compute_reg_loss(self, x):
        if not self.use_soft_pca:
            return 0
        
        # Compute regularization losses for soft PCA layers
        reg_loss1 = self.factor_layer1.compute_regularization_loss(x)
        
        # Get intermediate representation for second regularization
        x1 = self.factor_layer1(x)
        x1 = self.intermediate(x1)
        
        reg_loss2 = self.factor_layer2.compute_regularization_loss(x1)
        
        return reg_loss1 + reg_loss2


class VanillaNN(nn.Module):
    """
    Standard Neural Network without factor or additive structures.
    """
    def __init__(self, input_dim, output_dim, hidden_dim=32):
        super(VanillaNN, self).__init__()
        
        self.layers = nn.Sequential(
            nn.Linear(input_dim, hidden_dim),
            nn.LeakyReLU(0.1),
            nn.BatchNorm1d(hidden_dim),
            nn.Linear(hidden_dim, hidden_dim),
            nn.LeakyReLU(0.1),
            nn.BatchNorm1d(hidden_dim),
            nn.Linear(hidden_dim, output_dim)
        )
        
    def forward(self, x):
        return self.layers(x)


def generate_synthetic_data(n_samples=500, p_dim=500, latent_dim=5, obs_type=1, target_type=1):
    """
    Generate synthetic data based on the paper's data generating process.
    
    Parameters:
    - n_samples: Number of samples
    - p_dim: Dimensionality of observations
    - latent_dim: Number of latent factors
    - obs_type: 1 for linear observations, 2 for non-linear observations
    - target_type: 1 for additive structure
    
    Returns:
    - X: Observations
    - y: Target values
    - Z: Latent factors (for reference)
    """
    # Generate latent factors Z ~ Uniform(-1, 1)
    Z = np.random.uniform(-1, 1, size=(n_samples, latent_dim))
    
    # Generate factor loadings B ~ Uniform(-sqrt(3), sqrt(3))
    B = np.random.uniform(-np.sqrt(3), np.sqrt(3), size=(latent_dim, p_dim))
    
    # Generate idiosyncratic components u ~ Uniform(-1, 1)
    u = np.random.uniform(-1, 1, size=(n_samples, p_dim))
    
    # Generate observations based on obs_type
    if obs_type == 1:
        # Linear: X = Z*B + u
        X = np.dot(Z, B) + u
    else:
        # Non-linear: X = g(Z)*B + u, where g=exp
        X = np.dot(np.exp(Z), B) + u
    
    # Define candidate functions for target generation
    def f1(x): return np.cos(np.pi * x)
    def f2(x): return np.sin(x)
    def f3(x): return (1 - np.abs(x))**2
    def f4(x): return 1 / (1 + np.exp(-x))
    def f5(x): return 2 * np.sqrt(np.abs(x)) - 1
    def f6(x): return x**2
    
    candidate_functions = [f1, f2, f3, f4, f5, f6]
    
    # Randomly select functions for each factor
    selected_functions = np.random.choice(len(candidate_functions), size=latent_dim, replace=True)
    
    # Generate target with additive structure
    y = np.zeros(n_samples)
    for i in range(latent_dim):
        func = candidate_functions[selected_functions[i]]
        y += func(Z[:, i])
    
    # Add noise
    noise = np.random.normal(0, 0.3, size=n_samples)
    y += noise
    
    return X, y.reshape(-1, 1), Z


def train_model(model, X_train, y_train, X_val, y_val, epochs=100, batch_size=32, lr=0.001):
    """Train a model and return training history."""
    criterion = nn.MSELoss()
    optimizer = optim.Adam(model.parameters(), lr=lr)
    
    X_train_tensor = torch.FloatTensor(X_train)
    y_train_tensor = torch.FloatTensor(y_train)
    X_val_tensor = torch.FloatTensor(X_val)
    y_val_tensor = torch.FloatTensor(y_val)
    
    train_dataset = torch.utils.data.TensorDataset(X_train_tensor, y_train_tensor)
    train_loader = torch.utils.data.DataLoader(train_dataset, batch_size=batch_size, shuffle=True)
    
    train_losses = []
    val_losses = []
    best_val_loss = float('inf')
    best_model_state = None
    
    for epoch in range(epochs):
        model.train()
        epoch_loss = 0
        
        for batch_X, batch_y in train_loader:
            optimizer.zero_grad()
            outputs = model(batch_X)
            
            loss = criterion(outputs, batch_y)
            
            # Add regularization if using Soft PCA
            if hasattr(model, 'use_soft_pca') and model.use_soft_pca:
                reg_loss = model.compute_reg_loss(batch_X)
                loss += 0.01 * reg_loss
                
            loss.backward()
            optimizer.step()
            
            epoch_loss += loss.item() * batch_X.size(0)
            
        epoch_loss /= len(train_loader.dataset)
        train_losses.append(epoch_loss)
        
        # Validate
        model.eval()
        with torch.no_grad():
            val_outputs = model(X_val_tensor)
            val_loss = criterion(val_outputs, y_val_tensor).item()
            val_losses.append(val_loss)
            
            if val_loss < best_val_loss:
                best_val_loss = val_loss
                best_model_state = model.state_dict().copy()
        
        if (epoch + 1) % 10 == 0:
            print(f"Epoch {epoch+1}/{epochs}, Train Loss: {epoch_loss:.4f}, Val Loss: {val_loss:.4f}")
            
    # Load best model
    if best_model_state is not None:
        model.load_state_dict(best_model_state)
        
    return model, train_losses, val_losses


