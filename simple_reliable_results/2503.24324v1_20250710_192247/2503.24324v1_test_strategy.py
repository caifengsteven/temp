def test_msp_hedging_strategy():
    """Test MSP hedging strategy with simulated data"""
    print("\n=== Testing MSP Hedging Strategy ===")
    
    # Simulation parameters
    n_periods = 60  # 5 years of monthly data
    msp = 3000  # Minimum Support Price
    budget_cap = 5000000  # Budget cap for MSP expenditure
    
    # Simulate crop production and prices
    np.random.seed(42)
    monthly_production = np.random.normal(10000, 1000, n_periods)  # Monthly production in tons
    
    # Simulate market prices with seasonal pattern and volatility
    base_price = 3200
    seasonal_amp = 300
    t = np.arange(n_periods)
    seasonal = seasonal_amp * np.sin(2 * np.pi * t / 12)
    
    # Add trend and volatility
    trend = -5 * t  # Declining trend
    volatility = np.random.normal(0, 200, n_periods)
    
    # Calculate market prices
    market_prices = base_price + seasonal + trend + volatility
    
    # Calculate MSP expenditure (when market price falls below MSP)
    price_diff = np.maximum(0, msp - market_prices)
    msp_expenditure = price_diff * monthly_production
    
    # Calculate total MSP expenditure
    total_msp_expenditure = np.sum(msp_expenditure)
    
    print(f"Total MSP Expenditure: {total_msp_expenditure:.2f}")
    print(f"Average Monthly MSP Expenditure: {np.mean(msp_expenditure):.2f}")
    
    # Count months with MSP intervention
    msp_intervention_months = np.sum(price_diff > 0)
    print(f"Months with MSP intervention: {msp_intervention_months} out of {n_periods}")
    
    # Calculate insurance premium using Black-Scholes
    # We'll use the volatility of market prices as input
    price_volatility = np.std(market_prices) / np.mean(market_prices)
    
    annual_premium = BlackScholesPutOption.calculate_premium(
        S=np.mean(market_prices),  # Average market price
        K=msp,                     # MSP as strike price
        T=1,                       # 1 year to maturity
        r=0.05,                    # 5% risk-free rate
        sigma=price_volatility
    )
    
    # Calculate annual production
    annual_production = np.sum(monthly_production) / (n_periods / 12)
    
    # Calculate annual insurance cost
    annual_insurance_cost = annual_premium * annual_production
    
    print(f"Annual Insurance Premium: {annual_premium:.2f} per unit")
    print(f"Annual Insurance Cost: {annual_insurance_cost:.2f}")
    
    # Compare insurance cost with excess MSP expenditure
    excess_expenditure = max(0, total_msp_expenditure - budget_cap)
    
    print(f"Excess MSP Expenditure above Budget Cap: {excess_expenditure:.2f}")
    print(f"Total Insurance Cost for 5 years: {annual_insurance_cost * 5:.2f}")
    
    # Calculate benefit of insurance strategy
    if excess_expenditure > annual_insurance_cost * 5:
        savings = excess_expenditure - annual_insurance_cost * 5
        print(f"Insurance strategy would save: {savings:.2f}")
    else:
        cost = annual_insurance_cost * 5 - excess_expenditure
        print(f"Insurance strategy would cost extra: {cost:.2f}")
    
    return {
        "msp_expenditure": total_msp_expenditure,
        "insurance_cost": annual_insurance_cost * 5,
        "excess_expenditure": excess_expenditure
    }

