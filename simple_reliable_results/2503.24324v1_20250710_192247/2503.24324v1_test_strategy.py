class EGARCHModel:
    """EGARCH model for conditional volatility estimation"""
    
    def __init__(self, omega=0.01, alpha=0.1, gamma=0.05, beta=0.85):
        self.omega = omega   # constant term (ν)
        self.alpha = alpha   # coefficient for magnitude effect (κ)
        self.gamma = gamma   # coefficient for asymmetric effect (δ)
        self.beta = beta     # coefficient for persistence (φ)
    
    def simulate(self, n_periods=240, seed=42):
        """Simulate EGARCH process returns and volatility"""
        np.random.seed(seed)
        
        # Initialize arrays
        returns = np.zeros(n_periods)
        log_var = np.zeros(n_periods)
        sigma = np.zeros(n_periods)
        
        # Initial volatility
        log_var[0] = np.log(0.0001)
        sigma[0] = np.sqrt(np.exp(log_var[0]))
        
        # Generate process
        for t in range(1, n_periods):
            # Random innovation
            z = np.random.normal(0, 1)
            
            # EGARCH equation for log variance
            log_var[t] = (self.omega + 
                         self.alpha * (abs(z) - np.sqrt(2/np.pi)) + 
                         self.gamma * z + 
                         self.beta * log_var[t-1])
            
            # Convert to standard deviation
            sigma[t] = np.sqrt(np.exp(log_var[t]))
            
            # Generate returns
            returns[t] = sigma[t] * np.random.normal(0, 1)
        
        return returns, sigma

class SARIMAXModel:
    """SARIMAX model for volatility prediction using climate variables"""
    
    def __init__(self, order=(1,0,1), seasonal_order=(1,0,1,12)):
        self.order = order
        self.seasonal_order = seasonal_order
    
    def fit_predict(self, volatility, exog_train, exog_forecast=None, steps=60):
        """Fit SARIMAX model and forecast volatility"""
        
        # Fit the model
        model = SARIMAX(
            volatility, 
            exog=exog_train,
            order=self.order,
            seasonal_order=self.seasonal_order
        )
        
        try:
            results = model.fit(disp=False)
            
            # In-sample predictions
            pred_in = results.predict(exog=exog_train)
            
            # Forecast
            if exog_forecast is not None:
                pred_out = results.forecast(steps=steps, exog=exog_forecast)
            else:
                pred_out = results.forecast(steps=steps)
                
            return pred_in, pred_out, results
            
        except Exception as e:
            print(f"SARIMAX fitting error: {e}")
            return None, None, None

class BlackScholesPutOption:
    """Black-Scholes model for calculating put option premium"""
    
    @staticmethod
    def calculate_premium(S, K, T, r, sigma):
        """
        Calculate premium for a put option
        
        Parameters:
        S: Current asset price (spot price)
        K: Strike price (MSP)
        T: Time to maturity in years
        r: Risk-free interest rate
        sigma: Volatility
        
        Returns:
        Premium price
        """
        d1 = (np.log(S/K) + (r + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
        d2 = d1 - sigma * np.sqrt(T)
        
        put_price = K * np.exp(-r * T) * norm.cdf(-d2) - S * norm.cdf(-d1)
        
        return put_price

class ClimateScenario:
    """Generate climate scenarios based on historical data with trends"""
    
    def __init__(self, scenario="SSP2-4.5", start_year=2025, end_year=2050):
        self.scenario = scenario
        self.start_year = start_year
        self.end_year = end_year
        self.n_periods = (end_year - start_year + 1) * 12  # Monthly data
        
    def generate_temperature(self, base_temp=25, seasonal_amp=5, trend=0.03, volatility=1.5, seed=42):
        """Generate temperature data with trend and seasonality"""
        np.random.seed(seed)
        
        # Time steps
        t = np.arange(self.n_periods)
        
        # Seasonal component with 12-month cycle
        seasonal = seasonal_amp * np.sin(2 * np.pi * t / 12)
        
        # Trend component - stronger trend for SSP5-8.5
        if self.scenario == "SSP5-8.5":
            trend_component = trend * 1.7 * t
        else:
            trend_component = trend * t
            
        # Random component
        noise = np.random.normal(0, volatility, self.n_periods)
        
        # Combine components
        temperature = base_temp + seasonal + trend_component + noise
        
        return temperature
    
    def generate_precipitation(self, base_precip=100, seasonal_amp=50, trend=0.02, volatility=30, seed=43):
        """Generate precipitation data with trend and seasonality"""
        np.random.seed(seed)
        
        # Time steps
        t = np.arange(self.n_periods)
        
        # Seasonal component with 12-month cycle - shifted compared to temperature
        seasonal = seasonal_amp * np.sin(2 * np.pi * t / 12 + np.pi)
        
        # Trend component - different pattern for SSP5-8.5
        if self.scenario == "SSP5-8.5":
            # More extreme pattern: wetter wet seasons, drier dry seasons
            trend_component = trend * 1.3 * t * (1 + 0.5 * np.sin(2 * np.pi * t / 12))
        else:
            trend_component = trend * t
            
        # Random component (precipitation is more volatile)
        noise = np.random.normal(0, volatility, self.n_periods)
        
        # Combine components and ensure non-negative values
        precipitation = np.maximum(0, base_precip + seasonal + trend_component + noise)
        
        return precipitation

def simulate_crop_price(n_periods=240, base_price=2000, msp=1800, price_vol=0.03, seed=44):
    """Simulate monthly crop prices with MSP floor"""
    np.random.seed(seed)
    
    prices = np.zeros(n_periods)
    prices[0] = base_price
    
    # Generate log-normal price process
    for t in range(1, n_periods):
        shock = np.random.normal(0, price_vol)
        prices[t] = prices[t-1] * np.exp(shock)
        
        # Apply MSP floor
        prices[t] = max(prices[t], msp)
    
    return prices

