class SimpleTransformer(nn.Module):
    def __init__(self, input_dim, d_model=64, nhead=2, num_layers=2, dim_feedforward=128, dropout=0.1):
        super(SimpleTransformer, self).__init__()
        self.embedding = nn.Linear(input_dim, d_model)
        encoder_layer = nn.TransformerEncoderLayer(d_model=d_model, nhead=nhead, 
                                                 dim_feedforward=dim_feedforward, dropout=dropout)
        self.transformer_encoder = nn.TransformerEncoder(encoder_layer, num_layers=num_layers)
        self.pos_encoder = PositionalEncoding(d_model, dropout)
        self.classifier = nn.Linear(d_model, 2)  # Binary classification
        
    def forward(self, x):
        # x shape: [batch_size, seq_len, input_dim]
        x = self.embedding(x)  # [batch_size, seq_len, d_model]
        x = x.permute(1, 0, 2)  # [seq_len, batch_size, d_model]
        x = self.pos_encoder(x)
        x = self.transformer_encoder(x)
        # Use the last time step for classification
        x = x[-1]  # [batch_size, d_model]
        return self.classifier(x)

class ConvTransformer(nn.Module):
    def __init__(self, input_dim, d_model=64, nhead=2, num_layers=2, dim_feedforward=128, dropout=0.1):
        super(ConvTransformer, self).__init__()
        self.input_projection = nn.Linear(input_dim, d_model)
        self.conv1d = nn.Conv1d(d_model, d_model, kernel_size=3, padding=1)
        self.activation = nn.SiLU()  # SILU activation as mentioned in the paper
        self.pos_encoder = PositionalEncoding(d_model, dropout)
        
        encoder_layer = nn.TransformerEncoderLayer(d_model=d_model, nhead=nhead, 
                                                 dim_feedforward=dim_feedforward, dropout=dropout)
        self.transformer_encoder = nn.TransformerEncoder(encoder_layer, num_layers=num_layers)
        self.classifier = nn.Linear(d_model, 2)  # Binary classification
        
    def forward(self, x):
        # x shape: [batch_size, seq_len, input_dim]
        x = self.input_projection(x)  # [batch_size, seq_len, d_model]
        
        # Apply 1D convolution (need to reshape for Conv1D)
        x_orig = x
        x = x.permute(0, 2, 1)  # [batch_size, d_model, seq_len]
        x = self.conv1d(x)
        x = self.activation(x)
        x = x.permute(0, 2, 1)  # [batch_size, seq_len, d_model]
        
        # Residual connection
        x = x + x_orig
        
        # Transformer encoder expects [seq_len, batch_size, d_model]
        x = x.permute(1, 0, 2)
        x = self.pos_encoder(x)
        x = self.transformer_encoder(x)
        
        # Use the last time step for classification
        x = x[-1]  # [batch_size, d_model]
        return self.classifier(x)

class PositionalEncoding(nn.Module):
    def __init__(self, d_model, dropout=0.1, max_len=5000):
        super(PositionalEncoding, self).__init__()
        self.dropout = nn.Dropout(p=dropout)

        position = torch.arange(max_len).unsqueeze(1)
        div_term = torch.exp(torch.arange(0, d_model, 2) * (-np.log(10000.0) / d_model))
        pe = torch.zeros(max_len, 1, d_model)
        pe[:, 0, 0::2] = torch.sin(position * div_term)
        pe[:, 0, 1::2] = torch.cos(position * div_term)
        self.register_buffer('pe', pe)
        
    def forward(self, x):
        x = x + self.pe[:x.size(0)]
        return self.dropout(x)

# Function to generate synthetic cryptocurrency price data
def generate_synthetic_data(days=180, freq='5min'):
    # Start date (February 1 as mentioned in the paper)
    start_date = datetime(2024, 2, 1)
    end_date = start_date + timedelta(days=days)
    
    # Generate dates
    dates = pd.date_range(start=start_date, end=end_date, freq=freq)
    
    # Base price with random walk
    np.random.seed(42)
    returns = np.random.normal(0, 0.001, len(dates))
    price = 100 * np.exp(np.cumsum(returns))
    
    # Add some trends and volatility clusters
    for i in range(5, len(dates), 30):
        if np.random.random() > 0.5:
            # Create uptrend
            factor = np.linspace(1, 1.1, 20)
            if i + 20 < len(price):
                price[i:i+20] *= factor
        else:
            # Create downtrend
            factor = np.linspace(1, 0.9, 15)
            if i + 15 < len(price):
                price[i:i+15] *= factor
    
    # Create OHLC data
    data = pd.DataFrame(index=dates)
    data['Open'] = price
    data['High'] = price * (1 + np.random.uniform(0, 0.01, len(dates)))
    data['Low'] = price * (1 - np.random.uniform(0, 0.01, len(dates)))
    data['Close'] = price * (1 + np.random.normal(0, 0.003, len(dates)))
    
    # Ensure High is always highest and Low is always lowest
    data['High'] = np.maximum(data[['Open', 'High', 'Close']].max(axis=1), data['High'])
    data['Low'] = np.minimum(data[['Open', 'Low', 'Close']].min(axis=1), data['Low'])
    
    return data

# Feature engineering based on the paper
def engineer_features(data):
    # Simple Moving Average (SMA)
    data['SMA_5'] = data['Close'].rolling(window=5).mean()
    data['SMA_20'] = data['Close'].rolling(window=20).mean()
    
    # Exponential Moving Average (EMA)
    data['EMA_5'] = data['Close'].ewm(span=5, adjust=False).mean()
    data['EMA_20'] = data['Close'].ewm(span=20, adjust=False).mean()
    
    # Relative Strength Index (RSI)
    delta = data['Close'].diff()
    gain = (delta.where(delta > 0, 0)).rolling(window=14).mean()
    loss = (-delta.where(delta < 0, 0)).rolling(window=14).mean()
    rs = gain / loss
    data['RSI'] = 100 - (100 / (1 + rs))
    
    # Bollinger Bands
    data['BB_Middle'] = data['Close'].rolling(window=20).mean()
    std = data['Close'].rolling(window=20).std()
    data['BB_Upper'] = data['BB_Middle'] + 2 * std
    data['BB_Lower'] = data['BB_Middle'] - 2 * std
    
    # Volatility (as described in the paper)
    log_returns = np.log(data['Close'] / data['Close'].shift(1))
    data['Volatility'] = log_returns.rolling(window=5).std() * np.sqrt(5)
    
    # Fill NaN values that occur at the start due to rolling windows
    data = data.fillna(method='bfill')
    
    return data

# Create target labels based on the paper's methodology
def create_target_labels(data, k=2, threshold=0.005):
    # Create a copy to avoid modifying the original
    df = data.copy()
    
    # Initialize labels column
    df['Label'] = 0
    
    # Higher Highs detection
    for i in range(k + 1, len(df)):
        # Check for k consecutive higher peaks
        if (df['High'].iloc[i] > df['High'].iloc[i-1] and 
            df['High'].iloc[i-1] > df['High'].iloc[i-2]):
            
            # Apply volatility filter (price change > 0.5%)
            price_change = (df['Close'].iloc[i] - df['Open'].iloc[i-k]) / df['Open'].iloc[i-k]
            if price_change > threshold:
                df.loc[df.index[i-k:i+1], 'Label'] = 1
    
    return df

# Prepare data for model input
def prepare_data_for_model(data, sequence_length=20):
    features = data.drop(['Label'], axis=1).values
    labels = data['Label'].values
    
    X, y = [], []
    for i in range(len(features) - sequence_length):
        X.append(features[i:i+sequence_length])
        y.append(labels[i+sequence_length])  # Predict the label at the end of the sequence
    
    return np.array(X), np.array(y)

# Train and evaluate model
def train_and_evaluate(model, X_train, y_train, X_test, y_test, epochs=50, batch_size=64, learning_rate=0.001):
    # Convert data to PyTorch tensors
    X_train_tensor = torch.FloatTensor(X_train)
    y_train_tensor = torch.LongTensor(y_train)
    X_test_tensor = torch.FloatTensor(X_test)
    y_test_tensor = torch.LongTensor(y_test)
    
    # Create DataLoader
    train_dataset = TensorDataset(X_train_tensor, y_train_tensor)
    train_loader = DataLoader(train_dataset, batch_size=batch_size, shuffle=True)
    
    # Loss function and optimizer
    criterion = nn.CrossEntropyLoss(weight=torch.FloatTensor([1.0, 9.0]))  # Class weighting due to imbalance
    optimizer = optim.Adam(model.parameters(), lr=learning_rate)
    
    # Training loop
    for epoch in range(epochs):
        model.train()
        running_loss = 0.0
        
        for inputs, labels in train_loader:
            optimizer.zero_grad()
            outputs = model(inputs)
            loss = criterion(outputs, labels)
            loss.backward()
            optimizer.step()
            
            running_loss += loss.item()
        
        if (epoch + 1) % 10 == 0:
            print(f'Epoch {epoch+1}, Loss: {running_loss/len(train_loader):.4f}')
    
    # Evaluation
    model.eval()
    with torch.no_grad():
        y_pred = model(X_test_tensor)
        _, predicted = torch.max(y_pred, 1)
        
        accuracy = accuracy_score(y_test_tensor, predicted)
        f1 = f1_score(y_test_tensor, predicted, average=None)
        report = classification_report(y_test_tensor, predicted, target_names=['No Uptrend', 'Uptrend'])
        
    return accuracy, f1, report, predicted

