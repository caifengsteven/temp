class AlphaSharpeMetrics:
    """Implementation of AlphaSharpe metrics from the paper."""
    
    @staticmethod
    def sharpe_ratio(returns, risk_free_rate=0):
        """Traditional Sharpe Ratio."""
        excess_returns = returns - risk_free_rate
        return np.mean(excess_returns) / np.std(excess_returns)
    
    @staticmethod
    def probabilistic_sharpe_ratio(returns, risk_free_rate=0, benchmark_sharpe=0):
        """Probabilistic Sharpe Ratio (PSR)."""
        sr = AlphaSharpeMetrics.sharpe_ratio(returns, risk_free_rate)
        n = len(returns)
        skew = stats.skew(returns)
        kurt = stats.kurtosis(returns)
        
        # PSR formula from Bailey and López de Prado
        psr = stats.norm.cdf((sr - benchmark_sharpe) * np.sqrt(n-1) / 
                           np.sqrt(1 + (0.5 * sr**2 * kurt + sr * skew)))
        return psr
    
    @staticmethod
    def alpha_sharpe1(returns, risk_free_rate=0, epsilon=1e-6):
        """AlphaSharpe 1 (αS1) metric from the paper."""
        log_returns = np.log(1 + returns)
        log_excess_returns = log_returns - risk_free_rate
        
        var_log_returns = np.var(log_returns)
        std_log_returns = np.std(log_returns)
        
        return np.exp(np.mean(log_excess_returns)) / np.sqrt((var_log_returns + epsilon) * (std_log_returns + epsilon))
    
    @staticmethod
    def alpha_sharpe2(returns, risk_free_rate=0, epsilon=1e-6):
        """AlphaSharpe 2 (αS2) metric from the paper."""
        log_returns = np.log(1 + returns)
        log_excess_returns = log_returns - risk_free_rate
        
        # Base components
        var_log_returns = np.var(log_returns)
        std_log_returns = np.std(log_returns)
        
        # Downside risk component
        negative_returns_idx = returns < 0
        neg_returns = returns[negative_returns_idx]
        neg_returns_count = np.sum(negative_returns_idx)
        
        if neg_returns_count > 0:
            std_neg_returns = np.std(neg_returns) if len(neg_returns) > 1 else 0
            downside_risk = std_neg_returns + np.sqrt(neg_returns_count) * std_log_returns / (neg_returns_count + epsilon)
        else:
            downside_risk = 0
        
        # Forecasted volatility
        n = len(returns)
        forecast_window = max(int(n/4), 1)
        forecast_vol = np.sqrt(np.mean((returns[-forecast_window:] - np.mean(returns))**2))
        
        denominator = np.sqrt(var_log_returns + epsilon) + downside_risk + forecast_vol
        
        return np.exp(np.mean(log_excess_returns)) / denominator
    
    @staticmethod
    def alpha_sharpe3(returns, risk_free_rate=0, epsilon=1e-6):
        """AlphaSharpe 3 (αS3) metric from the paper."""
        # Calculate base αS2
        as2 = AlphaSharpeMetrics.alpha_sharpe2(returns, risk_free_rate, epsilon)
        
        # Higher-order moment adjustments
        skewness = stats.skew(returns)
        kurtosis = stats.kurtosis(returns)
        
        # Maximum drawdown calculation
        cumulative_returns = np.cumprod(1 + returns)
        running_max = np.maximum.accumulate(cumulative_returns)
        drawdowns = (cumulative_returns / running_max) - 1
        max_drawdown = abs(np.min(drawdowns))
        
        # Apply the adjustment formula
        higher_moment_adjustment = (1 - kurtosis/12) * ((1 + skewness/6) / (1 + max_drawdown))
        
        return as2 * higher_moment_adjustment
    
    @staticmethod
    def alpha_sharpe4(returns, risk_free_rate=0, epsilon=1e-6):
        """AlphaSharpe 4 (αS4) metric from the paper."""
        # Calculate base αS3
        as3 = AlphaSharpeMetrics.alpha_sharpe3(returns, risk_free_rate, epsilon)
        
        # Regime factor adjustment
        excess_returns = returns - risk_free_rate
        positive_regime = 1 if np.mean(excess_returns) > 0 else 0
        
        regime_adjustment = (1 + 0.1 * positive_regime)
        
        return as3 * regime_adjustment


