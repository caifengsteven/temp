class RealizedVolatilityForecaster:
    def __init__(self, threshold_percentile=25, subsequence_length=22):
        """
        Initialize the forecaster with threshold percentile and subsequence length.
        
        Args:
            threshold_percentile (int): Percentile threshold for DTW distance (25, 50, or 75)
            subsequence_length (int): Length of subsequences for similarity comparison
        """
        self.threshold_percentile = threshold_percentile
        self.subsequence_length = subsequence_length
        self.model = None
        self.selected_subsequences = []
    
    def _create_subsequences(self, source_data, subsequence_length):
        """
        Create non-overlapping subsequences from source data.
        
        Args:
            source_data (pd.DataFrame): Source data containing RV and predictors
            subsequence_length (int): Length of subsequences
            
        Returns:
            list: List of subsequences
        """
        subsequences = []
        excess = len(source_data) % subsequence_length
        
        for i in range((len(source_data) - excess) // subsequence_length):
            start_idx = excess + i * subsequence_length
            end_idx = excess + (i + 1) * subsequence_length
            subsequences.append(source_data.iloc[start_idx:end_idx])
        
        return subsequences
    
    def _compute_dtw_distances(self, target_data, source_subsequences):
        """
        Compute DTW distances between target data and source subsequences.
        
        Args:
            target_data (pd.DataFrame): Target data (recent observations)
            source_subsequences (list): List of source subsequences
            
        Returns:
            list: List of DTW distances
        """
        distances = []
        target_features = target_data[['RV_d', 'RV_w', 'RV_m']].values
        
        for subseq in source_subsequences:
            source_features = subseq[['RV_d', 'RV_w', 'RV_m']].values
            
            # Use DTW to calculate distance between target and source
            distance = dtw.distance(target_features, source_features)
            distances.append(distance)
        
        return distances
    
    def _select_subsequences(self, distances, source_subsequences):
        """
        Select source subsequences based on DTW distances and threshold.
        
        Args:
            distances (list): List of DTW distances
            source_subsequences (list): List of source subsequences
            
        Returns:
            list: Selected subsequences
        """
        threshold = np.percentile(distances, self.threshold_percentile)
        selected_indices = [i for i, dist in enumerate(distances) if dist <= threshold]
        selected_subsequences = [source_subsequences[i] for i in selected_indices]
        
        return selected_subsequences
    
    def fit(self, target_data, source_data_list, model_type='xgboost'):
        """
        Fit the model using transfer learning approach.
        
        Args:
            target_data (pd.DataFrame): Target data (new issue/spin-off)
            source_data_list (list): List of source data DataFrames
            model_type (str): Type of model to use ('xgboost', 'fnn', or 'har')
            
        Returns:
            self: Fitted model
        """
        # Use the last subsequence_length observations from target_data
        recent_target = target_data.iloc[-self.subsequence_length:]
        
        # Create subsequences from all source data
        all_subsequences = []
        for source_data in source_data_list:
            subsequences = self._create_subsequences(source_data, self.subsequence_length)
            all_subsequences.extend(subsequences)
        
        # Compute DTW distances and select subsequences
        distances = self._compute_dtw_distances(recent_target, all_subsequences)
        self.selected_subsequences = self._select_subsequences(distances, all_subsequences)
        
        # Combine target data with selected source subsequences
        combined_data = pd.concat([target_data] + self.selected_subsequences, ignore_index=True)
        
        # Prepare features and target for model training
        X = combined_data[['RV_d', 'RV_w', 'RV_m']]
        y = combined_data['RV_next']
        
        # Train model based on model_type
        if model_type == 'xgboost':
            self.model = XGBRegressor(n_estimators=40, max_depth=5, learning_rate=0.1, 
                                       subsample=0.75, reg_lambda=1.0)
        elif model_type == 'fnn':
            self.model = MLPRegressor(hidden_layer_sizes=(8, 4, 2), activation='relu',
                                      learning_rate_init=0.001, max_iter=500, early_stopping=True)
        elif model_type == 'har':
            # Simple linear regression for HAR model
            from sklearn.linear_model import LinearRegression
            self.model = LinearRegression()
        
        self.model.fit(X, y)
        return self
    
    def predict(self, X):
        """
        Make predictions using the fitted model.
        
        Args:
            X (pd.DataFrame): Features for prediction
            
        Returns:
            np.array: Predicted values
        """
        if self.model is None:
            raise ValueError("Model not fitted. Call fit() first.")
        
        preds = self.model.predict(X)
        # Ensure predictions are non-negative
        preds = np.maximum(preds, 0)
        return preds


def generate_synthetic_data(n_days=1000, volatility_level=0.2, memory_factor=0.8, seed=42):
    """
    Generate synthetic realized volatility data.
    
    Args:
        n_days (int): Number of days
        volatility_level (float): Base volatility level
        memory_factor (float): Autocorrelation factor
        seed (int): Random seed
        
    Returns:
        pd.DataFrame: Synthetic data
    """
    np.random.seed(seed)
    
    # Generate daily RV with long memory properties
    rv_d = np.zeros(n_days)
    rv_d[0] = volatility_level + np.random.normal(0, 0.05)
    
    for i in range(1, n_days):
        rv_d[i] = volatility_level + memory_factor * (rv_d[i-1] - volatility_level) + np.random.normal(0, 0.05)
    
    # Ensure non-negative values
    rv_d = np.maximum(rv_d, 0.01)
    
    # Calculate weekly and monthly components
    rv_w = np.zeros(n_days)
    rv_m = np.zeros(n_days)
    
    for i in range(5, n_days):
        rv_w[i] = np.mean(rv_d[i-5:i])
    
    for i in range(22, n_days):
        rv_m[i] = np.mean(rv_d[i-22:i])
    
    # Fill in first few days
    rv_w[:5] = rv_d[:5]
    rv_m[:22] = np.repeat(np.mean(rv_d[:22]), 22)
    
    # Create next-day realized volatility (target)
    rv_next = np.zeros(n_days)
    rv_next[:-1] = rv_d[1:]
    rv_next[-1] = rv_d[-1]  # Last day uses same value
    
    # Create DataFrame
    df = pd.DataFrame({
        'RV_d': rv_d,
        'RV_w': rv_w,
        'RV_m': rv_m,
        'RV_next': rv_next
    })
    
    return df


