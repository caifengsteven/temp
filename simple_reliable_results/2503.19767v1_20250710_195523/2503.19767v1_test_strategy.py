        features = {}
        
        # Get realized volatility
        rv = data['realized_volatility'][stock_name]
        
        # Add HAR components (daily, weekly, monthly)
        features['rv_daily'] = rv[t-1]
        features['rv_weekly'] = np.mean(rv[max(0, t-5):t])
        features['rv_monthly'] = np.mean(rv[max(0, t-22):t])
        
        # Add attention features if specified
        if self.use_attention:
            # Stock market attention
            for source, values in data['attention'][stock_name]['stock_market'].items():
                features[f'att_stock_{source}'] = values[t-1]
            
