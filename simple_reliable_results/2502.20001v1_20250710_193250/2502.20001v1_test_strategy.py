    il_trad = [trad_amm.calculate_impermanent_loss(m) for m in price_multipliers]
    il_bmm = [bmm.calculate_impermanent_loss(m) for m in price_multipliers]
    
    y_trad = [trad_amm.y * m**(-1/(trad_amm.n+1)) for m in price_multipliers]
    y_bmm = [bmm.y * m**(-1/(bmm.n+1)) for m in price_multipliers]
    
    retention_ratios = [bmm.calculate_retention_ratio(m) for m in price_multipliers]
    
    # Calculate slippage ratio
    slippage_ratio = bmm.calculate_slippage_ratio()
    
