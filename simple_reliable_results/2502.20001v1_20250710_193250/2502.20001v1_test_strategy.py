@dataclass
class MarketMakerParams:
    n: int  # Power-law exponent
    initial_x: float  # Initial volatile token reserve
    initial_y: float  # Initial stablecoin reserve
    fee_rate: float  # Base fee rate (gamma)
    max_rebate_ratio: float  # Maximum rebate ratio (rho_max)


class BetterMarketMaker:
    def __init__(self, params: MarketMakerParams):
        self.n = params.n
        self.x = params.initial_x
        self.y = params.initial_y
        self.k = self.x**self.n * self.y  # Invariant constant
        self.fee_rate = params.fee_rate
        self.max_rebate_ratio = params.max_rebate_ratio
        self.initial_price = self.calculate_price()
        self.initial_value = self.calculate_pool_value(self.initial_price)
        
    def calculate_price(self):
        """Calculate the current price of X in terms of Y"""
        return (self.n * self.y) / self.x
    
    def calculate_pool_value(self, price):
        """Calculate the total pool value in terms of Y"""
        return self.x * price + self.y
    
    def calculate_reserves_after_price_change(self, new_price):
        """Calculate new reserves after a price change"""
        # From the paper: X^n * Y = K and P = n*Y/X
        # Solving for X: X = (n*Y/P)^(1/(n+1))
        # And Y = K / X^n
        x_new = (self.n * self.k / new_price)**(1/(self.n+1))
        y_new = self.k / (x_new**self.n)
        return x_new, y_new
    
    def calculate_impermanent_loss(self, price_ratio):
        """Calculate impermanent loss for a given price ratio"""
        if self.n == 1:  # Traditional AMM
            return 1 - (2 * np.sqrt(price_ratio)) / (price_ratio + 1)
        else:  # BMM
            # For n > 1, using the paper's approximation
            g_n = (self.n + 1)**2 / (4 * self.n)
            il_trad = 1 - (2 * np.sqrt(price_ratio)) / (price_ratio + 1)
            return il_trad / g_n
    
    def calculate_liquidity_retention(self, price_ratio):
        """Calculate liquidity retention ratio for a given price ratio"""
        return self.y * price_ratio**(-1/(self.n+1))
    
    def calculate_retention_ratio(self, price_ratio):
        """Calculate the retention ratio compared to traditional AMM"""
        return price_ratio**(1 - 1/(self.n+1))
    
    def calculate_slippage_ratio(self):
        """Calculate slippage ratio compared to traditional AMM"""
        return (self.n + 1) / 2


class DynamicRebateSystem:
    def __init__(self, base_fee_rate, max_rebate_ratio, target_volume):
        self.base_fee_rate = base_fee_rate
        self.max_rebate_ratio = max_rebate_ratio
        self.target_volume = target_volume
        
    def calculate_rebate_ratio(self, volume):
        """Calculate dynamic rebate ratio based on current volume"""
        rho = 0.4 + 0.1 * (1 - volume / self.target_volume)
        return np.clip(rho, 0.3, 0.4)
    
    def calculate_fee_distribution(self, volume):
        """Calculate fee distribution for a given trading volume"""
        total_fee = self.base_fee_rate * volume
        rebate_ratio = self.calculate_rebate_ratio(volume)
        
        lp_fee = 0.3 * total_fee
        rebate = rebate_ratio * total_fee
        protocol = (0.7 - rebate_ratio) * total_fee
        
        return {
            'total_fee': total_fee,
            'lp_fee': lp_fee,
            'rebate': rebate,
            'protocol': protocol,
            'rebate_ratio': rebate_ratio
        }


def simulate_dynamic_rebate_system(days=100, initial_volume=1e6, target_volume=1e6, 
                                  sensitivity=0.05, noise_std=0.01):
    """Simulate trading volumes with static vs dynamic rebate systems"""
    static_rebate = 0.35
    
    vol_static = np.zeros(days)
    vol_dynamic = np.zeros(days)
    rebate_ratios = np.zeros(days)
    
    vol_static[0] = initial_volume
    vol_dynamic[0] = initial_volume
    rebate_ratios[0] = 0.35
    
    for t in range(1, days):
        noise_static = np.random.normal(0, noise_std)
        noise_dynamic = np.random.normal(0, noise_std)
        
        vol_static[t] = vol_static[t-1] * (1 + noise_static)
        
        current_rebate = 0.4 + 0.1 * (1 - vol_dynamic[t-1] / target_volume)
        current_rebate = np.clip(current_rebate, 0.3, 0.4)
        rebate_ratios[t] = current_rebate
        
        feedback = sensitivity * (current_rebate - static_rebate)
        vol_dynamic[t] = vol_dynamic[t-1] * (1 + feedback + noise_dynamic)
    
    return vol_static, vol_dynamic, rebate_ratios


