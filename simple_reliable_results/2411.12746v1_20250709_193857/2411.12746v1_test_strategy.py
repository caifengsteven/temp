class FinancialEnvironment:
    def __init__(self, data, initial_balance=10000, transaction_cost=0.003):
        """
        Financial environment for portfolio management
        
        Args:
            data: DataFrame with asset prices
            initial_balance: starting capital
            transaction_cost: cost per transaction (0.3%)
        """
        self.data = data
        self.initial_balance = initial_balance
        self.transaction_cost = transaction_cost
        self.current_step = 0
        self.portfolio = np.zeros(len(data.columns))
        self.cash_balance = initial_balance
        self.portfolio_value_history = []
        
    def reset(self):
        """Reset the environment to initial state"""
        self.current_step = 0
        self.portfolio = np.zeros(len(self.data.columns))
        self.cash_balance = self.initial_balance
        self.portfolio_value_history = []
        return self._get_state()
    
    def _get_state(self):
        """
        Get current state representation:
        - Price information (normalized)
        - Current portfolio weights
        - Cash balance (normalized)
        """
        prices = self.data.iloc[self.current_step].values
        normalized_prices = prices / prices.mean()  # Simple normalization
        portfolio_value = np.sum(self.portfolio * prices)
        total_value = portfolio_value + self.cash_balance
        
        if total_value > 0:
            portfolio_weights = self.portfolio * prices / total_value
            cash_weight = self.cash_balance / total_value
        else:
            portfolio_weights = np.zeros(len(self.portfolio))
            cash_weight = 1.0
            
        state = np.concatenate([
            normalized_prices,
            portfolio_weights,
            [cash_weight]
        ])
        
        return state
    
    def step(self, action):
        """
        Take an action in the environment
        
        Args:
            action: numpy array representing target portfolio weights
        
        Returns:
            next_state, reward, done, info
        """
        if self.current_step >= len(self.data) - 1:
            return self._get_state(), 0, True, {}
        
        # Current prices and portfolio value
        current_prices = self.data.iloc[self.current_step].values
        portfolio_value = np.sum(self.portfolio * current_prices)
        total_value = portfolio_value + self.cash_balance
        self.portfolio_value_history.append(total_value)
        
        # Target portfolio based on action
        target_portfolio_value = action * total_value
        target_units = np.zeros_like(self.portfolio)
        for i in range(len(target_units)):
            if current_prices[i] > 0:
                target_units[i] = target_portfolio_value[i] / current_prices[i]
            
        # Calculate transaction costs
        units_diff = np.abs(target_units - self.portfolio)
        transaction_cost = np.sum(units_diff * current_prices) * self.transaction_cost
        
        # Execute trade
        self.portfolio = target_units
        self.cash_balance = total_value - np.sum(target_units * current_prices) - transaction_cost
        
        # Move to next time step
        self.current_step += 1
        
        # Get new prices
        next_prices = self.data.iloc[self.current_step].values
        new_portfolio_value = np.sum(self.portfolio * next_prices)
        new_total_value = new_portfolio_value + self.cash_balance
        
        # Calculate reward (return)
        reward = (new_total_value / total_value) - 1
        
        # Check if done
        done = self.current_step >= len(self.data) - 1
        
        # Return new state, reward, done flag, and info dict
        return self._get_state(), reward, done, {'portfolio_value': new_total_value}

class DQNAgent:
    def __init__(self, state_size, action_size, n_assets):
        self.state_size = state_size
        self.action_size = action_size
        self.n_assets = n_assets
        self.memory = deque(maxlen=2000)
        self.gamma = 0.95    # discount rate
        self.epsilon = 1.0   # exploration rate
        self.epsilon_min = 0.01
        self.epsilon_decay = 0.995
        self.learning_rate = 0.001
        self.model = self._build_model()
        
    def _build_model(self):
        """Neural network model for DQN"""
        model = Sequential()
        model.add(Dense(24, input_dim=self.state_size, activation='relu'))
        model.add(Dense(24, activation='relu'))
        model.add(Dense(self.action_size, activation='softmax'))  # softmax for portfolio weights
        model.compile(loss='mse', optimizer=Adam(learning_rate=self.learning_rate))
        return model
    
    def remember(self, state, action, reward, next_state, done):
        """Store experience in memory"""
        self.memory.append((state, action, reward, next_state, done))
    
    def act(self, state):
        """Choose an action based on state"""
        if np.random.rand() <= self.epsilon:
            # Random allocation
            weights = np.random.random(self.n_assets)
            # Add cash option
            weights = np.append(weights, np.random.random())
            # Normalize to sum to 1
            weights = weights / weights.sum()
            return weights[:-1]  # Remove cash weight (will be calculated as remainder)
        
        act_values = self.model.predict(np.array([state]), verbose=0)
        weights = act_values[0]
        return weights
    
    def replay(self, batch_size):
        """Train model with experiences from memory"""
        if len(self.memory) < batch_size:
            return
        
        minibatch = random.sample(self.memory, batch_size)
        for state, action, reward, next_state, done in minibatch:
            target = reward
            if not done:
                target = reward + self.gamma * np.max(self.model.predict(np.array([next_state]), verbose=0)[0])
            
            target_f = self.model.predict(np.array([state]), verbose=0)
            target_f[0] = action * target
            
            self.model.fit(np.array([state]), target_f, epochs=1, verbose=0)
        
        if self.epsilon > self.epsilon_min:
            self.epsilon *= self.epsilon_decay
            

def create_simulated_data(n_assets=3, n_days=252, seed=42):
    """
    Create simulated price data for testing
    
    Args:
        n_assets: Number of assets
        n_days: Number of trading days
        seed: Random seed
        
    Returns:
        DataFrame with simulated prices
    """
    np.random.seed(seed)
    
    # Initial prices
    initial_prices = np.random.uniform(50, 200, n_assets)
    
    # Generate price series with correlation
    annual_returns = np.random.uniform(0.0, 0.2, n_assets)
    annual_volatility = np.random.uniform(0.1, 0.3, n_assets)
    
    # Create correlated returns
    correlation = np.random.uniform(0.1, 0.7, (n_assets, n_assets))
    correlation = (correlation + correlation.T) / 2  # Make it symmetric
    np.fill_diagonal(correlation, 1.0)
    
    # Ensure correlation matrix is positive semi-definite
    eigenvalues, eigenvectors = np.linalg.eigh(correlation)
    eigenvalues = np.maximum(eigenvalues, 0)
    correlation = eigenvectors @ np.diag(eigenvalues) @ eigenvectors.T
    
    # Calculate covariance matrix
    covariance = np.outer(annual_volatility, annual_volatility) * correlation
    
    # Generate daily returns
    daily_returns = np.random.multivariate_normal(
        mean=annual_returns/252, 
        cov=covariance/252, 
        size=n_days
    )
    
    # Generate price paths
    prices = np.zeros((n_days, n_assets))
    prices[0] = initial_prices
    for i in range(1, n_days):
        prices[i] = prices[i-1] * (1 + daily_returns[i])
    
    # Convert to DataFrame
    asset_names = [f'Asset_{i}' for i in range(n_assets)]
    df = pd.DataFrame(prices, columns=asset_names)
    
    return df

def test_strategy(data, agent=None, episodes=5):
    """
    Test the trading strategy with RL agent or a benchmark
    
    Args:
        data: Price data
        agent: RL agent (None for buy and hold benchmark)
        episodes: Number of episodes to train
        
    Returns:
        Portfolio value history
    """
    n_assets = len(data.columns)
    state_size = 2 * n_assets + 1  # prices, portfolio weights, cash weight
    action_size = n_assets
    
    if agent is None:
        agent = DQNAgent(state_size, action_size, n_assets)
    
    env = FinancialEnvironment(data)
    
    portfolio_values = []
    
    for e in range(episodes):
        state = env.reset()
        total_reward = 0
        
        while True:
            action = agent.act(state)
            next_state, reward, done, info = env.step(action)
            
            # Store experience
            agent.remember(state, action, reward, next_state, done)
            
            state = next_state
            total_reward += reward
            
            if done:
                print(f"Episode: {e+1}/{episodes}, Final Portfolio Value: ${info['portfolio_value']:.2f}, Return: {total_reward:.4f}")
                portfolio_values.append(env.portfolio_value_history)
                break
                
        # Train the model with experiences
        if len(agent.memory) > 32:
            agent.replay(32)
    
    return portfolio_values

def buy_and_hold_benchmark(data, initial_balance=10000):
    """
    Simple buy and hold strategy as benchmark
    
    Args:
        data: Price data
        initial_balance: Starting capital
        
    Returns:
        Portfolio value history
    """
    n_assets = len(data.columns)
    
    # Equally allocate funds to all assets
    initial_prices = data.iloc[0].values
    units = (initial_balance / n_assets) / initial_prices
    
    # Calculate portfolio value over time
    portfolio_values = []
    for i in range(len(data)):
        prices = data.iloc[i].values
        portfolio_value = np.sum(units * prices)
        portfolio_values.append(portfolio_value)
    
    return portfolio_values

def calculate_metrics(portfolio_values):
    """
    Calculate performance metrics
    
    Args:
        portfolio_values: List of portfolio values
        
    Returns:
        Dictionary with metrics
    """
    # Convert to numpy array
    values = np.array(portfolio_values)
    
    # Calculate returns
    returns = np.diff(values) / values[:-1]
    
    # Metrics
    total_return = (values[-1] / values[0]) - 1
    annual_return = (1 + total_return) ** (252 / len(values)) - 1
    sharpe_ratio = np.mean(returns) / np.std(returns) * np.sqrt(252)
    max_drawdown = np.max(np.maximum.accumulate(values) - values) / np.max(values)
    
    return {
        'total_return': total_return,
        'annual_return': annual_return,
        'sharpe_ratio': sharpe_ratio,
        'max_drawdown': max_drawdown
    }

