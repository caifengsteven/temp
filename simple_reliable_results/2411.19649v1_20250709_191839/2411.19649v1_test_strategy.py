def calculate_sortino_ratio(returns, risk_free_rate=0.0, target_return=0.0):
    """
    Calculate Sortino ratio for a series of returns
    
    Args:
        returns: Array of returns
        risk_free_rate: Risk-free rate
        target_return: Target/minimum acceptable return
        
    Returns:
        Sortino ratio
    """
    excess_return = np.mean(returns) - risk_free_rate
    
    # Calculate downside deviation
    downside_returns = np.where(returns < target_return, returns - target_return, 0)
    downside_deviation = np.sqrt(np.mean(downside_returns**2))
    
    # Avoid division by zero
    if downside_deviation == 0:
        return np.inf if excess_return >= 0 else -np.inf
    
    return excess_return / downside_deviation

