class SimpleGBM:
    """Geometric Brownian Motion model for financial time series generation."""
    
    def __init__(self, mu=0, sigma=1):
        self.mu = mu
        self.sigma = sigma
    
    def generate(self, n_steps=300, n_series=1):
        """Generate price series using GBM."""
        dt = 1/n_steps
        prices = np.zeros((n_series, n_steps+1))
        prices[:, 0] = 100  # Initial price
        
        for t in range(1, n_steps+1):
            # GBM equation: dP = mu*P*dt + sigma*P*dW
            dW = np.random.normal(0, np.sqrt(dt), n_series)
            prices[:, t] = prices[:, t-1] * (1 + self.mu*dt + self.sigma*dW)
            
        return prices


class SimpleGARCH:
    """GARCH(1,1) model for financial time series generation."""
    
    def __init__(self, omega=0.1, alpha=0.1, beta=0.8):
        self.omega = omega
        self.alpha = alpha
        self.beta = beta
    
    def generate(self, n_steps=300, n_series=1):
        """Generate return series using GARCH(1,1)."""
        returns = np.zeros((n_series, n_steps))
        variance = np.zeros((n_series, n_steps))
        
        # Initialize variance
        variance[:, 0] = self.omega / (1 - self.alpha - self.beta)
        
        for t in range(1, n_steps):
            # GARCH process
            epsilon = np.random.normal(0, 1, n_series)
            returns[:, t-1] = np.sqrt(variance[:, t-1]) * epsilon
            variance[:, t] = self.omega + self.alpha * returns[:, t-1]**2 + self.beta * variance[:, t-1]
        
        # Calculate the last return
        epsilon = np.random.normal(0, 1, n_series)
        returns[:, -1] = np.sqrt(variance[:, -1]) * epsilon
        
        # Convert returns to prices
        prices = np.zeros((n_series, n_steps+1))
        prices[:, 0] = 100  # Initial price
        for t in range(1, n_steps+1):
            prices[:, t] = prices[:, t-1] * np.exp(returns[:, t-1])
            
        return prices


