class FinancialMetrics:
    """Calculate financial metrics for stylized facts evaluation."""
    
    @staticmethod
    def calculate_returns(prices):
        """Calculate log returns from price series."""
        return np.diff(np.log(prices), axis=1)
    
    @staticmethod
    def calculate_trend(returns):
        """Calculate trend (sum of returns)."""
        return np.sum(returns, axis=1)
    
    @staticmethod
    def calculate_realized_volatility(returns):
        """Calculate realized volatility (sum of squared returns)."""
        return np.sum(returns**2, axis=1)
    
    @staticmethod
    def calculate_kurtosis(returns):
        """Calculate Fisher's kurtosis."""
        return kurtosis(returns, axis=1, fisher=True)
    
    @staticmethod
    def calculate_hill_index(returns, q=0.05):
        """Calculate Hill index for the top q quantile of absolute returns."""
        n_series, n_steps = returns.shape
        hill_indices = np.zeros(n_series)
        
        for i in range(n_series):
            abs_returns = np.abs(returns[i])
            sorted_returns = np.sort(abs_returns)
            k = int(n_steps * q)  # Number of observations in the tail
            if k > 0:
                # Calculate Hill estimator
                tail_returns = sorted_returns[-k:]
                threshold = sorted_returns[-k]
                log_excess = np.log(tail_returns / threshold)
                hill_indices[i] = 1 / np.mean(log_excess)
            else:
                hill_indices[i] = np.nan
                
        return hill_indices
    
    @staticmethod
    def calculate_autocorrelation(returns, lag=1):
        """Calculate autocorrelation of absolute returns at specified lag."""
        n_series, n_steps = returns.shape
        autocorrs = np.zeros(n_series)
        
        for i in range(n_series):
            abs_returns = np.abs(returns[i])
            if lag < n_steps:
                # Calculate autocorrelation
                mean = np.mean(abs_returns)
                numerator = np.sum((abs_returns[:-lag] - mean) * (abs_returns[lag:] - mean))
                denominator = np.sum((abs_returns - mean)**2)
                if denominator > 0:
                    autocorrs[i] = numerator / denominator
                else:
                    autocorrs[i] = 0
            else:
                autocorrs[i] = 0
                
        return autocorrs
    
    @staticmethod
    def calculate_diversity(returns_list, method='euclidean'):
        """Calculate diversity among a list of return series."""
        n_samples = len(returns_list)
        if n_samples <= 1:
            return 0
        
        # Calculate pairwise distances
        distances = []
        for i in range(n_samples):
            for j in range(i+1, n_samples):
                if method == 'euclidean':
                    dist = np.sqrt(np.sum((returns_list[i] - returns_list[j])**2))
                elif method == 'dtw':
                    # Simple DTW implementation
                    n = len(returns_list[i])
                    m = len(returns_list[j])
                    dtw_matrix = np.zeros((n+1, m+1))
                    dtw_matrix[0, :] = np.inf
                    dtw_matrix[:, 0] = np.inf
                    dtw_matrix[0, 0] = 0
                    
                    for ii in range(1, n+1):
                        for jj in range(1, m+1):
                            cost = abs(returns_list[i][ii-1] - returns_list[j][jj-1])
                            dtw_matrix[ii, jj] = cost + min(dtw_matrix[ii-1, jj], 
                                                          dtw_matrix[ii, jj-1],
                                                          dtw_matrix[ii-1, jj-1])
                    
                    dist = dtw_matrix[n, m]
                else:
                    raise ValueError(f"Unknown diversity method: {method}")
                
                distances.append(dist)
        
        return np.mean(distances), np.std(distances)


