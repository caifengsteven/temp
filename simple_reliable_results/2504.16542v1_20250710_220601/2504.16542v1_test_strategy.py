@dataclass
class LiquidityPosition:
    """Represents an LP's liquidity position in a concentrated liquidity AMM."""
    liquidity: float  # L
    lower_price_sqrt: float  # π_l
    upper_price_sqrt: float  # π_u
    
    def is_active(self, current_price_sqrt: float) -> bool:
        """Check if position is active at the current price."""
        return self.lower_price_sqrt <= current_price_sqrt <= self.upper_price_sqrt
    
    def real_reserves(self, current_price_sqrt: float) -> Tuple[float, float]:
        """Calculate real reserves based on current price and position bounds."""
        if current_price_sqrt < self.lower_price_sqrt:
            x_r = self.liquidity * (1/self.lower_price_sqrt - 1/self.upper_price_sqrt)
            y_r = 0
        elif self.lower_price_sqrt <= current_price_sqrt <= self.upper_price_sqrt:
            x_r = self.liquidity * (1/current_price_sqrt - 1/self.upper_price_sqrt)
            y_r = self.liquidity * (current_price_sqrt - self.lower_price_sqrt)
        else:  # current_price_sqrt > self.upper_price_sqrt
            x_r = 0
            y_r = self.liquidity * (self.upper_price_sqrt - self.lower_price_sqrt)
        
        return x_r, y_r


class LiquidityProvider:
    """Models a liquidity provider's strategy for concentrated liquidity provision."""
    
    def __init__(self, initial_wealth: float, alpha: float, reallocation_threshold: float = 0):
        """
        Initialize a liquidity provider.
        
        Args:
            initial_wealth: Initial wealth in USD
            alpha: Relative size of square root price interval (α > 1)
            reallocation_threshold: Threshold γ that triggers reallocation
        """
        self.initial_wealth = initial_wealth
        self.current_wealth = initial_wealth
        self.alpha = alpha
        self.gamma = reallocation_threshold
        
        self.position: Optional[LiquidityPosition] = None
        self.unclaimed_rewards = 0
        self.total_reallocations = 0
        self.total_rewards = 0
        self.wealth_history = [initial_wealth]
        
    def open_position(self, current_price_sqrt: float) -> None:
        """Open a new liquidity position around the current price."""
        lower_bound = current_price_sqrt / self.alpha
        upper_bound = current_price_sqrt * self.alpha
        
        # Calculate liquidity from wealth
        # For simplicity, we assume the LP provides half wealth in each token
        price = current_price_sqrt ** 2
        token_x_amount = self.current_wealth / (2 * price)
        token_y_amount = self.current_wealth / 2
        
        # Calculate liquidity based on reserves
        liquidity = (self.alpha / (self.alpha - 1)) * (token_y_amount / current_price_sqrt)
        
        self.position = LiquidityPosition(
            liquidity=liquidity,
            lower_price_sqrt=lower_bound,
            upper_price_sqrt=upper_bound
        )
        
    def should_reallocate(self, current_price_sqrt: float) -> bool:
        """Determine if position should be reallocated based on price and threshold."""
        if not self.position:
            return True
            
        if current_price_sqrt < self.position.lower_price_sqrt - self.gamma:
            return True
        if current_price_sqrt > self.position.upper_price_sqrt + self.gamma:
            return True
        return False
        
    def reallocate(self, current_price_sqrt: float, transaction_cost: float, 
                  trade_fee_rate: float) -> None:
        """Reallocate liquidity by closing existing position and opening a new one."""
        if not self.position:
            self.open_position(current_price_sqrt)
            return
            
        # Withdraw tokens from current position
        x_r, y_r = self.position.real_reserves(current_price_sqrt)
        current_price = current_price_sqrt ** 2
        position_value = x_r * current_price + y_r + self.unclaimed_rewards
        
        # Apply transaction cost
        position_value -= transaction_cost
        
        # Apply rebalancing cost (trading fee)
        # For simplicity, we assume a fixed percentage of rebalancing cost
        # In reality, this would depend on the specific trading needed
        rebalancing_cost = position_value * trade_fee_rate * 0.5
        position_value -= rebalancing_cost
        
        # Update wealth
        self.current_wealth = max(0, position_value)
        self.wealth_history.append(self.current_wealth)
        
        # Reset unclaimed rewards
        self.unclaimed_rewards = 0
        
        # Increment reallocation counter
        self.total_reallocations += 1
        
        # Open new position if we still have wealth
        if self.current_wealth > 0:
            self.open_position(current_price_sqrt)
        else:
            self.position = None
            
    def collect_fees(self, fee_amount: float) -> None:
        """Collect fees based on liquidity provision."""
        self.unclaimed_rewards += fee_amount
        self.total_rewards += fee_amount
        
    def get_return_percentage(self) -> float:
        """Calculate return as percentage of initial wealth."""
        final_value = self.current_wealth + self.unclaimed_rewards
        return ((final_value / self.initial_wealth) - 1) * 100


def simulate_price_path(initial_price: float, volatility: float, 
                       time_steps: int, dt: float = 1.0) -> List[float]:
    """
    Simulate a price path using Geometric Brownian Motion.
    
    Args:
        initial_price: Starting price
        volatility: Price volatility (σ)
        time_steps: Number of time steps to simulate
        dt: Time step size
        
    Returns:
        List of prices
    """
    # Initialize price path with initial price
    prices = [initial_price]
    
    # Simulate price path
    for _ in range(time_steps):
        # Generate random normal value for price movement
        z = np.random.normal(0, 1)
        
        # Calculate price change using GBM equation (no drift)
        current_price = prices[-1]
        price_change = current_price * volatility * np.sqrt(dt) * z
        new_price = current_price + price_change
        
        # Ensure price doesn't go negative
        new_price = max(0.01, new_price)
        prices.append(new_price)
        
    return prices


def simulate_liquidity_rewards(price_volatility: float, time_steps: int, 
                              base_fee_rate: float) -> List[float]:
    """
    Simulate liquidity rewards per unit of liquidity.
    
    Args:
        price_volatility: Volatility of price
        time_steps: Number of time steps
        base_fee_rate: Base fee rate
        
    Returns:
        List of fee rates per time step
    """
    # Base reward rate
    rewards = []
    
    # Generate rewards based on volatility and random trading volume
    for _ in range(time_steps):
        # More volatility typically means more trading volume
        volatility_factor = 1 + np.random.exponential(price_volatility)
        # Random trading volume multiplier
        volume_multiplier = np.random.lognormal(0, 0.5)
        
        # Calculate reward rate for this time step
        reward = base_fee_rate * volatility_factor * volume_multiplier
        rewards.append(reward)
        
    return rewards


