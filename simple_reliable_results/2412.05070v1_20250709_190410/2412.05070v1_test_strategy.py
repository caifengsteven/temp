class HestonModel:
    def __init__(self, kappa, theta, xi, rho, v0):
        """
        Initialize Heston model parameters
        kappa: speed of mean reversion
        theta: level of mean reversion
        xi: volatility of variance (vol of vol)
        rho: correlation coefficient
        v0: initial variance
        """
        self.kappa = kappa
        self.theta = theta
        self.xi = xi
        self.rho = rho
        self.v0 = v0
        
    def characteristic_function(self, u, T, S0, r):
        """Characteristic function of log returns in the Heston model"""
        i = complex(0, 1)
        
        d = np.sqrt((self.rho * self.xi * u * i - self.kappa)**2 - 
                    self.xi**2 * (-i * u - u**2))
        
        g = (self.kappa - self.rho * self.xi * u * i - d) / (self.kappa - self.rho * self.xi * u * i + d)
        
        exp_dt = np.exp(-d * T)
        
        tmp0 = i * u * (np.log(S0) + r * T)
        tmp1 = (self.kappa - self.rho * self.xi * u * i - d) * T - 2 * np.log((1 - g * exp_dt) / (1 - g))
        tmp2 = self.theta * self.kappa * self.xi**(-2) * tmp1
        tmp3 = self.v0 * self.xi**(-2) * (self.kappa - self.rho * self.xi * u * i - d) * (1 - exp_dt) / (1 - g * exp_dt)
        
        return np.exp(tmp0 + tmp2 + tmp3)
    
    def mu(self, T, S0, r):
        """Calculate E[log(S_T)]"""
        # Use numerical differentiation to approximate derivative at u=0
        h = 1e-8
        cf_h = self.characteristic_function(h, T, S0, r)
        cf_neg_h = self.characteristic_function(-h, T, S0, r)
        derivative = (cf_h - cf_neg_h) / (2 * h)
        return np.real(-complex(0, 1) * derivative)
    
    def centralized_cf(self, u, T, S0, r):
        """Characteristic function of centralized log returns"""
        return self.characteristic_function(u, T, S0, r) * np.exp(-complex(0, 1) * u * self.mu(T, S0, r))
    
    def estimate_mu_n(self, n, T, S0, r):
        """Estimate nth moment of centralized log returns"""
        # Use numerical differentiation to approximate nth derivative at u=0
        h = 1e-4
        result = 0
        
        # Simple finite difference approximation of nth derivative
        for k in range(n + 1):
            result += (-1)**(n-k) * cmath.comb(n, k) * self.centralized_cf(k*h, T, S0, r)
            
        result /= h**n
        return abs(result)
    
    def integrand_I_s(self, u, s, T, S0, r):
        """Integrand for calculating I_s"""
        return 1 / (2 * np.pi) * abs(u)**(s + 1) * abs(self.centralized_cf(u, T, S0, r))
    
    def estimate_I_s(self, s, T, S0, r):
        """Estimate I_s by numerical integration"""
        # Use a finite range instead of (-inf, inf) for practical computation
        result, _ = integrate.quad(lambda u: self.integrand_I_s(u, s, T, S0, r), -100, 100)
        return result**(1/s)

class COSMethod:
    def __init__(self, model, S0, r):
        self.model = model
        self.S0 = S0
        self.r = r
        
    def cosine_coefficients(self, L, T, N):
        """Calculate cosine coefficients of the density"""
        k = np.arange(N+1)
        coeffs = np.zeros(N+1)
        
        for j in range(N+1):
            cf_val = self.model.centralized_cf(j * np.pi / (2 * L), T, self.S0, self.r)
            coeffs[j] = 1 / L * np.real(cf_val * np.exp(complex(0, 1) * j * np.pi/2))
            
        return coeffs
    
    def vk_coefficients(self, K, L, T, N):
        """Calculate cosine coefficients for a put option"""
        mu = self.model.mu(T, self.S0, self.r)
        d = min(np.log(K) - mu, L)
        
        if d <= -L:
            return np.zeros(N+1)
            
        k = np.arange(N+1)
        psi0 = np.zeros(N+1)
        psi1 = np.zeros(N+1)
        
        # k=0 case
        psi0[0] = d + L
        psi1[0] = (np.exp(d) - np.exp(-L))
        
        # k>0 cases
        for j in range(1, N+1):
            psi0[j] = 2 * L / (j * np.pi) * np.sin(j * np.pi * (d + L) / (2 * L))
            
            tmp1 = j * np.pi / (2 * L) * np.sin(j * np.pi * (d + L) / (2 * L))
            tmp2 = np.cos(j * np.pi * (d + L) / (2 * L))
            tmp3 = 1 + (j * np.pi / (2 * L))**2
            psi1[j] = (np.exp(d) * (tmp1 + tmp2) - np.exp(-L)) / tmp3
            
        return np.exp(-self.r * T) * (K * psi0 - np.exp(mu) * psi1)
    
    def price_put(self, K, L, T, N):
        """Price a European put option using the COS method"""
        ck = self.cosine_coefficients(L, T, N)
        vk = self.vk_coefficients(K, L, T, N)
        
        # First term is weighted by 1/2
        result = 0.5 * ck[0] * vk[0]
        for j in range(1, N+1):
            result += ck[j] * vk[j]
            
        return result
    
    def price_call(self, K, L, T, N):
        """Price a European call option using put-call parity"""
        put_price = self.price_put(K, L, T, N)
        return put_price + self.S0 - K * np.exp(-self.r * T)
    
    def calculate_optimal_parameters(self, K, T, eps, s=20):
        """Calculate optimal truncation range L and number of terms N for given error tolerance"""
        try:
            # Estimate μ_n directly 
            mu_8 = self.model.estimate_mu_n(8, T, self.S0, self.r)
            L = (2 * K * np.exp(-self.r * T) * mu_8 / eps)**(1/8)
            
            # Estimate I_s
            I_s = self.model.estimate_I_s(s, T, self.S0, self.r)
            
            # Calculate number of terms
            tmp = 2**(s + 5/2) * I_s**s * L**(s + 2) * 12 * K * np.exp(-self.r * T)
            N = int(np.ceil((tmp / (s * np.pi**(s + 1) * eps))**(1/s)))
            
            return L, N
        except Exception as e:
            print(f"Error calculating parameters: {e}")
            # Fallback to some reasonable values
            return 10, 64

def generate_heston_parameters(n_samples):
    """Generate random Heston model parameters within realistic ranges"""
    np.random.seed(42)
    
    # Parameter ranges from the paper
    kappa = np.random.uniform(1e-3, 10, n_samples)
    theta = np.random.uniform(1e-3, 2, n_samples)
    xi = np.random.uniform(1e-2, 5, n_samples)
    rho = np.random.uniform(-0.99, 0.99, n_samples)
    v0 = np.random.uniform(1e-3, 2, n_samples)
    T = np.random.uniform(1/250, 10, n_samples)
    
    # Filter out parameters that don't satisfy the Feller condition
    valid_indices = 2 * kappa * theta >= xi**2
    
    if np.sum(valid_indices) < n_samples:
        print(f"Warning: {n_samples - np.sum(valid_indices)} samples don't satisfy Feller condition")
    
    return pd.DataFrame({
        'kappa': kappa[valid_indices],
        'theta': theta[valid_indices],
        'xi': xi[valid_indices],
        'rho': rho[valid_indices],
        'v0': v0[valid_indices],
        'T': T[valid_indices]
    }).reset_index(drop=True).iloc[:min(n_samples, np.sum(valid_indices))]

