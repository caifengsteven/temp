class NetworkAnalyzer:
    """Analyze trade flow networks using network theory"""
    
    def __init__(self, trade_flows_df):
        self.trade_flows_df = trade_flows_df
        self.networks = {}  # Store networks by commodity and time period
        
    def create_network(self, commodity=None, period=None):
        """Create a directed network from trade flows"""
        # Filter data if needed
        df = self.trade_flows_df
        if commodity:
            df = df[df['commodity'] == commodity]
        if period:
            df = df[df['quarter'] == period]
            
        # Create directed graph
        G = nx.DiGraph()
        
        # Add nodes (ports)
        load_ports = df['load_port'].unique()
        discharge_ports = df['discharge_port'].unique()
        all_ports = set(list(load_ports) + list(discharge_ports))
        
        for port in all_ports:
            G.add_node(port)
        
        # Add edges (trade flows)
        for _, row in df.iterrows():
            # Check if edge exists
            if G.has_edge(row['load_port'], row['discharge_port']):
                # Increment weight
                G[row['load_port']][row['discharge_port']]['weight'] += 1
                G[row['load_port']][row['discharge_port']]['volume'] += row['volume']
            else:
                # Create new edge
                G.add_edge(row['load_port'], row['discharge_port'], 
                          weight=1, volume=row['volume'], days=row['days_steaming'])
        
        # Store network
        key = f"{commodity if commodity else 'all'}_{period if period else 'all'}"
        self.networks[key] = G
        
        return G
    
    def analyze_network(self, G):
        """Calculate network metrics"""
        if not G:
            return None
            
        metrics = {}
        
        # Basic metrics
        metrics['nodes'] = G.number_of_nodes()
        metrics['edges'] = G.number_of_edges()
        metrics['density'] = nx.density(G)
        
        # Degree statistics
        in_degrees = [d for _, d in G.in_degree(weight='weight')]
        out_degrees = [d for _, d in G.out_degree(weight='weight')]
        
        metrics['avg_in_degree'] = np.mean(in_degrees) if in_degrees else 0
        metrics['avg_out_degree'] = np.mean(out_degrees) if out_degrees else 0
        
        # Component analysis
        metrics['weakly_connected_components'] = nx.number_weakly_connected_components(G)
        metrics['strongly_connected_components'] = nx.number_strongly_connected_components(G)
        
        # Giant component analysis
        largest_wcc = max(nx.weakly_connected_components(G), key=len)
        largest_scc = max(nx.strongly_connected_components(G), key=len)
        
        metrics['giant_wcc_size'] = len(largest_wcc)
        metrics['giant_scc_size'] = len(largest_scc)
        metrics['giant_wcc_percentage'] = len(largest_wcc) / G.number_of_nodes() * 100
        metrics['giant_scc_percentage'] = len(largest_scc) / G.number_of_nodes() * 100
        
        # Path length (only for strongly connected component)
        if len(largest_scc) > 1:
            scc_subgraph = G.subgraph(largest_scc)
            try:
                metrics['avg_path_length'] = nx.average_shortest_path_length(scc_subgraph)
            except:
                metrics['avg_path_length'] = None
        else:
            metrics['avg_path_length'] = None
        
        # Clustering coefficient (treat as undirected for this calculation)
        undirected_G = G.to_undirected()
        metrics['clustering_coefficient'] = nx.average_clustering(undirected_G)
        
        # Try to detect communities
        try:
            partition = community_louvain.best_partition(undirected_G)
            metrics['communities'] = len(set(partition.values()))
            metrics['modularity'] = community_louvain.modularity(partition, undirected_G)
        except:
            metrics['communities'] = None
            metrics['modularity'] = None
        
        return metrics
    
    def analyze_all_commodities(self, periods=None):
        """Analyze networks for all commodities and periods"""
        commodities = ['Coal', 'Grain', 'Iron Ore', None]  # None means all commodities
        
        if not periods:
            # Get all periods from data
            periods = [None] + list(self.trade_flows_df['quarter'].unique())
        
        results = []
        
        for commodity in commodities:
            for period in periods:
                G = self.create_network(commodity, period)
                metrics = self.analyze_network(G)
                
                if metrics:
                    metrics['commodity'] = commodity if commodity else 'All'
                    metrics['period'] = str(period) if period else 'All'
                    results.append(metrics)
        
        return pd.DataFrame(results)
    
    def calculate_distance_matrix(self, commodity, periods):
        """Calculate distance matrix between networks in different periods"""
        networks = {}
        
        # Create networks for each period
        for period in periods:
            networks[period] = self.create_network(commodity, period)
        
        # Calculate distance matrix
        n = len(periods)
        distance_matrix = np.zeros((n, n))
        
        for i, period_i in enumerate(periods):
            for j, period_j in enumerate(periods):
                if i == j:
                    distance_matrix[i, j] = 0
                else:
                    G_i = networks[period_i]
                    G_j = networks[period_j]
                    
                    # Calculate Jaccard distance between edge sets
                    edges_i = set(G_i.edges())
                    edges_j = set(G_j.edges())
                    
                    intersection = len(edges_i.intersection(edges_j))
                    denominator = np.sqrt(len(edges_i) * len(edges_j))
                    
                    if denominator > 0:
                        similarity = intersection / denominator
                        distance_matrix[i, j] = 1 - similarity
                    else:
                        distance_matrix[i, j] = 1  # Maximum distance
        
        return distance_matrix, periods

