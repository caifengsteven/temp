def simulate_cluster_var_data(n_samples=1000, n_clusters=3, assets_per_cluster=[3, 5, 8], 
                              var_lag=2, within_corr=0.7, cross_corr=0.3):
    """
    Simulate VAR data with cluster structure for testing.
    
    Parameters:
    -----------
    n_samples : int
        Number of time periods
    n_clusters : int
        Number of clusters
    assets_per_cluster : list
        Number of assets in each cluster
    var_lag : int
        VAR lag order
    within_corr : float
        Correlation within clusters
    cross_corr : float
        Correlation across clusters
    
    Returns:
    --------
    data : pandas DataFrame
        Simulated return data
    clusters : dict
        Mapping of asset names to cluster numbers
    """
    n_assets = sum(assets_per_cluster)
    
    # Create cluster mapping
    clusters = {}
    asset_idx = 0
    for c in range(n_clusters):
        for i in range(assets_per_cluster[c]):
            asset_name = f"Asset_{c+1}_{i+1}"
            clusters[asset_name] = c
            asset_idx += 1
    
    # Create VAR coefficient matrices
    # Make North American assets more influential
    A = np.zeros((n_assets, n_assets, var_lag))
    
    # First lag coefficients (stronger connections within clusters)
    for lag in range(var_lag):
        decay = 0.7 ** lag  # Coefficient decay with lag
        
        # Set base coefficients
        for i in range(n_assets):
            for j in range(n_assets):
                # Determine if i and j are in the same cluster
                i_cluster = next(c for asset, c in clusters.items() if asset == f"Asset_{clusters.get(f'Asset_{i//assets_per_cluster[0]+1}_{i%assets_per_cluster[0]+1}')+1}_{i%assets_per_cluster[0]+1}")
                j_cluster = next(c for asset, c in clusters.items() if asset == f"Asset_{clusters.get(f'Asset_{j//assets_per_cluster[0]+1}_{j%assets_per_cluster[0]+1}')+1}_{j%assets_per_cluster[0]+1}")
                
                # Stronger connections within clusters
                if i_cluster == j_cluster:
                    A[i, j, lag] = 0.3 * decay + 0.1 * np.random.randn()
                else:
                    A[i, j, lag] = 0.1 * decay + 0.05 * np.random.randn()
                    
                # First cluster (North America) has stronger influence on others
                if j_cluster == 0:
                    A[i, j, lag] *= 1.5
    
    # Create error covariance matrix with cluster structure
    Sigma = np.zeros((n_assets, n_assets))
    
    # Fill diagonal with ones (unit variances)
    np.fill_diagonal(Sigma, 1.0)
    
    # Fill off-diagonal elements based on cluster
    asset_idx = 0
    for c1 in range(n_clusters):
        for i in range(assets_per_cluster[c1]):
            asset_i = asset_idx + i
            other_idx = 0
            for c2 in range(n_clusters):
                for j in range(assets_per_cluster[c2]):
                    asset_j = other_idx + j
                    
                    if asset_i != asset_j:  # Off-diagonal elements
                        if c1 == c2:  # Same cluster
                            Sigma[asset_i, asset_j] = within_corr + 0.05 * np.random.randn()
                        else:  # Different clusters
                            Sigma[asset_i, asset_j] = cross_corr + 0.05 * np.random.randn()
                
                other_idx += assets_per_cluster[c2]
            asset_idx += assets_per_cluster[c1]
    
    # Ensure Sigma is positive definite and symmetric
    Sigma = (Sigma + Sigma.T) / 2
    min_eig = np.min(np.linalg.eigvals(Sigma))
    if min_eig < 0:
        Sigma += (-min_eig + 0.01) * np.eye(n_assets)
    
    # Generate VAR data
    data = np.zeros((n_samples + 100, n_assets))  # Extra 100 for burn-in
    
    # Initialize with random values
    for t in range(var_lag):
        data[t] = np.random.multivariate_normal(np.zeros(n_assets), Sigma)
    
    # Generate the rest based on VAR equation
    for t in range(var_lag, n_samples + 100):
        data[t] = np.random.multivariate_normal(np.zeros(n_assets), Sigma)
        for lag in range(var_lag):
            data[t] += A[:, :, lag].T @ data[t-lag-1]
    
    # Discard burn-in
    data = data[100:]
    
    # Convert to DataFrame
    asset_names = list(clusters.keys())
    df = pd.DataFrame(data, columns=asset_names)
    
    return df, clusters

