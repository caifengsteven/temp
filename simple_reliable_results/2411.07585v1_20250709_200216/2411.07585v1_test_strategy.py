def generate_stock_data(days=500, volatility=0.01):
    np.random.seed(42)
    price = 100
    prices = [price]
    
    for _ in range(days-1):
        change = np.random.normal(0, volatility)
        price *= (1 + change)
        prices.append(price)
    
    dates = pd.date_range(start="2020-01-01", periods=days)
    
    # Create OHLCV data
    df = pd.DataFrame({
        'date': dates,
        'open': prices,
        'high': [p * (1 + np.random.uniform(0, 0.005)) for p in prices],
        'low': [p * (1 - np.random.uniform(0, 0.005)) for p in prices],
        'close': [p * (1 + np.random.normal(0, 0.001)) for p in prices],
        'volume': [int(np.random.uniform(1000000, 10000000)) for _ in prices]
    })
    
    # Calculate technical indicators
    df = calculate_indicators(df)
    
    return df

# Calculate technical indicators
def calculate_indicators(df):
    # Convert to numpy arrays for TA-Lib
    close = df['close'].values
    high = df['high'].values
    low = df['low'].values
    open_prices = df['open'].values
    volume = df['volume'].values
    
    # Calculate indicators as mentioned in the paper
    df['sma'] = ta.SMA(close, timeperiod=14)
    df['obv'] = ta.OBV(close, volume)
    df['momentum'] = ta.MOM(close, timeperiod=14)
    df['stoch_k'], df['stoch_d'] = ta.STOCH(high, low, close)
    df['macd'], df['macd_signal'], df['macd_hist'] = ta.MACD(close)
    df['cci'] = ta.CCI(high, low, close)
    df['adx'] = ta.ADX(high, low, close)
    df['trix'] = ta.TRIX(close)
    df['roc'] = ta.ROC(close)
    df['sar'] = ta.SAR(high, low)
    df['tema'] = ta.TEMA(close)
    df['trima'] = ta.TRIMA(close)
    df['wma'] = ta.WMA(close)
    df['dema'] = ta.DEMA(close)
    df['mfi'] = ta.MFI(high, low, close, volume)
    df['cmo'] = ta.CMO(close)
    
    # For STOCHRSI, first calculate RSI then STOCH on it
    rsi = ta.RSI(close)
    df['stochrsi_k'], df['stochrsi_d'] = ta.STOCH(rsi, rsi, rsi)
    
    # UO - Ultimate Oscillator
    df['uo'] = ta.ULTOSC(high, low, close)
    
    # BOP - Balance of Power
    df['bop'] = ta.BOP(open_prices, high, low, close)
    
    # ATR - Average True Range
    df['atr'] = ta.ATR(high, low, close)
    
    # Drop NaN values
    df = df.dropna()
    
    return df

