# Evaluate trading performance
def evaluate_performance(env):
    # Calculate performance metrics from the paper
    trades = env.trades
    
    if not trades:
        return {
            "return_pct": 0,
            "annual_return_pct": 0,
            "volatility_pct": 0,
            "sharpe_ratio": 0,
            "win_rate_pct": 0,
            "total_trades": 0
        }
    
    # Extract buy and sell trades
    buys = [t for t in trades if t[0] == 'BUY']
    sells = [t for t in trades if t[0] == 'SELL']
    
    # Pair buys and sells
    paired_trades = []
    for i in range(min(len(buys), len(sells))):
        if buys[i][1] < sells[i][1]:  # Ensure buy happens before sell
            paired_trades.append((buys[i][2], sells[i][2]))
    
    if not paired_trades:
        return {
            "return_pct": 0,
            "annual_return_pct": 0,
            "volatility_pct": 0,
            "sharpe_ratio": 0,
            "win_rate_pct": 0,
            "total_trades": 0
        }
    
    # Calculate returns for each trade
    returns = [(sell_price / buy_price) - 1 for buy_price, sell_price in paired_trades]
    
    # Calculate total return
    total_return = (1 + sum(returns)) - 1
    
    # Annualize return (assuming 252 trading days per year)
    days = env.df.shape[0]
    annual_return = (1 + total_return) ** (252 / days) - 1
    
    # Calculate volatility (annualized)
    if len(returns) > 1:
        volatility = np.std(returns) * np.sqrt(252 / len(returns))
    else:
        volatility = 0
    
    # Calculate Sharpe ratio (assuming risk-free rate of 0 for simplicity)
    sharpe_ratio = annual_return / volatility if volatility > 0 else 0
    
    # Calculate win rate
    win_rate = sum(1 for r in returns if r > 0) / len(returns) if returns else 0
    
    return {
        "return_pct": total_return * 100,
        "annual_return_pct": annual_return * 100,
        "volatility_pct": volatility * 100,
        "sharpe_ratio": sharpe_ratio,
        "win_rate_pct": win_rate * 100,
        "total_trades": len(paired_trades)
    }

