# Deep Q-Network (DQN) Agent
class DQNAgent:
    def __init__(self, state_size, action_size, learning_rate=1e-2):
        self.state_size = state_size
        self.action_size = action_size
        self.memory = deque(maxlen=100000)  # Buffer size
        self.gamma = 0.99  # Discount factor
        self.epsilon = 1.0  # Exploration rate
        self.epsilon_min = 0.01
        self.epsilon_decay = 0.995
        self.learning_rate = learning_rate
        self.batch_size = 128
        self.model = self._build_model()
        self.target_model = self._build_model()
        self.update_target_counter = 0
        self.target_update_interval = 1000
        
    def _build_model(self):
        # Simple neural network for demonstration
        # In a real implementation, you would use a proper deep learning library
        # like TensorFlow or PyTorch
        class SimpleNN:
            def __init__(self, input_size, output_size, learning_rate):
                self.weights = np.random.rand(input_size, output_size) * 0.1
                self.bias = np.zeros(output_size)
                self.lr = learning_rate
                
            def predict(self, state):
                # Flatten the state if it's 2D
                if len(state.shape) > 1:
                    state = state.flatten()
                return np.dot(state, self.weights) + self.bias
            
            def train(self, states, targets):
                for i in range(len(states)):
                    state = states[i].flatten()
                    target = targets[i]
                    prediction = self.predict(state)
                    
                    # Compute gradients
                    error = target - prediction
                    gradient = state.reshape(-1, 1) * error
                    
                    # Update weights and bias
                    self.weights += self.lr * gradient
                    self.bias += self.lr * error
        
        return SimpleNN(self.state_size[0] * self.state_size[1], self.action_size, self.learning_rate)
    
    def remember(self, state, action, reward, next_state, done):
        self.memory.append((state, action, reward, next_state, done))
    
    def act(self, state):
        if np.random.rand() <= self.epsilon:
            return random.randrange(self.action_size)
        
        act_values = self.model.predict(state)
        return np.argmax(act_values)
    
    def replay(self):
        if len(self.memory) < self.batch_size:
            return
        
        minibatch = random.sample(self.memory, self.batch_size)
        
        states = np.array([mb[0] for mb in minibatch])
        actions = np.array([mb[1] for mb in minibatch])
        rewards = np.array([mb[2] for mb in minibatch])
        next_states = np.array([mb[3] for mb in minibatch])
        dones = np.array([mb[4] for mb in minibatch])
        
        targets = np.zeros((self.batch_size, self.action_size))
        
        for i in range(self.batch_size):
            # Non-terminal states
            if not dones[i]:
                target = rewards[i] + self.gamma * np.max(self.target_model.predict(next_states[i]))
            # Terminal states
            else:
                target = rewards[i]
                
            targets[i] = self.model.predict(states[i])
            targets[i, actions[i]] = target
        
        self.model.train(states, targets)
        
        # Decay epsilon
        if self.epsilon > self.epsilon_min:
            self.epsilon *= self.epsilon_decay
            
        # Update target network
        self.update_target_counter += 1
        if self.update_target_counter >= self.target_update_interval:
            self.update_target_model()
            self.update_target_counter = 0
    
    def update_target_model(self):
        # Copy weights from model to target_model
        self.target_model.weights = self.model.weights.copy()
        self.target_model.bias = self.model.bias.copy()


