# Custom Trading Environment
class TradingEnv(gym.Env):
    def __init__(self, df, window_size=20):
        super(TradingEnv, self).__init__()
        
        self.df = df
        self.window_size = window_size
        self.reset_index = 0
        
        # Define action and observation space
        # Discrete action space: Buy (0) or Sell (1)
        self.action_space = spaces.Discrete(2)
        
        # Observation space: window_size rows x 20 technical indicators
        self.observation_space = spaces.Box(
            low=-np.inf, 
            high=np.inf, 
            shape=(window_size, 20),  # 20 technical indicators
            dtype=np.float32
        )
        
        # Trading variables
        self.position = 0  # 0: no position, 1: long position
        self.trades = []
        self.current_step = 0
        self.last_trade_price = 0
        self.total_reward = 0
        self.equity = 10000  # Initial capital
        
    def reset(self):
        # Reset environment state
        self.current_step = self.window_size
        self.position = 0
        self.trades = []
        self.total_reward = 0
        self.equity = 10000
        self.last_trade_price = 0
        
        return self._get_observation()
    
    def _get_observation(self):
        # Get the window of features
        obs = self.df[self.current_step-self.window_size:self.current_step].values
        return obs
    
    def step(self, action):
        # Get current price
        current_price = self.df.iloc[self.current_step]['close']
        
        # Initialize reward
        reward = 0
        
        # Execute action
        if action == Actions.BUY.value:  # Buy
            if self.position == 0:  # If no position, buy
                self.position = 1
                self.last_trade_price = current_price
                self.trades.append(('BUY', self.current_step, current_price))
            # Else already in position, no action
        
        elif action == Actions.SELL.value:  # Sell
            if self.position == 1:  # If in position, sell
                reward = np.log(current_price / self.last_trade_price)  # Log return
                self.position = 0
                self.trades.append(('SELL', self.current_step, current_price))
                # Update equity
                self.equity *= (1 + (current_price - self.last_trade_price) / self.last_trade_price)
            # Else no position to sell, no action
        
        # Move to next step
        self.current_step += 1
        
        # Check if done
        done = self.current_step >= len(self.df) - 1
        
        # Get new observation
        obs = self._get_observation()
        
        # Add immediate reward to total
        self.total_reward += reward
        
        # Info dictionary for additional details
        info = {
            'current_step': self.current_step,
            'position': self.position,
            'trades': self.trades,
            'equity': self.equity
        }
        
        return obs, reward, done, info
    
