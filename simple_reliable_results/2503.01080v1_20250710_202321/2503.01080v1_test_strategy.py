class DynamicFactorCorrelationModel:
    """Implementation of Dynamic Factor Correlation Model from Tong & Hansen (2025)"""
    
    def __init__(self, n_assets=12, n_factors=8, n_blocks=4, block_sizes=None, 
                 distribution='CT', use_sparse_blocks=True):
        """
        Initialize the model
        
        Parameters:
        -----------
        n_assets : int
            Number of assets
        n_factors : int
            Number of factors
        n_blocks : int
            Number of blocks in the correlation structure
        block_sizes : list
            List of block sizes (must sum to n_assets)
        distribution : str
            Distribution type ('Gauss', 'MT', 'CT', 'HT')
        use_sparse_blocks : bool
            Whether to use sparse block structure for idiosyncratic correlations
        """
        self.n_assets = n_assets
        self.n_factors = n_factors
        self.n_blocks = n_blocks
        
        if block_sizes is None:
            # Default to equal-sized blocks
            block_sizes = [n_assets // n_blocks] * n_blocks
            block_sizes[-1] += n_assets % n_blocks
        
        assert sum(block_sizes) == n_assets, "Block sizes must sum to n_assets"
        self.block_sizes = block_sizes
        
        self.distribution = distribution
        self.use_sparse_blocks = use_sparse_blocks
        
        # Initialize model parameters
        self.tau = np.zeros((n_assets, n_factors))  # Factor loading parameters
        self.rho = np.zeros((n_assets, n_factors))  # Factor loadings
        
        # Parameters for dynamic model of factor loadings
        self.kappa = np.zeros((n_assets, n_factors))
        self.alpha = 0.02 * np.ones((n_assets, n_factors))
        self.beta = 0.95 * np.ones((n_assets, n_factors))
        
        # Initialize idiosyncratic correlation parameters
        self.eta = np.zeros(n_blocks)  # For diagonal block correlation
        self.Ce = self._initialize_Ce()
        
        # Degrees of freedom parameters for t-distributions
        if distribution in ['MT', 'CT', 'HT']:
            if distribution == 'MT':
                self.nu = 5.0  # Single df for multivariate t
            elif distribution == 'CT':
                self.nu = 4.0 * np.ones(n_blocks)  # One df per block
            elif distribution == 'HT':
                self.nu = 4.0 * np.ones(n_assets)  # One df per asset
    
    def _initialize_Ce(self):
        """Initialize the idiosyncratic correlation matrix"""
        if self.use_sparse_blocks:
            # Initialize with block diagonal structure
            block_matrices = []
            for size in self.block_sizes:
                # Create equicorrelation blocks with 0.5 correlation
                block = 0.5 * np.ones((size, size))
                np.fill_diagonal(block, 1.0)
                block_matrices.append(block)
            return block_diag(*block_matrices)
        else:
            # Initialize with full block structure
            Ce = np.eye(self.n_assets)
            start_idx = 0
            for size in self.block_sizes:
                end_idx = start_idx + size
                Ce[start_idx:end_idx, start_idx:end_idx] = 0.5
                np.fill_diagonal(Ce, 1.0)
                start_idx = end_idx
            
            # Add some between-block correlations
            if self.n_blocks > 1:
                for i in range(self.n_blocks-1):
                    start_i = sum(self.block_sizes[:i])
                    end_i = start_i + self.block_sizes[i]
                    start_j = end_i
                    end_j = start_j + self.block_sizes[i+1]
                    Ce[start_i:end_i, start_j:end_j] = 0.1
                    Ce[start_j:end_j, start_i:end_i] = 0.1
            
            return Ce
    
    def tau_to_rho(self, tau):
        """
        Convert tau parameters to factor loadings (rho) using the variation-free parametrization
        
        This implements the formula from Theorem 1 in the paper.
        """
        rho = np.zeros_like(tau)
        for i in range(self.n_assets):
            tau_i = tau[i]
            tau_norm = np.sqrt(np.sum(tau_i**2))
            
            if tau_norm > 0:
                rho[i] = np.tanh(tau_norm) / tau_norm * tau_i
            
        return rho
    
    def rho_to_tau(self, rho):
        """Convert factor loadings (rho) to tau parameters"""
        tau = np.zeros_like(rho)
        for i in range(self.n_assets):
            rho_i = rho[i]
            rho_norm = np.sqrt(np.sum(rho_i**2))
            
            if rho_norm > 0 and rho_norm < 1:
                tau[i] = np.arctanh(rho_norm) / rho_norm * rho_i
            
        return tau
    
    def compute_omega(self, rho):
        """Compute idiosyncratic variance proportion"""
        omega = np.zeros(self.n_assets)
        for i in range(self.n_assets):
            rho_i = rho[i]
            omega[i] = np.sqrt(1 - np.sum(rho_i**2))
        return omega
    
    def simulate_data(self, T=500, CF=None, seed=None):
        """
        Simulate data from the model
        
        Parameters:
        -----------
        T : int
            Number of time periods
        CF : ndarray
            Factor correlation matrix (if None, identity is used)
        seed : int
            Random seed
            
        Returns:
        --------
        Z : ndarray
            Standardized asset returns
        F : ndarray
            Standardized factor returns
        U : ndarray
            Orthogonalized factor returns
        """
        if seed is not None:
            np.random.seed(seed)
            
        # Initialize factor correlation matrix if not provided
        if CF is None:
            CF = np.eye(self.n_factors)
            # Add some correlations between factors
            for i in range(self.n_factors):
                for j in range(i+1, self.n_factors):
                    CF[i, j] = 0.3 if (i % 2 == 0 and j % 2 == 0) else 0.0
                    CF[j, i] = CF[i, j]
        
        # Generate orthogonalized factor returns
        U = np.random.normal(0, 1, size=(T, self.n_factors))
        
        # Convert to correlated factor returns
        CF_sqrt = np.linalg.cholesky(CF)
        F = np.dot(U, CF_sqrt.T)
        
        # Initialize arrays for returns and dynamic parameters
        Z = np.zeros((T, self.n_assets))
        self.tau_t = np.zeros((T, self.n_assets, self.n_factors))
        self.rho_t = np.zeros((T, self.n_assets, self.n_factors))
        self.omega_t = np.zeros((T, self.n_assets))
        
        # Generate time-varying factor loadings
        for t in range(T):
            if t == 0:
                self.tau_t[t] = self.tau
            else:
                # Add some dynamic movements to tau
                innovation = 0.1 * np.random.normal(0, 1, size=(self.n_assets, self.n_factors))
                self.tau_t[t] = self.kappa + self.beta * self.tau_t[t-1] + self.alpha * innovation
            
            # Convert tau to rho
            self.rho_t[t] = self.tau_to_rho(self.tau_t[t])
            
            # Compute omega (idiosyncratic variance proportion)
            self.omega_t[t] = self.compute_omega(self.rho_t[t])
        
        # Generate idiosyncratic shocks based on the chosen distribution
        if self.distribution == 'Gauss':
            e = np.random.multivariate_normal(np.zeros(self.n_assets), self.Ce, size=T)
        elif self.distribution == 'MT':
            # Multivariate t-distribution
            chi_sq = np.random.chisquare(self.nu, size=T) / self.nu
            chi_sq = chi_sq.reshape(-1, 1)
            e = np.random.multivariate_normal(np.zeros(self.n_assets), self.Ce, size=T)
            e = e / np.sqrt(chi_sq)
        elif self.distribution == 'CT':
            # Cluster-t distribution
            e = np.zeros((T, self.n_assets))
            start_idx = 0
            for i, size in enumerate(self.block_sizes):
                end_idx = start_idx + size
                chi_sq = np.random.chisquare(self.nu[i], size=T) / self.nu[i]
                chi_sq = chi_sq.reshape(-1, 1)
                block_e = np.random.multivariate_normal(
                    np.zeros(size), 
                    self.Ce[start_idx:end_idx, start_idx:end_idx], 
                    size=T
                )
                e[:, start_idx:end_idx] = block_e / np.sqrt(chi_sq)
                start_idx = end_idx
        elif self.distribution == 'HT':
            # Heterogeneous t-distribution
            e = np.zeros((T, self.n_assets))
            for i in range(self.n_assets):
                chi_sq = np.random.chisquare(self.nu[i], size=T) / self.nu[i]
                e[:, i] = np.random.normal(0, 1, size=T) / np.sqrt(chi_sq)
            # Apply correlation structure
            C_sqrt = np.linalg.cholesky(self.Ce)
            e = np.dot(e, C_sqrt.T)
        
        # Generate asset returns
        for t in range(T):
            # Z = ρ'U + Λω e
            factor_component = np.sum(self.rho_t[t] * U[t], axis=1)
            idiosyncratic_component = self.omega_t[t] * e[t]
            Z[t] = factor_component + idiosyncratic_component
            
        return Z, F, U
    
    def calculate_likelihood(self, Z, U):
        """Calculate log-likelihood for a static model given data"""
        T = Z.shape[0]
        log_likelihood = 0
        
        # For simplicity, we're just implementing the Gaussian case
        # and leaving other distributions as an exercise
        for t in range(T):
            factor_component = np.sum(self.rho * U[t], axis=1)
            residual = Z[t] - factor_component
            omega = self.compute_omega(self.rho)
            scaled_residual = residual / omega
            
            # Gaussian log-likelihood with correlation Ce
            try:
                ll = -0.5 * np.log(np.linalg.det(self.Ce))
                ll -= 0.5 * scaled_residual.T @ np.linalg.inv(self.Ce) @ scaled_residual
                ll -= 0.5 * self.n_assets * np.log(2 * np.pi)
                log_likelihood += ll
            except:
                log_likelihood -= 1000  # Penalty for numerical issues
        
        return log_likelihood
    
    def fit_static_model(self, Z, U, max_iter=100):
        """
        Fit a static version of the model (non-dynamic parameters)
        
        This is a simplified version that only estimates factor loadings
        """
        def neg_likelihood(params):
            # Reshape parameters
            rho_flat = params[:self.n_assets * self.n_factors]
            self.rho = rho_flat.reshape(self.n_assets, self.n_factors)
            
            # Ensure constraints
            for i in range(self.n_assets):
                rho_norm_sq = np.sum(self.rho[i]**2)
                if rho_norm_sq >= 1:
                    return 1e10  # Return large value if constraint is violated
            
            # Convert rho to tau
            self.tau = self.rho_to_tau(self.rho)
            
            return -self.calculate_likelihood(Z, U)
        
        # Initial guess - small random values
        initial_params = 0.1 * np.random.randn(self.n_assets * self.n_factors)
        
        # Fit model
        result = minimize(
            neg_likelihood, 
            initial_params, 
            method='L-BFGS-B',
            options={'maxiter': max_iter}
        )
        
        # Update model parameters
        self.rho = result.x[:self.n_assets * self.n_factors].reshape(self.n_assets, self.n_factors)
        self.tau = self.rho_to_tau(self.rho)
        
        return result

