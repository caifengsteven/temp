class GJRGARCHSimulator:
    """Simulates price paths using GJR-GARCH(1,1) model"""
    
    def __init__(self, mu, nu0, nu, xi, lam):
        self.mu = mu
        self.nu0 = nu0
        self.nu = nu
        self.xi = xi
        self.lam = lam
    
    def simulate_paths(self, S0, T, dt, num_paths):
        """
        Simulates stock price paths using GJR-GARCH(1,1) model
        
        Args:
            S0: Initial stock price
            T: Time to expiry in years
            dt: Time step size in years
            num_paths: Number of paths to simulate
            
        Returns:
            Numpy array of shape (num_paths, T+1) with simulated prices
        """
        num_steps = int(T/dt)
        paths = np.zeros((num_paths, num_steps+1))
        paths[:, 0] = S0
        
        # Initialize volatilities and previous returns
        sigma2 = np.ones(num_paths) * self.nu0 / (1 - self.nu - self.xi - self.lam/2)
        prev_return = np.zeros(num_paths)
        
        for t in range(1, num_steps+1):
            # Generate random shocks
            z = np.random.standard_normal(num_paths)
            
            # Compute returns
            eps = np.sqrt(sigma2) * z
            returns = self.mu + eps
            
            # Update prices
            paths[:, t] = paths[:, t-1] * np.exp(returns)
            
            # Update indicator for negative returns
            I = (prev_return < self.mu).astype(float)
            
            # Update volatility
            sigma2 = self.nu0 + (self.nu + self.lam * I) * eps**2 + self.xi * sigma2
            
            # Store returns for next iteration
            prev_return = returns
            
        return paths

class MCPGPolicy(nn.Module):
    """Neural network policy for Monte Carlo Policy Gradient"""
    
    def __init__(self, input_dim=3, hidden_dims=[64, 64, 64, 64], output_dim=1):
        super(MCPGPolicy, self).__init__()
        
        layers = []
        prev_dim = input_dim
        
        for hidden_dim in hidden_dims:
            layers.append(nn.Linear(prev_dim, hidden_dim))
            layers.append(nn.ReLU())
            prev_dim = hidden_dim
        
        layers.append(nn.Linear(prev_dim, output_dim))
        layers.append(nn.Sigmoid())  # Output in [0, 1] to represent delta
        
        self.network = nn.Sequential(*layers)
    
    def forward(self, state):
        return self.network(state)

def black_scholes_delta(S, K, T, t, r, sigma):
    """Calculate Black-Scholes delta for a call option"""
    tau = T - t
    
    if tau <= 0:
        return 0.0 if S <= K else 1.0
    
    d1 = (np.log(S/K) + (r + 0.5 * sigma**2) * tau) / (sigma * np.sqrt(tau))
    return norm.cdf(d1)

def calculate_hedging_pnl(stock_prices, hedge_ratios, K, r, dt):
    """
    Calculate P&L from hedging strategy
    
    Args:
        stock_prices: Array of stock prices (T+1,)
        hedge_ratios: Array of hedge ratios (T,)
        K: Strike price
        r: Risk-free rate
        dt: Time step size
        
    Returns:
        P&L at expiry, portfolio values at each time step
    """
    num_steps = len(stock_prices) - 1
    
    # Initialize portfolio
    cash = np.zeros(num_steps+1)
    cash[0] = stock_prices[0] * hedge_ratios[0]  # Initial premium is delta * S0
    
    for t in range(1, num_steps):
        # Update cash from previous period with interest
        cash[t] = cash[t-1] * np.exp(r * dt)
        
        # Buy/sell stock to adjust delta
        delta_hedge = hedge_ratios[t] - hedge_ratios[t-1]
        cash[t] -= delta_hedge * stock_prices[t]
    
    # Final step
    cash[num_steps] = cash[num_steps-1] * np.exp(r * dt)
    
    # Calculate portfolio value at expiry
    final_stock_price = stock_prices[num_steps]
    option_payoff = max(0, final_stock_price - K)
    
    # Final P&L (negative of the loss)
    pnl = cash[num_steps] + hedge_ratios[num_steps-1] * final_stock_price - option_payoff
    
    # Portfolio values at each time step
    portfolio_values = cash + hedge_ratios * stock_prices[:-1]
    portfolio_values = np.append(portfolio_values, cash[num_steps] + hedge_ratios[-1] * final_stock_price)
    
    return pnl, portfolio_values

def calculate_rsqp(pnls):
    """Calculate Root Semi-Quadratic Penalty risk measure"""
    negative_pnls = np.maximum(-pnls, 0)  # Only consider losses (negative P&L)
    return np.sqrt(np.mean(negative_pnls**2))

