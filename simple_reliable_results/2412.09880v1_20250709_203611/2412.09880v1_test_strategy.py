class SimplifiedTimesFM:
    """A simplified model to mimic the fine-tuned TimesFM behavior."""
    
    def __init__(self, context_length: int = 512, prediction_accuracy: float = 0.58):
        """
        Initialize the model.
        
        Args:
            context_length: Maximum lookback window
            prediction_accuracy: Simulated accuracy rate to mimic fine-tuned model
        """
        self.context_length = context_length
        self.prediction_accuracy = prediction_accuracy
        
    def predict(self, time_series: np.ndarray, horizon: int = 128) -> np.ndarray:
        """
        Predict future price movements.
        
        Args:
            time_series: Historical price data
            horizon: Prediction horizon length
            
        Returns:
            Predicted future prices
        """
        # Use only the last context_length points if available
        if len(time_series) > self.context_length:
            context = time_series[-self.context_length:]
        else:
            context = time_series
            
        # Create a simple trend prediction
        last_price = context[-1]
        
        # Calculate the true trend from past data
        if len(context) > 10:
            true_trend = np.mean(np.diff(context[-10:])) 
        else:
            true_trend = 0
            
        # With probability equal to prediction_accuracy, predict correctly
        if random.random() < self.prediction_accuracy:
            # Correct prediction - follow the true trend
            predictions = np.array([last_price + true_trend * i for i in range(1, horizon + 1)])
        else:
            # Incorrect prediction - go opposite the true trend
            predictions = np.array([last_price - true_trend * i for i in range(1, horizon + 1)])
            
        return predictions


class AR1Model:
    """Simple AR(1) model for comparison."""
    
    def __init__(self):
        self.model = LinearRegression()
        self.fitted = False
        
    def fit(self, time_series: np.ndarray):
        """Fit AR(1) model to time series."""
        if len(time_series) < 3:
            return
            
        X = time_series[:-1].reshape(-1, 1)
        y = time_series[1:]
        self.model.fit(X, y)
        self.fitted = True
        
    def predict(self, time_series: np.ndarray, horizon: int = 128) -> np.ndarray:
        """Make AR(1) predictions."""
        if not self.fitted:
            self.fit(time_series)
            
        predictions = []
        last_val = time_series[-1]
        
        for _ in range(horizon):
            next_val = self.model.predict([[last_val]])[0]
            predictions.append(next_val)
            last_val = next_val
            
        return np.array(predictions)


class RandomModel:
    """Random prediction model based on historical up/down ratio."""
    
    def __init__(self, up_probability: float = 0.53):
        self.up_probability = up_probability
        
    def predict(self, time_series: np.ndarray, horizon: int = 128) -> np.ndarray:
        """Make random predictions based on historical probability."""
        last_price = time_series[-1]
        predictions = [last_price]
        
        for i in range(horizon):
            # Random walk with bias according to up_probability
            if random.random() < self.up_probability:
                change = abs(random.normalvariate(0, 0.01))  # Positive change
            else:
                change = -abs(random.normalvariate(0, 0.01))  # Negative change
                
            next_price = predictions[-1] * (1 + change)
            predictions.append(next_price)
            
        return np.array(predictions[1:])


def generate_synthetic_market(n_assets: int = 100, days: int = 500,
                             drift: float = 0.0002, volatility: float = 0.015) -> pd.DataFrame:
    """
    Generate synthetic market data.
    
    Args:
        n_assets: Number of assets to simulate
        days: Number of trading days
        drift: Daily drift component
        volatility: Daily volatility
        
    Returns:
        DataFrame with simulated price data
    """
    start_date = datetime(2022, 1, 1)
    dates = [start_date + timedelta(days=i) for i in range(days)]
    
    # Create a market factor that affects all assets
    market_factor = np.cumprod(1 + np.random.normal(drift*1.5, volatility*0.8, days))
    
    data = {}
    for i in range(n_assets):
        # Each asset has correlation with market plus idiosyncratic moves
        asset_correlation = random.uniform(0.5, 0.9)
        idiosyncratic_vol = volatility * np.sqrt(1 - asset_correlation**2)
        
        # Generate returns that combine market and idiosyncratic components
        market_component = np.diff(np.log(market_factor), prepend=np.log(market_factor[0])) * asset_correlation
        idiosyncratic_component = np.random.normal(drift, idiosyncratic_vol, days)
        
        # Combine to get total returns
        total_returns = market_component + idiosyncratic_component
        
        # Convert returns to price series
        prices = 100 * np.cumprod(1 + total_returns)
        data[f'asset_{i}'] = prices
    
    return pd.DataFrame(data, index=dates)


def execute_market_neutral_strategy(
    model,
    price_data: pd.DataFrame, 
    horizon: int = 128,
    context_length: int = 512
) -> Tuple[pd.Series, Dict]:
    """
    Execute market neutral trading strategy based on the paper.
    
    Args:
        model: Prediction model (TimesFM, AR1, or Random)
        price_data: DataFrame with price data
        horizon: Trading horizon
        context_length: Context length for predictions
        
    Returns:
        Daily returns series and performance metrics
    """
    assets = price_data.columns
    n_assets = len(assets)
    trading_days = len(price_data) - horizon  # Reduce by horizon to have test data
    
    # Store positions and daily PnL
    positions = pd.DataFrame(0, index=price_data.index, columns=assets)
    daily_pnl = pd.Series(0, index=price_data.index)
    
    # Execute trading strategy
    for day in range(trading_days):
        day_positions = []
        
        # For each asset, predict and take position
        for asset in assets:
            # Get historical data
            historical_data = price_data[asset].iloc[max(0, day-context_length):day+1].values
            
            # Get current price and predict future
            current_price = historical_data[-1]
            predicted_prices = model.predict(historical_data, horizon=horizon)
            future_price = predicted_prices[-1]  # Price at horizon
            
            # Determine position (+1 for buy, -1 for sell)
            if future_price > current_price:
                position = 1
            else:
                position = -1
                
            day_positions.append(position)
        
        # Convert to market neutral by subtracting the mean
        day_positions = np.array(day_positions)
        day_positions = day_positions - np.mean(day_positions)
        
        # Scale positions to have fixed exposure
        if np.sum(np.abs(day_positions)) > 0:
            scaling_factor = 1.0 / (horizon - 1) / np.sum(np.abs(day_positions)) * n_assets
            day_positions = day_positions * scaling_factor
        
        # Record positions
        current_date = price_data.index[day+1]
        positions.loc[current_date, assets] = day_positions
        
        # Calculate PnL if we have held positions for the required horizon
        if day >= horizon:
            exit_date = price_data.index[day+1]
            entry_date = price_data.index[day-horizon+1]
            
            # Get prices at entry and exit
            entry_prices = price_data.loc[entry_date, assets].values
            exit_prices = price_data.loc[exit_date, assets].values
            
            # Get positions we took at entry
            entry_positions = positions.loc[entry_date, assets].values
            
            # Calculate PnL for this day's trades
            price_returns = (exit_prices - entry_prices) / entry_prices
            daily_pnl[exit_date] = np.sum(entry_positions * price_returns)
    
    # Calculate cumulative returns
    cumulative_pnl = daily_pnl.cumsum()
    
    # Calculate performance metrics
    trading_pnl = daily_pnl[~daily_pnl.isna() & (daily_pnl != 0)]
    
    if len(trading_pnl) > 0:
        ann_return = trading_pnl.mean() * 252
        ann_vol = trading_pnl.std() * np.sqrt(252)
        sharpe_ratio = ann_return / ann_vol if ann_vol > 0 else 0
        
        # Calculate maximum drawdown
        running_max = cumulative_pnl.cummax()
        drawdown = (cumulative_pnl - running_max) / running_max
        max_drawdown = drawdown.min() if len(drawdown) > 0 else 0
        
        # Calculate neutral cost
        if cumulative_pnl.iloc[-1] > 0:
            # How much cost would zero out returns
            neutral_cost = cumulative_pnl.iloc[-1] / (np.abs(positions).sum().sum() / 2)
        else:
            neutral_cost = 0
    else:
        ann_return = 0
        ann_vol = 0
        sharpe_ratio = 0
        max_drawdown = 0
        neutral_cost = 0
    
    metrics = {
        'Ann Returns': ann_return,
        'Ann Volatility': ann_vol,
        'Ann Sharpe': sharpe_ratio,
        'Max Drawdown': max_drawdown,
        'Neutral Cost (%)': neutral_cost * 100
    }
    
    return cumulative_pnl, metrics


def test_strategy():
    """Run tests of the trading strategy with different models and parameters."""
    
    # Generate synthetic market data
    print("Generating synthetic market data...")
    market_data = generate_synthetic_market(n_assets=50, days=1000)
    
    # Split into train/test sets
    train_data = market_data.iloc[:700]
    test_data = market_data.iloc[600:]  # Overlap to have sufficient context
    
    # Define models for testing
    models = {
        'Fine-tuned TimesFM': SimplifiedTimesFM(prediction_accuracy=0.58),
        'Original TimesFM': SimplifiedTimesFM(prediction_accuracy=0.51),
        'Random': RandomModel(),
        'AR1': AR1Model()
    }
    
    # Fit AR1 model on training data
    for asset in train_data.columns:
        models['AR1'].fit(train_data[asset].values)
    
    # Test horizons
    horizons = [32, 64, 128]
    
    # Store results
    results = {}
    
    # Run tests for each model and horizon
    for model_name, model in models.items():
        results[model_name] = {}
        for horizon in horizons:
            print(f"Testing {model_name} with horizon {horizon}...")
            try:
                pnl, metrics = execute_market_neutral_strategy(
                    model, 
                    test_data,
                    horizon=horizon
                )
                results[model_name][horizon] = {
                    'pnl': pnl,
                    'metrics': metrics
                }
            except Exception as e:
                print(f"Error testing {model_name} with horizon {horizon}: {e}")
    
    # Display results
    print("\n== RESULTS ==")
    for horizon in horizons:
        print(f"\nHorizon: {horizon}")
        
        # Compare Sharpe ratios
        print("Annual Sharpe Ratio:")
        for model_name in models.keys():
            if model_name in results and horizon in results[model_name]:
                sharpe = results[model_name][horizon]['metrics']['Ann Sharpe']
                print(f"  {model_name}: {sharpe:.2f}")
        
        # Compare neutral costs
        print("Neutral Cost (%):")
        for model_name in models.keys():
            if model_name in results and horizon in results[model_name]:
                cost = results[model_name][horizon]['metrics']['Neutral Cost (%)']
                print(f"  {model_name}: {cost:.2f}%")
    
    # Plot cumulative PnL for horizon 128
    plt.figure(figsize=(12, 6))
    for model_name, model_results in results.items():
        if 128 in model_results:
            pnl = model_results[128]['pnl']
            plt.plot(pnl.index, pnl.values, label=model_name)
    
    plt.title('Cumulative PnL - Horizon 128')
    plt.xlabel('Date')
    plt.ylabel('Cumulative PnL')
    plt.legend()
    plt.grid(True, alpha=0.3)
    plt.tight_layout()
    
    try:
        plt.savefig('pnl_comparison.png')
        print("\nPnL comparison chart saved as 'pnl_comparison.png'")
    except Exception as e:
        print(f"Could not save chart: {e}")
    
    try:
        plt.show()
    except Exception:
        print("Could not display chart (likely running in headless environment)")
    
    return results


