# Calculate volatility using GARCH model as mentioned in the paper
def calculate_volatility(returns_series):
    model = arch_model(returns_series, vol='GARCH', p=1, q=1)
    try:
        model_fit = model.fit(disp='off')
        volatility = pd.Series(np.sqrt(model_fit.conditional_volatility), index=returns_series.index)
        return volatility
    except:
        # Fallback to simpler method if GARCH fitting fails
        print("GARCH model fitting failed, using rolling standard deviation instead")
        return returns_series.rolling(window=21).std()

# Test for stationarity (ADF test)
def test_stationarity(series, series_name):
    result = adfuller(series.dropna())
    print(f"ADF test for {series_name}")
    print(f"ADF Statistic: {result[0]}")
    print(f"p-value: {result[1]}")
    print(f"Critical Values: {result[4]}")
    is_stationary = result[1] < 0.05
    print(f"Series is {'stationary' if is_stationary else 'non-stationary'}")
    return is_stationary

# Perform principal component analysis as described in the paper
def perform_pca(df):
    # Select variables for PCA
    variables = ['usd_cny_rate', 'cn_bond_yield', 'us_bond_yield']
    
    # Add lagged variables
    for var in variables:
        df[f"{var}_lag1"] = df[var].shift(1)
    
    # Add volatility and its lag
    df['volatility'] = calculate_volatility(df['shanghai_returns'])
    df['volatility_lag1'] = df['volatility'].shift(1)
    
    # Drop NAs
    df_clean = df.dropna()
    
    # Variables for PCA
    pca_vars = [
        'volatility_lag1',
        'usd_cny_rate', 'usd_cny_rate_lag1',
        'cn_bond_yield', 'cn_bond_yield_lag1',
        'us_bond_yield', 'us_bond_yield_lag1'
    ]
    
    # Standardize data
    df_std = (df_clean[pca_vars] - df_clean[pca_vars].mean()) / df_clean[pca_vars].std()
    
    # Perform PCA
    pca = PCA()
    principal_components = pca.fit_transform(df_std)
    
    # Print PCA results
    print("\nPrincipal Component Analysis Results:")
    print(f"Explained variance ratios: {pca.explained_variance_ratio_}")
    print("Component loadings:")
    for i, var in enumerate(pca_vars):
        print(f"{var}: {pca.components_[0][i]:.4f} (PC1), {pca.components_[1][i]:.4f} (PC2)")
    
    # Add first two principal components to dataframe
    df_clean['PC1'] = principal_components[:, 0]
    df_clean['PC2'] = principal_components[:, 1]
    
    return df_clean

# Run simple ARDL regression model
def run_ardl_model(df):
    # Create lagged variables of volatility
    df['volatility_lag1'] = df['volatility'].shift(1)
    df['volatility_lag2'] = df['volatility'].shift(2)
    
    # Create model formula
    X = df[['PC1', 'PC2', 'volatility_lag1', 'volatility_lag2']].dropna()
    y = df['volatility'].loc[X.index]
    
    # Use simple OLS regression as a proxy for ARDL
    from sklearn.linear_model import LinearRegression
    model = LinearRegression()
    model.fit(X, y)
    
    # Print results
    print("\nARDL Model Results (Simplified):")
    print(f"R² score: {model.score(X, y):.4f}")
    print("Coefficients:")
    for i, var in enumerate(['PC1', 'PC2', 'volatility_lag1', 'volatility_lag2']):
        print(f"{var}: {model.coef_[i]:.6f}")
    print(f"Intercept: {model.intercept_:.6f}")
    
    # Make predictions
    y_pred = model.predict(X)
    
    return y, y_pred

