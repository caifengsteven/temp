@dataclass
class ModelParameters:
    """Parameters for the stochastic control model"""
    A: Callable[[float], float]  # Drift coefficient for state
    B: Callable[[float], float]  # Control coefficient for drift
    C: Callable[[float], float]  # Constant term in drift
    I: Callable[[float], float]  # State coefficient for diffusion
    D: Callable[[float], float]  # Control coefficient for diffusion
    F: Callable[[float], float]  # Constant term in diffusion
    gamma: float                 # Risk aversion parameter
    T: float                     # Time horizon
    x0: float                    # Initial state

class TimeInconsistentControl:
    """Implementation of time-inconsistent stochastic control with higher-order moments"""
    
    def __init__(self, params: ModelParameters, 
                 phi: Callable[[List[float]], float],
                 n: int = 2):
        """
        Initialize the control model
        
        Args:
            params: Model parameters
            phi: Function of higher-order central moments
            n: Highest moment order divided by 2
        """
        self.params = params
        self.phi = phi
        self.n = n
        
        # Verify that D satisfies the assumption |D_t| >= ι > 0
        t_values = np.linspace(0, params.T, 100)
        D_values = np.array([params.D(t) for t in t_values])
        assert np.all(np.abs(D_values) > 1e-6), "D must satisfy |D_t| >= ι > 0"
        
        # Verify that B satisfies the assumption ∫_τ^T |B_s| ds > 0 for every τ ∈ [0,T)
        for tau in np.linspace(0, params.T * 0.9, 10):
            integral, _ = quad(lambda s: abs(params.B(s)), tau, params.T)
            assert integral > 0, f"B must satisfy ∫_{tau}^{params.T} |B_s| ds > 0"

    def mean_variance_equilibrium_control(self, t: float) -> float:
        """
        Calculate the mean-variance equilibrium control at time t
        
        Args:
            t: Current time
            
        Returns:
            The control value u_t
        """
        # Implementation of formula (5) from the paper
        def integrand(s):
            return self.params.A(s) - (self.params.B(s) / self.params.D(s)) * self.params.I(s)
        
        integral, _ = quad(integrand, t, self.params.T)
        exp_term = np.exp(-integral)
        
        return (self.params.B(t) / (self.params.gamma * (self.params.D(t)**2))) * exp_term - \
               (self.params.F(t) / self.params.D(t))
    
    def simulate_wealth_process(self, control_func: Callable[[float], float], 
                               num_paths: int = 1000, num_steps: int = 1000) -> np.ndarray:
        """
        Simulate the wealth process using the given control function
        
        Args:
            control_func: Function that returns control at time t
            num_paths: Number of simulation paths
            num_steps: Number of time steps
            
        Returns:
            Array of simulated wealth paths
        """
        dt = self.params.T / num_steps
        t_values = np.linspace(0, self.params.T, num_steps + 1)
        
        # Initialize paths
        X = np.zeros((num_paths, num_steps + 1))
        X[:, 0] = self.params.x0
        
        # Generate Brownian motion increments
        dW = np.random.normal(0, np.sqrt(dt), (num_paths, num_steps))
        
        # Simulate using Euler-Maruyama scheme
        for i in range(num_steps):
            t = t_values[i]
            u = control_func(t)
            
            drift = (self.params.A(t) * X[:, i] + 
                     self.params.B(t) * u + 
                     self.params.C(t)) * dt
                     
            diffusion = (self.params.I(t) * X[:, i] + 
                         self.params.D(t) * u + 
                         self.params.F(t)) * dW[:, i]
                         
            X[:, i+1] = X[:, i] + drift + diffusion
        
        return X, t_values
    
    def compute_moments(self, terminal_values: np.ndarray) -> dict:
        """
        Compute various moments of the terminal wealth distribution
        
        Args:
            terminal_values: Array of terminal wealth values from simulation
            
        Returns:
            Dictionary of moments
        """
        mean = np.mean(terminal_values)
        central_moments = {}
        
        for j in range(2, 2*self.n + 1):
            central_moments[j] = np.mean((terminal_values - mean)**j)
            
        return {
            'mean': mean,
            'variance': central_moments[2],
            'central_moments': central_moments,
            'skewness': central_moments[3] / (central_moments[2]**(3/2)) if central_moments[2] > 0 else 0,
            'kurtosis': central_moments[4] / (central_moments[2]**2) if central_moments[2] > 0 else 0
        }
    
    def compute_objective(self, terminal_values: np.ndarray) -> float:
        """
        Compute the objective functional value
        
        Args:
            terminal_values: Array of terminal wealth values
            
        Returns:
            Value of the objective functional
        """
        moments = self.compute_moments(terminal_values)
        mean = moments['mean']
        variance = moments['variance']
        
        # Extract higher-order central moments as a list
        higher_moments = [moments['central_moments'][j] for j in range(2, 2*self.n + 1)]
        
        # Compute mean-variance utility
        mv_utility = mean - (self.params.gamma / 2) * variance
        
        # Add higher-order moment term
        return mv_utility - self.phi(higher_moments)

def homogeneity_test_phi(moments: List[float]) -> float:
    """
    A phi function that satisfies the homogeneity condition (Assumption 2.3)
    This implements a standardized moment combination (skewness/kurtosis)
    
    Args:
        moments: List of central moments [m2, m3, ..., m2n]
        
    Returns:
        Value of phi
    """
    m2 = moments[0]  # Variance
    m3 = moments[1]  # Third central moment
    m4 = moments[2]  # Fourth central moment
    
    # Standardized skewness
    skewness = m3 / (m2**(3/2)) if m2 > 0 else 0
    
    # Standardized kurtosis
    kurtosis = m4 / (m2**2) if m2 > 0 else 0
    
    # Linear combination of standardized moments (satisfies homogeneity)
    return 0.1 * skewness - 0.05 * kurtosis

def non_homogeneity_test_phi(moments: List[float]) -> float:
    """
    A phi function that does NOT satisfy the homogeneity condition
    
    Args:
        moments: List of central moments [m2, m3, ..., m2n]
        
    Returns:
        Value of phi
    """
    m2 = moments[0]  # Variance
    m3 = moments[1]  # Third central moment
    
    # This doesn't satisfy the homogeneity condition due to the square root term
    return 0.1 * np.sqrt(m2) + 0.05 * abs(m3)

