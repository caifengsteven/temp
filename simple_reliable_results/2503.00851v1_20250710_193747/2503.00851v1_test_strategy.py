def simulate_price_path(n_days=250, intraday_obs=78, sigma=0.01, jump_prob=0.05, jump_size=0.03):
    """
    Simulate a price path with intraday observations and jumps
    """
    np.random.seed(42)
    total_obs = n_days * intraday_obs
    
    # Simulate continuous returns (without jumps)
    continuous_returns = np.random.normal(0, sigma, total_obs)
    
    # Add jumps
    jumps = np.random.binomial(1, jump_prob, total_obs) * np.random.normal(0, jump_size, total_obs)
    
    # Combine continuous and jump components
    returns = continuous_returns + jumps
    
    # Generate price path from returns
    prices = 100 * np.exp(np.cumsum(returns))
    
    return returns, prices


