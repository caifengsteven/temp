def simulate_hierarchical_stock_returns(n_stocks=50, n_days=1000, n_scales=3, seed=42):
    """
    Simulate stock returns with hierarchical structure following Matrix H-theory
    
    Parameters:
    -----------
    n_stocks : int
        Number of stocks to simulate
    n_days : int
        Number of days to simulate
    n_scales : int
        Number of hierarchical scales
    seed : int
        Random seed
        
    Returns:
    --------
    DataFrame : Simulated returns
    array : Background variance process
    """
    np.random.seed(seed)
    
    # Define parameters for hierarchical structure
    betas = [3.5, 6.6, 9.7][:n_scales]  # Based on the paper's optimal values for Wishart class
    gammas = [0.1, 0.2, 0.3][:n_scales]  # Decay rates
    kappas = [0.2, 0.3, 0.4][:n_scales]  # Noise amplitudes
    s = 0.5  # Exponent value for Wishart class
    
    # Initialize covariance matrix process at different scales
    epsilon = np.ones((n_scales+1, n_days+100))  # Add burn-in period
    epsilon[0] = 1.0  # Largest scale (constant)
    
    # Simulate hierarchical evolution following Eq. 3
    dt = 1.0
    for i in range(1, n_scales+1):
        for t in range(1, n_days+100):
            # Hierarchical evolution of internal degrees of freedom
            drift = -gammas[i-1] * (epsilon[i, t-1] - epsilon[i-1, t-1]) * dt
            diffusion = kappas[i-1] * (epsilon[i, t-1]**s) * (epsilon[i-1, t-1]**(1-s)) * np.random.normal(0, np.sqrt(dt))
            epsilon[i, t] = max(0.01, epsilon[i, t-1] + drift + diffusion)  # Ensure positivity
    
    # Remove burn-in period
    epsilon = epsilon[:, 100:]
    
    # Generate covariance matrix for each day
    # For simplicity, we'll use a block diagonal structure with correlation within sectors
    n_sectors = 5
    stocks_per_sector = n_stocks // n_sectors
    
    # Generate returns
    returns = np.zeros((n_stocks, n_days))
    for t in range(n_days):
        # Create base correlation matrix (block diagonal)
        corr_matrix = np.eye(n_stocks)
        for s in range(n_sectors):
            start_idx = s * stocks_per_sector
            end_idx = (s + 1) * stocks_per_sector
            # Within sector correlation
            corr_matrix[start_idx:end_idx, start_idx:end_idx] = 0.3
            np.fill_diagonal(corr_matrix, 1.0)
        
        # Scale by the hierarchical variance to get the covariance matrix
        cov_matrix = corr_matrix * epsilon[n_scales, t]
        
        # Generate multivariate normal returns
        returns[:, t] = np.random.multivariate_normal(np.zeros(n_stocks), cov_matrix)
    
    # Convert to DataFrame
    stock_names = [f'Stock_{i}' for i in range(n_stocks)]
    dates = pd.date_range(start='2020-01-01', periods=n_days)
    returns_df = pd.DataFrame(returns.T, index=dates, columns=stock_names)
    
    return returns_df, epsilon[n_scales]


def estimate_background_variances(returns, window_size=14):
    """
    Estimate background variances from return series
    
    Parameters:
    -----------
    returns : array-like
        Return series
    window_size : int
        Rolling window size for variance estimation
        
    Returns:
    --------
    array : Estimated variances
    """
    if isinstance(returns, pd.DataFrame):
        # If DataFrame, convert to flattened array
        returns_array = returns.values.flatten()
    else:
        returns_array = returns
    
    # Normalize returns
    normalized_returns = (returns_array - np.mean(returns_array)) / np.std(returns_array)
    
    # Calculate rolling variances
    variances = []
    for i in range(window_size, len(normalized_returns)):
        window = normalized_returns[i-window_size:i]
        variances.append(np.var(window))
    
    return np.array(variances)


