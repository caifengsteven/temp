def compare_action_distributions(fixed_fees_actions, variable_fees_actions):
    """Compare action distributions between fixed and variable fees models"""
    fixed_diffs = []
    variable_diffs = []
    
    # Calculate action differences (order sizes)
    for day_actions in fixed_fees_actions:
        for i in range(1, len(day_actions)):
            fixed_diffs.append(abs(day_actions[i] - day_actions[i-1]))
    
    for day_actions in variable_fees_actions:
        for i in range(1, len(day_actions)):
            variable_diffs.append(abs(day_actions[i] - day_actions[i-1]))
    
    plt.figure(figsize=(12, 6))
    
    plt.subplot(1, 2, 1)
    plt.hist(fixed_diffs, bins=20, alpha=0.7, label='Fixed Fees')
    plt.title('Order Size Distribution - Fixed Fees')
    plt.xlabel('Order Size')
    plt.ylabel('Frequency')
    
    plt.subplot(1, 2, 2)
    plt.hist(variable_diffs, bins=20, alpha=0.7, label='Variable Fees')
    plt.title('Order Size Distribution - Variable Fees')
    plt.xlabel('Order Size')
    plt.ylabel('Frequency')
    
    plt.tight_layout()
    plt.show()

def compare_reward_distributions(risk_neutral_rewards, risk_averse_rewards, risk_param, risk_measure):
    """Compare reward distributions between risk-neutral and risk-averse models"""
    # Flatten rewards
    risk_neutral_flat = [r for day_rewards in risk_neutral_rewards for r in day_rewards]
    risk_averse_flat = [r for day_rewards in risk_averse_rewards for r in day_rewards]
    
    plt.figure(figsize=(10, 6))
    
    # Plot distributions
    plt.hist(risk_neutral_flat, bins=30, alpha=0.5, label='Risk-Neutral')
    plt.hist(risk_averse_flat, bins=30, alpha=0.5, label=f'Risk-Averse ({risk_measure}, param={risk_param})')
    
    plt.title('Reward Distribution Comparison')
    plt.xlabel('Reward')
    plt.ylabel('Frequency')
    plt.legend()
    plt.grid(True)
    plt.show()
    
    # Calculate statistics
    rn_mean = np.mean(risk_neutral_flat)
    rn_std = np.std(risk_neutral_flat)
    ra_mean = np.mean(risk_averse_flat)
    ra_std = np.std(risk_averse_flat)
    
    print(f"Risk-Neutral: Mean={rn_mean:.2f}, Std={rn_std:.2f}")
    print(f"Risk-Averse: Mean={ra_mean:.2f}, Std={ra_std:.2f}")
    print(f"Std Reduction: {(1 - ra_std/rn_std)*100:.2f}%")

