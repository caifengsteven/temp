    def generate_stock_data(self):
        """Generate simulated stock price data"""
        stocks_data = {}
        
        # Generate sample tickers (S&P-like)
        tickers = [f"STOCK_{i}" for i in range(1, self.n_stocks + 1)]
        
        for ticker in tickers:
            # Start with a price between 50 and 200
            start_price = np.random.uniform(50, 200)
            
            # Generate daily returns with slight upward drift
            daily_returns = np.random.normal(0.0005, self.volatility, self.n_days)
            
            # Calculate price series
            prices = [start_price]
            for ret in daily_returns:
                prices.append(prices[-1] * (1 + ret))
            
            # Generate trading volume
            volume = np.random.normal(1000000, 300000, self.n_days + 1)
            volume = np.abs(volume).astype(int)
            
            # Create dataframe
            dates = pd.date_range(end='2024-10-25', periods=self.n_days + 1)
            df = pd.DataFrame({
                'Date': dates,
                'Close': prices,
                'Volume': volume
            })
            
            # Calculate returns
            df['Return'] = df['Close'].pct_change().fillna(0)
            
            # Calculate RSI (14-day)
            delta = df['Close'].diff().fillna(0)
            gain = (delta.where(delta > 0, 0)).rolling(window=14).mean()
            loss = (-delta.where(delta < 0, 0)).rolling(window=14).mean()
            rs = gain / loss
            df['RSI'] = 100 - (100 / (1 + rs))
            df['RSI'].fillna(50, inplace=True)
            
            # Calculate volatility (5-day)
            df['Volatility'] = df['Return'].rolling(window=5).std().fillna(0)
            
            stocks_data[ticker] = df
            
        return stocks_data, tickers
    
    def prepare_model_data(self, stocks_data, tickers, look_back=10):
        """Prepare features and targets for model training"""
        X_all = []
        y_all = []
        
        for ticker in tickers:
            df = stocks_data[ticker]
            
            # Prepare features
            features = df[['Return', 'RSI', 'Volume', 'Volatility']].values
            
            # Scale features
            scaler = StandardScaler()
            features_scaled = scaler.fit_transform(features)
            
            # Create sequences
            X, y = [], []
            for i in range(look_back, len(df) - 1):
                X.append(features_scaled[i-look_back:i])
                y.append(df['Return'].values[i+1])  # Next day's return
                
            X_all.extend(X)
            y_all.extend(y)
            
        return np.array(X_all), np.array(y_all)
    
