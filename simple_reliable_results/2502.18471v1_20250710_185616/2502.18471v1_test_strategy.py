    def process_data_request(self, structured_request: Dict) -> Dict:
        """Process a structured data request and return relevant financial data"""
        companies = structured_request.get("companies", [])
        metrics = structured_request.get("metrics", [])
        date_range = structured_request.get("date_range", {})
        
        # Extract date range if provided
        start_date = None
        end_date = None
        if date_range:
            start_date_str = date_range.get("start")
            end_date_str = date_range.get("end")
            
            if start_date_str:
                start_date = datetime.strptime(start_date_str, "%Y-%m-%d")
            if end_date_str:
                end_date = datetime.strptime(end_date_str, "%Y-%m-%d")
        
        # If no date range specified, use latest data
        if not start_date and not end_date:
            end_date = datetime.now()
            start_date = end_date - timedelta(days=180)  # Default to last 6 months
        
        # Collect data for requested companies and metrics
        result = {
            "financial_data": {},
            "relevant_news": []
        }
        
        for company in companies:
            if company in self.financial_metrics.companies or company.endswith(" Peers"):
                # Handle company peers case
                if company.endswith(" Peers"):
                    base_company = company.replace(" Peers", "")
                    if base_company in self.financial_metrics.companies:
                        sector = self.financial_metrics.companies[base_company]["sector"]
                        company_list = [c for c, info in self.financial_metrics.companies.items() 
                                      if info["sector"] == sector and c != base_company]
                    else:
                        company_list = []
                else:
                    company_list = [company]
                
                for actual_company in company_list:
                    if actual_company not in result["financial_data"]:
                        result["financial_data"][actual_company] = {}
                    
                    # Get data for requested metrics
                    for metric in metrics:
                        if metric in self.financial_metrics.metrics_data.get(actual_company, {}):
                            # Filter data by date range
                            filtered_data = []
                            for entry in self.financial_metrics.metrics_data[actual_company][metric]:
                                entry_date = datetime.strptime(entry["date"], "%Y-%m-%d")
                                if ((not start_date or entry_date >= start_date) and
                                    (not end_date or entry_date <= end_date)):
                                    filtered_data.append(entry)
                            
                            if filtered_data:
                                result["financial_data"][actual_company][metric] = filtered_data
            
            # Get related news
            for news in self.financial_metrics.news_data:
                news_date = datetime.strptime(news["date"], "%Y-%m-%d")
                if ((not start_date or news_date >= start_date) and
                    (not end_date or news_date <= end_date)):
                    if company in news["company"] or company in news["headline"]:
                        # Check if news mentions any of the requested metrics
                        for metric in metrics:
                            if metric in news["headline"] or metric in news["content"]:
                                result["relevant_news"].append(news)
                                break
        
        return result


