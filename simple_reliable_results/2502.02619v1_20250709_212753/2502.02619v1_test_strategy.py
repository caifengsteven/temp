class PortfolioEnv(gym.Env):
    """
    Portfolio optimization environment using the regret-based approach
    from the "Regret-Optimized Portfolio Enhancement through Deep Reinforcement Learning" paper
    """
    
    def __init__(self, 
                 df: pd.DataFrame,
                 window_size: int = 60,
                 return_lookback: int = 40,
                 std_lookback: int = 60,
                 future_window: int = 14,
                 tc_max: float = 0.0025,
                 tc_scheduler_steps: int = 500,
                 tc_alpha: float = 1.0,
                 episode_length: int = 252):
        
        super(PortfolioEnv, self).__init__()
        
        # Store data and parameters
        self.df = df
        self.window_size = window_size
        self.return_lookback = return_lookback
        self.std_lookback = std_lookback
        self.future_window = future_window
        self.tc_max = tc_max
        self.tc_scheduler_steps = tc_scheduler_steps
        self.tc_alpha = tc_alpha
        self.episode_length = episode_length
        self.risk_free_rate = 0.0
        
        # Portfolio parameters
        self.n_assets = 3  # DevEquity, 60/40, Govies
        
        # Define action and observation spaces
        self.action_space = spaces.Box(low=0, high=1, shape=(self.n_assets,), dtype=np.float32)
        
        # Observation: asset returns, index returns, rolling returns, std deviations, previous weights, TC
        obs_dim = (3 + 3 + 3 + 3 + 3 + 3 + 1)
        self.observation_space = spaces.Box(low=-np.inf, high=np.inf, shape=(obs_dim,), dtype=np.float32)
        
        # Initialize variables
        self._reset_state()
        
    def _reset_state(self):
        self.current_step = self.window_size
        self.weights = np.array([0.0, 1.0, 0.0])  # Start with 60/40 portfolio
        self.total_steps = 0
        
    def calculate_transaction_cost(self, old_weights, new_weights):
        """Calculate transaction costs based on L1 norm of weight changes"""
        tc_current = self.get_current_tc()
        return tc_current * np.sum(np.abs(new_weights - old_weights))
    
    def get_current_tc(self):
        """Implement transaction cost scheduler"""
        if self.total_steps >= self.tc_scheduler_steps:
            return self.tc_max
        else:
            # Schedule transaction costs according to Equation 7 in the paper
            x = self.total_steps
            return (self.tc_max / (self.tc_scheduler_steps ** self.tc_alpha)) * (x ** self.tc_alpha)
    
    def reset(self):
        self._reset_state()
        return self._get_observation()
    
    def _get_observation(self):
        """Create observation vector from current state"""
        idx = self.current_step
        
        # Daily returns for assets
        asset_returns = self.df.iloc[idx, :3].values
        
        # Daily returns for indices
        index_returns = self.df.iloc[idx, 3:6].values
        
        # Rolling return over past 40 days
        rolling_returns = np.array([
            self.df.iloc[idx-self.return_lookback:idx, i].mean() 
            for i in range(3)
        ])
        
        # Rolling std over past 60 days for assets
        asset_stds = np.array([
            self.df.iloc[idx-self.std_lookback:idx, i].std() 
            for i in range(3)
        ])
        
        # Rolling std over past 60 days for indices
        index_stds = np.array([
            self.df.iloc[idx-self.std_lookback:idx, i+3].std() 
            for i in range(3)
        ])
        
        # Previous weights
        prev_weights = self.weights
        
        # Current transaction cost
        current_tc = np.array([self.get_current_tc()])
        
        # Combine into observation vector
        obs = np.concatenate([
            asset_returns, index_returns, rolling_returns, 
            asset_stds, index_stds, prev_weights, current_tc
        ])
        
        return obs
    
    def _calculate_future_returns(self):
        """Calculate future returns for Oracle knowledge"""
        idx = self.current_step
        future_returns = np.array([
            self.df.iloc[idx:idx+self.future_window, i].mean() 
            for i in range(3)
        ])
        return future_returns
    
    def _calculate_covariance(self):
        """Calculate covariance matrix for Sharpe calculation"""
        idx = self.current_step
        start_idx = idx - (3 * self.future_window)
        end_idx = idx + (3 * self.future_window)
        
        # Ensure indices are within bounds
        start_idx = max(0, start_idx)
        end_idx = min(len(self.df), end_idx)
        
        # Extract returns for the period
        returns = self.df.iloc[start_idx:end_idx, :3].values
        
        # Calculate covariance matrix
        cov_matrix = np.cov(returns.T)
        return cov_matrix
    
    def _find_optimal_weights(self, future_returns, cov_matrix, prev_weights):
        """
        Find optimal weights that maximize Sharpe ratio 
        considering transaction costs, as defined in Equation 9
        """
        # For simplicity in this example, we'll use a grid search approach
        # In a real implementation, this would use quadratic programming
        
        best_sharpe = -np.inf
        best_weights = np.array([0.33, 0.34, 0.33])  # Default balanced weights
        
        # Generate weight combinations that sum to 1
        for w1 in np.linspace(0, 1, 11):
            for w2 in np.linspace(0, 1, 11):
                if w1 + w2 <= 1:
                    w3 = 1 - w1 - w2
                    weights = np.array([w1, w2, w3])
                    
                    # Calculate portfolio return and risk
                    port_return = np.dot(weights, future_returns)
                    port_risk = np.sqrt(weights.T @ cov_matrix @ weights)
                    
                    # Avoid division by zero
                    if port_risk == 0:
                        port_risk = 1e-6
                    
                    # Calculate Sharpe ratio
                    sharpe = (port_return - self.risk_free_rate) / port_risk
                    
                    # Subtract transaction costs
                    tc = self.calculate_transaction_cost(prev_weights, weights)
                    adjusted_sharpe = sharpe - tc
                    
                    if adjusted_sharpe > best_sharpe:
                        best_sharpe = adjusted_sharpe
                        best_weights = weights
        
        return best_weights
    
    def _calculate_reward(self, weights, optimal_weights, future_returns):
        """
        Calculate reward based on negative Sharpe regret 
        as defined in Equation 8
        """
        # Negative of the difference in returns between optimal and taken actions
        reward = -np.dot(future_returns, (optimal_weights - weights))
        return reward
    
    def step(self, action):
        # Ensure action is a valid allocation (sums to 1)
        action = np.array(action, dtype=np.float32)
        action = np.clip(action, 0, 1)
        action = action / action.sum()
        
        # Store previous weights
        prev_weights = self.weights
        
        # Update weights
        self.weights = action
        
        # Calculate transaction costs
        tc = self.calculate_transaction_cost(prev_weights, self.weights)
        
        # Get future returns for Oracle calculation
        future_returns = self._calculate_future_returns()
        
        # Calculate covariance matrix
        cov_matrix = self._calculate_covariance()
        
        # Find optimal weights
        optimal_weights = self._find_optimal_weights(future_returns, cov_matrix, prev_weights)
        
        # Calculate reward
        reward = self._calculate_reward(self.weights, optimal_weights, future_returns)
        
        # Update current step
        self.current_step += 1
        self.total_steps += 1
        
        # Check if episode is done
        done = self.current_step >= len(self.df) - self.future_window or self.total_steps >= self.episode_length
        
        # Get new observation
        obs = self._get_observation()
        
        info = {
            "portfolio_return": np.dot(self.weights, self.df.iloc[self.current_step, :3].values),
            "transaction_cost": tc,
            "optimal_weights": optimal_weights,
            "future_returns": future_returns
        }
        
        return obs, reward, done, info


class CircularBlockBootstrap:
    """
    Implements circular block bootstrap method for synthetic data generation
    as described in the paper
    """
    
    def __init__(self, data, block_size_ratio=0.8):
        self.data = data
        self.block_size = int(len(data) * block_size_ratio)
        
    def generate(self):
        """Generate synthetic data using circular block bootstrap"""
        result = pd.DataFrame(columns=self.data.columns)
        
        # Determine number of blocks needed to match original data length
        n_blocks = int(np.ceil(len(self.data) / self.block_size))
        
        # Generate synthetic data
        for _ in range(n_blocks):
            # Randomly select block start
            start_idx = np.random.randint(0, len(self.data))
            
            # Handle circular wrapping
            indices = [(start_idx + i) % len(self.data) for i in range(self.block_size)]
            block = self.data.iloc[indices].copy()
            
            # Append block to result
            result = pd.concat([result, block])
            
        # Trim to match original length
        result = result.iloc[:len(self.data)].reset_index(drop=True)
        
        return result


def generate_test_data(days=1000, seed=42):
    """Generate synthetic price data for testing"""
    np.random.seed(seed)
    
    # Generate dates
    start_date = datetime(2010, 1, 1)
    dates = [start_date + timedelta(days=i) for i in range(days)]
    
    # Price paths with realistic correlations and volatilities
    # Initial prices
    prices = np.zeros((days, 6))
    prices[0, 0] = 100  # DevEquity
    prices[0, 1] = 100  # 60/40
    prices[0, 2] = 100  # Govies
    prices[0, 3] = 20   # VIX
    prices[0, 4] = 5    # High-Yield Bond Spread
    prices[0, 5] = 15   # Option Volatility
    
    # Mean returns and volatilities
    mean_returns = np.array([0.08, 0.06, 0.03, 0.0, 0.0, 0.0]) / 252
    volatilities = np.array([0.18, 0.12, 0.05, 0.3, 0.2, 0.25]) / np.sqrt(252)
    
    # Correlation matrix
    corr = np.array([
        [1.0, 0.8, 0.2, -0.7, -0.6, -0.7],  # DevEquity
        [0.8, 1.0, 0.6, -0.6, -0.5, -0.6],  # 60/40
        [0.2, 0.6, 1.0, -0.3, -0.3, -0.3],  # Govies
        [-0.7, -0.6, -0.3, 1.0, 0.7, 0.8],  # VIX
        [-0.6, -0.5, -0.3, 0.7, 1.0, 0.7],  # High-Yield Bond Spread
        [-0.7, -0.6, -0.3, 0.8, 0.7, 1.0]   # Option Volatility
    ])
    
    # Construct covariance matrix
    cov = np.diag(volatilities) @ corr @ np.diag(volatilities)
    
    # Generate correlated returns
    returns = np.random.multivariate_normal(mean_returns, cov, size=days-1)
    
    # Convert returns to prices
    for i in range(1, days):
        prices[i] = prices[i-1] * (1 + returns[i-1])
    
    # Create DataFrame
    df = pd.DataFrame(
        prices, 
        columns=['DevEquity', '60/40', 'Govies', 'VIX', 'HYSpread', 'OptVol']
    )
    df['Date'] = dates
    
    # Convert prices to returns for the environment
    returns_df = df.iloc[:, 0:6].pct_change().fillna(0)
    returns_df['Date'] = dates
    
    return df, returns_df


def calculate_metrics(returns, benchmark_returns=None):
    """Calculate financial metrics for evaluation"""
    cumulative_returns = (1 + returns).cumprod() - 1
    
    # Annual return
    annual_return = (1 + cumulative_returns.iloc[-1]) ** (252 / len(returns)) - 1
    
    # Volatility
    volatility = returns.std() * np.sqrt(252)
    
    # Sharpe ratio
    sharpe_ratio = annual_return / volatility if volatility > 0 else 0
    
    # Maximum drawdown
    cumulative_max = cumulative_returns.cummax()
    drawdown = (cumulative_returns - cumulative_max) / (1 + cumulative_max)
    max_drawdown = drawdown.min()
    
    # Calmar ratio
    calmar_ratio = annual_return / abs(max_drawdown) if max_drawdown != 0 else 0
    
    # Calculate relative metrics if benchmark is provided
    outperformance = None
    if benchmark_returns is not None:
        benchmark_cum_returns = (1 + benchmark_returns).cumprod() - 1
        benchmark_annual_return = (1 + benchmark_cum_returns.iloc[-1]) ** (252 / len(benchmark_returns)) - 1
        outperformance = annual_return - benchmark_annual_return
    
    return {
        "annual_return": annual_return,
        "volatility": volatility,
        "sharpe_ratio": sharpe_ratio,
        "max_drawdown": max_drawdown,
        "calmar_ratio": calmar_ratio,
        "outperformance": outperformance
    }


