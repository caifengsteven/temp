# Constants based on the paper
T = 1.0  # Trading horizon (1 day)
S0 = 2820  # Initial exchange rate (ETH-USDC)
Z0 = S0  # Initial pool exchange rate
sigma = 0.0569 * S0  # Daily volatility
xi = 300  # Average traded quantity in 10-min window
r = 0.01 * xi * Z0  # Fee collected by venue per transaction
Y0 = 50000  # Initial ETH in pool
c0 = Y0 * (Y0 * Z0)  # Initial pool depth
eta = 1e-10  # Volatility of liquidity provision
gamma = 1e-18  # LP's risk aversion
zeta = 1e-6  # Venue's risk aversion
a = 1e-14  # Temporary price impact in external venue
a1 = 142.7  # Baseline intensity
a2 = 1e-5  # Sensitivity of order flow to pool depth
a3 = 13.6  # Arbitrage sensitivity
a0 = 0.1  # Minimum intensity
