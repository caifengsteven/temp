# Define xLSTM Cell
class xLSTMCell(nn.Module):
    def __init__(self, input_size, hidden_size):
        super(xLSTMCell, self).__init__()
        self.input_size = input_size
        self.hidden_size = hidden_size
        
        # xLSTM parameters - simplified implementation
        self.Wi = nn.Linear(input_size, hidden_size)
        self.Wf = nn.Linear(input_size, hidden_size)
        self.Wo = nn.Linear(input_size, hidden_size)
        self.Wg = nn.Linear(input_size, hidden_size)
        
        self.Ui = nn.Linear(hidden_size, hidden_size)
        self.Uf = nn.Linear(hidden_size, hidden_size)
        self.Uo = nn.Linear(hidden_size, hidden_size)
        self.Ug = nn.Linear(hidden_size, hidden_size)
        
        # Exponential gating - one of xLSTM's improvements
        self.exp_gate = nn.Linear(hidden_size, hidden_size)
        
    def forward(self, x, hidden=None):
        if hidden is None:
            h_prev = torch.zeros(x.size(0), self.hidden_size, device=x.device)
            c_prev = torch.zeros(x.size(0), self.hidden_size, device=x.device)
        else:
            h_prev, c_prev = hidden
            
        # Gates with exponential activation for improved gradient flow
        i = torch.sigmoid(self.Wi(x) + self.Ui(h_prev))
        f = torch.sigmoid(self.Wf(x) + self.Uf(h_prev))
        o = torch.sigmoid(self.Wo(x) + self.Uo(h_prev))
        g = torch.tanh(self.Wg(x) + self.Ug(h_prev))
        
        # xLSTM memory update with exponential mechanism
        exp_gate = torch.exp(self.exp_gate(h_prev))
        c = f * c_prev + i * g + torch.tanh(exp_gate * c_prev)  # Modified memory mixing
        h = o * torch.tanh(c)
        
        return h, (h, c)

# xLSTM Network
class xLSTM(nn.Module):
    def __init__(self, input_size, hidden_size, num_layers=1):
        super(xLSTM, self).__init__()
        self.hidden_size = hidden_size
        self.num_layers = num_layers
        
        self.cells = nn.ModuleList([
            xLSTMCell(input_size if i == 0 else hidden_size, hidden_size)
            for i in range(num_layers)
        ])
        
    def forward(self, x, hidden=None):
        # x shape: [batch, sequence, features]
        batch_size, seq_len, _ = x.size()
        
        if hidden is None:
            hidden = [(torch.zeros(batch_size, self.hidden_size, device=x.device),
                      torch.zeros(batch_size, self.hidden_size, device=x.device))
                     for _ in range(self.num_layers)]
        
        outputs = []
        for t in range(seq_len):
            layer_input = x[:, t, :]
            for i, cell in enumerate(self.cells):
                h, c = hidden[i]
                h, hidden[i] = cell(layer_input, (h, c))
                layer_input = h
            
            outputs.append(h)
            
        outputs = torch.stack(outputs, dim=1)  # [batch, sequence, hidden]
        return outputs, hidden

# Actor network with xLSTM
class Actor(nn.Module):
    def __init__(self, state_dim, action_dim, hidden_dim=128):
        super(Actor, self).__init__()
        self.xlstm = xLSTM(state_dim, hidden_dim)
        self.mu_head = nn.Linear(hidden_dim, action_dim)
        self.sigma_head = nn.Linear(hidden_dim, action_dim)
        
    def forward(self, state, hidden=None):
        x, hidden = self.xlstm(state, hidden)
        mu = torch.tanh(self.mu_head(x[:, -1, :]))  # Use only the last output
        sigma = torch.softplus(self.sigma_head(x[:, -1, :])) + 0.001
        return mu, sigma, hidden
    
    def get_action(self, state, hidden=None):
        mu, sigma, hidden = self.forward(state, hidden)
        dist = Normal(mu, sigma)
        action = dist.sample()
        return action, dist.log_prob(action), hidden

# Critic network with xLSTM
class Critic(nn.Module):
    def __init__(self, state_dim, hidden_dim=128):
        super(Critic, self).__init__()
        self.xlstm = xLSTM(state_dim, hidden_dim)
        self.value_head = nn.Linear(hidden_dim, 1)
        
    def forward(self, state, hidden=None):
        x, hidden = self.xlstm(state, hidden)
        value = self.value_head(x[:, -1, :])  # Use only the last output
        return value, hidden

# PPO Agent
class PPOAgent:
    def __init__(self, state_dim, action_dim, hidden_dim=128, lr=0.001, gamma=0.99, clip_ratio=0.2):
        self.actor = Actor(state_dim, action_dim, hidden_dim)
        self.critic = Critic(state_dim, hidden_dim)
        self.actor_optimizer = optim.Adam(self.actor.parameters(), lr=lr)
        self.critic_optimizer = optim.Adam(self.critic.parameters(), lr=lr)
        self.gamma = gamma
        self.clip_ratio = clip_ratio
        self.memory = deque(maxlen=10000)
        
    def select_action(self, state, actor_hidden=None, critic_hidden=None):
        state = torch.FloatTensor(state).unsqueeze(0)  # Add batch dimension
        action, log_prob, new_actor_hidden = self.actor.get_action(state, actor_hidden)
        value, new_critic_hidden = self.critic(state, critic_hidden)
        
        return action.detach().numpy()[0], log_prob.detach().numpy()[0], value.detach().numpy()[0], new_actor_hidden, new_critic_hidden
    
    def store_transition(self, state, action, reward, next_state, log_prob, value, done):
        self.memory.append((state, action, reward, next_state, log_prob, value, done))
    
    def update(self, batch_size=32, epochs=10):
        if len(self.memory) < batch_size:
            return
        
        # Sample batch from memory
        indices = np.random.choice(len(self.memory), batch_size, replace=False)
        states, actions, rewards, next_states, log_probs_old, values, dones = zip(*[self.memory[i] for i in indices])
        
        states = torch.FloatTensor(np.array(states))
        actions = torch.FloatTensor(np.array(actions))
        rewards = torch.FloatTensor(np.array(rewards)).unsqueeze(1)
        next_states = torch.FloatTensor(np.array(next_states))
        log_probs_old = torch.FloatTensor(np.array(log_probs_old)).unsqueeze(1)
        values = torch.FloatTensor(np.array(values)).unsqueeze(1)
        dones = torch.FloatTensor(np.array(dones)).unsqueeze(1)
        
        # Calculate returns and advantages
        next_values, _ = self.critic(next_states)
        returns = rewards + self.gamma * next_values * (1 - dones)
        advantages = returns - values
        
        for _ in range(epochs):
            # Recalculate log probs and values for the current policy
            mu, sigma, _ = self.actor(states)
            dist = Normal(mu, sigma)
            log_probs = dist.log_prob(actions).unsqueeze(1)
            values, _ = self.critic(states)
            
            # Calculate ratio and PPO loss
            ratio = torch.exp(log_probs - log_probs_old)
            clip = torch.clamp(ratio, 1 - self.clip_ratio, 1 + self.clip_ratio)
            actor_loss = -torch.min(ratio * advantages, clip * advantages).mean()
            
            # Calculate critic loss
            critic_loss = nn.MSELoss()(values, returns)
            
            # Update actor
            self.actor_optimizer.zero_grad()
            actor_loss.backward()
            self.actor_optimizer.step()
            
            # Update critic
            self.critic_optimizer.zero_grad()
            critic_loss.backward()
            self.critic_optimizer.step()

# Stock Trading Environment
class StockTradingEnv(gym.Env):
    def __init__(self, data, initial_balance=1000000, transaction_cost_pct=0.001, window_size=30):
        super(StockTradingEnv, self).__init__()
        self.data = data
        self.initial_balance = initial_balance
        self.transaction_cost_pct = transaction_cost_pct
        self.window_size = window_size
        
        # Define action and observation space
        self.action_space = spaces.Box(low=-1, high=1, shape=(len(self.data.columns)-1,))  # Action for each stock
        
        # Features + balance + shares for each stock
        self.observation_space = spaces.Box(
            low=0, high=np.inf, shape=(window_size, len(self.data.columns) * 2)
        )
        
        self.reset()
        
    def reset(self):
        self.current_step = self.window_size
        self.balance = self.initial_balance
        self.shares_held = np.zeros(len(self.data.columns)-1)  # Initialize with no shares
        self.asset_value = self.initial_balance
        self.total_asset_history = [self.asset_value]
        self.rewards_history = []
        
        return self._get_observation()
    
    def step(self, actions):
        # Get current prices
        current_prices = self.data.iloc[self.current_step, 1:].values  # Skip date column
        
        # Calculate transaction costs
        transaction_costs = 0
        
        # Execute trades based on actions (-1 to 1 scaled to sell all or buy max possible)
        for i, action in enumerate(actions):
            if action > 0:  # Buy
                shares_to_buy = (action * self.balance) / current_prices[i]
                cost = shares_to_buy * current_prices[i]
                transaction_cost = cost * self.transaction_cost_pct
                if self.balance >= (cost + transaction_cost):
                    self.shares_held[i] += shares_to_buy
                    self.balance -= (cost + transaction_cost)
                    transaction_costs += transaction_cost
            elif action < 0:  # Sell
                shares_to_sell = -action * self.shares_held[i]
                revenue = shares_to_sell * current_prices[i]
                transaction_cost = revenue * self.transaction_cost_pct
                self.shares_held[i] -= shares_to_sell
                self.balance += (revenue - transaction_cost)
                transaction_costs += transaction_cost
        
        # Move to the next day
        self.current_step += 1
        
        # Calculate new asset value
        prev_asset_value = self.asset_value
        self.asset_value = self.balance + np.sum(self.shares_held * current_prices)
        self.total_asset_history.append(self.asset_value)
        
        # Calculate reward
        reward = (self.asset_value - prev_asset_value) - transaction_costs
        
        # Check if done
        done = self.current_step >= len(self.data) - 1
        
        # Store reward
        self.rewards_history.append(reward)
        
        return self._get_observation(), reward, done, {}
    
    def _get_observation(self):
        # Get the window of data
        data_window = self.data.iloc[self.current_step-self.window_size:self.current_step]
        
        # Extract features (normalize by dividing by the first value in the window)
        price_features = data_window.iloc[:, 1:].values
        first_prices = price_features[0]
        normalized_prices = price_features / first_prices
        
        # Combine with portfolio information
        portfolio_info = np.column_stack([
            np.repeat(self.balance / self.initial_balance, self.window_size).reshape(-1, 1),
            np.repeat(self.shares_held.reshape(1, -1), self.window_size, axis=0)
        ])
        
        return np.column_stack([normalized_prices, portfolio_info])
    
    def render(self, mode='human'):
        profit_percent = (self.asset_value - self.initial_balance) / self.initial_balance * 100
        print(f"Step: {self.current_step}, Asset Value: ${self.asset_value:.2f}, "
              f"Profit: {profit_percent:.2f}%, Balance: ${self.balance:.2f}, "
              f"Shares: {self.shares_held}")

# Generate simulated stock data
def generate_stock_data(num_days=1000, num_stocks=5):
    # Generate dates
    end_date = datetime(2022, 1, 1)
    start_date = end_date - timedelta(days=num_days)
    dates = pd.date_range(start=start_date, end=end_date, freq='D')
    
    # Create dataframe with dates
    df = pd.DataFrame({'Date': dates})
    
    # Generate price data for each stock
    stock_names = ['AAPL', 'MSFT', 'NVDA', 'GOOGL', 'AMZN'][:num_stocks]
    for stock in stock_names:
        # Start with a random price between 50 and 200
        price = np.random.uniform(50, 200)
        prices = [price]
        
        # Generate a price series with some random walk and momentum
        for _ in range(1, len(dates)):
            # Random daily change percentage (-3% to +3%) with momentum
            momentum = 0.6 * (prices[-1] - prices[-2]) if len(prices) > 1 else 0
            daily_return = np.random.normal(0.0005, 0.015) + momentum / prices[-1]
            price = price * (1 + daily_return)
            prices.append(max(price, 1))  # Ensure price doesn't go below 1
            
        df[stock] = prices
    
    # Calculate turbulence index (simplified version)
    returns = df.iloc[:, 1:].pct_change().dropna()
    cov_matrix = returns.cov()
    turbulence = np.zeros(len(df))
    
    for i in range(len(returns)):
        if i > 0:
            ret = returns.iloc[i].values.reshape(1, -1)
            turbulence[i+1] = np.sqrt(ret @ np.linalg.pinv(cov_matrix) @ ret.T)[0][0]
    
    df['Turbulence'] = turbulence
    
    return df

# Function to calculate evaluation metrics
def calculate_metrics(env):
    # Cumulative Return (CR)
    final_value = env.total_asset_history[-1]
    cr = (final_value - env.initial_balance) / env.initial_balance
    
    # Max Earning Rate (MER)
    max_value = max(env.total_asset_history)
    mer = (max_value - env.initial_balance) / env.initial_balance
    
    # Maximum Pullback (MPB)
    peak = env.initial_balance
    mpb = 0
    for value in env.total_asset_history:
        if value > peak:
            peak = value
        else:
            pullback = (peak - value) / peak
            mpb = max(mpb, pullback)
    
    # Average Profitability Per Trade (APPT)
    # Simplified - assuming each non-zero action is a trade
    total_return = final_value - env.initial_balance
    num_trades = len([r for r in env.rewards_history if abs(r) > 0])
    appt = total_return / max(1, num_trades)  # Avoid division by zero
    
    # Sharpe Ratio (SR)
    # Assuming risk-free rate of 0 for simplicity
    daily_returns = np.diff(env.total_asset_history) / env.total_asset_history[:-1]
    sr = np.mean(daily_returns) / np.std(daily_returns) if np.std(daily_returns) > 0 else 0
    
    return {
        'Cumulative Return': cr * 100,
        'Max Earning Rate': mer * 100,
        'Maximum Pullback': mpb * 100,
        'Average Profitability Per Trade': appt,
        'Sharpe Ratio': sr
    }

