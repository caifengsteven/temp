def test_feller_condition(params):
    """Test if the Feller condition is satisfied"""
    print("\n=== Testing Feller Condition ===")
    
    # For Heston/hSABR: 2λθ² > ν²
    heston_feller = 2 * params.lambda_ * params.theta**2 > params.nu**2
    print(f"Heston Feller condition (2λθ² > ν²): {'Satisfied' if heston_feller else 'Violated'}")
    print(f"  Left side: {2 * params.lambda_ * params.theta**2:.4f}, Right side: {params.nu**2:.4f}")
    
    # For mrSABR: λ > ν²/2
    mrsabr_feller = params.lambda_ > params.nu**2/2
    print(f"mrSABR condition (λ > ν²/2): {'Satisfied' if mrsabr_feller else 'Violated'}")
    print(f"  Left side: {params.lambda_:.4f}, Right side: {params.nu**2/2:.4f}")
    
    # For CIR-ZABR: 2λθ > ν²
    cir_zabr_feller = 2 * params.lambda_ * params.theta > params.nu**2
    print(f"CIR-ZABR condition (2λθ > ν²): {'Satisfied' if cir_zabr_feller else 'Violated'}")
    print(f"  Left side: {2 * params.lambda_ * params.theta:.4f}, Right side: {params.nu**2:.4f}")

