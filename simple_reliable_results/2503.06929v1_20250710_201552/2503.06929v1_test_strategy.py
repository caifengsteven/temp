def calculate_metrics(predictions, actual_values, rrv_values):
    """Calculate evaluation metrics: MSE, QLIKE, and CRPS"""
    results = {}
    
    # Calculate MSE between predicted volatility and RRV
    mse = np.mean((predictions - rrv_values)**2)
    results['MSE'] = mse
    
    # Calculate QLIKE
    qlike = np.mean(rrv_values / predictions + np.log(predictions))
    results['QLIKE'] = qlike
    
    # Simplified CRPS calculation (using Monte Carlo approximation would be more accurate)
    # For simplicity, we're using a rough approximation
    crps = np.mean(np.abs(predictions - np.sqrt(rrv_values)))
    results['CRPS (%)'] = crps * 100
    
    return results


