class BetterMarketMaker:
    """Implementation of the power-law AMM (BMM) with XⁿY = K"""
    
    def __init__(self, x: float, y: float, n: int = 4, fee_rate: float = 0.003):
        self.x = x
        self.y = y
        self.n = n
        self.fee_rate = fee_rate
        self.k = (x ** n) * y
        self.initial_x = x
        self.initial_y = y
        
    def get_price(self) -> float:
        """Calculate current price of X in terms of Y"""
        return (self.n * self.y) / self.x
    
    def calculate_output_amount(self, input_amount: float, input_is_x: bool) -> float:
        """Calculate the output amount for a given input"""
        if input_is_x:
            # Trading X for Y
            x_after = self.x + input_amount
            # Maintain XⁿY = K
            y_after = self.k / (x_after ** self.n)
            return self.y - y_after
        else:
            # Trading Y for X
            y_after = self.y + input_amount
            # Maintain XⁿY = K
            x_after = (self.k / y_after) ** (1 / self.n)
            return self.x - x_after
    
    def swap(self, input_amount: float, input_is_x: bool) -> float:
        """Execute a swap and return the output amount"""
        # Apply fee
        input_amount_after_fee = input_amount * (1 - self.fee_rate)
        
        output_amount = self.calculate_output_amount(input_amount_after_fee, input_is_x)
        
        # Update reserves
        if input_is_x:
            self.x += input_amount_after_fee
            self.y -= output_amount
        else:
            self.y += input_amount_after_fee
            self.x -= output_amount
            
        return output_amount
    
    def calculate_impermanent_loss(self, current_price: float) -> float:
        """Calculate impermanent loss for current price relative to initial price"""
        initial_price = (self.n * self.initial_y) / self.initial_x
        price_ratio = current_price / initial_price
        
        # Calculate value if held
        value_if_held = self.initial_x * current_price + self.initial_y
        
        # Calculate current value in pool
        value_in_pool = self.x * current_price + self.y
        
        # Impermanent loss
        il = 1 - (value_in_pool / value_if_held)
        return il
    
    def calculate_liquidity_retention(self, price_multiplier: float) -> float:
        """Calculate stablecoin retention after price change"""
        return self.initial_y * (price_multiplier ** (1 - 1/(self.n + 1)))


class DynamicRebateSystem:
    """Implementation of the Dynamic Rebate System (DRS)"""
    
    def __init__(self, base_fee_rate: float = 0.005, target_volume: float = 1e6):
        self.base_fee_rate = base_fee_rate
        self.target_volume = target_volume
        self.daily_volumes = []
        self.rebate_history = []
    
    def calculate_rebate_ratio(self, current_volume: float) -> float:
        """Calculate dynamic rebate ratio based on current trading volume"""
        # ρ = 0.4 + 0.1 * (1 - V/Vmax)
        rebate_ratio = 0.4 + 0.1 * (1 - current_volume / self.target_volume)
        # Cap between 0.3 and 0.4
        return max(0.3, min(0.4, rebate_ratio))
    
    def distribute_fees(self, trading_volume: float) -> Tuple[float, float, float]:
        """Distribute fees among LPs, rebates, and protocol"""
        total_fees = self.base_fee_rate * trading_volume
        rebate_ratio = self.calculate_rebate_ratio(trading_volume)
        
        # Record history
        self.daily_volumes.append(trading_volume)
        self.rebate_history.append(rebate_ratio)
        
        # Allocate fees
        lp_fees = 0.3 * total_fees
        rebate_fees = rebate_ratio * total_fees
        protocol_fees = total_fees - lp_fees - rebate_fees
        
        return lp_fees, rebate_fees, protocol_fees


def run_price_volatility_simulation(
    bmm: BetterMarketMaker, 
    traditional_amm: BetterMarketMaker,
    price_multipliers: List[float]
) -> Tuple[List[float], List[float], List[float], List[float]]:
    """Simulate price changes and compare BMM vs traditional AMM (XY=K)"""
    
    bmm_retention = []
    trad_retention = []
    bmm_il = []
    trad_il = []
    
    for multiplier in price_multipliers:
        # Calculate theoretical liquidity retention
        bmm_ret = bmm.calculate_liquidity_retention(multiplier)
        trad_ret = traditional_amm.calculate_liquidity_retention(multiplier)
        
        # Initial price
        initial_price_bmm = bmm.get_price()
        initial_price_trad = traditional_amm.get_price()
        
        # Calculate impermanent loss
        il_bmm = bmm.calculate_impermanent_loss(initial_price_bmm * multiplier)
        il_trad = traditional_amm.calculate_impermanent_loss(initial_price_trad * multiplier)
        
        # Store results
        bmm_retention.append(bmm_ret)
        trad_retention.append(trad_ret)
        bmm_il.append(il_bmm)
        trad_il.append(il_trad)
    
    return bmm_retention, trad_retention, bmm_il, trad_il


def simulate_trading_volumes(
    drs: DynamicRebateSystem,
    days: int = 100,
    initial_volume: float = 1e6,
    sensitivity: float = 0.05,
    noise_std: float = 0.01
) -> Tuple[List[float], List[float]]:
    """Simulate trading volumes with dynamic vs static rebate systems"""
    
    # Static model with fixed rebate
    static_rebate = 0.35
    static_volumes = [initial_volume]
    dynamic_volumes = [initial_volume]
    
    for t in range(1, days):
        # Random noise for both models
        noise_static = np.random.normal(0, noise_std)
        noise_dynamic = np.random.normal(0, noise_std)
        
        # Static model: volume changes only due to noise
        static_volumes.append(static_volumes[-1] * (1 + noise_static))
        
        # Dynamic model: volume includes feedback from rebate difference
        current_rebate = drs.calculate_rebate_ratio(dynamic_volumes[-1])
        feedback = sensitivity * (current_rebate - static_rebate)
        dynamic_volumes.append(dynamic_volumes[-1] * (1 + feedback + noise_dynamic))
        
    return static_volumes, dynamic_volumes


