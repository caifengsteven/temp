class CovarianceEstimators:
    @staticmethod
    def sample_covariance(X):
        """Compute the sample covariance matrix from data matrix X"""
        n, t = X.shape
        return (X @ X.T) / t
    
    @staticmethod
    def holdout_estimator(X_train, X_test):
        """
        Compute the holdout estimator as defined in the paper
        X_train: training data matrix
        X_test: testing data matrix
        """
        n = X_train.shape[0]
        
        # Compute sample covariance matrices
        E_in = CovarianceEstimators.sample_covariance(X_train)
        E_out = CovarianceEstimators.sample_covariance(X_test)
        
        # Get eigenvectors of E_in
        _, V_in = la.eigh(E_in)
        
        # Compute holdout estimator
        diag_values = np.diag(V_in.T @ E_out @ V_in)
        return V_in @ np.diag(diag_values) @ V_in.T
    
    @staticmethod
    def oracle_estimator(E, Sigma):
        """
        Compute the oracle estimator as defined in the paper
        E: sample covariance matrix
        Sigma: population covariance matrix
        """
        _, V = la.eigh(E)
        diag_values = np.diag(V.T @ Sigma @ V)
        return V @ np.diag(diag_values) @ V.T
    
    @staticmethod
    def linear_shrinkage(E, r):
        """
        Compute the linear shrinkage estimator
        E: sample covariance matrix
        r: shrinkage intensity
        """
        n = E.shape[0]
        return r * E + (1 - r) * np.eye(n)


def generate_data(n, t, p, seed=None):
    """
    Generate synthetic data from inverse Wishart population covariance
    n: matrix dimension
    t: number of samples
    p: inverse Wishart parameter
    """
    if seed is not None:
        np.random.seed(seed)
    
    # Ensure valid parameters for inverse Wishart
    df = n + 1 + 2/p  # Degrees of freedom for inverse Wishart
    
    # Scale matrix that ensures E[Sigma] = I when Sigma ~ Inv-Wishart
    scale_matrix = (df - n - 1) * np.eye(n)
    
    # Generate population covariance from inverse Wishart
    Sigma = invwishart.rvs(df=df, scale=scale_matrix)
    
    # Generate data from multivariate normal with covariance Sigma
    X = np.random.multivariate_normal(np.zeros(n), Sigma, t).T
    
    return X, Sigma


def compute_frobenius_error(estimator, true_matrix):
    """Compute the normalized Frobenius error between estimator and true matrix"""
    n = estimator.shape[0]
    return np.sum((estimator - true_matrix)**2) / n


def theoretical_holdout_error(n, t, p, k):
    """
    Compute the theoretical holdout error for white inverse Wishart case
    n: matrix dimension
    t: total number of samples
    p: inverse Wishart parameter
    k: train-test ratio factor (t/t_out)
    """
    t_out = t/k
    q_in = n/(t-t_out)
    
    r_in = p/(p + q_in)
    return ((2*k/t - 1) * (p**2 * r_in**2 + 1) + 1 + p)


def theoretical_optimal_k(n, t, p):
    """
    Compute the theoretical optimal k that minimizes the holdout error
    n: matrix dimension
    t: total number of samples
    p: inverse Wishart parameter
    """
    q = n/t
    
    numerator = p * np.sqrt(2*q + p*(2 + 2*p + q) + p*np.sqrt(2*q**2 + 2*n*(p+q)*(p+p**2+q)))
    denominator = 2*(p+q)*(p+p**2+q)
    
    return numerator/denominator


