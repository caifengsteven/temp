@dataclass
class UniqueInstrument:
    """Base class representing a financial instrument with unitary nominal amount"""
    ticker: str
    instrument_type: str  # 'stock', 'futures', 'call_option', 'put_option'
    value: float
    delta: float
    vega: float = 0.0
    gamma: float = 0.0
    trading_cost_factor: float = 0.001  # Cost factor (based on delta/vega)
    historical_pnl: np.ndarray = None
    
    def __post_init__(self):
        if self.historical_pnl is None:
            # Default initialization with random historical P&L
            self.historical_pnl = np.random.normal(0, abs(self.value * 0.02), 250)
    
    def trading_cost(self, notional: float) -> float:
        """Calculate trading cost for given notional amount"""
        cost = 0.0
        if self.instrument_type in ['call_option', 'put_option']:
            cost += 0.5 * abs(self.vega) * 0.01 * abs(notional)  # Vega cost component
        cost += 0.5 * abs(self.delta) * 0.005 * abs(notional)  # Delta cost component
        return cost


class Portfolio:
    """Represents a portfolio of financial instruments with their notional amounts"""
    
    def __init__(self, instruments: List[UniqueInstrument] = None, notionals: List[float] = None):
        self.instruments = instruments or []
        self.notionals = notionals or []
        if len(self.instruments) != len(self.notionals):
            raise ValueError("Number of instruments must match number of notionals")
    
    def add_position(self, instrument: UniqueInstrument, notional: float):
        """Add a position to the portfolio"""
        self.instruments.append(instrument)
        self.notionals.append(notional)
    
    def value(self) -> float:
        """Calculate portfolio value"""
        return sum(instrument.value * notional for instrument, notional in zip(self.instruments, self.notionals))
    
    def delta(self) -> float:
        """Calculate portfolio delta"""
        return sum(instrument.delta * notional for instrument, notional in zip(self.instruments, self.notionals))
    
    def vega(self) -> float:
        """Calculate portfolio vega"""
        return sum(instrument.vega * notional for instrument, notional in zip(self.instruments, self.notionals))
    
    def gamma(self) -> float:
        """Calculate portfolio gamma"""
        return sum(instrument.gamma * notional for instrument, notional in zip(self.instruments, self.notionals))
    
    def trading_cost(self) -> float:
        """Calculate total trading cost for the portfolio"""
        return sum(instrument.trading_cost(notional) for instrument, notional in zip(self.instruments, self.notionals))
    
    def historical_pnl(self) -> np.ndarray:
        """Calculate historical P&L for the portfolio"""
        if not self.instruments:
            return np.zeros(250)
        pnl = np.zeros_like(self.instruments[0].historical_pnl)
        for instrument, notional in zip(self.instruments, self.notionals):
            pnl += instrument.historical_pnl * notional
        return pnl
    
    def expected_pnl(self) -> float:
        """Calculate expected P&L for the portfolio"""
        return np.mean(self.historical_pnl())
    
    def var(self, beta: float = 0.01, decay_factor: float = 0.97) -> float:
        """Calculate Value at Risk at the beta percentile with decay factor"""
        pnl = self.historical_pnl()
        s = len(pnl)
        alpha = 1 - beta * (1 - decay_factor/s)
        i_star = int(np.ceil(np.log(alpha) / np.log(decay_factor)))
        sorted_pnl = np.sort(pnl)
        if i_star >= len(sorted_pnl):
            i_star = len(sorted_pnl) - 1
        return sorted_pnl[i_star]
    
    def combine(self, other: 'Portfolio') -> 'Portfolio':
        """Combine this portfolio with another one"""
        combined_instruments = self.instruments.copy()
        combined_notionals = self.notionals.copy()
        
        for instrument, notional in zip(other.instruments, other.notionals):
            combined_instruments.append(instrument)
            combined_notionals.append(notional)
            
        return Portfolio(combined_instruments, combined_notionals)


