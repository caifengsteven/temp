    def calculate_transition_matrix(self, orders):
        """Calculate transition probability matrix from order sequence"""
        n = len(self.order_types)
        counts = np.zeros((n, n))
        
        # Count transitions
        for i in range(len(orders) - 1):
            from_idx = self.order_types.index(orders[i])
            to_idx = self.order_types.index(orders[i+1])
            counts[from_idx, to_idx] += 1
        
        # Convert to probabilities
        tpm = np.zeros((n, n))
        for i in range(n):
            row_sum = np.sum(counts[i])
            if row_sum > 0:
                tpm[i] = counts[i] / row_sum
            else:
                tpm[i] = np.ones(n) / n  # Uniform if no data
        
        return tpm
    
    def g_test(self, orders):
        """Perform G-test of independence on order sequence"""
        n = len(self.order_types)
        observed = np.zeros((n, n))
        
        # Count transitions
        for i in range(len(orders) - 1):
            from_idx = self.order_types.index(orders[i])
            to_idx = self.order_types.index(orders[i+1])
            observed[from_idx, to_idx] += 1
        
        # Calculate expected frequencies under independence
        row_sums = np.sum(observed, axis=1)
        col_sums = np.sum(observed, axis=0)
        total = np.sum(observed)
        expected = np.outer(row_sums, col_sums) / total
        
        # Calculate G-statistic
        G = 0
        for i in range(n):
            for j in range(n):
                if observed[i,j] > 0 and expected[i,j] > 0:
                    G += observed[i,j] * np.log(observed[i,j] / expected[i,j])
        G *= 2
        
        # Calculate p-value
        df = (n - 1) * (n - 1)  # Degrees of freedom
        p_value = 1 - chi2.cdf(G, df)
        
        return G, p_value
    
    def calculate_stationary_distribution(self, tpm, iterations=100):
        """Calculate stationary distribution of a Markov chain"""
        n = len(tpm)
        pi = np.ones(n) / n  # Start with uniform distribution
        
        # Power method
        for _ in range(iterations):
            pi_new = np.dot(pi, tpm)
            if np.allclose(pi, pi_new):
                break
            pi = pi_new
            
        return pi
    
    def jensen_shannon_divergence(self, p, q):
        """Calculate Jensen-Shannon divergence between two distributions"""
        m = 0.5 * (p + q)
        
        # KL divergence
        kl_p_m = 0
        for i in range(len(p)):
            if p[i] > 0 and m[i] > 0:
                kl_p_m += p[i] * np.log2(p[i] / m[i])
                
        kl_q_m = 0
        for i in range(len(q)):
            if q[i] > 0 and m[i] > 0:
                kl_q_m += q[i] * np.log2(q[i] / m[i])
        
        return 0.5 * (kl_p_m + kl_q_m)
    
