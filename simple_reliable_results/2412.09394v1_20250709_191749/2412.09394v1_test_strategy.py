def generate_residual_returns(n_stocks=100, n_days=1000, mean_reversion=0.3):
    """Generate synthetic residual returns with mean reversion property."""
    residuals = np.zeros((n_days, n_stocks))
    
    # Initialize with random values
    residuals[0] = np.random.normal(0, 0.01, n_stocks)
    
    # Generate mean-reverting residuals
    for t in range(1, n_days):
        residuals[t] = -mean_reversion * residuals[t-1] + np.random.normal(0, 0.01, n_stocks)
    
    return residuals


def exponential_moving_average(returns, alpha):
    """Calculate exponential moving average of returns."""
    ema = np.zeros_like(returns)
    ema[0] = returns[0]
    
    for t in range(1, len(returns)):
        ema[t] = alpha * ema[t-1] + returns[t]
        
    return ema


def short_term_reversal(returns, beta=0.8):
    """Implement short-term reversal strategy."""
    ema_returns = exponential_moving_average(returns, beta)
    # Negative sign to go against recent trend
    return -ema_returns


def calculate_portfolio_weights(predictions, n_long_short=None):
    """Calculate portfolio weights based on predictions ranking."""
    n_stocks = len(predictions)
    if n_long_short is None:
        n_long_short = n_stocks
    
    # Rank predictions
    ranked_indices = np.argsort(predictions)
    
    # Initialize weights
    weights = np.zeros(n_stocks)
    
    # Assign weights based on rankings
    median_rank = n_stocks // 2
    for i, idx in enumerate(ranked_indices):
        weights[idx] = (i - median_rank)
    
    # Normalize weights to sum to zero (dollar neutral)
    weights = weights / np.sum(np.abs(weights))
    
    return weights


