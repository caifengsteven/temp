# Parameters for the SABR model and capped volatility process
@dataclass
class SABRParams:
    beta: float  # 0 <= beta < 1
    rho: float   # correlation parameter (typically negative)
    omega: float  # volatility of volatility
    v0: float    # initial volatility
    a: float     # volatility cap parameter
    b: float     # drift cap parameter


def compute_sigma_v(v, params):
    """Compute the volatility function σV(v) in the volatility process"""
    beta, rho, omega = params.beta, params.rho, params.omega
    return np.sqrt(omega**2 + (beta - 1)**2 * v**2 + 2 * rho * (beta - 1) * omega * v)


def compute_mu_v(v, params):
    """Compute the drift function μV(v) in the volatility process"""
    beta, rho, omega = params.beta, params.rho, params.omega
    return v * (beta - 1) * (0.5 * (beta - 2) * v + rho * omega)


def compute_capped_sigma_v(v, params):
    """Compute the capped volatility function σ̂V(v)"""
    sigma_v = compute_sigma_v(v, params)
    return np.minimum(params.a, sigma_v)


def compute_capped_mu_v(v, params):
    """Compute the capped drift function μ̂V(v)"""
    mu_v = compute_mu_v(v, params)
    if mu_v > 0:
        return np.minimum(params.b, mu_v)
    else:
        return np.maximum(-params.b, mu_v)


def compute_v_hat(params):
    """Compute v̂, the value at which the cap on σ̂V(v) is reached"""
    beta, rho, omega, a = params.beta, params.rho, params.omega, params.a
    return (rho * omega + np.sqrt(a**2 + (rho**2 - 1) * omega**2)) / (1 - beta)


def simulate_capped_volatility_process(params, T, num_steps, num_paths):
    """
    Simulate the capped volatility process using Euler scheme
    Returns paths of vt
    """
    dt = T / num_steps
    sqrt_dt = np.sqrt(dt)
    v = np.zeros((num_paths, num_steps + 1))
    v[:, 0] = params.v0
    
    for i in range(num_steps):
        # Generate random normal increments
        dW = np.random.normal(0, sqrt_dt, num_paths)
        
        # Current volatility values
        current_v = v[:, i]
        
        # Compute drift and diffusion terms
        sigma_v = np.array([compute_capped_sigma_v(vt, params) for vt in current_v])
        mu_v = np.array([compute_capped_mu_v(vt, params) for vt in current_v])
        
        # Euler update
        v[:, i+1] = current_v * np.exp((mu_v - 0.5 * sigma_v**2) * dt + sigma_v * dW)
    
    return v


def calculate_vix(v_paths, T, tau=30/365):
    """
    Calculate VIX from simulated volatility paths
    VIX is estimated as the spot volatility at time T for simplicity
    """
    # In the paper, as tau approaches 0, VIX_T approaches v_T
    return v_paths[:, -1]


def bs_call_price(F, K, T, sigma, r=0):
    """Black-Scholes formula for call option price"""
    d1 = (np.log(F/K) + 0.5 * sigma**2 * T) / (sigma * np.sqrt(T))
    d2 = d1 - sigma * np.sqrt(T)
    return np.exp(-r * T) * (F * norm.cdf(d1) - K * norm.cdf(d2))


def bs_put_price(F, K, T, sigma, r=0):
    """Black-Scholes formula for put option price"""
    d1 = (np.log(F/K) + 0.5 * sigma**2 * T) / (sigma * np.sqrt(T))
    d2 = d1 - sigma * np.sqrt(T)
    return np.exp(-r * T) * (K * norm.cdf(-d2) - F * norm.cdf(-d1))


def compute_implied_volatility(option_price, F, K, T, is_call=True, r=0, tol=1e-6, max_iter=100):
    """Compute Black-Scholes implied volatility using Newton-Raphson method"""
    # Initial guess
    sigma = 0.3
    
    for i in range(max_iter):
        if is_call:
            price = bs_call_price(F, K, T, sigma, r)
            vega = F * np.sqrt(T) * norm.pdf((np.log(F/K) + 0.5 * sigma**2 * T) / (sigma * np.sqrt(T)))
        else:
            price = bs_put_price(F, K, T, sigma, r)
            vega = F * np.sqrt(T) * norm.pdf((np.log(F/K) + 0.5 * sigma**2 * T) / (sigma * np.sqrt(T)))
        
        diff = option_price - price
        
        if abs(diff) < tol:
            return sigma
        
        # Update sigma using Newton-Raphson
        sigma = sigma + diff / (vega + 1e-10)  # Add small constant to avoid division by zero
        
        # Ensure sigma remains positive
        sigma = max(0.001, sigma)
    
    # If we reach here, Newton-Raphson didn't converge
    return np.nan


def price_vix_options(vix_values, strikes, T, r=0):
    """Price VIX options using Monte Carlo"""
    num_paths = len(vix_values)
    call_prices = []
    put_prices = []
    
    # Calculate forward price
    fwd_vix = np.mean(vix_values)
    
    for K in strikes:
        # Calculate payoffs
        call_payoffs = np.maximum(vix_values - K, 0)
        put_payoffs = np.maximum(K - vix_values, 0)
        
        # Calculate option prices
        call_price = np.exp(-r * T) * np.mean(call_payoffs)
        put_price = np.exp(-r * T) * np.mean(put_payoffs)
        
        call_prices.append(call_price)
        put_prices.append(put_price)
    
    return fwd_vix, np.array(call_prices), np.array(put_prices)


def compute_theoretical_vix_iv(v0, K, params):
    """
    Compute the theoretical short-maturity VIX implied volatility in equation (59)
    """
    log_moneyness = np.log(K/v0)
    
    # If K is too close to v0, return σV(v0)
    if abs(log_moneyness) < 1e-10:
        return compute_sigma_v(v0, params)
    
    # For the denominator, we need to calculate the integral
    # For simplicity, we'll use numerical integration
    num_points = 100
    v_points = np.linspace(min(v0, K), max(v0, K), num_points)
    integrand = 1 / (v_points * compute_sigma_v(v_points, params))
    integral = np.trapz(integrand, v_points)
    
    return abs(log_moneyness / integral)


def test_sabr_vix_options():
    # Model parameters from the paper
    params = SABRParams(
        beta=0.5,
        rho=-0.7,  # Negative correlation typical for equity
        omega=1.0,
        v0=0.1,
        a=2.0,  # Cap on volatility
        b=1.0   # Cap on drift
    )
    
    # Simulation parameters
    T = 0.1        # Maturity in years
    num_steps = 100
    num_paths = 10000
    
    print(f"Computing v_hat for cap level: {compute_v_hat(params):.4f}")
    
    # Simulate volatility paths
    v_paths = simulate_capped_volatility_process(params, T, num_steps, num_paths)
    
    # Calculate VIX values
    vix_values = calculate_vix(v_paths, T)
    
    # Calculate forward VIX
    fwd_vix = np.mean(vix_values)
    print(f"Forward VIX (T={T}): {fwd_vix:.6f} ± {np.std(vix_values)/np.sqrt(num_paths):.6f}")
    
    # Create strikes around the forward
    log_strikes = np.linspace(-1.0, 1.0, 21)
    strikes = v_paths[0, 0] * np.exp(log_strikes)
    
    # Price VIX options
    fwd_vix, call_prices, put_prices = price_vix_options(vix_values, strikes, T)
    
    # Compute implied volatilities
    call_ivs = []
    put_ivs = []
    
    for i, K in enumerate(strikes):
        if K > fwd_vix:  # OTM call
            call_iv = compute_implied_volatility(call_prices[i], fwd_vix, K, T, is_call=True)
            call_ivs.append(call_iv)
            put_ivs.append(np.nan)
        else:  # OTM put
            put_iv = compute_implied_volatility(put_prices[i], fwd_vix, K, T, is_call=False)
            put_ivs.append(put_iv)
            call_ivs.append(np.nan)
    
    # Combine call and put IVs
    implied_vols = np.array([call_iv if not np.isnan(call_iv) else put_iv 
                             for call_iv, put_iv in zip(call_ivs, put_ivs)])
    
    # Calculate theoretical IVs
    theoretical_ivs = np.array([compute_theoretical_vix_iv(params.v0, K, params) for K in strikes])
    
    # Plot results
    plt.figure(figsize=(10, 6))
    plt.plot(log_strikes, implied_vols, 'ro', label='MC Simulation')
    plt.plot(log_strikes, theoretical_ivs, 'k-', label='Theoretical (short-maturity)')
    plt.xlabel('log(K/v0)')
    plt.ylabel('VIX Implied Volatility')
    plt.title(f'VIX Implied Volatility Smile (SABR, ρ={params.rho}, T={T})')
    plt.grid(True)
    plt.legend()
    
    # Save plot
    plt.savefig('vix_sabr_smile.png')
    plt.close()
    
    print("VIX option simulation completed and smile plot saved.")
    
    return {
        'fwd_vix': fwd_vix,
        'strikes': strikes,
        'implied_vols': implied_vols,
        'theoretical_ivs': theoretical_ivs
    }


