# Add occasional volume spikes
def add_volume_spikes(data, spike_probability=0.05, spike_magnitude_range=(2, 5)):
    """Add random volume spikes to the data"""
    
    # Get unique dates
    dates = data['date'].unique()
    
    # For each date, randomly add spikes
    for date in dates:
        if np.random.random() < spike_probability:
            # Choose a random minute (avoiding first and last 30 minutes)
            minute = np.random.randint(30, 360)
            
            # Choose a spike magnitude
            magnitude = np.random.uniform(*spike_magnitude_range)
            
            # Apply the spike
            mask = (data['date'] == date) & (data['minute'] == minute)
            
            # Increase volume and related metrics
            data.loc[mask, 'volume'] *= magnitude
            data.loc[mask, 'volume_ratio'] *= magnitude
            data.loc[mask, 'trade_amount'] *= magnitude
            
            # Recalculate accumulated volume and normalize volume_ratio
            day_mask = data['date'] == date
            data.loc[day_mask, 'accumulated_volume'] = data.loc[day_mask, 'volume'].cumsum()
            total_volume = data.loc[day_mask, 'volume'].sum()
            data.loc[day_mask, 'volume_ratio'] = data.loc[day_mask, 'volume'] / total_volume
    
    return data

# Simple prediction model to simulate IVE's outputs
def simulate_ive_predictions(data, error_std=0.02, std_base=0.05, std_spike_sensitivity=0.2):
    """
    Simulate IVE's predictions including mean and standard deviation
    - Mean prediction includes some error from the true values
    - Std prediction is higher for upcoming volume spikes
    """
    # Copy data
    prediction_data = data.copy()
    
    # Add prediction columns
    prediction_data['predicted_mean'] = 0.0
    prediction_data['predicted_std'] = 0.0
    
    # Process each date separately
    for date in prediction_data['date'].unique():
        day_mask = prediction_data['date'] == date
        true_values = prediction_data.loc[day_mask, 'volume_ratio'].values
        
        # Generate predictions with some error
        errors = np.random.normal(0, error_std, len(true_values))
        predicted_means = np.maximum(true_values + errors, 0.0001)
        
        # Generate standard deviations - higher before volume spikes
        predicted_stds = np.ones_like(true_values) * std_base
        
        # For each minute, set std higher if next minute has a spike
        for i in range(len(true_values) - 1):
            if true_values[i+1] > 1.5 * true_values[i]:
                predicted_stds[i] += std_spike_sensitivity * (true_values[i+1] - true_values[i])
        
        # Store predictions
        prediction_data.loc[day_mask, 'predicted_mean'] = predicted_means
        prediction_data.loc[day_mask, 'predicted_std'] = predicted_stds
    
    return prediction_data

