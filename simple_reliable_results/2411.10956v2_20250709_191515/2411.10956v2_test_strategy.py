# Volatility Interruption simulation
def simulate_volatility_interruption(data, vi_probability=0.05, price_change_range=(0.1, 0.15)):
    """
    Simulate Volatility Interruption (VI) events
    - VI occurs when price changes drastically
    - Creates significant temporary price deviations
    """
    # Copy data
    vi_data = data.copy()
    vi_events = []
    
    # Process each date
    for date in vi_data['date'].unique():
        if np.random.random() < vi_probability:
            # Choose a random minute (avoiding first and last 30 minutes)
            vi_minute = np.random.randint(30, 360)
            
            # Choose a direction (up or down)
            direction = 1 if np.random.random() > 0.5 else -1
            
            # Choose a magnitude
            magnitude = np.random.uniform(*price_change_range) * direction
            
            # Apply price change
            day_mask = (vi_data['date'] == date) & (vi_data['minute'] >= vi_minute)
            
            # Store original prices
            original_prices = vi_data.loc[day_mask, 'price'].copy()
            
            # Apply price jump at VI minute
            vi_data.loc[day_mask, 'price'] = original_prices * (1 + magnitude)
            
            # Record VI event
            vi_events.append({
                'date': date,
                'vi_minute': vi_minute,
                'magnitude': magnitude
            })
    
    return vi_data, pd.DataFrame(vi_events)

