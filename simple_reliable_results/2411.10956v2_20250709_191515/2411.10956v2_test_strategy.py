class PositionalEncoding(nn.Module):
    def __init__(self, d_model, max_len=5000):
        super(PositionalEncoding, self).__init__()
        
        pe = torch.zeros(max_len, d_model)
        position = torch.arange(0, max_len, dtype=torch.float).unsqueeze(1)
        div_term = torch.exp(torch.arange(0, d_model, 2).float() * (-math.log(10000.0) / d_model))
        
        pe[:, 0::2] = torch.sin(position * div_term)
        pe[:, 1::2] = torch.cos(position * div_term)
        pe = pe.unsqueeze(0)
        
        self.register_buffer('pe', pe)
        
    def forward(self, x):
        return x + self.pe[:, :x.size(1)]

class TimeEncoding(nn.Module):
    def __init__(self, d_model):
        super(TimeEncoding, self).__init__()
        self.encoding = nn.Embedding(390, d_model)  # 390 minutes in a trading day
        
    def forward(self, x, time_idx):
        # time_idx should be the absolute minute index in the trading day
        return x + self.encoding(time_idx)

class IVEModel(nn.Module):
    def __init__(self, input_dim, d_model=64, nhead=4, num_encoder_layers=4, 
                 num_decoder_layers=4, dim_feedforward=256, dropout=0.1):
        super(IVEModel, self).__init__()
        
        # Input projection
        self.input_projection = nn.Linear(input_dim, d_model)
        
        # Positional encoding
        self.pos_encoder = PositionalEncoding(d_model)
        self.time_encoder = TimeEncoding(d_model)
        
        # Transformer
        self.transformer = nn.Transformer(
            d_model=d_model,
            nhead=nhead,
            num_encoder_layers=num_encoder_layers,
            num_decoder_layers=num_decoder_layers,
            dim_feedforward=dim_feedforward,
            dropout=dropout
        )
        
        # Distribution head for Student's t-distribution
        self.mean_head = nn.Linear(d_model, 1)
        self.std_head = nn.Linear(d_model, 1)
        self.df_head = nn.Linear(d_model, 1)  # Degrees of freedom
        
    def forward(self, src, tgt, src_time_idx, tgt_time_idx):
        # Project input
        src = self.input_projection(src)
        tgt = self.input_projection(tgt)
        
        # Add positional encoding
        src = self.pos_encoder(src)
        tgt = self.pos_encoder(tgt)
        
        # Add time encoding
        src = self.time_encoder(src, src_time_idx)
        tgt = self.time_encoder(tgt, tgt_time_idx)
        
        # Create masks for transformer
        src_mask = None
        tgt_mask = self.generate_square_subsequent_mask(tgt.size(1)).to(tgt.device)
        
        # Pass through transformer
        output = self.transformer(src, tgt, src_mask, tgt_mask)
        
        # Get distribution parameters
        mean = self.mean_head(output)
        std = torch.exp(self.std_head(output))  # Ensure positivity
        df = 5.0 + torch.exp(self.df_head(output))  # Ensure df > 5
        
        return mean, std, df
    
    def generate_square_subsequent_mask(self, sz):
        mask = (torch.triu(torch.ones(sz, sz)) == 1).transpose(0, 1)
        mask = mask.float().masked_fill(mask == 0, float('-inf')).masked_fill(mask == 1, float(0.0))
        return mask

