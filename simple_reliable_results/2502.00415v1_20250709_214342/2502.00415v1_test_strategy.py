class DynamicsAgent(MarketSenseAIAgent):
    """Agent responsible for analyzing price dynamics"""
    def __init__(self):
        super().__init__("Dynamics Agent")
    
    def process(self, price_data: pd.DataFrame, market_data: pd.DataFrame = None) -> Dict:
        """Process price data and return technical analysis"""
        if price_data is None or len(price_data) < 90:  # Need at least 90 days
            return {"score": 0, "summary": "Insufficient price data"}
        
        # Calculate key metrics
        returns = price_data['price'].pct_change().dropna()
        
        # Short, medium and long term momentum
        short_momentum = returns.iloc[-20:].mean() * 20  # Last month
        medium_momentum = returns.iloc[-60:].mean() * 60  # Last quarter
        long_momentum = returns.iloc[-90:].mean() * 90   # Last 4.5 months
        
        # Volatility
        volatility = returns.std() * np.sqrt(252)  # Annualized
        
        # Simple scoring model
        momentum_score = short_momentum * 0.5 + medium_momentum * 0.3 + long_momentum * 0.2
        adjusted_score = momentum_score / (volatility * 0.5)  # Adjust for risk
        
        # Calculate beta if market data provided
        beta = None
        if market_data is not None:
            # Align dates
            aligned_data = pd.merge(
                price_data[['date', 'price']],
                market_data[['date', 'price']],
                on='date', 
                how='inner',
                suffixes=('_stock', '_market')
            )
            
            if len(aligned_data) > 30:
                stock_returns = aligned_data['price_stock'].pct_change().dropna()
                market_returns = aligned_data['price_market'].pct_change().dropna()
                
                if len(stock_returns) > 1:
                    cov = np.cov(stock_returns, market_returns)[0][1]
                    var = np.var(market_returns)
                    beta = cov / var if var != 0 else 1.0
        
        summary = f"Momentum: {momentum_score:.1%}, Volatility: {volatility:.1%}"
        if beta is not None:
            summary += f", Beta: {beta:.2f}"
            
        return {
            "score": adjusted_score,
            "short_momentum": short_momentum,
            "medium_momentum": medium_momentum,
            "long_momentum": long_momentum,
            "volatility": volatility,
            "beta": beta,
            "summary": summary
        }


class MacroeconomicAgent(MarketSenseAIAgent):
    """Agent responsible for macroeconomic analysis"""
    def __init__(self):
        super().__init__("Macroeconomic Agent")
    
    def process(self, indicators: pd.DataFrame, reports: pd.DataFrame = None) -> Dict:
        """Process macroeconomic data and return analysis"""
        if indicators is None or len(indicators) < 3:
            return {"score": 0, "summary": "Insufficient macroeconomic data"}
        
        # Get most recent indicators
        recent = indicators.iloc[-1]
        
        # Simple economic health score
        gdp_score = recent['gdp_growth'] * 10  # Scale up for better weighting
        inflation_penalty = max(0, recent['inflation'] - 0.02) * 5  # Penalty for inflation > 2%
        unemployment_penalty = max(0, recent['unemployment'] - 0.04) * 10  # Penalty for unemployment > 4%
        
        econ_score = gdp_score - inflation_penalty - unemployment_penalty
        
        # Adjust based on report sentiment if available
        report_sentiment = 0
        if reports is not None and len(reports) > 0:
            # Use recent reports (last 30 days)
            cutoff_date = indicators.iloc[-1]['date'] - pd.Timedelta(days=30)
            recent_reports = reports[reports['date'] >= cutoff_date]
            
            if len(recent_reports) > 0:
                report_sentiment = recent_reports['sentiment'].mean()
                econ_score += report_sentiment * 2
        
        # Generate summary
        summary = (f"GDP Growth: {recent['gdp_growth']:.1%}, Inflation: {recent['inflation']:.1%}, "
                  f"Unemployment: {recent['unemployment']:.1%}, Interest Rate: {recent['interest_rate']:.1%}")
        
        if reports is not None and len(reports) > 0:
            summary += f", Report Sentiment: {report_sentiment:.2f}"
        
        return {
            "score": econ_score,
            "gdp_growth": recent['gdp_growth'],
            "inflation": recent['inflation'],
            "unemployment": recent['unemployment'],
            "interest_rate": recent['interest_rate'],
            "report_sentiment": report_sentiment,
            "summary": summary
        }


class SignalAgent(MarketSenseAIAgent):
    """Agent responsible for generating final investment signals"""
    def __init__(self):
        super().__init__("Signal Agent")
    
    def process(self, news_analysis: Dict, fundamentals_analysis: Dict, 
                dynamics_analysis: Dict, macro_analysis: Dict) -> Dict:
        """Process all analyses and generate final investment signal"""
        # Weight for each component
        news_weight = 0.15
        fundamentals_weight = 0.35
        dynamics_weight = 0.30
        macro_weight = 0.20
        
        # Calculate weighted score
        weighted_score = (
            news_analysis.get('sentiment', 0) * news_weight +
            fundamentals_analysis.get('score', 0) * fundamentals_weight +
            dynamics_analysis.get('score', 0) * dynamics_weight +
            macro_analysis.get('score', 0) * macro_weight
        )
        
        # Determine signal based on score threshold
        signal = 'HOLD'
        confidence = 0.5 + min(abs(weighted_score) / 0.1, 0.5)  # Scale confidence between 0.5-1.0
        
        if weighted_score > 0.05:
            signal = 'BUY'
        elif weighted_score < -0.05:
            signal = 'SELL'
        
        # Generate explanation
        explanation = f"Final score: {weighted_score:.4f} (Confidence: {confidence:.1%})\n"
        explanation += f"• News: {news_analysis.get('summary', 'No data')}\n"
        explanation += f"• Fundamentals: {fundamentals_analysis.get('summary', 'No data')}\n"
        explanation += f"• Dynamics: {dynamics_analysis.get('summary', 'No data')}\n"
        explanation += f"• Macroeconomic: {macro_analysis.get('summary', 'No data')}"
        
        return {
            "signal": signal,
            "confidence": confidence,
            "score": weighted_score,
            "explanation": explanation
        }


