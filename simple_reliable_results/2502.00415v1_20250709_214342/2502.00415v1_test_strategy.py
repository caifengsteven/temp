class Portfolio:
    """Class to track portfolio performance"""
    def __init__(self, initial_capital: float = 1000000):
        self.initial_capital = initial_capital
        self.current_capital = initial_capital
        self.holdings = {}  # ticker -> {shares, entry_price}
        self.history = []
        
    def rebalance(self, signals: List[Dict], stock_data: Dict[str, StockData], date: datetime):
        """Rebalance portfolio based on signals"""
        # Get prices for this date
        prices = {}
        for ticker, stock in stock_data.items():
            price_on_date = stock.price_data[stock.price_data['date'] <= date]
            if len(price_on_date) > 0:
                prices[ticker] = price_on_date.iloc[-1]['price']
        
        # Sell everything first (simplified approach)
        for ticker, holding in list(self.holdings.items()):
            if ticker in prices:
                self.current_capital += holding['shares'] * prices[ticker]
                self.history.append({
                    'date': date,
                    'action': 'SELL',
                    'ticker': ticker,
                    'shares': holding['shares'],
                    'price': prices[ticker],
                    'value': holding['shares'] * prices[ticker]
                })
        
        self.holdings = {}
        
        # Buy stocks with BUY signals
        buy_signals = [s for s in signals if s['signal']['signal'] == 'BUY']
        
        if buy_signals:
            # Equal weight allocation
            allocation_per_stock = self.current_capital / len(buy_signals)
            
            for signal in buy_signals:
                ticker = signal['ticker']
                if ticker in prices:
                    price = prices[ticker]
                    shares = allocation_per_stock / price
                    
                    self.holdings[ticker] = {
                        'shares': shares,
                        'entry_price': price
                    }
                    
                    self.current_capital -= shares * price
                    
                    self.history.append({
                        'date': date,
                        'action': 'BUY',
                        'ticker': ticker,
                        'shares': shares,
                        'price': price,
                        'value': shares * price
                    })
    
    def calculate_value(self, date: datetime, stock_data: Dict[str, StockData]) -> float:
        """Calculate portfolio value at a specific date"""
        value = self.current_capital
        
        for ticker, holding in self.holdings.items():
            price_on_date = stock_data[ticker].price_data[stock_data[ticker].price_data['date'] <= date]
            if len(price_on_date) > 0:
                price = price_on_date.iloc[-1]['price']
                value += holding['shares'] * price
        
        return value
    
    def get_performance_history(self, dates: List[datetime], stock_data: Dict[str, StockData]) -> pd.DataFrame:
        """Calculate portfolio value for a list of dates"""
        values = []
        
        for date in dates:
            values.append({
                'date': date,
                'value': self.calculate_value(date, stock_data)
            })
        
        return pd.DataFrame(values)


