        paths['vol'][0] = self.current_vol
        
        for i in range(1, days + 1):
            # Generate correlated random shocks
            shocks = self.generate_correlated_normals()
            
            # Update volatility
            vol_drift = self.vol_mean_reversion * (self.vol_long_term - paths['vol'][i-1])
            vol_diffusion = self.vol_of_vol * paths['vol'][i-1] * shocks[0]
            new_vol = paths['vol'][i-1] + vol_drift * dt + vol_diffusion * np.sqrt(dt)
            paths['vol'][i] = max(0.01, new_vol)  # Ensure positive volatility
            
