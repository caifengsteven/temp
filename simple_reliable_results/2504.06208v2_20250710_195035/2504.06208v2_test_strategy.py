class IVSurface:
    """Class to model the implied volatility surface based on the paper's parametric form"""
    
    def __init__(self, Tconv=0.25, Tmin=6/252, Tmax=5):
        self.Tconv = Tconv
        self.Tmin = Tmin
        self.Tmax = Tmax
        
    def compute_iv(self, M, tau, beta):
        """
        Compute implied volatility based on moneyness, time-to-maturity and beta factors
        
        Args:
            M: Moneyness = 1/sqrt(tau) * log(S*e^((r-q)*tau)/K)
            tau: Time-to-maturity in years
            beta: IV factors coefficients (vector of 5 elements)
        """
        # Long-term ATM IV level
        f1 = beta[0]
        
        # Time-to-maturity slope
        f2 = beta[1] * np.exp(-np.sqrt(tau)/self.Tconv)
        
        # Moneyness slope
        f3 = beta[2] * (M * (M >= 0) + (np.exp(2*M) - 1)/(np.exp(2*M) + 1) * (M < 0))
        
        # Smile attenuation
        f4 = beta[3] * (1 - np.exp(-M**2)) * np.log(tau/self.Tmax)
        
        # Smirk
        f5 = beta[4] * (1 - np.exp((3*M)**3)) * np.log(tau/self.Tmax) * (M < 0)
        
        return f1 + f2 + f3 + f4 + f5
    
    def compute_moneyness(self, S, K, r, q, tau):
        """Calculate moneyness"""
        return (1/np.sqrt(tau)) * np.log(S * np.exp((r-q)*tau) / K)


class BlackScholes:
    """Basic Black-Scholes model for option pricing and Greeks calculation"""
    
    @staticmethod
    def norm_cdf(x):
        """Standard normal cumulative distribution function"""
        return 0.5 * (1 + np.erf(x/np.sqrt(2)))
    
    @staticmethod
    def norm_pdf(x):
        """Standard normal probability density function"""
        return (1/np.sqrt(2*np.pi)) * np.exp(-0.5*x**2)
    
    @staticmethod
    def d1(S, K, r, q, sigma, tau):
        """d1 parameter for Black-Scholes formula"""
        return (np.log(S/K) + (r - q + 0.5*sigma**2)*tau) / (sigma*np.sqrt(tau))
    
    @staticmethod
    def d2(S, K, r, q, sigma, tau):
        """d2 parameter for Black-Scholes formula"""
        return BlackScholes.d1(S, K, r, q, sigma, tau) - sigma*np.sqrt(tau)
    
    @staticmethod
    def call_price(S, K, r, q, sigma, tau):
        """Calculate call option price"""
        if tau <= 0:
            return max(0, S - K)
        d1 = BlackScholes.d1(S, K, r, q, sigma, tau)
        d2 = BlackScholes.d2(S, K, r, q, sigma, tau)
        return S * np.exp(-q*tau) * BlackScholes.norm_cdf(d1) - K * np.exp(-r*tau) * BlackScholes.norm_cdf(d2)
    
    @staticmethod
    def put_price(S, K, r, q, sigma, tau):
        """Calculate put option price"""
        if tau <= 0:
            return max(0, K - S)
        d1 = BlackScholes.d1(S, K, r, q, sigma, tau)
        d2 = BlackScholes.d2(S, K, r, q, sigma, tau)
        return K * np.exp(-r*tau) * BlackScholes.norm_cdf(-d2) - S * np.exp(-q*tau) * BlackScholes.norm_cdf(-d1)
    
    @staticmethod
    def straddle_price(S, K, r, q, sigma, tau):
        """Calculate straddle (call + put) price"""
        return BlackScholes.call_price(S, K, r, q, sigma, tau) + BlackScholes.put_price(S, K, r, q, sigma, tau)
    
    @staticmethod
    def delta_call(S, K, r, q, sigma, tau):
        """Calculate call option delta"""
        if tau <= 0:
            return 1.0 if S > K else 0.0
        d1 = BlackScholes.d1(S, K, r, q, sigma, tau)
        return np.exp(-q*tau) * BlackScholes.norm_cdf(d1)
    
    @staticmethod
    def delta_put(S, K, r, q, sigma, tau):
        """Calculate put option delta"""
        if tau <= 0:
            return -1.0 if S < K else 0.0
        d1 = BlackScholes.d1(S, K, r, q, sigma, tau)
        return np.exp(-q*tau) * (BlackScholes.norm_cdf(d1) - 1)
    
    @staticmethod
    def delta_straddle(S, K, r, q, sigma, tau):
        """Calculate straddle delta"""
        if tau <= 0:
            return 1.0 if S > K else -1.0
        d1 = BlackScholes.d1(S, K, r, q, sigma, tau)
        return np.exp(-q*tau) * (2*BlackScholes.norm_cdf(d1) - 1)
    
    @staticmethod
    def gamma(S, K, r, q, sigma, tau):
        """Calculate gamma (same for call and put)"""
        if tau <= 0:
            return 0.0
        d1 = BlackScholes.d1(S, K, r, q, sigma, tau)
        return np.exp(-q*tau) * BlackScholes.norm_pdf(d1) / (S * sigma * np.sqrt(tau))


