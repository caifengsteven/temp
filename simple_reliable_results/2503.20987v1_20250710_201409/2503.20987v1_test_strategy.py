def construct_portfolio(model, test_loader, returns):
    """Construct a portfolio based on model predictions."""
    device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
    model = model.to(device)
    model.eval()
    
    all_predictions = []
    
    with torch.no_grad():
        for X, _ in test_loader:
            X = X.to(device)
            predictions, _ = model(X)
            all_predictions.append(predictions.cpu().numpy())
    
    all_predictions = np.concatenate(all_predictions, axis=0)
    
    # Rank stocks by predicted returns
    ranked_indices = np.argsort(-all_predictions.flatten())
    
    # Construct portfolio weights (long-only)
    n_stocks = len(all_predictions)
    weights = np.zeros(n_stocks)
    
    # Assign weights based on ranks
    for i, idx in enumerate(ranked_indices):
        weights[idx] = (n_stocks - i) / (n_stocks * (n_stocks + 1) / 2)
    
    # Calculate portfolio returns
    portfolio_return = np.sum(weights * returns)
    
    return portfolio_return, weights

def calculate_metrics(returns, benchmark_returns=None):
    """Calculate performance metrics for a returns series."""
    # Cumulative Annual Growth Rate (CAGR)
    n_days = len(returns)
    cumulative_return = np.prod(1 + returns) - 1
    cagr = (1 + cumulative_return) ** (252 / n_days) - 1
    
    # Sharpe Ratio
    annual_return = cagr
    annual_volatility = returns.std() * np.sqrt(252)
    sharpe_ratio = annual_return / annual_volatility if annual_volatility > 0 else 0
    
    # Max Drawdown
    cumulative = np.cumprod(1 + returns)
    max_dd = 0
    peak = cumulative[0]
    
    for value in cumulative:
        if value > peak:
            peak = value
        dd = (peak - value) / peak
        if dd > max_dd:
            max_dd = dd
    
    # Alpha and Beta (if benchmark provided)
    alpha, beta = None, None
    if benchmark_returns is not None:
        covariance = np.cov(returns, benchmark_returns)[0, 1]
        benchmark_variance = np.var(benchmark_returns)
        beta = covariance / benchmark_variance if benchmark_variance > 0 else 0
        alpha = annual_return - beta * (np.mean(benchmark_returns) * 252)
    
    return {
        'CAGR': cagr,
        'Sharpe Ratio': sharpe_ratio,
        'Max Drawdown': max_dd,
        'Alpha': alpha,
        'Beta': beta
    }

