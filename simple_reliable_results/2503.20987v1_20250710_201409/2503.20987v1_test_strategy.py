class LSTM(nn.Module):
    """LSTM model for financial time series prediction."""
    
    def __init__(self, input_size, hidden_size, num_layers, output_dim):
        super(LSTM, self).__init__()
        self.hidden_size = hidden_size
        self.num_layers = num_layers
        
        self.lstm = nn.LSTM(input_size, hidden_size, num_layers, batch_first=True, bidirectional=True)
        self.lstm2 = nn.LSTM(hidden_size * 2, hidden_size, batch_first=True, bidirectional=True)
        self.lstm3 = nn.LSTM(hidden_size * 2, hidden_size, batch_first=True)
        self.fc = nn.Linear(hidden_size, output_dim, bias=False)
        
    def forward(self, x):
        # x shape: (batch_size, seq_len, input_size)
        h0 = torch.zeros(self.num_layers * 2, x.size(0), self.hidden_size).to(x.device)
        c0 = torch.zeros(self.num_layers * 2, x.size(0), self.hidden_size).to(x.device)
        
        out, _ = self.lstm(x, (h0, c0))
        
        h1 = torch.zeros(self.num_layers * 2, x.size(0), self.hidden_size).to(x.device)
        c1 = torch.zeros(self.num_layers * 2, x.size(0), self.hidden_size).to(x.device)
        
        out, _ = self.lstm2(out, (h1, c1))
        
        h2 = torch.zeros(self.num_layers, x.size(0), self.hidden_size).to(x.device)
        c2 = torch.zeros(self.num_layers, x.size(0), self.hidden_size).to(x.device)
        
        out, _ = self.lstm3(out, (h2, c2))
        out = out[:, -1, :]  # Get the last time step
        
        out = self.fc(out)
        return out

class CausalModel(nn.Module):
    """Model implementing causal discovery for stock prediction."""
    
    def __init__(self, feature_extractor, causal_dim):
        super(CausalModel, self).__init__()
        self.feature_extractor = feature_extractor
        self.causal_dim = causal_dim
        self.causal_projection = nn.Linear(32, causal_dim, bias=False)
        self.linear = nn.Parameter(torch.ones(causal_dim) / causal_dim)
        
    def feature_representation(self, x):
        """Extract feature representation."""
        features = self.feature_extractor(x)
        causal_features = self.causal_projection(features)
        return causal_features
    
    def forward(self, x):
        """Forward pass to predict returns."""
        causal_features = self.feature_representation(x)
        prediction = torch.sum(causal_features * self.linear, dim=1, keepdim=True)
        return prediction, causal_features

def standardize_domain_wise(features, domains):
    """Standardize features within each domain."""
    standardized_features = features.clone()
    
    for domain_idx in domains:
        domain_mask = domains == domain_idx
        domain_features = features[domain_mask]
        
        mean = domain_features.mean(dim=0, keepdim=True)
        std = domain_features.std(dim=0, keepdim=True) + 1e-6
        
        standardized_features[domain_mask] = (domain_features - mean) / std
    
    return standardized_features

def calculate_domain_invariance_loss(causal_features, predictions, targets, domains):
    """Calculate invariance loss as described in the paper."""
    unique_domains = torch.unique(domains)
    invariance_loss = 0.0
    domain_weights = []
    
    # Calculate domain-wise regression coefficients
    for domain_idx in unique_domains:
        domain_mask = domains == domain_idx
        domain_features = causal_features[domain_mask]
        domain_targets = targets[domain_mask]
        
        # Calculate domain-specific weights analytically
        # ν^φ_t-i = E_t-i[φ(X)φ(X)^T]^-1 E_t-i[φ(X)R]
        features_t = domain_features
        cov_matrix = torch.mm(features_t.t(), features_t) / features_t.size(0)
        cov_with_target = torch.mm(features_t.t(), domain_targets) / features_t.size(0)
        
        # Add small regularization for numerical stability
        cov_matrix += torch.eye(cov_matrix.size(0)).to(cov_matrix.device) * 1e-5
        
        # Calculate domain-specific weights
        domain_weight = torch.mm(torch.inverse(cov_matrix), cov_with_target)
        domain_weights.append(domain_weight)
    
    # Calculate the average weight
    avg_weight = torch.mean(torch.stack(domain_weights), dim=0)
    
    # Calculate invariance loss: 1/T Σ ||ν^φ_t-i - ν||^2
    for domain_weight in domain_weights:
        invariance_loss += torch.sum((domain_weight - avg_weight) ** 2)
    
    invariance_loss /= len(unique_domains)
    return invariance_loss, avg_weight

def calculate_alignment_loss(causal_features, domains):
    """Calculate alignment loss to decorrelate features."""
    unique_domains = torch.unique(domains)
    alignment_loss = 0.0
    
    for domain_idx in unique_domains:
        domain_mask = domains == domain_idx
        domain_features = causal_features[domain_mask]
        
        # Calculate correlation matrix
        corr_matrix = torch.mm(domain_features.t(), domain_features) / domain_features.size(0)
        
        # We want off-diagonal elements to be close to 0 (decorrelation)
        # and diagonal elements to be close to 1 (unit variance)
        target_matrix = torch.eye(corr_matrix.size(0)).to(corr_matrix.device)
        alignment_loss += torch.sum((corr_matrix - target_matrix) ** 2)
    
    alignment_loss /= len(unique_domains)
    return alignment_loss

def train_causal_model(model, train_loader, val_loader, domains_train, domains_val, 
                       lambda1=5.0, lambda2=1.0, num_epochs=50, learning_rate=0.0002, 
                       early_stop_patience=5):
    """Train the causal model with invariance objectives."""
    device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
    model = model.to(device)
    optimizer = optim.Adam(model.parameters(), lr=learning_rate)
    
    criterion = nn.MSELoss()
    
    best_val_loss = float('inf')
    patience_counter = 0
    
    train_losses = []
    val_losses = []
    
    for epoch in range(num_epochs):
        model.train()
        epoch_loss = 0
        epoch_pred_loss = 0
        epoch_inv_loss = 0
        epoch_align_loss = 0
        
        for batch_idx, (X, y) in enumerate(train_loader):
            X, y = X.to(device), y.to(device)
            batch_domains = domains_train[batch_idx * X.size(0):batch_idx * X.size(0) + X.size(0)].to(device)
            
            optimizer.zero_grad()
            
            # Forward pass
            predictions, causal_features = model(X)
            
            # Standardize features domain-wise
            causal_features = standardize_domain_wise(causal_features, batch_domains)
            
            # Calculate prediction loss
            pred_loss = criterion(predictions, y)
            
            # Calculate invariance loss
            inv_loss, avg_weight = calculate_domain_invariance_loss(causal_features, predictions, y, batch_domains)
            
            # Calculate alignment loss for decorrelation
            align_loss = calculate_alignment_loss(causal_features, batch_domains)
            
            # Total loss
            loss = pred_loss + lambda1 * inv_loss + lambda2 * align_loss
            
            # Backward and optimize
            loss.backward()
            optimizer.step()
            
            # Update model's linear weights with the average weight
            with torch.no_grad():
                model.linear.copy_(avg_weight.squeeze())
            
            epoch_loss += loss.item()
            epoch_pred_loss += pred_loss.item()
            epoch_inv_loss += inv_loss.item()
            epoch_align_loss += align_loss.item()
        
        # Validation
        model.eval()
        val_loss = 0
        with torch.no_grad():
            for batch_idx, (X, y) in enumerate(val_loader):
                X, y = X.to(device), y.to(device)
                predictions, _ = model(X)
                batch_loss = criterion(predictions, y)
                val_loss += batch_loss.item()
        
        # Calculate average losses
        avg_train_loss = epoch_loss / len(train_loader)
        avg_pred_loss = epoch_pred_loss / len(train_loader)
        avg_inv_loss = epoch_inv_loss / len(train_loader)
        avg_align_loss = epoch_align_loss / len(train_loader)
        avg_val_loss = val_loss / len(val_loader)
        
        train_losses.append(avg_train_loss)
        val_losses.append(avg_val_loss)
        
        print(f'Epoch {epoch+1}/{num_epochs}:')
        print(f'  Train Loss: {avg_train_loss:.4f} (Pred: {avg_pred_loss:.4f}, Inv: {avg_inv_loss:.4f}, Align: {avg_align_loss:.4f})')
        print(f'  Val Loss: {avg_val_loss:.4f}')
        
        # Early stopping
        if avg_val_loss < best_val_loss:
            best_val_loss = avg_val_loss
            patience_counter = 0
        else:
            patience_counter += 1
            if patience_counter >= early_stop_patience:
                print(f'Early stopping at epoch {epoch+1}')
                break
    
    return model, train_losses, val_losses

