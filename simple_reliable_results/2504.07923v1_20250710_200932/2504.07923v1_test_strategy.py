class TradingGNN(nn.Module):
    """Trading Graph Neural Network (TGNN) implementation."""
    
    def __init__(self):
        super(TradingGNN, self).__init__()
        # Parameters to learn
        self.theta_x = nn.Parameter(torch.FloatTensor([0.1]))  # Initialize close to zero
        self.theta_y = nn.Parameter(torch.FloatTensor([0.1]))
        self.gamma = nn.Parameter(torch.FloatTensor([0.1]))
    
    def forward(self, data, max_iterations=10, convergence_threshold=1e-4):
        """
        Forward pass of the TGNN model.
        
        Args:
            data: Dictionary containing network data
            max_iterations: Maximum number of message passing iterations
            convergence_threshold: Convergence threshold for dealer values
            
        Returns:
            Dictionary of predicted prices and intermediate values
        """
        # Extract data
        asset_features = data['asset_features']
        dealer_features = data['dealer_features']
        relationship_features = data['relationship_features']
        customer_values = data['customer_values']
        networks = data['networks']
        
        # Calculate dealer costs using parameters
        dealer_costs = {}
        for i, k, t in data['dealer_indices']:
            cost_factor = (asset_features[k, t] * self.theta_x + 
                          dealer_features[i, t] * self.theta_y)
            dealer_costs[(i, k, t)] = torch.exp(cost_factor)
        
        # Calculate bargaining powers using parameters
        bargaining_powers = {}
        for i, j, k, t in data['edge_indices']:
            edge_feature = relationship_features.get((i, j, k, t), 0)
            bargaining_powers[(i, j, k, t)] = torch.sigmoid(edge_feature * self.gamma)
        
        # Initialize dealer values
        dealer_values = {}
        for i, k, t in data['dealer_indices']:
            dealer_values[(i, k, t)] = -dealer_costs[(i, k, t)] + customer_values[(i, k, t)]
        
        # Message passing iterations (contraction mapping)
        for iteration in range(max_iterations):
            old_values = dealer_values.copy()
            
            # Update potential transaction prices
            potential_prices = {}
            for i, j, k, t in data['edge_indices']:
                bp = bargaining_powers[(i, j, k, t)]
                potential_prices[(i, j, k, t)] = (bp * dealer_values[(i, k, t)] + 
                                               (1 - bp) * dealer_values[(j, k, t)])
            
            # Update dealer values
            max_change = 0
            for i, k, t in data['dealer_indices']:
                G = networks[(k, t)]
                neighbors = list(G.successors(i))
                
                if neighbors:
                    best_price = float('-inf')
                    for j in neighbors:
                        price = potential_prices.get((i, j, k, t), float('-inf'))
                        best_price = max(best_price, price)
                    
                    new_value = -dealer_costs[(i, k, t)] + max(best_price, customer_values[(i, k, t)])
                    change = abs(new_value - dealer_values[(i, k, t)])
                    max_change = max(max_change, change)
                    dealer_values[(i, k, t)] = new_value
                else:
                    dealer_values[(i, k, t)] = -dealer_costs[(i, k, t)] + customer_values[(i, k, t)]
            
            if max_change < convergence_threshold:
                break
        
        # Determine predicted best prices
        predicted_prices = {}
        for seller, buyer, asset, day in data['observed_indices']:
            G = networks[(asset, day)]
            neighbors = list(G.successors(seller))
            
            if neighbors:
                best_price = float('-inf')
                for j in neighbors:
                    price = potential_prices.get((seller, j, asset, day), float('-inf'))
                    if price > best_price:
                        best_price = price
                
                if best_price > customer_values[(seller, asset, day)]:
                    predicted_prices[(seller, buyer, asset, day)] = best_price
                else:
                    predicted_prices[(seller, buyer, asset, day)] = customer_values[(seller, asset, day)]
            else:
                predicted_prices[(seller, buyer, asset, day)] = customer_values[(seller, asset, day)]
        
        return {
            'predicted_prices': predicted_prices,
            'dealer_values': dealer_values,
            'bargaining_powers': bargaining_powers,
            'dealer_costs': dealer_costs,
            'potential_prices': potential_prices
        }


def train_tgnn(data_df, network, n_epochs=200, learning_rate=0.01):
    """
    Train the TGNN model on simulated data.
    
    Args:
        data_df: DataFrame containing observed prices
        network: TradingNetwork object with network structure
        n_epochs: Number of training epochs
        learning_rate: Learning rate for optimization
        
    Returns:
        Trained model and training statistics
    """
    # Create model
    model = TradingGNN()
    optimizer = optim.Adam(model.parameters(), lr=learning_rate)
    
    # Prepare data for model
    model_data = {
        'asset_features': network.asset_features,
        'dealer_features': network.dealer_features,
        'relationship_features': network.relationship_features,
        'customer_values': {(i, k, t): torch.tensor(network.customer_values[i, k, t], dtype=torch.float32)
                           for i in range(network.n_dealers)
                           for k in range(network.n_assets)
                           for t in range(network.n_days)},
        'networks': network.networks,
        'dealer_indices': [(i, k, t) for i in range(network.n_dealers)
                          for k in range(network.n_assets)
                          for t in range(network.n_days)],
        'edge_indices': list(network.relationship_features.keys()),
        'observed_indices': [(row['seller'], row['buyer'], row['asset'], row['day']) 
                            for _, row in data_df.iterrows()]
    }
    
    # Observed prices tensor
    observed_prices = {(row['seller'], row['buyer'], row['asset'], row['day']): torch.tensor(row['price'], dtype=torch.float32)
                      for _, row in data_df.iterrows()}
    
    # Training loop
    losses = []
    parameters = {'theta_x': [], 'theta_y': [], 'gamma': []}
    
    for epoch in range(n_epochs):
        optimizer.zero_grad()
        
        # Forward pass
        outputs = model(model_data)
        predicted_prices = outputs['predicted_prices']
        
        # Calculate loss (MSE)
        loss = 0
        for idx in observed_prices:
            if idx in predicted_prices:
                loss += (predicted_prices[idx] - observed_prices[idx])**2
        
        if len(observed_prices) > 0:
            loss /= len(observed_prices)
        
        # Backward pass and optimization
        loss.backward()
        optimizer.step()
        
        # Track progress
        losses.append(loss.item())
        parameters['theta_x'].append(model.theta_x.item())
        parameters['theta_y'].append(model.theta_y.item())
        parameters['gamma'].append(model.gamma.item())
        
        if (epoch + 1) % 50 == 0:
            print(f"Epoch {epoch+1}/{n_epochs}, Loss: {loss.item():.6f}, "
                  f"Parameters: θₓ={model.theta_x.item():.4f}, "
                  f"θᵧ={model.theta_y.item():.4f}, "
                  f"γ={model.gamma.item():.4f}")
    
    training_stats = {
        'losses': losses,
        'parameters': parameters
    }
    
    return model, training_stats


def bootstrap_confidence_intervals(data_df, network, n_bootstrap=50, n_epochs=100):
    """
    Compute bootstrap confidence intervals for model parameters.
    
    Args:
        data_df: DataFrame of observed prices
        network: TradingNetwork object
        n_bootstrap: Number of bootstrap samples
        n_epochs: Number of training epochs per bootstrap
        
    Returns:
        Dictionary of parameter estimates with confidence intervals
    """
    bootstrap_results = {
        'theta_x': [],
        'theta_y': [],
        'gamma': []
    }
    
    # Run bootstrap iterations
    for b in tqdm(range(n_bootstrap), desc="Bootstrap Progress"):
        try:
            # Sample with replacement from observed prices
            bootstrap_sample = data_df.sample(n=len(data_df), replace=True)
            
            # Train model on bootstrap sample
            model, _ = train_tgnn(bootstrap_sample, network, n_epochs=n_epochs, learning_rate=0.01)
            
            # Save parameter estimates
            bootstrap_results['theta_x'].append(model.theta_x.item())
            bootstrap_results['theta_y'].append(model.theta_y.item())
            bootstrap_results['gamma'].append(model.gamma.item())
        except Exception as e:
            print(f"Error in bootstrap iteration {b}: {e}")
            continue
    
    # Calculate confidence intervals (95%)
    confidence_intervals = {}
    for param in bootstrap_results:
        values = np.array(bootstrap_results[param])
        confidence_intervals[param] = {
            'mean': np.mean(values),
            'median': np.median(values),
            'lower': np.percentile(values, 2.5),
            'upper': np.percentile(values, 97.5),
            'std': np.std(values)
        }
    
    return confidence_intervals


