def evaluate_model_performance(model, data_df, network):
    """
    Evaluate TGNN model performance on test data.
    
    Args:
        model: Trained TGNN model
        data_df: DataFrame of observed prices
        network: TradingNetwork object
        
    Returns:
        Dictionary of performance metrics
    """
    # Prepare data for model evaluation
    model_data = {
        'asset_features': network.asset_features,
        'dealer_features': network.dealer_features,
        'relationship_features': network.relationship_features,
        'customer_values': {(i, k, t): torch.tensor(network.customer_values[i, k, t], dtype=torch.float32)
                           for i in range(network.n_dealers)
                           for k in range(network.n_assets)
                           for t in range(network.n_days)},
        'networks': network.networks,
        'dealer_indices': [(i, k, t) for i in range(network.n_dealers)
                          for k in range(network.n_assets)
                          for t in range(network.n_days)],
        'edge_indices': list(network.relationship_features.keys()),
        'observed_indices': [(row['seller'], row['buyer'], row['asset'], row['day']) 
                            for _, row in data_df.iterrows()]
    }
    
    # Get model predictions
    with torch.no_grad():
        outputs = model(model_data)
    
    # Extract predictions
    predicted_prices = outputs['predicted_prices']
    
    # Create arrays of actual and predicted values
    actual = []
    predicted = []
    
    for _, row in data_df.iterrows():
        idx = (row['seller'], row['buyer'], row['asset'], row['day'])
        if idx in predicted_prices:
            actual.append(row['price'])
            predicted.append(predicted_prices[idx].item())
    
    # Calculate metrics
    actual = np.array(actual)
    predicted = np.array(predicted)
    
    mse = np.mean((actual - predicted)**2)
    mae = np.mean(np.abs(actual - predicted))
    r2 = 1 - np.sum((actual - predicted)**2) / np.sum((actual - np.mean(actual))**2)
    
    # Calculate information criteria (AIC and BIC)
    n = len(actual)
    k = 3  # Number of parameters in TGNN
    aic = n * np.log(mse) + 2 * k
    bic = n * np.log(mse) + k * np.log(n)
    
    return {
        'mse': mse,
        'mae': mae,
        'r2': r2,
        'aic': aic,
        'bic': bic,
        'actual': actual,
        'predicted': predicted
    }


def visualize_results(training_stats, bootstrap_results, performance, network_type="random"):
    """
    Visualize training results and model performance.
    
    Args:
        training_stats: Dictionary of training statistics
        bootstrap_results: Dictionary of bootstrap confidence intervals
        performance: Dictionary of performance metrics
        network_type: Type of network used in simulation
    """
    # Create figure with subplots
    fig, axs = plt.subplots(2, 2, figsize=(14, 10))
    
    # Plot training loss
    axs[0, 0].plot(training_stats['losses'])
    axs[0, 0].set_title('Training Loss')
    axs[0, 0].set_xlabel('Epoch')
    axs[0, 0].set_ylabel('MSE Loss')
    axs[0, 0].grid(True)
    
    # Plot parameter convergence
    axs[0, 1].plot(training_stats['parameters']['theta_x'], label='θₓ')
    axs[0, 1].plot(training_stats['parameters']['theta_y'], label='θᵧ')
    axs[0, 1].plot(training_stats['parameters']['gamma'], label='γ')
    axs[0, 1].axhline(y=1.0, color='r', linestyle='--', alpha=0.5)  # True value
    axs[0, 1].set_title('Parameter Convergence')
    axs[0, 1].set_xlabel('Epoch')
    axs[0, 1].set_ylabel('Parameter Value')
    axs[0, 1].legend()
    axs[0, 1].grid(True)
    
    # Plot bootstrap distributions
    params = ['theta_x', 'theta_y', 'gamma']
    colors = ['blue', 'green', 'orange']
    
    for i, param in enumerate(params):
        values = np.array(bootstrap_results[param])
        if len(values) > 0:
            # Kernel density estimation
            density = np.linspace(min(values), max(values), 100)
            kde = norm.pdf(density, np.mean(values), np.std(values))
            
            axs[1, 0].plot(density, kde, color=colors[i], label=f"{param}")
            axs[1, 0].axvline(x=1.0, color='r', linestyle='--', alpha=0.5)  # True value
            axs[1, 0].axvline(x=np.mean(values), color=colors[i], linestyle='-', alpha=0.7)
            
    axs[1, 0].set_title('Bootstrap Parameter Distributions')
    axs[1, 0].set_xlabel('Parameter Value')
    axs[1, 0].set_ylabel('Density')
    axs[1, 0].legend()
    axs[1, 0].grid(True)
    
    # Plot predicted vs actual prices
    axs[1, 1].scatter(performance['actual'], performance['predicted'], alpha=0.6)
    min_val = min(min(performance['actual']), min(performance['predicted']))
    max_val = max(max(performance['actual']), max(performance['predicted']))
    axs[1, 1].plot([min_val, max_val], [min_val, max_val], 'r--')
    axs[1, 1].set_title('Predicted vs Actual Prices')
    axs[1, 1].set_xlabel('Actual Price')
    axs[1, 1].set_ylabel('Predicted Price')
    axs[1, 1].grid(True)
    
    plt.suptitle(f'TGNN Results on {network_type.capitalize()} Network', fontsize=16)
    plt.tight_layout(rect=[0, 0, 1, 0.96])
    plt.show()


