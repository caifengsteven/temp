    total_volume = sum(trade.volume for trade in day_trades)
    prices = [trade.price for trade in day_trades]
    volatility = (max(prices) - min(prices)) / prices[0]
    
    # Generate metaorders
    original_metaorders = generator.generate_metaorders(day_trades)
    random_metaorders = generator.generate_metaorders(random_day_trades)
    
