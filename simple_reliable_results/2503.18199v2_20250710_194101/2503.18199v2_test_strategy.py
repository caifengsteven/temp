class Trade:
    """Represents a single trade from public data"""
    def __init__(self, timestamp: datetime, price: float, volume: float, sign: int):
        self.timestamp = timestamp
        self.price = price
        self.volume = volume  # Trade volume
        self.sign = sign      # 1 for buy, -1 for sell
        self.trader_id = None # Will be assigned by mapping function

class Metaorder:
    """A collection of child orders from the same trader with the same sign"""
    def __init__(self, trader_id: int, sign: int, start_time: datetime):
        self.trader_id = trader_id
        self.sign = sign
        self.start_time = start_time
        self.end_time = None
        self.child_orders: List[Trade] = []
        self.start_price = None
        self.end_price = None
        self.total_volume = 0
        
    def add_child_order(self, trade: Trade):
        """Add a child order to this metaorder"""
        self.child_orders.append(trade)
        self.total_volume += trade.volume
        self.end_time = trade.timestamp
        
    def set_prices(self, start_price: float, end_price: float):
        """Set the start and end prices for impact calculation"""
        self.start_price = start_price
        self.end_price = end_price
        
    def impact(self) -> float:
        """Calculate price impact according to the paper's definition"""
        if self.start_price is None or self.end_price is None:
            return np.nan
        return self.sign * (self.end_price - self.start_price) / self.start_price
    
    def duration(self) -> timedelta:
        """Return the duration of the metaorder"""
        if self.end_time is None:
            return timedelta(0)
        return self.end_time - self.start_time
    
    def __str__(self):
        return f"Metaorder: trader={self.trader_id}, sign={self.sign}, " \
               f"n_child_orders={len(self.child_orders)}, volume={self.total_volume:.2f}, " \
               f"impact={self.impact() if self.start_price else 'N/A'}"


class MetaorderGenerator:
    """Implements the algorithm described in the paper"""
    
    def __init__(self, num_traders: int = 20, distribution_type: str = "homogeneous", power_law_exponent: float = 2.0):
        """
        Initialize the generator with mapping function parameters
        
        Args:
            num_traders: Number of traders to simulate
            distribution_type: "homogeneous" or "power_law"
            power_law_exponent: Exponent for power law distribution (if used)
        """
        self.num_traders = num_traders
        self.distribution_type = distribution_type
        self.power_law_exponent = power_law_exponent
        
    def _generate_trader_frequencies(self) -> np.ndarray:
        """Generate frequencies for each trader based on distribution type"""
        if self.distribution_type == "homogeneous":
            return np.ones(self.num_traders)
        elif self.distribution_type == "power_law":
            # Generate power law distributed frequencies
            ranks = np.arange(1, self.num_traders + 1)
            frequencies = ranks ** (-self.power_law_exponent)
            return frequencies
        else:
            raise ValueError(f"Unknown distribution type: {self.distribution_type}")
    
    def _map_trades_to_traders(self, trades: List[Trade]) -> None:
        """Implement the mapping function as described in Algorithm 2"""
        frequencies = self._generate_trader_frequencies()
        probabilities = frequencies / np.sum(frequencies)
        cumulative_probs = np.cumsum(probabilities)
        
        for trade in trades:
            u = np.random.random()
            trader_id = np.searchsorted(cumulative_probs, u)
            trade.trader_id = trader_id
    
    def generate_metaorders(self, trades: List[Trade]) -> List[Metaorder]:
        """
        Generate synthetic metaorders from public trade data
        
        Args:
            trades: List of trades with price, volume, and sign information
            
        Returns:
            List of synthetic metaorders
        """
        # Step 1: Apply mapping function to assign trader IDs
        self._map_trades_to_traders(trades)
        
        # Step 2: Sort trades by trader and timestamp (already sorted by timestamp)
        trades_by_trader = defaultdict(list)
        for trade in trades:
            trades_by_trader[trade.trader_id].append(trade)
            
        # Step 3: Create metaorders by aggregating consecutive same-sign trades
        metaorders = []
        
        for trader_id, trader_trades in trades_by_trader.items():
            current_metaorder = None
            
            for i, trade in enumerate(trader_trades):
                # Start a new metaorder if needed
                if current_metaorder is None or current_metaorder.sign != trade.sign:
                    if current_metaorder is not None:
                        # Set end price as the price before the first trade from another metaorder
                        if i < len(trader_trades) - 1:
                            current_metaorder.set_prices(
                                current_metaorder.child_orders[0].price,
                                trade.price
                            )
                        metaorders.append(current_metaorder)
                        
                    current_metaorder = Metaorder(trader_id, trade.sign, trade.timestamp)
                
                # Add the trade to the current metaorder
                current_metaorder.add_child_order(trade)
                
                # Set start price as the price before the first child order
                if len(current_metaorder.child_orders) == 1:
                    # In a real implementation, we'd look at the actual order book state
                    # For simulation, we'll use the trade price as an approximation
                    current_metaorder.start_price = trade.price
            
            # Don't forget the last metaorder
            if current_metaorder is not None:
                if trader_trades:
                    current_metaorder.set_prices(
                        current_metaorder.child_orders[0].price,
                        trader_trades[-1].price
                    )
                metaorders.append(current_metaorder)
        
        # Filter out metaorders with only one child order
        metaorders = [mo for mo in metaorders if len(mo.child_orders) > 1]
        
        return metaorders
    
    @staticmethod
    def analyze_square_root_law(metaorders: List[Metaorder], daily_volume: float, daily_volatility: float) -> Tuple[np.ndarray, np.ndarray]:
        """
        Analyze metaorders to validate the Square Root Law
        
        Args:
            metaorders: List of metaorders
            daily_volume: Total daily volume
            daily_volatility: Daily price volatility
            
        Returns:
            x, y: Arrays for plotting sqrt(Q/V_D) vs I(Q)/sigma_D
        """
        q_v_ratios = []
        normalized_impacts = []
        
        for mo in metaorders:
            q_v_ratio = mo.total_volume / daily_volume
            impact = mo.impact()
            
            if not np.isnan(impact) and q_v_ratio > 0:
                normalized_impact = impact / daily_volatility
                q_v_ratios.append(q_v_ratio)
                normalized_impacts.append(normalized_impact)
        
        # Convert to numpy arrays for further processing
        x = np.array(q_v_ratios)
        y = np.array(normalized_impacts)
        
        return x, y


def generate_simulated_trade_data(n_days: int = 1, trades_per_day: int = 1000) -> List[Trade]:
    """
    Generate simulated trade data for testing
    
    Args:
        n_days: Number of days to simulate
        trades_per_day: Number of trades per day
        
    Returns:
        List of simulated trades
    """
    trades = []
    base_price = 100.0
    price = base_price
    daily_vol = 0.015  # 1.5% daily volatility
    
    # Create trade sign autocorrelation (as per empirical research)
    # Using simple AR(1) process for signs with persistence
    sign_persistence = 0.7
    current_sign = 1 if random.random() > 0.5 else -1
    
    start_date = datetime(2023, 1, 1, 9, 30)
    
    for day in range(n_days):
        day_start = start_date + timedelta(days=day)
        
        # Reset price at the start of each day (simplified)
        price = base_price * (1 + np.random.normal(0, 0.01))
        
        for i in range(trades_per_day):
            # Time within trading day (6.5 hours)
            seconds_in_day = random.randint(0, 6 * 60 * 60 + 30 * 60)
            timestamp = day_start + timedelta(seconds=seconds_in_day)
            
            # Generate trade sign with autocorrelation
            if random.random() > sign_persistence:
                current_sign = -current_sign
            
            # Random volume - lognormal distribution
            volume = np.random.lognormal(mean=3, sigma=1)
            
            # Price impact - small random movement plus impact from order
            # Square root impact on price as per paper
            impact_factor = 0.1
            price_impact = impact_factor * current_sign * (volume ** 0.5) / (trades_per_day ** 0.5)
            
            # Add some random noise
            noise = np.random.normal(0, daily_vol / np.sqrt(trades_per_day))
            price *= (1 + price_impact + noise)
            
            trade = Trade(timestamp, price, volume, current_sign)
            trades.append(trade)
    
    # Sort by timestamp (should already be sorted but just to be sure)
    trades.sort(key=lambda x: x.timestamp)
    
    return trades


