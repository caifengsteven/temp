class OptimizationProblem:
    """Base class for optimization problems"""
    
    def __init__(self, noise_level: float = 1.0):
        self.noise_level = noise_level
        
    def objective(self, x: np.ndarray) -> float:
        """Returns the true (noiseless) objective function value"""
        raise NotImplementedError
    
    def noisy_objective(self, x: np.ndarray) -> float:
        """Returns a noisy evaluation of the objective function"""
        return self.objective(x) + np.random.normal(0, self.noise_level)
    
    def optimal_point(self) -> np.ndarray:
        """Returns the optimal solution"""
        raise NotImplementedError
    
    def optimal_value(self) -> float:
        """Returns the optimal value"""
        return self.objective(self.optimal_point())
    
    def dimension(self) -> int:
        """Returns the dimension of the problem"""
        raise NotImplementedError


