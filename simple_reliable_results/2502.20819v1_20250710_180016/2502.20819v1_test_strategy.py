class KWSAOptimizer:
    """Kiefer-Wolfowitz Stochastic Approximation (KWSA) Optimizer"""
    
    def __init__(self, 
                 problem: OptimizationProblem, 
                 init_point: np.ndarray,
                 max_fevals: int = 10000,
                 theta_a: float = 1.0,
                 theta_c: float = 1.0):
        """
        Initialize the KWSA optimizer
        
        Args:
            problem: The optimization problem
            init_point: Initial point
            max_fevals: Maximum number of function evaluations
            theta_a: Step size parameter
            theta_c: Perturbation parameter
        """
        self.problem = problem
        self.x = init_point.copy()
        self.max_fevals = max_fevals
        self.fevals = 0
        self.theta_a = theta_a
        self.theta_c = theta_c
        self.dim = problem.dimension()
        self.iterations = 0
        self.history = {'x': [self.x.copy()], 
                       'f': [problem.objective(self.x)],
                       'fevals': [0]}
        self.oscillations = 0
        self.boundary = np.array([-50, 50])  # Boundaries for test problems
    
    def optimize(self) -> Tuple[np.ndarray, float, int]:
        """Run the optimization algorithm"""
        prev_x = self.x.copy()
        
        while self.fevals < self.max_fevals:
            self.iterations += 1
            
            # Calculate step size and perturbation
            a_k = self.theta_a / self.iterations
            c_k = self.theta_c / (self.iterations ** 0.25)
            
            # Estimate gradient using finite differences
            grad = np.zeros(self.dim)
            for i in range(self.dim):
                x_plus = self.x.copy()
                x_minus = self.x.copy()
                x_plus[i] += c_k
                x_minus[i] -= c_k
                
                f_plus = self.problem.noisy_objective(x_plus)
                f_minus = self.problem.noisy_objective(x_minus)
                
                self.fevals += 2
                
                grad[i] = (f_plus - f_minus) / (2 * c_k)
            
            # Update solution
            self.x = self.x - a_k * grad
            
            # Enforce boundaries
            if self.dim == 1:
                if np.any(self.x < self.boundary[0]) or np.any(self.x > self.boundary[1]):
                    self.x = np.clip(self.x, self.boundary[0], self.boundary[1])
                    # Check for oscillation at boundary
                    if np.any(prev_x == self.boundary[0]) or np.any(prev_x == self.boundary[1]):
                        if not np.array_equal(prev_x, self.x):
                            self.oscillations += 1
            
            prev_x = self.x.copy()
            
            # Update history
            self.history['x'].append(self.x.copy())
            self.history['f'].append(self.problem.objective(self.x))
            self.history['fevals'].append(self.fevals)
            
            # Print progress
            if self.iterations % 100 == 0:
                print(f"Iteration {self.iterations}: f={self.history['f'][-1]:.6f}, "
                      f"fevals={self.fevals}, step_size={a_k:.6f}")
        
        return self.x, self.problem.objective(self.x), self.fevals


class SPSAOptimizer:
    """Simultaneous Perturbation Stochastic Approximation (SPSA) Optimizer"""
    
    def __init__(self, 
                 problem: OptimizationProblem, 
                 init_point: np.ndarray,
                 max_fevals: int = 10000,
                 theta_a: float = 1.0,
                 theta_c: float = 0.1):
        """
        Initialize the SPSA optimizer
        
        Args:
            problem: The optimization problem
            init_point: Initial point
            max_fevals: Maximum number of function evaluations
            theta_a: Step size parameter
            theta_c: Perturbation parameter
        """
