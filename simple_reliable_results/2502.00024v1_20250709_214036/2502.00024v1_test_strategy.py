        month_combined = pd.concat([walmart_month, amazon_month], ignore_index=True)
        results['month_of_year_comparison'] = month_combined
        
        # 3. Gift Cards correlation with Google Trends
        # First, generate Google Trends data if it doesn't exist
        if self.google_trends_data is None:
            self.generate_google_trends_data(keywords=["Amazon Giftcard"])
        
        # Filter Amazon data for gift cards
        gift_card_reviews = self.amazon_review_data[self.amazon_review_data['category'] == 'Gift Cards'].copy()
        
        # Aggregate by week
        gift_card_reviews['year_week'] = gift_card_reviews['review_date'].dt.strftime('%Y-%U')
        weekly_gift_card = gift_card_reviews.groupby('year_week').size().reset_index(name='review_count')
        
        # Convert Google Trends data to weekly format
        google_trends_weekly = self.google_trends_data.copy()
        google_trends_weekly['year_week'] = google_trends_weekly['date'].dt.strftime('%Y-%U')
        
        # Check if 'Amazon Giftcard' is in the columns
        if 'Amazon Giftcard' in google_trends_weekly.columns:
            trends_gift_card = google_trends_weekly[['year_week', 'Amazon Giftcard']].rename(
                columns={'Amazon Giftcard': 'trend_value'})
            
            # Merge the datasets
            gift_card_correlation = pd.merge(
                weekly_gift_card, 
                trends_gift_card, 
                on='year_week', 
                how='outer'
            ).fillna(0)
            
            results['gift_card_correlation'] = gift_card_correlation
        
        return results

