    def test_google_trends_prediction(self):
        """Test prediction of Google Trends data using decision tree regressor."""
        if self.google_trends_data is None:
            self.generate_google_trends_data()
        
        # Select a sample keyword
        keyword = "smartphone"
        
        # Prepare the data
        data = self.google_trends_data[['date', keyword]].copy()
        
        # Feature engineering as described in the PDF
        data['year'] = data['date'].dt.year
        data['month'] = data['date'].dt.month
        data['day'] = data['date'].dt.day
        
        # Season feature (1: spring, 2: summer, 3: fall, 4: winter)
        def get_season(month):
            if month in [3, 4, 5]:
                return 1  # Spring
            elif month in [6, 7, 8]:
                return 2  # Summer
            elif month in [9, 10, 11]:
                return 3  # Fall
            else:
                return 4  # Winter
        
        data['season'] = data['month'].apply(get_season)
        
        # Holiday feature
        def is_holiday(date):
            # Check for major holidays (simplified)
            month, day = date.month, date.day
            
            # Christmas
            if (month == 12 and day >= 15 and day <= 31) or (month == 1 and day <= 5):
                return 1
            # Thanksgiving
            elif month == 11 and day >= 20 and day <= 30:
                return 1
            # Valentine's Day
            elif month == 2 and day >= 7 and day <= 14:
                return 1
            # Black Friday
            elif month == 11 and day >= 20 and day <= 30:
                return 1
            # New Year
            elif (month == 12 and day >= 26) or (month == 1 and day <= 5):
                return 1
            else:
                return 0
        
        data['is_holiday'] = data['date'].apply(is_holiday)
        
        # Day of week and weekend features
        data['day_of_week'] = data['date'].dt.dayofweek + 1  # 1-7 (Monday to Sunday)
        data['is_weekend'] = ((data['day_of_week'] == 1) | (data['day_of_week'] == 7)).astype(int)
        
        # Cyclical features for season
        data['day_of_year'] = data['date'].dt.dayofyear
        data['sin_season'] = np.sin(2 * np.pi * data['day_of_year'] / 365)
        data['cos_season'] = np.cos(2 * np.pi * data['day_of_year'] / 365)
        
        # Prepare features for the model
        features = ['year', 'month', 'day', 'season', 'is_holiday', 
                    'day_of_week', 'is_weekend', 'sin_season', 'cos_season']
        
        X = data[features]
        y = data[keyword]
        
        # Split data into training and testing sets (80% train, 20% test)
        split_idx = int(len(data) * 0.8)
        X_train, X_test = X[:split_idx], X[split_idx:]
        y_train, y_test = y[:split_idx], y[split_idx:]
        
        # Train decision tree regressor
        dt_model = DecisionTreeRegressor(random_state=42)
        dt_model.fit(X_train, y_train)
        
        # Make predictions
        y_pred = dt_model.predict(X_test)
        
        # Calculate RMSE
        rmse = np.sqrt(mean_squared_error(y_test, y_pred))
        
        # Make a prediction for a future date (e.g., 2024-12-31)
        future_date = pd.Timestamp('2024-12-31')
        future_features = pd.DataFrame({
            'year': [future_date.year],
            'month': [future_date.month],
            'day': [future_date.day],
            'season': [get_season(future_date.month)],
            'is_holiday': [is_holiday(future_date)],
            'day_of_week': [future_date.dayofweek + 1],
            'is_weekend': [1 if future_date.dayofweek in [5, 6] else 0],
            'sin_season': [np.sin(2 * np.pi * future_date.dayofyear / 365)],
            'cos_season': [np.cos(2 * np.pi * future_date.dayofyear / 365)]
        })
        
        future_prediction = dt_model.predict(future_features)[0]
        
        return {
            'keyword': keyword,
            'rmse': rmse,
            'future_date': '2024-12-31',
            'future_prediction': future_prediction
        }
    
