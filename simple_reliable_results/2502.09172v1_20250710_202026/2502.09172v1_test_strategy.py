def calculate_price_impact(states, messages, lag_times):
    """Calculate price impact response functions as described in the paper"""
    # Event classification according to paper
    impact_events = []
    
    for i, msg in enumerate(messages):
        if i >= len(states) - 1:
            continue
            
        event_type = None
        affects_mid_price = False
        
        # Check if the event affects the mid-price
        mid_before = states[i].mid_price
        mid_after = states[i+1].mid_price
        affects_mid_price = abs(mid_after - mid_before) > 0
        
        # Classify the event
        if msg.type_id == 1:  # Limit order
            event_type = "LO1" if affects_mid_price else "LO0"
        elif msg.type_id == 2:  # Cancellation
            event_type = "CA1" if affects_mid_price else "CA0"
        elif msg.type_id == 3 or msg.type_id == 4:  # Execution (treat as market order)
            event_type = "MO1" if affects_mid_price else "MO0"
        
        if event_type:
            impact_events.append({
                'index': i,
                'type': event_type,
                'direction': msg.direction,
                'epsilon': msg.direction if event_type.startswith(('MO', 'LO')) else -msg.direction,
                'time': msg.time
            })
    
    # Calculate response functions for each event type and lag
    response_functions = defaultdict(list)
    
    for lag in lag_times:
        for event_type in ["MO0", "MO1", "LO0", "LO1", "CA0", "CA1"]:
            responses = []
            
            for event in impact_events:
                if event['type'] != event_type or event['index'] + lag >= len(states):
                    continue
                
                # Calculate price change
                price_before = states[event['index']].mid_price
                price_after = states[event['index'] + lag].mid_price
                price_change = price_after - price_before
                
                # Adjust by epsilon
                adjusted_change = price_change * event['epsilon']
                responses.append(adjusted_change)
            
            # Average response for this event type and lag
            if responses:
                avg_response = np.mean(responses)
                response_functions[event_type].append((lag, avg_response))
    
    return response_functions

def evaluate_price_impact(real_response, gen_response):
    """Calculate the L1 distance between real and generated response functions"""
    impact_scores = {}
    
    for event_type in ["MO0", "MO1", "LO0", "LO1", "CA0", "CA1"]:
        if event_type not in real_response or event_type not in gen_response:
            continue
            
        real_lags, real_responses = zip(*real_response[event_type])
        gen_lags, gen_responses = zip(*gen_response[event_type])
        
        # Ensure we have the same lags
        if set(real_lags) != set(gen_lags):
            continue
            
        # Calculate L1 distance
        diffs = [abs(real - gen) for (real, gen) in zip(real_responses, gen_responses)]
        l1 = np.mean(diffs) if diffs else 0
        
        impact_scores[event_type] = l1
    
    # Aggregate score
    impact_scores['mean'] = np.mean(list(impact_scores.values())) if impact_scores else 0
    
    return impact_scores

