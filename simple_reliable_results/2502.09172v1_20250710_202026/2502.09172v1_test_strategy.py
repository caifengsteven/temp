def update_lob_state(current_state, message):
    """Update the LOB state based on a new message"""
    # Create a copy of the current state
    new_state = LOBState(
        current_state.bid_prices.copy(),
        current_state.bid_sizes.copy(),
        current_state.ask_prices.copy(),
        current_state.ask_sizes.copy(),
        message.time
    )
    
    # Process the message
    if message.type_id == 1:  # New limit order
        if message.direction == 1:  # Buy
            # Find the correct position in the bid side
            idx = 0
            while idx < len(new_state.bid_prices) and message.price < new_state.bid_prices[idx]:
                idx += 1
            
            # Insert the new order
            if idx < len(new_state.bid_prices) and message.price == new_state.bid_prices[idx]:
                new_state.bid_sizes[idx] += message.size
            else:
                new_state.bid_prices.insert(idx, message.price)
                new_state.bid_sizes.insert(idx, message.size)
                
                # Keep only top 10 levels
                if len(new_state.bid_prices) > 10:
                    new_state.bid_prices = new_state.bid_prices[:10]
                    new_state.bid_sizes = new_state.bid_sizes[:10]
        else:  # Sell
            # Find the correct position in the ask side
            idx = 0
            while idx < len(new_state.ask_prices) and message.price > new_state.ask_prices[idx]:
                idx += 1
            
            # Insert the new order
            if idx < len(new_state.ask_prices) and message.price == new_state.ask_prices[idx]:
                new_state.ask_sizes[idx] += message.size
            else:
                new_state.ask_prices.insert(idx, message.price)
                new_state.ask_sizes.insert(idx, message.size)
                
                # Keep only top 10 levels
                if len(new_state.ask_prices) > 10:
                    new_state.ask_prices = new_state.ask_prices[:10]
                    new_state.ask_sizes = new_state.ask_sizes[:10]
    
    elif message.type_id == 2:  # Cancellation
        if message.direction == 1:  # Buy
            try:
                idx = new_state.bid_prices.index(message.price)
                new_state.bid_sizes[idx] -= message.size
                if new_state.bid_sizes[idx] <= 0:
                    new_state.bid_prices.pop(idx)
                    new_state.bid_sizes.pop(idx)
            except ValueError:
                pass  # Price level not found
        else:  # Sell
            try:
                idx = new_state.ask_prices.index(message.price)
                new_state.ask_sizes[idx] -= message.size
                if new_state.ask_sizes[idx] <= 0:
                    new_state.ask_prices.pop(idx)
                    new_state.ask_sizes.pop(idx)
            except ValueError:
                pass  # Price level not found
    
    elif message.type_id == 3:  # Execution
        if message.direction == 1:  # Buy (executing against ask)
            new_state.ask_sizes[0] -= message.size
            if new_state.ask_sizes[0] <= 0:
                new_state.ask_prices.pop(0)
                new_state.ask_sizes.pop(0)
        else:  # Sell (executing against bid)
            new_state.bid_sizes[0] -= message.size
            if new_state.bid_sizes[0] <= 0:
                new_state.bid_prices.pop(0)
                new_state.bid_sizes.pop(0)
    
    return new_state

def generate_lob_sequence(initial_state, n_messages):
    """Generate a sequence of LOB states and messages"""
    generator = LOBGenerator(initial_state)
    states = [initial_state]
    messages = []
    
    for _ in range(n_messages):
        msg = generator.generate_next_message()
        new_state = update_lob_state(states[-1], msg)
        messages.append(msg)
        states.append(new_state)
    
    return states, messages

def l1_distance(hist1, hist2):
    """Compute L1 distance between two histograms (normalized)"""
    if len(hist1) != len(hist2):
        raise ValueError("Histograms must have the same length")
    
    # Normalize histograms
    norm1 = hist1 / np.sum(hist1) if np.sum(hist1) > 0 else hist1
    norm2 = hist2 / np.sum(hist2) if np.sum(hist2) > 0 else hist2
    
    # Calculate L1 distance
    return 0.5 * np.sum(np.abs(norm1 - norm2))

def evaluate_spread_distribution(real_states, generated_states):
    """Evaluate the bid-ask spread distribution"""
    real_spreads = [state.spread for state in real_states]
    gen_spreads = [state.spread for state in generated_states]
    
    # Calculate statistics
    min_spread = min(min(real_spreads), min(gen_spreads))
    max_spread = max(max(real_spreads), max(gen_spreads))
    
    # Create histograms
    bins = np.linspace(min_spread, max_spread, 20)
    real_hist, _ = np.histogram(real_spreads, bins=bins)
    gen_hist, _ = np.histogram(gen_spreads, bins=bins)
    
    # Calculate L1 distance
    l1 = l1_distance(real_hist, gen_hist)
    
    # Calculate Wasserstein distance
    ws = wasserstein_distance(real_spreads, gen_spreads)
    
    return {
        'l1_distance': l1,
        'wasserstein_distance': ws
    }

