    plt.figure(figsize=(12, 6))
    
    # Calculate the efficient frontiers
    def calculate_frontier_points(results, n_points=20):
        min_return = np.min(results['terminal_wealth'])
        max_return = np.max(results['terminal_wealth'])
        returns = np.linspace(min_return, max_return, n_points)
        variances = []
        
        for ret in returns:
            # Find the portfolio with the closest return
            idx = np.argmin(np.abs(results['terminal_wealth'] - ret))
            variances.append(np.var(results['terminal_wealth'][idx:idx+1]))
        
        return returns, variances
    
    returns_ns, variances_ns = calculate_frontier_points(comparison_results['no_shorting'])
    returns_card, variances_card = calculate_frontier_points(comparison_results['cardinality'])
    returns_benchmark, variances_benchmark = calculate_frontier_points(comparison_results['benchmark'])
    
