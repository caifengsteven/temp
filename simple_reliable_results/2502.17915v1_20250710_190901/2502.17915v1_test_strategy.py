def generate_synthetic_data(n_assets: int, n_factors: int, n_periods: int, seed: int = 42) -> Tuple[np.ndarray, np.ndarray]:
    """
    Generate synthetic return and factor data based on a linear factor model.
    
    Args:
        n_assets: Number of assets
        n_factors: Number of factors
        n_periods: Number of time periods
        seed: Random seed
        
    Returns:
        Tuple of (returns, factors)
    """
    np.random.seed(seed)
    
    # Generate factor data with autocorrelation
    factors = np.zeros((n_periods, n_factors))
    factors[0] = np.random.normal(0, 1, n_factors)
    
    # Mean-reverting factor dynamics: s_t = (I - Φ)s_{t-1} + ξ_t
    Phi = 0.2 * np.eye(n_factors)
    for t in range(1, n_periods):
        factors[t] = (np.eye(n_factors) - Phi) @ factors[t-1] + np.random.normal(0, 0.2, n_factors)
    
    # Generate return data based on factor model: r_t = α + Bs_t + ε_t
    alpha = np.random.normal(0.01, 0.005, n_assets)
    B = np.random.normal(0, 0.5, (n_assets, n_factors))
    
    returns = np.zeros((n_periods, n_assets))
    for t in range(n_periods):
        returns[t] = alpha + B @ factors[t] + np.random.normal(0, 0.05, n_assets)
    
    return returns, factors


def compare_strategies(returns: np.ndarray, factors: np.ndarray, risk_free_rate: float = 0.01):
    """
    Compare different portfolio strategies:
    1. Factor-based MMV with no-shorting constraint
    2. Factor-based MMV with cardinality constraint
    3. Benchmark MMV (ignoring factor structure) with no-shorting constraint
    
    Args:
        returns: Matrix of asset returns
        factors: Matrix of factor values
        risk_free_rate: Risk-free rate
        
    Returns:
        Dictionary with comparison results
    """
    n_assets = returns.shape[1]
    n_factors = factors.shape[1]
    T = 6  # Investment horizon
    
    # 1. Factor-based MMV with no-shorting constraint
    model_ns = DynamicFactorMVPortfolio(
        n_assets=n_assets,
        n_factors=n_factors,
        T=T,
        risk_free_rate=risk_free_rate,
        constraint_type='no_shorting',
        target_wealth=1.2,
        initial_wealth=1.0
    )
    model_ns.fit_factor_model(returns, factors)
    
    # 2. Factor-based MMV with cardinality constraint
    model_card = DynamicFactorMVPortfolio(
        n_assets=n_assets,
        n_factors=n_factors,
        T=T,
        risk_free_rate=risk_free_rate,
        constraint_type='cardinality',
        cardinality=3,  # Allow only 3 active assets
        target_wealth=1.2,
        initial_wealth=1.0
    )
    model_card.fit_factor_model(returns, factors)
    
    # 3. Benchmark MMV (ignoring factor structure) with no-shorting constraint
    # For benchmark, we'll estimate the parameters without factor model
    model_benchmark = DynamicFactorMVPortfolio(
        n_assets=n_assets,
        n_factors=1,  # Dummy factor
        T=T,
        risk_free_rate=risk_free_rate,
        constraint_type='no_shorting',
        target_wealth=1.2,
        initial_wealth=1.0
    )
    
    # Create a dummy factor (just a constant)
    dummy_factors = np.ones((returns.shape[0], 1))
    model_benchmark.fit_factor_model(returns, dummy_factors)
    
    # Simulate performance
    results_ns = model_ns.simulate(n_simulations=100)
    results_card = model_card.simulate(n_simulations=100)
    results_benchmark = model_benchmark.simulate(n_simulations=100)
    
    return {
        'no_shorting': results_ns,
        'cardinality': results_card,
        'benchmark': results_benchmark
    }


