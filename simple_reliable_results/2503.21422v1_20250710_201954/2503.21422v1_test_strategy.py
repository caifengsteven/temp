class MarketSimulator:
    """Simulates market data for multiple assets"""
    
    def __init__(self, num_assets: int, days: int, volatility: float = 0.02):
        self.num_assets = num_assets
        self.days = days
        self.volatility = volatility
        self.price_data = None
        self.fundamental_data = None
        self.sentiment_data = None
        
    def generate_data(self) -> Tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
        """Generate price, fundamental, and sentiment data for simulation"""
        # Generate dates
        dates = [dt.datetime.now() - dt.timedelta(days=i) for i in range(self.days)]
        dates.reverse()
        
        # Asset names
        assets = [f"ASSET_{i}" for i in range(self.num_assets)]
        
        # Generate price data with random walk (geometric brownian motion)
        start_prices = np.random.uniform(50, 200, self.num_assets)
        daily_returns = np.random.normal(0.0005, self.volatility, (self.days, self.num_assets))
        
        # Create price matrix
        price_matrix = np.zeros((self.days, self.num_assets))
        price_matrix[0] = start_prices
        
        for i in range(1, self.days):
            price_matrix[i] = price_matrix[i-1] * (1 + daily_returns[i])
        
        # Convert to DataFrame
        self.price_data = pd.DataFrame(price_matrix, index=dates, columns=assets)
        
        # Generate fundamental data (quarterly)
        quarters = self.days // 60 + 1  # Approximately 60 trading days per quarter
        revenue_growth = np.random.normal(0.03, 0.02, (quarters, self.num_assets))
        profit_margin = np.random.normal(0.15, 0.05, (quarters, self.num_assets))
        
        # Expand quarterly data to daily (forward fill)
        revenue = np.zeros((self.days, self.num_assets))
        profit = np.zeros((self.days, self.num_assets))
        
        for i in range(quarters):
            start_idx = i * 60
            end_idx = min(start_idx + 60, self.days)
            for j in range(start_idx, end_idx):
                if j < self.days:
                    # Base revenue on price with some noise
                    revenue[j] = price_matrix[j] * (10 + np.random.normal(0, 2, self.num_assets))
                    # Profit is a percentage of revenue
                    quarter_profit_margin = profit_margin[i]
                    profit[j] = revenue[j] * quarter_profit_margin
        
        # Create DataFrames
        revenue_df = pd.DataFrame(revenue, index=dates, columns=assets)
        profit_df = pd.DataFrame(profit, index=dates, columns=assets)
        
        self.fundamental_data = {
            'revenue': revenue_df,
            'profit': profit_df
        }
        
        # Generate sentiment data (daily)
        # Sentiment partially correlates with recent price movements
        sentiment = np.zeros((self.days, self.num_assets))
        
        for i in range(5, self.days):
            # Recent price change affects sentiment
            recent_return = (price_matrix[i] - price_matrix[i-5]) / price_matrix[i-5]
            # Sentiment = price change effect + random noise
            sentiment[i] = 0.6 * recent_return + np.random.normal(0, 0.01, self.num_assets)
        
        self.sentiment_data = pd.DataFrame(sentiment, index=dates, columns=assets)
        
        return self.price_data, self.fundamental_data, self.sentiment_data
    
    def get_data(self) -> Tuple[pd.DataFrame, Dict[str, pd.DataFrame], pd.DataFrame]:
        """Return generated data or generate if not available"""
        if self.price_data is None:
            return self.generate_data()
        return self.price_data, self.fundamental_data, self.sentiment_data


class FactorGenerator:
    """Generates alpha factors from market data"""
    
    def __init__(self, price_data: pd.DataFrame, fundamental_data: Dict[str, pd.DataFrame], 
                 sentiment_data: pd.DataFrame):
        self.price_data = price_data
        self.fundamental_data = fundamental_data
        self.sentiment_data = sentiment_data
    
    def calculate_momentum(self, window: int = 20) -> pd.DataFrame:
        """Calculate price momentum factor"""
        return self.price_data.pct_change(window).fillna(0)
    
    def calculate_mean_reversion(self, window: int = 5) -> pd.DataFrame:
        """Calculate mean reversion factor"""
        rolling_mean = self.price_data.rolling(window=window).mean()
        return (rolling_mean - self.price_data) / self.price_data
    
    def calculate_pe_ratio(self) -> pd.DataFrame:
        """Calculate P/E ratio factor"""
        # Use quarterly profit, annualized
        pe_ratio = self.price_data / (self.fundamental_data['profit'] * 4 + 1e-10)  # Avoid division by zero
        return pe_ratio
    
    def calculate_sentiment_score(self) -> pd.DataFrame:
        """Use sentiment data directly as a factor"""
        return self.sentiment_data
    
    def generate_combined_factor(self) -> pd.DataFrame:
        """Combine multiple factors with equal weighting"""
        momentum = self.calculate_momentum()
        mean_reversion = self.calculate_mean_reversion()
        pe_ratio = self.calculate_pe_ratio()
        sentiment = self.calculate_sentiment_score()
        
        # Normalize factors
        scaler = StandardScaler()
        factors = []
        
        for factor in [momentum, mean_reversion, sentiment]:
            # Reshape for sklearn
            factor_values = factor.values.flatten()
            factor_values = factor_values.reshape(-1, 1)
            
            # Scale and reshape back
            scaled_values = scaler.fit_transform(factor_values)
            scaled_values = scaled_values.reshape(factor.shape)
            
            # Convert back to DataFrame and add to list
            scaled_factor = pd.DataFrame(scaled_values, index=factor.index, columns=factor.columns)
            factors.append(scaled_factor)
        
        # Inverse PE ratio (higher is better)
        pe_values = pe_ratio.values.flatten()
        pe_values = pe_values.reshape(-1, 1)
        scaled_pe = scaler.fit_transform(-pe_values)  # Negative to invert
        scaled_pe = scaled_pe.reshape(pe_ratio.shape)
        scaled_pe = pd.DataFrame(scaled_pe, index=pe_ratio.index, columns=pe_ratio.columns)
        factors.append(scaled_pe)
        
        # Combine with equal weights
        combined_factor = sum(factors) / len(factors)
        
        return combined_factor


class DeepLearningPredictor:
    """Simple predictor model (simplified to linear regression for demonstration)"""
    
    def __init__(self, factor_data: pd.DataFrame, price_data: pd.DataFrame, 
                 prediction_horizon: int = 5):
        self.factor_data = factor_data
        self.price_data = price_data
        self.prediction_horizon = prediction_horizon
        self.models = {}
    
    def prepare_data(self) -> Tuple[Dict[str, np.ndarray], Dict[str, np.ndarray]]:
        """Prepare data for training prediction models"""
        X_dict = {}
        y_dict = {}
        
        for asset in self.factor_data.columns:
            X = self.factor_data[asset].values[:-self.prediction_horizon]
            X = X.reshape(-1, 1)  # Reshape for sklearn
            
            # Future returns as target
            future_returns = self.price_data[asset].pct_change(self.prediction_horizon).shift(-self.prediction_horizon)
            y = future_returns.values[:-self.prediction_horizon]
            
            X_dict[asset] = X
            y_dict[asset] = y
            
        return X_dict, y_dict
    
    def train(self):
        """Train prediction models for each asset"""
        X_dict, y_dict = self.prepare_data()
        
        for asset in self.factor_data.columns:
            # In a real deep learning model, this would be a neural network
            # Using Linear Regression for simplicity
            model = LinearRegression()
            model.fit(X_dict[asset], y_dict[asset])
            self.models[asset] = model
    
    def predict(self, factor_data: pd.DataFrame) -> pd.DataFrame:
        """Make predictions using trained models"""
        predictions = {}
        
        for asset in factor_data.columns:
            if asset in self.models:
                X = factor_data[asset].values
                X = X.reshape(-1, 1)
                pred = self.models[asset].predict(X)
                predictions[asset] = pred
        
        return pd.DataFrame(predictions, index=factor_data.index)


class PortfolioOptimizer:
    """Portfolio optimization with risk constraints"""
    
    def __init__(self, expected_returns: pd.DataFrame, price_data: pd.DataFrame, 
                 max_position: float = 0.2, risk_aversion: float = 1.0):
        self.expected_returns = expected_returns
        self.price_data = price_data
        self.max_position = max_position
        self.risk_aversion = risk_aversion
    
    def calculate_covariance(self, window: int = 60) -> pd.DataFrame:
        """Calculate return covariance matrix"""
        returns = self.price_data.pct_change().fillna(0)
        return returns.rolling(window=window).cov().dropna()
    
    def optimize(self, date: pd.Timestamp) -> Dict[str, float]:
        """Simple portfolio optimization for demonstration"""
        assets = self.expected_returns.columns
        
        # Get expected returns for the given date
        if date in self.expected_returns.index:
            exp_returns = self.expected_returns.loc[date]
        else:
            # Use the most recent date before the given date
            available_dates = self.expected_returns.index[self.expected_returns.index <= date]
            if len(available_dates) > 0:
                exp_returns = self.expected_returns.loc[available_dates[-1]]
            else:
                # No data available, return empty portfolio
                return {asset: 0.0 for asset in assets}
        
        # Rank assets by expected return
        ranked_assets = exp_returns.sort_values(ascending=False)
        
        # Allocate based on rank and max position constraint
        portfolio = {}
        remaining_weight = 1.0
        
        for asset, _ in ranked_assets.items():
            # Skip negative expected returns
            if exp_returns[asset] <= 0:
                portfolio[asset] = 0.0
                continue
                
            weight = min(self.max_position, remaining_weight)
            portfolio[asset] = weight
            remaining_weight -= weight
            
            if remaining_weight <= 0:
                break
        
        # Add zero weights for remaining assets
        for asset in assets:
            if asset not in portfolio:
                portfolio[asset] = 0.0
        
        return portfolio


class OrderExecutor:
    """Simulates order execution with market impact"""
    
    def __init__(self, price_data: pd.DataFrame, impact_factor: float = 0.1):
        self.price_data = price_data
        self.impact_factor = impact_factor
        self.current_positions = {asset: 0.0 for asset in price_data.columns}
    
    def execute_orders(self, target_portfolio: Dict[str, float], 
                       date: pd.Timestamp, capital: float) -> Dict[str, float]:
        """Execute orders to reach target portfolio allocation"""
        # Get current prices
        if date in self.price_data.index:
            current_prices = self.price_data.loc[date]
        else:
            # Use the most recent available prices
            available_dates = self.price_data.index[self.price_data.index <= date]
            if len(available_dates) > 0:
                current_prices = self.price_data.loc[available_dates[-1]]
            else:
                # No data available
                return self.current_positions
        
        executed_positions = {}
        total_value = capital  # Simplified, assume we start with cash only
        
        # Calculate target positions in shares
        target_positions_value = {asset: target_portfolio[asset] * total_value 
                                 for asset in target_portfolio}
        
        target_positions_shares = {asset: target_positions_value[asset] / current_prices[asset] 
                                  if current_prices[asset] > 0 else 0
                                  for asset in target_portfolio}
        
        # Simulate market impact
        for asset, target_shares in target_positions_shares.items():
            current_shares = self.current_positions.get(asset, 0)
            shares_to_trade = target_shares - current_shares
            
            # Market impact increases with order size
            impact = abs(shares_to_trade) / (current_prices[asset] * 1000) * self.impact_factor
            executed_price = current_prices[asset] * (1 + np.sign(shares_to_trade) * impact)
            
            # Execute order
            executed_positions[asset] = target_shares
            
        self.current_positions = executed_positions
        return executed_positions


class AlphaStrategy:
    """Complete alpha strategy pipeline"""
    
    def __init__(self, simulator: MarketSimulator, training_days: int = 180, 
                 testing_days: int = 90, initial_capital: float = 1000000):
        self.simulator = simulator
        self.training_days = training_days
        self.testing_days = testing_days
        self.initial_capital = initial_capital
        self.capital = initial_capital
        self.portfolio_values = []
        self.dates = []
    
    def run(self) -> pd.DataFrame:
        """Run the complete alpha strategy pipeline"""
        # Generate data
        price_data, fundamental_data, sentiment_data = self.simulator.get_data()
        
        # Split data for training and testing
        split_idx = len(price_data) - self.testing_days
        
        train_price = price_data.iloc[:split_idx]
        train_fundamental = {k: v.iloc[:split_idx] for k, v in fundamental_data.items()}
        train_sentiment = sentiment_data.iloc[:split_idx]
        
        test_price = price_data.iloc[split_idx-5:]  # Include some overlap for initial prediction
        test_fundamental = {k: v.iloc[split_idx-5:] for k, v in fundamental_data.items()}
        test_sentiment = sentiment_data.iloc[split_idx-5:]
        
        # Generate factors
        factor_generator = FactorGenerator(train_price, train_fundamental, train_sentiment)
        train_factors = factor_generator.generate_combined_factor()
        
        # Train predictor
        predictor = DeepLearningPredictor(train_factors, train_price)
        predictor.train()
        
        # Initialize portfolio optimizer and order executor
        optimizer = PortfolioOptimizer(pd.DataFrame(), test_price)
        executor = OrderExecutor(test_price)
        
        # Run simulation on test data
        test_dates = test_price.index[5:]  # Skip the overlap days
        portfolio_values = [self.initial_capital]
        self.dates = [test_dates[0] - dt.timedelta(days=1)]  # Start one day before
        current_positions = {asset: 0 for asset in test_price.columns}
        
        for i, date in enumerate(test_dates):
            # Generate factors for test data
            test_factor_generator = FactorGenerator(
                test_price.iloc[:i+5], 
                {k: v.iloc[:i+5] for k, v in test_fundamental.items()},
                test_sentiment.iloc[:i+5]
            )
            test_factors = test_factor_generator.generate_combined_factor()
            
            # Make predictions
            predictions = predictor.predict(test_factors.iloc[-1:])
            optimizer.expected_returns = predictions
            
            # Optimize portfolio
            target_portfolio = optimizer.optimize(date)
            
            # Execute orders
            current_positions = executor.execute_orders(target_portfolio, date, self.capital)
            
            # Calculate portfolio value
            portfolio_value = 0
            current_prices = test_price.loc[date]
            
            for asset, shares in current_positions.items():
                portfolio_value += shares * current_prices[asset]
            
            self.capital = portfolio_value
            portfolio_values.append(portfolio_value)
            self.dates.append(date)
        
        self.portfolio_values = portfolio_values
        
        # Create performance summary
        performance = pd.DataFrame({
            'Date': self.dates,
            'Portfolio Value': self.portfolio_values
        })
        
        performance['Daily Return'] = performance['Portfolio Value'].pct_change()
        performance['Cumulative Return'] = (
            (1 + performance['Daily Return']).cumprod() - 1
        )
        
        # Calculate metrics
        performance['Drawdown'] = 1 - performance['Portfolio Value'] / performance['Portfolio Value'].cummax()
        
        return performance
    
    def plot_performance(self, performance: pd.DataFrame):
        """Plot strategy performance"""
        plt.figure(figsize=(12, 8))
        
        # Plot portfolio value
        plt.subplot(2, 1, 1)
        plt.plot(performance['Date'], performance['Portfolio Value'])
        plt.title('Portfolio Value Over Time')
        plt.grid(True)
        
        # Plot drawdown
        plt.subplot(2, 1, 2)
        plt.fill_between(performance['Date'], 0, performance['Drawdown'], color='red', alpha=0.3)
        plt.title('Portfolio Drawdown')
        plt.grid(True)
        
        plt.tight_layout()
        plt.show()


def calculate_performance_metrics(performance: pd.DataFrame) -> Dict:
    """Calculate key performance metrics"""
    daily_returns = performance['Daily Return'].dropna()
    
    total_return = performance['Portfolio Value'].iloc[-1] / performance['Portfolio Value'].iloc[0] - 1
    annualized_return = (1 + total_return) ** (252 / len(performance)) - 1
    
    volatility = daily_returns.std() * np.sqrt(252)
    sharpe_ratio = annualized_return / volatility if volatility > 0 else 0
    
    max_drawdown = performance['Drawdown'].max()
    
    return {
        'Total Return': total_return,
        'Annualized Return': annualized_return,
        'Annualized Volatility': volatility,
        'Sharpe Ratio': sharpe_ratio,
        'Maximum Drawdown': max_drawdown
    }


