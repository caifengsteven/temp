class NestedOUModel:
    """Implementation of the multi-level nested Ornstein-Uhlenbeck model for pegged assets."""
    
    def __init__(self, kappa, sigma, eta, nu, u_bar):
        """
        Initialize the model with parameters.
        
        Parameters:
        kappa: mean reversion rate of S towards U
        sigma: volatility of S
        eta: mean reversion rate of U towards u_bar
        nu: volatility of U
        u_bar: long-term mean
        """
        self.kappa = kappa
        self.sigma = sigma
        self.eta = eta
        self.nu = nu
        self.u_bar = u_bar
        self.nu_hat = nu * np.sqrt(kappa * nu / sigma) / (eta + np.sqrt(eta**2 + (kappa*nu/sigma)**2))
    
    def simulate_path(self, s0, u0, T, dt):
        """Simulate a path of the price process."""
        steps = int(T / dt)
        t = np.linspace(0, T, steps+1)
        
        # Initialize arrays
        s = np.zeros(steps+1)
        u = np.zeros(steps+1)
        u_hat = np.zeros(steps+1)
        
        s[0] = s0
        u[0] = u0
        u_hat[0] = self.u_bar  # Initialize u_hat at the long-term mean
        
        # Simulate the processes
        for i in range(1, steps+1):
            # Innovation Brownian motion
            dW_s = np.random.normal(0, np.sqrt(dt))
            dW_u = np.random.normal(0, np.sqrt(dt))
            
            # Update the hidden process U
            u[i] = u[i-1] + self.eta * (self.u_bar - u[i-1]) * dt + self.nu * np.sqrt(dt) * dW_u
            
            # Update the observable price process S
            s[i] = s[i-1] + self.kappa * (u[i-1] - s[i-1]) * dt + self.sigma * dW_s
            
            # Update the filtered process U_hat using the filtering equation
            u_hat[i] = u_hat[i-1] + self.eta * (self.u_bar - u_hat[i-1]) * dt + \
                       self.nu_hat * dW_s
        
        return t, s, u, u_hat
    
    def filter_path(self, s, dt):
        """Apply filtering to estimate u_hat from observed prices."""
        steps = len(s)
        u_hat = np.zeros(steps)
        u_hat[0] = self.u_bar
        
        for i in range(1, steps):
            # Innovation process
            innov = s[i] - s[i-1] - self.kappa * (s[i-1] - u_hat[i-1]) * dt
            innov_scaled = innov / (self.sigma * np.sqrt(dt))
            
            # Update u_hat
            u_hat[i] = u_hat[i-1] + self.eta * (self.u_bar - u_hat[i-1]) * dt + \
                       self.nu_hat * innov_scaled
                       
        return u_hat

