class RiskManager(Agent):
    """Agent for risk assessment and management"""
    def __init__(self, name: str, max_drawdown: float = 0.05):
        super().__init__(name, "Risk Manager")
        self.max_drawdown = max_drawdown
        
    def analyze(self, data: Dict) -> Dict:
        """Assess risk of trading decision"""
        ticker = data.get("ticker", "")
        trading_decision = data.get("trading_decision", {})
        portfolio = data.get("portfolio", {})
        
        if not trading_decision:
            return {
                "type": "risk_assessment",
                "ticker": ticker,
                "approval": False,
                "summary": "No trading decision to evaluate"
            }
            
        action = trading_decision.get("action", "hold")
        confidence = trading_decision.get("confidence", "low")
        
        # Calculate current exposure to this ticker
        current_position = portfolio.get(ticker, {"quantity": 0, "value": 0})
        portfolio_value = sum(p.get("value", 0) for p in portfolio.values())
        current_exposure = current_position.get("value", 0) / portfolio_value if portfolio_value > 0 else 0
        
        # Calculate risk metrics
        volatility = data.get("volatility", 0.2)  # Default volatility if not provided
        max_allocation = min(0.2, 0.5 / volatility)  # Higher volatility -> lower max allocation
        
        # Determine if action increases or decreases risk
        if action == "buy":
            risk_change = 1
        elif action == "sell":
            risk_change = -1
        else:  # hold
            risk_change = 0
            
        # Check if action would exceed risk limits
        if action == "buy" and current_exposure >= max_allocation:
            approval = False
            reason = f"Position in {ticker} already at maximum allocation of {max_allocation:.1%}"
        elif action == "buy" and confidence == "low":
            approval = False
            reason = f"Low confidence buy signal for {ticker} does not meet risk threshold"
        elif action == "sell" and confidence == "high":
            approval = True
            reason = f"High confidence sell signal for {ticker} approved to reduce risk"
        else:
            approval = True
            reason = f"Action for {ticker} within acceptable risk parameters"
            
        # Adjust position size based on confidence
        position_sizing = {
            "high": 1.0,  # Full position size
            "medium": 0.6,  # 60% position size
            "low": 0.3  # 30% position size
        }
        
        size_factor = position_sizing.get(confidence, 0.5)
        
        return {
            "type": "risk_assessment",
            "ticker": ticker,
            "approval": approval,
            "size_factor": size_factor,
            "metrics": {
                "current_exposure": current_exposure,
                "max_allocation": max_allocation,
                "volatility": volatility
            },
            "summary": reason
        }


class TradingAgentsFramework:
    """Main framework class for the TradingAgents multi-agent system"""
    def __init__(self):
        # Initialize all agents
        self.agents = {
            "fundamentals": AnalystAgent("Fundamentals Analyst", "Fundamental"),
            "technicals": AnalystAgent("Technical Analyst", "Technical"),
            "sentiment": AnalystAgent("Sentiment Analyst", "Sentiment"),
            "news": AnalystAgent("News Analyst", "News"),
            "bull_researcher": ResearchAgent("Bull Researcher", "Bullish"),
            "bear_researcher": ResearchAgent("Bear Researcher", "Bearish"),
            "trader": TraderAgent("Head Trader", "moderate"),
            "risk_manager": RiskManager("Risk Manager", 0.05)
        }
        
        self.portfolio = {}
        self.cash = 100000  # Initial cash
        self.trade_history = []
        
    def run_trading_cycle(self, market_data: Dict) -> Dict:
        """Execute a full trading cycle"""
        ticker = market_data.get("ticker", "Unknown")
        date = market_data.get("date", datetime.now().strftime("%Y-%m-%d"))
        
        try:
            # Step 1: Analyst team analysis
            analyst_reports = []
            for analyst_name in ["fundamentals", "technicals", "sentiment", "news"]:
                if analyst_name in self.agents:
                    report = self.agents[analyst_name].analyze(market_data)
                    analyst_reports.append(report)
            
            # Step 2: Research team analysis
            research_data = {
                "ticker": ticker,
                "analyst_reports": analyst_reports
            }
            research_reports = []
            for researcher_name in ["bull_researcher", "bear_researcher"]:
                if researcher_name in self.agents:
                    report = self.agents[researcher_name].analyze(research_data)
                    research_reports.append(report)
            
            # Step 3: Trader decision
            trading_data = {
                "ticker": ticker,
                "research_reports": research_reports
            }
            trading_decision = self.agents["trader"].analyze(trading_data)
            
            # Step 4: Risk assessment
            risk_data = {
                "ticker": ticker,
                "trading_decision": trading_decision,
                "portfolio": self.portfolio,
                "volatility": market_data.get("volatility", 0.2)
            }
            risk_assessment = self.agents["risk_manager"].analyze(risk_data)
            
            # Step 5: Execute trade if approved
            execution_result = self._execute_trade(ticker, trading_decision, risk_assessment, market_data)
            
            # Return the complete cycle results
            return {
                "date": date,
                "ticker": ticker,
                "analyst_reports": analyst_reports,
                "research_reports": research_reports,
                "trading_decision": trading_decision,
                "risk_assessment": risk_assessment,
                "execution": execution_result
            }
            
        except Exception as e:
            return {
                "date": date,
                "ticker": ticker,
                "error": str(e),
                "status": "Failed trading cycle"
            }
    
    def _execute_trade(self, ticker: str, decision: Dict, risk_assessment: Dict, market_data: Dict) -> Dict:
        """Execute the trade based on trading decision and risk assessment"""
        action = decision.get("action", "hold")
        approval = risk_assessment.get("approval", False)
        size_factor = risk_assessment.get("size_factor", 0.5)
        
        if not approval or action == "hold":
            return {
                "status": "No trade executed",
                "reason": "Risk assessment disapproval" if not approval else "Hold recommendation"
            }
        
        # Get current price
        price = market_data.get("price", 0)
        if price <= 0:
            return {
                "status": "Failed",
                "reason": "Invalid price data"
            }
        
        # Calculate position size
        portfolio_value = sum(p.get("value", 0) for p in self.portfolio.values()) + self.cash
        position_value = portfolio_value * 0.05 * size_factor  # 5% of portfolio adjusted by confidence
        shares = int(position_value / price)
        
        # Execute trade based on action
        if action == "buy" and shares > 0:
            cost = shares * price
            
            if cost > self.cash:
                shares = int(self.cash / price)
                cost = shares * price
                
            if shares > 0:
                # Update portfolio
                if ticker in self.portfolio:
                    self.portfolio[ticker]["quantity"] += shares
                    self.portfolio[ticker]["value"] = self.portfolio[ticker]["quantity"] * price
                else:
                    self.portfolio[ticker] = {
                        "quantity": shares,
                        "value": shares * price
                    }
                
                # Update cash
                self.cash -= cost
                
                # Record trade
                self.trade_history.append({
                    "date": market_data.get("date", datetime.now().strftime("%Y-%m-%d")),
                    "ticker": ticker,
                    "action": "buy",
                    "shares": shares,
                    "price": price,
                    "cost": cost
                })
                
                return {
                    "status": "Executed",
                    "action": "buy",
                    "shares": shares,
                    "price": price,
                    "cost": cost
                }
            else:
                return {
                    "status": "Failed",
                    "reason": "Insufficient funds"
                }
                
        elif action == "sell":
            # Check if we own the stock
            if ticker not in self.portfolio or self.portfolio[ticker]["quantity"] <= 0:
                return {
                    "status": "Failed",
                    "reason": "No shares to sell"
                }
            
            # Determine number of shares to sell based on confidence
            owned_shares = self.portfolio[ticker]["quantity"]
            sell_shares = int(owned_shares * size_factor)
            
            if sell_shares > 0:
                revenue = sell_shares * price
                
                # Update portfolio
                self.portfolio[ticker]["quantity"] -= sell_shares
                if self.portfolio[ticker]["quantity"] <= 0:
                    self.portfolio.pop(ticker)
                else:
                    self.portfolio[ticker]["value"] = self.portfolio[ticker]["quantity"] * price
                
                # Update cash
                self.cash += revenue
                
                # Record trade
                self.trade_history.append({
                    "date": market_data.get("date", datetime.now().strftime("%Y-%m-%d")),
                    "ticker": ticker,
                    "action": "sell",
                    "shares": sell_shares,
                    "price": price,
                    "revenue": revenue
                })
                
                return {
                    "status": "Executed",
                    "action": "sell",
                    "shares": sell_shares,
                    "price": price,
                    "revenue": revenue
                }
            else:
                return {
                    "status": "Failed",
                    "reason": "No shares to sell"
                }
        
        return {
            "status": "No action taken",
            "reason": "Invalid action or conditions"
        }
    
    def get_portfolio_value(self) -> float:
        """Calculate total portfolio value"""
        total_value = self.cash
        for ticker, position in self.portfolio.items():
            total_value += position.get("value", 0)
        return total_value
    
    def get_performance_metrics(self) -> Dict:
        """Calculate performance metrics"""
        # Calculate daily portfolio values
        if not self.trade_history:
            return {
                "cumulative_return": 0,
                "sharpe_ratio": 0,
                "max_drawdown": 0
            }
        
        # Extract unique dates from trade history
        dates = sorted(set(trade["date"] for trade in self.trade_history))
        
        # Calculate daily portfolio values and returns
        initial_value = 100000  # Initial portfolio value
        portfolio_values = [initial_value]
        
        # Simple calculation for demo purposes
        for trade in self.trade_history:
            if trade["action"] == "buy":
                portfolio_values.append(portfolio_values[-1] - trade["cost"] + trade["shares"] * trade["price"])
            else:  # sell
                portfolio_values.append(portfolio_values[-1] + trade["revenue"] - trade["shares"] * trade["price"])
        
        # Calculate returns
        returns = [(portfolio_values[i] / portfolio_values[i-1]) - 1 for i in range(1, len(portfolio_values))]
        
        # Calculate metrics
        final_value = portfolio_values[-1]
        cumulative_return = (final_value / initial_value) - 1
        
        # Calculate Sharpe ratio (assuming risk-free rate of 0 for simplicity)
        if returns and np.std(returns) > 0:
            sharpe_ratio = (np.mean(returns) * 252) / (np.std(returns) * np.sqrt(252))
        else:
            sharpe_ratio = 0
        
        # Calculate maximum drawdown
        max_drawdown = 0
        peak = portfolio_values[0]
        
        for value in portfolio_values:
            if value > peak:
                peak = value
            drawdown = (peak - value) / peak
            max_drawdown = max(max_drawdown, drawdown)
        
        return {
            "cumulative_return": cumulative_return,
            "annualized_return": cumulative_return * (252 / len(returns)) if returns else 0,
            "sharpe_ratio": sharpe_ratio,
            "max_drawdown": max_drawdown
        }


