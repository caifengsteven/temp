def plot_portfolio_performance(framework):
    """Plot the portfolio performance over time"""
    if not framework.trade_history:
        print("No trades to plot")
        return
    
    # Extract dates and calculate cumulative portfolio values
    trades_by_date = {}
    for trade in framework.trade_history:
        date = trade["date"]
        if date not in trades_by_date:
            trades_by_date[date] = []
        trades_by_date[date].append(trade)
    
    # Sort dates
    dates = sorted(trades_by_date.keys())
    
    # Calculate portfolio value over time
    portfolio_values = []
    cash = 100000  # Initial cash
    holdings = {}
    
    for date in dates:
        # Process all trades for this date
        for trade in trades_by_date[date]:
            ticker = trade["ticker"]
            price = trade["price"]
            shares = trade["shares"]
            
            if trade["action"] == "buy":
                cash -= shares * price
                holdings[ticker] = holdings.get(ticker, 0) + shares
            else:  # sell
                cash += shares * price
                holdings[ticker] = holdings.get(ticker, 0) - shares
        
        # Calculate total portfolio value including holdings
        portfolio_value = cash
        for ticker, shares in holdings.items():
            # Use the last known price for this ticker
            last_price = 0
            for trade in reversed(framework.trade_history):
                if trade["ticker"] == ticker:
                    last_price = trade["price"]
                    break
            
            if last_price > 0:
                portfolio_value += shares * last_price
        
        portfolio_values.append(portfolio_value)
    
    # Plot portfolio value over time
    plt.figure(figsize=(10, 6))
    plt.plot(range(len(dates)), portfolio_values, marker='o', linestyle='-')
    plt.title('TradingAgents Portfolio Performance')
    plt.xlabel('Trading Days')
    plt.ylabel('Portfolio Value ($)')
    plt.grid(True)
    plt.tight_layout()
    plt.show()


