        conviction_values = {"high": 3, "medium": 2, "low": 1}
        bullish_value = conviction_values.get(bullish_conviction, 1)
        bearish_value = conviction_values.get(bearish_conviction, 1)
        
        # Apply risk profile adjustments
        if self.risk_profile == "aggressive":
            bullish_value *= 1.5
            bearish_value *= 0.8
        elif self.risk_profile == "conservative":
            bullish_value *= 0.8
            bearish_value *= 1.5
        
        # Determine action based on adjusted conviction values
        diff = bullish_value - bearish_value
        
        if diff > 1.5:
            action = "buy"
            confidence = "high"
        elif diff > 0.5:
            action = "buy"
            confidence = "medium"
        elif diff > -0.5:
            action = "hold"
            confidence = "medium"
        elif diff > -1.5:
            action = "sell"
            confidence = "medium"
        else:
            action = "sell"
            confidence = "high"
            
